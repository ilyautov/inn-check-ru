"""
label.py — исход «банкрот / выжил / исключён» по ответу ЕФРСБ (чистая функция).

Окно исхода — заявление о банкротстве подано в 2022–2024, то есть после
отчётности за 2021 год. Год подачи берётся из номера дела арбитражного суда:
«А65-37758/2017» — дело зарегистрировано в 2017-м.

Почему по номеру дела, а не по дате стадии. ЕФРСБ отдаёт дату ТЕКУЩЕЙ стадии
(у «ВИМ-Авиа» конкурс — 26.09.2018), а процедура началась раньше (дело 2017 г.).
Дата стадии сдвигает начало банкротства вперёд и пропускает в выборку компании,
которые на дату отчёта уже были в суде: их отчётность — не прогноз, а симптом.
Такие компании — класс «исключён», в метрики они не идут ни с какой стороны.

Ограничение: ЕФРСБ показывает только ПОСЛЕДНЕЕ дело. Если у компании было дело
2022 года, прекращённое, а сейчас идёт дело 2025-го, она уйдёт в «выжил».
"""

import re

ОКНО = (2022, 2024)     # три года после отчёта за 2021 (решено 23.09.2026: 2022–2023 давали ~50 случаев)
ОТЧЁТНЫЙ_ГОД = 2021

_НОМЕР = re.compile(r"/\s*((?:19|20)\d{2})\s*$")


def год_дела(номер):
    """«А65-37758/2017» -> 2017; нет года в конце -> None."""
    m = _НОМЕР.search(str(номер or ""))
    return int(m.group(1)) if m else None


def исход(inn, ответ):
    """Ответ cmpbankrupts?searchString=<ИНН> -> {"класс", "год_дела", ...}.

    Классы: «банкрот» (год дела в ОКНЕ), «выжил» (записи нет или дело позже окна),
    «исключён» (дело подано до/в отчётном году или между отчётным годом и окном),
    «не проверено» (ответ не разобран, у записи нет номера дела с годом).
    Поиск ЕФРСБ нечёткий, поэтому берутся только записи с ТОЧНЫМ совпадением ИНН.
    """
    if not isinstance(ответ, dict) or not isinstance(ответ.get("pageData"), list):
        return {"класс": "не проверено", "причина": "ответ ЕФРСБ без pageData"}
    свои = [r for r in ответ["pageData"]
            if isinstance(r, dict) and str(r.get("inn") or "").strip() == str(inn)]
    if not свои:
        return {"класс": "выжил", "год_дела": None}
    годы = []
    for r in свои:
        дело = r.get("lastLegalCase") or {}
        г = год_дела(дело.get("number"))
        if г is None:
            return {"класс": "не проверено",
                    "причина": "у записи ЕФРСБ нет номера дела с годом: %r"
                               % дело.get("number")}
        годы.append((г, дело))
    г, дело = min(годы, key=lambda x: x[0])   # самое раннее из видимых дел
    стадия = (дело.get("status") or {})
    out = {"год_дела": г, "номер": дело.get("number"),
           "стадия": стадия.get("code"), "дата_стадии": стадия.get("date")}
    if г <= ОТЧЁТНЫЙ_ГОД or г < ОКНО[0]:
        out["класс"] = "исключён"
    elif г <= ОКНО[1]:
        out["класс"] = "банкрот"
    else:
        out["класс"] = "выжил"
    return out
