#!/usr/bin/env python3
"""
measured_svetofor.py — измеренный светофор (волна 5, блок F): как финансовая
часть профиля `отсрочка` разделяет компании по исходу. Исследование, не
резолвер: profiles.resolve не вызывается — без обязательных источников (ЕГРЮЛ,
ФССП, суды на 2022 год) он справедливо не дал бы 🟢, а подставлять их — подлог.

    python3 calibration/measured_svetofor.py            # svetofor_report.json
    python3 calibration/measured_svetofor.py --справочник  # таблица в references

Вход — только calibration/cohort_2021.csv (флаги движка по отчётности за 2021
год, исход по ЕФРСБ, двухфазные веса evaluate.py). Сети нет, результат
детерминирован seed'ом.

Дизайн (спека волны 5, блок F):
- дата проверки — 01.07.2022 (отчётность за 2021 год опубликована); исход — «дело о
  банкротстве заявлено в окне 01.07.2022…31.12.2024», «выжил» — «дела в окне не
  найдено». Год заявления известен из номера дела, месяц — нет: дела 2022 года
  могли быть поданы и до даты проверки. Поэтому два варианта: «строгий» (дела
  2022 года исключены целиком) и «с делами 2022» (оценка чувствительности);
- классы финансовой части: 🔴 (ча_отрицательные_2года — deal-killer профиля),
  🟡 (любой другой финансовый сигнал), «нет сигналов при полном покрытии пяти
  измеримых показателей», «не измерено» (сигналов нет, но хотя бы один
  показатель не рассчитан — упрощённая отчётность, пропуски). «Не измерено» не
  сливается с «нет сигналов»;
- исключаются банки (ОКВЭД 64.1), страховые и пенсионные (ОКВЭД 65) и
  некоммерческие организации (ОКОПФ не на 1 и не на 6);
- `предоплата` не считается: её вердикт определяют не финансы.
"""

