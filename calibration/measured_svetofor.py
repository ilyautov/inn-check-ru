def отчёт(rows, повторы, seed):
    варианты = {}
    for ключ, с_2022, с_нко in (("строгий", False, False), ("с_делами_2022", True, False),
                                ("строгий_с_нко", False, True)):
        строки, выпало = строки_варианта(rows, с_2022, с_нко)
        m = метрики(строки)
        m["ди95"] = бутстреп(строки, повторы, seed)
        m["n"] = len(строки)
        m["случаев"] = sum(1 for r in строки if r["случай"])
        m["выпало"] = выпало
        варианты[ключ] = m
    return {
        "дизайн": "docs/superpowers/specs/2026-09-26-wave5-osint-evidence-design.md (блок F)",
        "профиль": "отсрочка (только финансовая часть)",
        "дата_проверки": ДАТА_ПРОВЕРКИ,
        "окно_исхода": list(ОКНО),
        "измеримые_показатели": list(ПОКАЗАТЕЛИ),
        "не_измеряются": list(НЕ_ИЗМЕРЯЮТСЯ),
        "бутстреп": {"повторы": повторы, "seed": seed},
        "варианты": варианты,
        "оговорки": ОГОВОРКИ,
    }


def _п(x, знаков=1):
    return "—" if x is None else ("%.*f%%" % (знаков, 100 * x)).replace(".", ",")


def _ди(ди, ключ, знаков=1):
    v = (ди or {}).get(ключ)
    return "—" if not v else "%s–%s" % (_п(v[0], знаков), _п(v[1], знаков))


def таблица_md(rep):
    out = []
    имена = {"строгий": "Строгий вариант: дела 2022 года исключены (теряет дела "
                        "второй половины 2022)",
             "с_делами_2022": "Чувствительность: с делами 2022 года (включает и "
                             "поданные до 01.07.2022)",
             "строгий_с_нко": "Чувствительность: строгий вариант с некоммерческими "
                             "организациями (ТСЖ, ТСН, АНО, кооперативы — пороги на них "
                             "не рассчитаны)"}
    for ключ, заголовок in имена.items():
        m = rep["варианты"][ключ]
        ди = m["ди95"]
        out.append("#### %s\n" % заголовок)
        out.append("В расчёте %d компаний, из них %d с делом по правилу варианта; "
                   "базовая частота на весах — %s (без интервала: ДИ ниже условны на "
                   "числе дел)." % (
                       m["n"], m["случаев"], _п(m["базовая_частота"], 2)))
        out.append("")
        out.append("| класс финансовой части | n | с делом | доля компаний (на весах) | "
                   "P(дело \\| класс) (95% ДИ) |")
        out.append("|---|---|---|---|---|")
        for к in КЛАССЫ:
            c = m["классы"][к]
            out.append("| %s | %d | %d | %s | %s (%s) |" % (
                к, c["n"], c["случаев"], _п(c["доля_на_весах"]), _п(c["p_дело"], 2),
                _ди(ди, "p_дело|" + к, 2)))
        out.append("")
        out.append("- дела, при которых финансовая часть молчала, из %d: узкая доля "
                   "P(«нет сигналов» \\| дело) — **%s** (%s), широкая P(«нет сигналов» "
                   "или «не измерено» \\| дело) — **%s** (%s); среди дел с измеренной "
                   "финансовой частью — %s (%s);" % (
                       m["случаев"], _п(m["p_нет_сигналов_при_деле"]),
                       _ди(ди, "p_нет_сигналов_при_деле"),
                       _п(m["p_без_сигналов_при_деле"]), _ди(ди, "p_без_сигналов_при_деле"),
                       _п(m["p_нет_сигналов_при_деле_среди_измеренных"]),
                       _ди(ди, "p_нет_сигналов_при_деле_среди_измеренных")))
        out.append("- покрытие (все пять показателей рассчитаны или есть сигнал): %s (%s); "
                   "дел с «не измерено» — %s;"
                   % (_п(m["покрытие"]), _ди(ди, "покрытие"), _п(m["p_не_измерено_при_деле"])))
        out.append("- выпало из расчёта и пометки: %s." % (", ".join(
            "%s — %d" % (k, v) for k, v in sorted(m["выпало"].items())) or "ничего"))
        out.append("")
    out.append("**Оговорки.**\n")
    out.extend("- %s" % о for о in rep["оговорки"])
    return "\n".join(out).rstrip() + "\n"


def вписать_в_справочник(rep, путь=СПРАВОЧНИК):
    with open(путь, encoding="utf-8") as f:
        текст = f.read()
    if МАРКЕР_НАЧАЛО not in текст or МАРКЕР_КОНЕЦ not in текст:
        raise SystemExit("в %s нет маркеров измеренного светофора" % путь)
    до, _, хвост = текст.partition(МАРКЕР_НАЧАЛО)
    _, _, после = хвост.partition(МАРКЕР_КОНЕЦ)
    with open(путь, "w", encoding="utf-8") as f:
        f.write(до + МАРКЕР_НАЧАЛО + "\n\n" + таблица_md(rep) + "\n" + МАРКЕР_КОНЕЦ + после)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--повторы", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=2021)
    ap.add_argument("--справочник", action="store_true",
                    help="переписать таблицу в references/kalibrovka.md из svetofor_report.json")
    a = ap.parse_args(argv)
    if a.справочник:
        with open(ОТЧЁТ, encoding="utf-8") as f:
            вписать_в_справочник(json.load(f))
        return 0
    rep = отчёт(прочитать(), a.повторы, a.seed)
    with open(ОТЧЁТ, "w", encoding="utf-8") as f:
        json.dump(rep, f, ensure_ascii=False, indent=1)
        f.write("\n")
    for ключ, m in rep["варианты"].items():
        print("%s: n=%d, дел=%d, молчала финчасть: узко %s, широко %s; покрытие %s" % (
            ключ, m["n"], m["случаев"], _п(m["p_нет_сигналов_при_деле"]),
            _п(m["p_без_сигналов_при_деле"]), _п(m["покрытие"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
