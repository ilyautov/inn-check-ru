МАРКЕР_КОНЕЦ = "<!-- измеренный светофор из calibration/svetofor_report.json: конец -->"

ДАТА_ПРОВЕРКИ = "2022-07-01"
ОКНО = ("2022-07-01", "2024-12-31")
# Флаг движка -> показатель, без которого флаг не считается (как в evaluate.py).
ПОКАЗАТЕЛИ = {
    "ча_отрицательные_2года": "ча_отрицательные_2года",
    "коэффициент_автономии": "автономия",
    "текущая_ликвидность": "ликвидность",
    "падение_выручки": "падение_выручки",
    "убыток_2года": "убыток_2года",
}
КРАСНЫЕ = {"ча_отрицательные_2года"}      # deal_killers профиля `отсрочка`
# Финансовые сигналы профиля, которые в ретро не измеряются: уставного капитала
# на 2022 год в когорте нет, транзитный профиль по отчётности 2021 не считался.
НЕ_ИЗМЕРЯЮТСЯ = ("ча_ниже_уставного_капитала", "транзитный_профиль")
КЛАССЫ = ("🔴", "🟡", "нет сигналов", "не измерено")


def исключена(r):
    """Банк, страховая/пенсионный фонд или НКО -> причина, иначе None."""
    okved, окопф = (r.get("okved") or "").strip(), (r.get("окопф") or "").strip()
    if okved == "64.1" or okved.startswith("64.1"):
        return "банк (ОКВЭД 64.1)"
    if okved == "65" or okved.startswith("65."):
        return "страхование/пенсионный фонд (ОКВЭД 65)"
    # Правило первой цифры — для кодов ОКОПФ-2012 (5 цифр). Старые двузначные
    # коды (65 — ООО, 53 — КФХ) так не читаются: они остаются в расчёте и
    # считаются в отчёте отдельно, а не выпадают как «некоммерческие».
    if len(окопф) == 5 and окопф[0] not in "16":
        return "некоммерческая или иная не коммерческая форма (ОКОПФ %s)" % окопф
    return None


def класс(r):
    флаги = {f for f in (r.get("флаги") or "").split(";") if f}
    if флаги & КРАСНЫЕ:
        return "🔴"
    if флаги & set(ПОКАЗАТЕЛИ):
        return "🟡"
    if any((r.get(п) or "") == "" for п in ПОКАЗАТЕЛИ.values()):
        return "не измерено"
    return "нет сигналов"


def прочитать(путь=КОГОРТА):
    with open(путь, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def строки_варианта(rows, с_делами_2022, с_нко=False):
    """Строки расчёта и учёт выпавших (с причинами)."""
    out, выпало = [], {}
    старый_окопф = 0
    for r in rows:
        причина = исключена(r)
        if с_нко and причина and причина.startswith("некоммерческая"):
            причина = None
        if причина is None and r["класс"] == "банкрот" and r["год_дела"] == "2022" \
                and not с_делами_2022:
            причина = "дело 2022 года — могло быть заявлено до даты проверки"
        if причина:
            ключ = причина.split(" (")[0]
            выпало[ключ] = выпало.get(ключ, 0) + 1
            continue
        старый_окопф += bool(r.get("окопф")) and len(r["окопф"]) != 5
        out.append({"случай": r["класс"] == "банкрот", "вес": float(r["вес"]),
                    "класс": класс(r)})
    if старый_окопф:
        выпало["оставлено в расчёте: ОКОПФ старого формата"] = старый_окопф
    return out, выпало


def метрики(строки):
    W = {к: 0.0 for к in КЛАССЫ}
    C = {к: 0.0 for к in КЛАССЫ}
    n = {к: 0 for к in КЛАССЫ}
    случаев = {к: 0 for к in КЛАССЫ}
    for r in строки:
        к = r["класс"]
        W[к] += r["вес"]
        n[к] += 1
        if r["случай"]:
            C[к] += r["вес"]
            случаев[к] += 1
    всего_W, всего_C = sum(W.values()), sum(C.values())
    измерено_C = всего_C - C["не измерено"]
    return {
        "классы": {к: {"n": n[к], "случаев": случаев[к], "вес": W[к],
                       "доля_на_весах": W[к] / всего_W if всего_W else None,
                       "p_дело": C[к] / W[к] if W[к] else None} for к in КЛАССЫ},
        "базовая_частота": всего_C / всего_W if всего_W else None,
        # доля ложно-зелёных: дело было, а финансовая часть молчала
        "p_нет_сигналов_при_деле": C["нет сигналов"] / всего_C if всего_C else None,
        "p_нет_сигналов_при_деле_среди_измеренных": (
            C["нет сигналов"] / измерено_C if измерено_C else None),
        "p_не_измерено_при_деле": C["не измерено"] / всего_C if всего_C else None,
        # Широкая доля: живой профиль при части пропусков (например, без
        # ликвидности) может показать 🟢, поэтому «не измерено» — тоже
        # потенциально зелёное. Это верхняя граница для финансовой части.
        "p_без_сигналов_при_деле": ((C["нет сигналов"] + C["не измерено"]) / всего_C
                                    if всего_C else None),
        "покрытие": 1 - W["не измерено"] / всего_W if всего_W else None,
    }


# Базовой частоты среди ключей нет: стратифицированный ресэмплинг держит число
# дел наблюдаемым, её интервал вырожден. Все ДИ условны на этом числе —
# неопределённость первой фазы (сколько дел попало в когорту) в них не входит.
КЛЮЧИ_ДИ = ("p_нет_сигналов_при_деле", "p_нет_сигналов_при_деле_среди_измеренных",
            "p_без_сигналов_при_деле", "покрытие")


def бутстреп(строки, повторы, seed):
    """95% ДИ перцентилями; случаи и контроли ресэмплятся раздельно (дизайн фазы 2)."""
    rng = random.Random(seed)
    случаи = [r for r in строки if r["случай"]]
    контроли = [r for r in строки if not r["случай"]]
    выборки = {k: [] for k in КЛЮЧИ_ДИ}
    выборки.update({"p_дело|" + к: [] for к in КЛАССЫ})
    for _ in range(повторы):
        б = [rng.choice(случаи) for _ in случаи] + [rng.choice(контроли) for _ in контроли]
        m = метрики(б)
        for k in КЛЮЧИ_ДИ:
            if m[k] is not None:
                выборки[k].append(m[k])
        for к in КЛАССЫ:
            if m["классы"][к]["p_дело"] is not None:
                выборки["p_дело|" + к].append(m["классы"][к]["p_дело"])
    ди = {}
    for k, v in выборки.items():
        if len(v) >= max(20, повторы // 2):
            v.sort()
            ди[k] = [v[int(0.025 * (len(v) - 1))], v[int(0.975 * (len(v) - 1))]]
    return ди


