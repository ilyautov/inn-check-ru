// было проверить в Node (eval/run_extension_eval.py). Правила — те же, что у
// хоста (scripts/native_host.py): ИНН с контрольной суммой, сайты источников,
// id операции. Хост всё перепроверяет сам; здесь — чтобы не слать заведомо
// негодное и честно показать ошибку в окне.

export const ХОСТ = "ru.inn_check_ru.host";

// Сайты браузерных источников — как native_host.ХОСТЫ (eval сверяет).
export const ХОСТЫ = {
  "фссп": ["fssp.gov.ru"], "суды": ["kad.arbitr.ru"], "залоги": ["reestr-zalogov.ru"],
};

// Блоки, у которых поля считает хост из вставленного текста страницы
// (manual_block.РАЗБОР_ТЕКСТА).
export const РАЗБОР_ТЕКСТА = ["залоги"];
export const МАКС_ТЕКСТ = 512 * 1024;

// Поля сигналов, которые форма обязана спросить, — как manual_block.ПОЛЯ.
export const ПОЛЯ = {
  "фссп": [
    { имя: "производств", тип: "целое", подпись: "Исполнительных производств", обязательно: true },
    { имя: "крупные", тип: "да-нет", подпись: "Суммы сопоставимы с активами или сделкой", обязательно: true },
    { имя: "сумма", тип: "число", подпись: "Общая сумма, ₽", обязательно: false },
  ],
  "суды": [
    { имя: "ответчик_крупные", тип: "да-нет", подпись: "Крупные иски к компании-ответчику", обязательно: true },
    { имя: "ответчик_дел", тип: "целое", подпись: "Дел в роли ответчика", обязательно: false },
    { имя: "ответчик_сумма", тип: "число", подпись: "Сумма исков к ответчику, ₽", обязательно: false },
  ],
  // поле считает хост из текста страницы; вручную — только «ничего не найдено» (0)
  "залоги": [
    { имя: "уведомлений", тип: "целое", подпись: "Уведомлений о залоге (если текст не вставлен)", обязательно: false },
  ],
};

function контроль(цифры, веса) {
  let s = 0;
  for (let i = 0; i < веса.length; i++) s += Number(цифры[i]) * веса[i];
  return (s % 11) % 10;
}

export function иннВерен(инн) {
  if (!/^(\d{10}|\d{12})$/.test(инн)) return false;
  if (инн.length === 10) return контроль(инн, [2, 4, 10, 3, 5, 9, 4, 6, 8]) === Number(инн[9]);
  return контроль(инн, [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]) === Number(инн[10])
    && контроль(инн, [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]) === Number(инн[11]);
}

// Первый верный ИНН в выделенном тексте: сначала отдельное число из 10/12 цифр,
// иначе группы цифр через пробелы (\s в JS включает NBSP) и дефисы склеиваются
// до 10 или 12 цифр (строже profiles._первый_инн: запятая ИНН не склеивает).
// null — ИНН нет.
export function иннИзТекста(текст) {
  const s = String(текст || "").slice(0, 2000);
  for (const m of s.matchAll(/\d+(?:[\s-]+\d+)*/g)) {
    const группы = m[0].split(/[\s-]+/);
    // «12 7707083893» не склеивается в 12 цифр: целое число — первым
    for (const n of группы) {
      if ((n.length === 10 || n.length === 12) && иннВерен(n)) return n;
    }
    let набрано = "";
    for (const г of группы) {
      набрано += г;
      if (набрано.length > 12) break;
      if ((набрано.length === 10 || набрано.length === 12) && иннВерен(набрано)) return набрано;
    }
  }
  return null;
}

// Источник по URL вкладки: только https и только сайт источника (поддомены —
// тоже). null — страница не из реестра, форма не показывается.
export function источникПоUrl(url) {
  if (typeof url !== "string" || /[\\\s\x00-\x1f\x7f]/.test(url)) return null;
  let u;
  try { u = new URL(url); } catch { return null; }
  // как хост: только https, без userinfo, порт — стандартный
  if (u.protocol !== "https:" || u.username || u.password || u.port !== "") return null;
  const хост = u.hostname.toLowerCase();
  for (const [ист, хосты] of Object.entries(ХОСТЫ)) {
    if (хосты.some((х) => хост === х || хост.endsWith("." + х))) return ист;
  }
  return null;
}

export function сегодня(дата = new Date()) {
  const д = (n) => String(n).padStart(2, "0");
  return `${дата.getFullYear()}-${д(дата.getMonth() + 1)}-${д(дата.getDate())}`;
}

export function новаяОперация(uuid) {
  return String(uuid).replace(/[^A-Za-z0-9-]/g, "").slice(0, 64);
}

// Форма -> сообщение хосту «ручной_блок». Ошибки — массив строк для окна.
export function сообщениеБлока(форма, url, операция) {
  const ошибки = [];
  const блок = источникПоUrl(url);
  if (!блок) ошибки.push("страница не с сайта ФССП, kad.arbitr.ru или реестра залогов");
  const текст = блок && РАЗБОР_ТЕКСТА.includes(блок) ? String(форма.текст || "") : "";
  if (текст.length > МАКС_ТЕКСТ) ошибки.push("текст страницы длиннее 512 КБ");
  if (!иннВерен(форма.инн || "")) ошибки.push("ИНН: 10 или 12 цифр с верной контрольной суммой");
  const итог = форма.итог === "не проверено" ? "не проверено" : "проверено";
  const поля = {};
  // с текстом поля не вводятся: их считает хост
  for (const п of (блок && !текст.trim() ? ПОЛЯ[блок] : [])) {
    const v = форма.поля?.[п.имя];
    if (v === undefined || v === "") {
      if (п.обязательно && итог === "проверено") ошибки.push(`не заполнено: ${п.подпись}`);
      continue;
    }
    if (п.тип === "да-нет") поля[п.имя] = v === true || v === "да";
    else if (п.тип === "целое" && !/^\d+$/.test(String(v).replace(/\s/g, ""))) {
      ошибки.push(`${п.подпись}: целое число ≥ 0`);   // как int у manual_block.ПОЛЯ
    } else if (!/^\d+(?:[.,]\d+)?$/.test(String(v).replace(/\s/g, ""))) ошибки.push(`${п.подпись}: число ≥ 0`);
    else поля[п.имя] = String(v).replace(/\s/g, "");
  }
  if (итог === "не проверено" && !String(форма.причина || "").trim()) {
    ошибки.push("укажите, почему не проверено (капча, вход, поиск не завершён)");
  }
  const сообщение = {
    команда: "ручной_блок", операция, инн: форма.инн, блок, url,
    дата: форма.дата, итог, поля,
  };
  if (текст.trim() && итог === "проверено") сообщение.текст = текст;
  for (const k of ["найдено", "параметры", "причина"]) {
    if (String(форма[k] || "").trim()) сообщение[k] = String(форма[k]).trim().slice(0, 500);
  }
  return { сообщение, ошибки };
}

// Снимок — только юрлицо (у ИП на странице ФССП — ФИО) и только с
// подтверждением пользователя, что ФИО физлиц на экране нет.
export function снимокРазрешён(инн, подтверждено) {
  if (String(инн || "").length !== 10) return "снимок только для юрлица: у ИП на странице ФИО";
  if (!подтверждено) return "подтвердите, что на экране нет ФИО физлиц";
  return null;
}

// Та же вкладка и та же страница, что при открытии окна: иначе блок или снимок
// относились бы к другой странице.
export function таЖеСтраница(вкладка, исходная) {
  return Boolean(вкладка && исходная) && вкладка.id === исходная.id
    && вкладка.url === исходная.url;
}

// Сообщение service worker'у — только от своего окна расширения.
export function своёОкно(отправитель, idРасширения, urlОкна) {
  return Boolean(отправитель) && отправитель.id === idРасширения
    && String(отправитель.url || "").startsWith(urlОкна);
}

// The popup also runs as a local preview. Storage failures never stop the UI.
const память = { local: {}, session: {} };
export const хранилище = (область) => ({
  async get(ключ) {
    try {
      if (globalThis.chrome?.storage?.[область]) return await chrome.storage[область].get(ключ);
    } catch { /* unavailable extension context: use the in-memory preview */ }
    return { [ключ]: память[область][ключ] };
  },
  async set(данные) {
    Object.assign(память[область], данные);
    try { await globalThis.chrome?.storage?.[область]?.set(данные); } catch { /* preview */ }
  },
});

export function runIdВерен(id) {
  return typeof id === "string" && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(id);
}

export function выбраннаяПроверка(ответ, runId) {
  if (ответ?.status === "error" || ответ?.run_id !== runId || !runIdВерен(runId)
      || !Number.isInteger(ответ.revision) || ответ.revision < 1
      || !иннВерен(ответ.data?.fetch?.инн)) return null;
  const f = ответ.data.fetch;
  return { run_id: runId, revision: ответ.revision, инн: f.инн,
    название: f.егрюл?.название || f.название || "Название не получено",
    профиль: ответ.data.metadata?.profile || "—", pending_actions: ответ.pending_actions || [] };
}

export function сообщениеПроверки(форма, url, run, подтверждено, operationId) {
  const outcome = форма.outcome;
  const { сообщение, ошибки } = сообщениеБлока({ ...форма,
    итог: outcome === "completed" ? "проверено" : "не проверено" }, url, operationId);
  if (!run || !runIdВерен(run.run_id)) ошибки.push("Выберите и загрузите сохранённую проверку");
  if (!подтверждено) ошибки.push("Подтвердите привязку к показанной проверке");
  if (run && форма.инн !== run.инн) ошибки.push("ИНН формы не совпадает с выбранной проверкой");
  if (!["completed", "declined", "incomplete"].includes(outcome)) ошибки.push("Выберите исход ручного шага");
  if (outcome === "completed" && форма.pagination_complete !== true) ошибки.push("Подтвердите, что просмотрены все страницы результатов");
  if (outcome === "completed" && !форма.параметры?.trim()) ошибки.push("Укажите параметры поиска, включая ИНН");
  if (форма.текст?.trim()) ошибки.push("Для привязки к проверке укажите поля вручную; разбор текста доступен в отдельном блоке");
  const поля = Object.fromEntries(Object.entries(сообщение.поля).map(([k, v]) =>
    [k, typeof v === "boolean" ? v : Number(String(v).replace(",", "."))]));
  return { ошибки, сообщение: { команда: "run_manual", run_id: run?.run_id,
    expected_revision: run?.revision, operation_id: operationId,
    blocks: { [сообщение.блок]: { ...поля, инн: форма.инн, url,
      дата_проверки: форма.дата, статус: outcome === "completed" ? "проверено" : "не проверено",
      outcome, pagination_complete: форма.pagination_complete === true,
      параметры_поиска: форма.параметры || "", найдено: форма.найдено || "", reason: форма.причина || "" } } } };
}
