def перцентиль(отсортированные, q):
    """Линейная интерполяция по отсортированному списку (метод numpy 'linear')."""
    n = len(отсортированные)
    if n == 0:
        return None
    if n == 1:
        return float(отсортированные[0])
    поз = (q / 100.0) * (n - 1)
    низ = int(поз)
    верх = min(низ + 1, n - 1)
    доля = поз - низ
    return отсортированные[низ] + (отсортированные[верх] - отсортированные[низ]) * доля


def медиана(значения):
    if not значения:
        return None
    s = sorted(значения)
    return перцентиль(s, 50)


def позиция_перцентиля(значение, точки):
    """Обратная задача: где значение среди опубликованных перцентилей.

    `точки` — [(перцентиль, значение), ...] по возрастанию значения. Возвращает
    (перцентиль, оговорка). Между точками — линейная интерполяция; за краями
    честно говорится, что оценка граничная: p10/p90 — всё, что опубликовано."""
    точки = [(p, v) for p, v in точки if v is not None]
    if not точки:
        return None, "в группе нет опубликованных перцентилей"
    точки.sort(key=lambda t: t[1])
    if значение <= точки[0][1]:
        return точки[0][0], ("не выше %d-го перцентиля: ниже опубликованного "
                             "края группы" % точки[0][0])
    if значение >= точки[-1][1]:
        return точки[-1][0], ("не ниже %d-го перцентиля: выше опубликованного "
                              "края группы" % точки[-1][0])
    for i in range(len(точки) - 1):
        (p1, v1), (p2, v2) = точки[i], точки[i + 1]
        if v1 <= значение <= v2:
            if v2 == v1:
                return p2, None
            доля = (значение - v1) / (v2 - v1)
            return round(p1 + (p2 - p1) * доля), None
    return точки[-1][0], None


# ---------------------------------------------------------------- агрегация

def _статистики(куча):
    выручки = sorted(куча["выручка"])
    нагрузки = куча["нагрузка"]
    ссч = куча["ссч"]
    на_сотрудника = куча["на_сотрудника"]
    ндс = куча["ндс"]
    return [
        len(выручки),
        round(перцентиль(выручки, 10)),
        round(перцентиль(выручки, 25)),
        round(перцентиль(выручки, 50)),
        round(перцентиль(выручки, 75)),
        round(перцентиль(выручки, 90)),
        round(медиана(нагрузки), 4) if нагрузки else None,
        round(медиана(ссч), 1) if ссч else None,
        round(медиана(на_сотрудника)) if на_сотрудника else None,
        round(куча["усн"] / куча["усн_знаменатель"], 3)
        if куча["усн_знаменатель"] else None,
        round(медиана(ндс), 4) if ндс else None,
    ]


def _новая_куча():
    return {"выручка": [], "нагрузка": [], "ссч": [], "на_сотрудника": [],
            "ндс": [], "усн": 0, "усн_знаменатель": 0}


def _добавить(куча, зап):
    доход = зап["доход"]
    куча["выручка"].append(доход)
    if зап.get("налоги") is not None and доход > 0:
        куча["нагрузка"].append(зап["налоги"] / доход)
    if зап.get("ндс") is not None and доход > 0:
        куча["ндс"].append(зап["ндс"] / доход)
    ссч = зап.get("ссч")
    if ссч is not None:
        куча["ссч"].append(float(ссч))
        if ссч > 0:
            куча["на_сотрудника"].append(доход / ссч)
    усн = зап.get("усн")
    if усн is not None:
        куча["усн_знаменатель"] += 1
        куча["усн"] += 1 if усн else 0


def агрегировать(компании, пороги, порог_n=ПОРОГ_N):
    """Поток записей о компаниях -> (группы, группы_без_региона, статистика).

    Запись: {"оквэд2","регион","доход","налоги","ндс","ссч","усн"}. Функция
    вынесена отдельно от чтения дампов именно затем, чтобы eval проверял
    агрегацию на синтетике с известным ответом."""
    с_регионом = {}
    без_региона = {}
    всего = 0
    for зап in компании:
        оквэд2, регион, доход = зап.get("оквэд2"), зап.get("регион"), зап.get("доход")
        if not оквэд2 or доход is None or доход <= 0:
            continue
        размер = размерная_группа(доход, пороги)
        if размер is None:
            continue
        всего += 1
        if регион:
            ключ = "%s|%s|%s" % (оквэд2, регион, размер)
            _добавить(с_регионом.setdefault(ключ, _новая_куча()), зап)
        ключ2 = "%s|%s" % (оквэд2, размер)
        _добавить(без_региона.setdefault(ключ2, _новая_куча()), зап)

    групп_всего = len(с_регионом)
    группы = {k: _статистики(v) for k, v in с_регионом.items()
              if len(v["выручка"]) >= порог_n}
    схлопнутые = {k: _статистики(v) for k, v in без_региона.items()
                  if len(v["выручка"]) >= порог_n}
    статистика = {
        "компаний_в_агрегации": всего,
        "групп_оквэд_регион_размер_всего": групп_всего,
        "групп_опубликовано": len(группы),
        "групп_отсеяно_порогом": групп_всего - len(группы),
        "групп_без_региона_всего": len(без_региона),
        "групп_без_региона_опубликовано": len(схлопнутые),
        "групп_без_региона_отсеяно_порогом": len(без_региона) - len(схлопнутые),
    }
    return группы, схлопнутые, статистика


# ---------------------------------------------------------------- сборка

def _налоги_и_ндс(налоги):
    """{наименование: сумма} -> (сумма налогов и сборов, сумма НДС)."""
    сумма = 0.0
    ндс = 0.0
    for имя, v in налоги.items():
        if имя in НАИМЕНОВАНИЯ_НЕ_НАЛОГ or имя.startswith(ПРЕФИКСЫ_НЕ_НАЛОГ):
            continue
        сумма += v
        if имя == НАИМЕНОВАНИЕ_НДС:
            ндс += v
    return сумма, ндс


class _Карта:
    """ОКВЭД2 + код региона по ИНН из дампа МСП, упакованные в один int64.

    комб = инн * 10000 + оквэд2 * 100 + регион. Массив отсортирован по комб,
    а значит и по ИНН, поэтому поиск — bisect по инн*10000. На 2,2 млн юрлиц
    это ≈18 МБ против ≈400 МБ у dict {str: tuple}."""

    def __init__(self):
        self._сырое = []
        self.комб = None
        self.регионы = {}

    def добавить(self, инн, оквэд2, регион, наим=None, тип=None):
        try:
            и, о, р = int(инн), int(оквэд2), int(регион)
        except (TypeError, ValueError):
            return
        # Упаковка держит ровно два знака на ОКВЭД2 и на код региона: всё,
        # что не влезло, — не наш формат, и молча искажать его нельзя.
        if not (0 < и < 10 ** 12 and 0 <= о <= 99 and 0 <= р <= 99):
            return
        self._сырое.append(и * 10000 + о * 100 + р)
        if наим and регион not in self.регионы:
            self.регионы[регион] = ("%s %s" % (наим, тип)).strip() if тип else наим

    def закрыть(self):
        self._сырое.sort()
        self.комб = array("q", self._сырое)
        self._сырое = []
        return self

    def __len__(self):
        return len(self.комб) if self.комб is not None else len(self._сырое)

    def индекс(self, инн):
        try:
            ключ = int(инн) * 10000
        except (TypeError, ValueError):
            return -1
        i = bisect_left(self.комб, ключ)
        if i < len(self.комб) and self.комб[i] // 10000 == int(инн):
            return i
        return -1

    def оквэд_регион(self, i):
        v = self.комб[i]
        return "%02d" % ((v // 100) % 100), "%02d" % (v % 100)


def _прогресс(метка, тихо):
    if тихо:
        return None

    def cb(имя, номер, всего):
        if номер % 200 == 0 or номер == всего:
            sys.stderr.write("\r%s: файл %d/%d" % (метка, номер, всего))
            sys.stderr.flush()
            if номер == всего:
                sys.stderr.write("\n")
    return cb


def собрать_записи(пути=None, тихо=False, лимит=None):
    """Пять дампов -> поток записей о компаниях. Потоково: в памяти живут
    только упакованные массивы, ни один дамп целиком не разворачивается."""
    пути = пути or {}
    карта = _Карта()
    for рec in od.итерировать("rsmp", пути.get("rsmp"), лимит=лимит,
                              на_файл=_прогресс("rsmp (ОКВЭД)", тихо)):
        if рec.get("тип") != "юрлицо":
            continue
        if not рec.get("оквэд2") or not рec.get("регион"):
            continue
        карта.добавить(рec["инн"], рec["оквэд2"], рec["регион"],
                       рec.get("регион_наименование"), рec.get("регион_тип"))
    карта.закрыть()
    n = len(карта)
    доход = array("d", bytes(8 * n))
    налоги = array("d", bytes(8 * n))
    ндс = array("d", bytes(8 * n))
    ссч = array("i", bytes(4 * n))
    усн = array("b", bytes(n))
    есть = array("b", bytes(n))      # 1 — доход из revexp
    есть_налоги = array("b", bytes(n))
    есть_ссч = array("b", bytes(n))
    есть_усн = array("b", bytes(n))
    периоды = {}

    for рec in od.итерировать("revexp", пути.get("revexp"), лимит=лимит,
                              на_файл=_прогресс("revexp (доходы)", тихо)):
        i = карта.индекс(рec["инн"])
        if i < 0 or рec.get("доход") is None:
            continue
        доход[i] = рec["доход"]
        есть[i] = 1
        периоды.setdefault("revexp", рec.get("дата_сост"))

    for рec in od.итерировать("paytax", пути.get("paytax"), лимит=лимит,
                              на_файл=_прогресс("paytax (налоги)", тихо)):
        i = карта.индекс(рec["инн"])
        if i < 0:
            continue
        налоги[i], ндс[i] = _налоги_и_ндс(рec.get("налоги") or {})
        есть_налоги[i] = 1
        периоды.setdefault("paytax", рec.get("дата_сост"))

    for рec in od.итерировать("sshr2019", пути.get("sshr2019"), лимит=лимит,
                              на_файл=_прогресс("sshr2019 (ССЧ)", тихо)):
        i = карта.индекс(рec["инн"])
        if i < 0 or рec.get("ссч") is None:
            continue
        ссч[i] = рec["ссч"]
        есть_ссч[i] = 1
        периоды.setdefault("sshr2019", рec.get("дата_сост"))

    for рec in od.итерировать("snr", пути.get("snr"), лимит=лимит,
                              на_файл=_прогресс("snr (спецрежимы)", тихо)):
        i = карта.индекс(рec["инн"])
        if i < 0 or рec.get("усн") is None:
            continue
        усн[i] = 1 if рec["усн"] else 0
        есть_усн[i] = 1
        периоды.setdefault("snr", рec.get("дата_сост"))

    покрытие = {
        "юрлиц_в_реестре_мсп": n,
        "из_них_с_доходом_revexp": sum(есть),
        "из_них_с_налогами_paytax": sum(есть_налоги),
        "из_них_с_ссч_sshr2019": sum(есть_ссч),
        "из_них_со_спецрежимом_snr": sum(есть_усн),
    }

    def поток():
        for i in range(n):
            if not есть[i]:
                continue
            оквэд2, регион = карта.оквэд_регион(i)
            yield {
                "оквэд2": оквэд2,
                "регион": регион,
                "доход": доход[i],
                "налоги": налоги[i] if есть_налоги[i] else None,
                "ндс": ндс[i] if есть_налоги[i] else None,
                "ссч": ссч[i] if есть_ссч[i] else None,
                "усн": bool(усн[i]) if есть_усн[i] else None,
            }

    return поток(), карта.регионы, покрытие, периоды


