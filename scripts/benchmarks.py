def загрузить(путь=ТАБЛИЦА_ПУТЬ):
    """Таблица норм или (None, причина). Нет таблицы -> честное «не проверено»."""
    текст = None
    try:
        with open(путь, encoding="utf-8") as fh:
            текст = fh.read()
    except OSError:
        try:
            from importlib.resources import files
            текст = (files("inn_check_ru_data") / "benchmarks_ru.json").read_text(
                encoding="utf-8")
        except Exception:
            текст = None
    if текст is None:
        return None, ("нормы не построены: нет data/benchmarks_ru.json — "
                      "соберите локально: benchmarks.py --построить")
    try:
        таблица = json.loads(текст)
    except ValueError as e:
        return None, "таблица норм битая (%s)" % e
    if not isinstance(таблица.get("группы"), dict):
        return None, "таблица норм без блока «группы» — формат изменился"
    причина = причина_урезанной_сборки(таблица)
    if причина:
        return None, причина
    return таблица, None


def причина_урезанной_сборки(таблица):
    """Таблица, собранная с --лимит, — не нормы, а правдоподобная выдумка.

    Лимит режет каждый дамп независимо, поэтому джойн пяти источников
    разваливается: в группе остаётся случайное подмножество, n при этом
    выглядит настоящим. Такую таблицу читать нельзя ни через загрузить(),
    ни через оценить(таблица=...)."""
    лимит = (таблица or {}).get("лимит")
    if лимит:
        return ("таблица собрана с --лимит %s: каждый дамп урезан независимо, "
                "джойн неполный, нормы по ней недостоверны. Соберите полную: "
                "benchmarks.py --построить" % лимит)
    return None


# Тип субъекта в названии — шум для сопоставления: реестр МСП пишет
# «Краснодарский край», ЕГРЮЛ — «Краснодарский край», pb — «КРАСНОДАРСКИЙ КРАЙ»,
# а «Кемеровская область - Кузбасс обл.» тащит тип дважды. Сравниваем множества
# значимых слов, а не строки.
#
# «Прозрачный бизнес» пишет субъект как «ГОРОД ФЕДЕРАЛЬНОГО ЗНАЧЕНИЯ МОСКВА»,
# а реестр МСП — как «Москва г.»: без слов «федерального» и «значения» в
# стоп-листе ключи не совпадали, код региона не резолвился, и норма молча
# падала на федеральный уровень каждый раз, когда ЕГРЮЛ не проверен и регион
# пришёл из pb. Примечание при этом было, а регионального разреза — нет.
ТИПЫ_РЕГИОНА = frozenset((
    "респ", "республика", "обл", "область", "край", "г", "город", "аобл",
    "аокр", "ао", "автономный", "автономная", "автономного", "округ", "окр",
    "народная", "федерального", "значения", "федерального значения", "-", "—",
))


def нормализовать_регион(текст):
    """«Респ Саха /Якутия/» и «Саха (Якутия) респ.» -> один ключ «саха якутия»."""
    if not текст:
        return None
    т = str(текст).lower().replace("ё", "е")
    for символ in "().,/\\«»\"'":
        т = т.replace(символ, " ")
    слова = []
    for слово in т.split():
        слово = слово.replace(".", "").strip("-—")
        if слово and слово not in ТИПЫ_РЕГИОНА:
            слова.append(слово)
    return " ".join(sorted(set(слова))) or None


def индекс_регионов(таблица):
    """{нормализованное имя: код} по блоку «регионы» самой таблицы."""
    индекс = таблица.get("_индекс_регионов")
    if индекс is None:
        индекс = {}
        for код, имя in (таблица.get("регионы") or {}).items():
            ключ = нормализовать_регион(имя)
            if ключ:
                индекс.setdefault(ключ, код)
        таблица["_индекс_регионов"] = индекс
    return индекс


def код_региона(значение, таблица):
    """Код субъекта из кода («50») или из названия («Краснодарский край»)."""
    if значение is None:
        return None
    текст = str(значение).strip()
    if not текст:
        return None
    if текст.isdigit():
        return текст.zfill(2)
    индекс = индекс_регионов(таблица)
    ключ = нормализовать_регион(текст)
    if ключ in индекс:
        return индекс[ключ]
    # частичное совпадение принимается, только если оно единственное:
    # «Осетия» не должна тихо стать Северной Осетией, если кандидатов два
    слова = set((ключ or "").split())
    похожие = {к: v for к, v in индекс.items() if слова and слова <= set(к.split())}
    if len(похожие) == 1:
        return next(iter(похожие.values()))
    return None


def _как_dict(значения, поля):
    return dict(zip(поля, значения))


def найти_группу(таблица, оквэд, регион, размер):
    """(данные группы, уровень, ключ) или (None, None, причина)."""
    оквэд2 = (оквэд or "").split(".")[0].strip().zfill(2)
    поля = таблица.get("поля") or ПОЛЯ
    if регион:
        регион = str(регион).strip().zfill(2)
        ключ = "%s|%s|%s" % (оквэд2, регион, размер)
        зап = таблица["группы"].get(ключ)
        if зап:
            return _как_dict(зап, поля), "ОКВЭД2 + регион + размер", ключ
    ключ2 = "%s|%s" % (оквэд2, размер)
    зап2 = (таблица.get("группы_без_региона") or {}).get(ключ2)
    if зап2:
        return _как_dict(зап2, поля), "ОКВЭД2 + размер (регион схлопнут)", ключ2
    return None, None, ("нормы по этой отрасли и размеру не построены: группы "
                        "%s и %s нет в таблице (в обеих n < %s)"
                        % (("%s|%s|%s" % (оквэд2, регион, размер)) if регион
                           else "ОКВЭД2|регион|размер", ключ2,
                           таблица.get("порог_n")))


def _руб(v):
    """59206475000 -> '59,2 млрд руб.'"""
    if v is None:
        return "—"
    for делитель, имя in ((1e9, "млрд"), (1e6, "млн"), (1e3, "тыс."), (1, "руб.")):
        if abs(v) >= делитель:
            число = v / делитель
            текст = ("%.1f" % число if делитель > 1 else "%.0f" % число)
            return ("%s %s руб." % (текст.replace(".", ","), имя)
                    if делитель > 1 else "%s руб." % текст)
    return "%.0f руб." % v


def год_периода_норм(таблица):
    """Отчётный год, к которому относятся перцентили дохода, или None.

    Берётся из ДатаСост дампа revexp («31.12.2025»), а НЕ из даты выгрузки:
    выгрузка 2026 года несёт отчётность за 2025-й, и подмена дала бы
    систематический сдвиг на год."""
    период = (таблица.get("период_данных") or {}).get("revexp")
    if isinstance(период, str) and len(период) == 10:
        try:
            return int(период[6:])
        except ValueError:
            return None
    return None


def оценить(инн, оквэд, регион, выручка, путь=ТАБЛИЦА_ПУТЬ, таблица=None,
            год=None):
    """Положение компании относительно нормы. Нет данных -> «не проверено».

    `год` — год отчётности, из которого взята выручка. Без него сравнимость
    периодов не проверяется, и ответ прямо об этом говорит."""
    запрос = {"инн": инн, "оквэд": оквэд, "регион": регион, "выручка": выручка,
              "год_отчётности": год}
    если_нет = {"статус": НЕ_ПРОВЕРЕНО, "запрос": запрос,
                "год_отчётности": год,
                "дата_проверки": time.strftime("%Y-%m-%d")}
    if таблица is None:
        таблица, причина = загрузить(путь)
        if таблица is None:
            если_нет["причина"] = причина
            return если_нет
    else:
        причина = причина_урезанной_сборки(таблица)
        if причина:
            если_нет["причина"] = причина
            return если_нет
    if not оквэд:
        если_нет["причина"] = ("не передан ОКВЭД — отрасль неизвестна, норму "
                               "выбрать не из чего")
        return если_нет
    if выручка is None:
        если_нет["причина"] = ("не передана выручка — ни размерная группа, ни "
                               "перцентиль не считаются")
        return если_нет
    границы = (таблица.get("размерные_группы") or {}).get("границы_дохода_руб")
    if not границы:
        если_нет["причина"] = "в таблице нет границ размерных групп"
        return если_нет
    # Период. Компания, переставшая сдавать отчётность, — сама по себе признак,
    # и отдавать ей бодрый перцентиль по нормам другого года нельзя.
    год_норм = год_периода_норм(таблица)
    разрыв = abs(год_норм - год) if (год_норм and год) else None
    if разрыв is not None and разрыв >= ПОРОГ_РАЗРЫВА_ЛЕТ:
        если_нет["причина"] = (
            "отчётность за %s г. сравнивать с нормами за %s г. нельзя: разрыв "
            "%d г. при допустимом меньше %d. Последняя отчётность компании "
            "старше норм — это то, что видно в данных, а не 50-й перцентиль"
            % (год, год_норм, разрыв, ПОРОГ_РАЗРЫВА_ЛЕТ))
        если_нет["год_норм"] = год_норм
        если_нет["разрыв_лет"] = разрыв
        если_нет["размерная_группа"] = размерная_группа(выручка, границы)
        если_нет["дата_дампов"] = таблица.get("дата_дампов")
        return если_нет
    размер = размерная_группа(выручка, границы)
    код = код_региона(регион, таблица)
    if регион and код is None:
        если_нет["примечание"] = ("регион %r не сопоставлен с кодом субъекта — "
                                  "ищем норму на уровне (ОКВЭД2, размер)" % регион)
    данные, уровень, ключ = найти_группу(таблица, оквэд, код, размер)
    if данные is None:
        если_нет["причина"] = ключ
        если_нет["размерная_группа"] = размер
        если_нет["дата_дампов"] = таблица.get("дата_дампов")
        return если_нет
    точки = [(p, данные.get("p%d" % p)) for p in (10, 25, 50, 75, 90)]
    место, оговорка = позиция_перцентиля(выручка, точки)
    # Группа без единого перцентиля — не «0-й перцентиль» и не TypeError в
    # форматировании фразы, а честное «не проверено» с названной причиной.
    if место is None:
        если_нет["причина"] = ("группа %s найдена (n = %s), но перцентилей "
                               "дохода в ней нет: %s"
                               % (ключ, данные.get("n"), оговорка))
        если_нет["размерная_группа"] = размер
        если_нет["код_региона"] = код
        если_нет["дата_дампов"] = таблица.get("дата_дампов")
        return если_нет
    регион_имя = (таблица.get("регионы") or {}).get(код or "")
    # Регион называем во фразе, только если норма действительно региональная:
    # у схлопнутой группы ключ короче (ОКВЭД2|размер), и говорить «в регионе»
    # про неё — враньё.
    по_региону = (ключ or "").count("|") == 2
    где = " в регионе %s" % регион_имя if (регион_имя and по_региону) else ""
    когда = (" за %s г. против норм за %s г." % (год, год_норм) if (год and год_норм)
             else (" за %s г." % год if год else ""))
    фраза = ("доход %s%s — %d-й перцентиль по ОКВЭД %s%s, группа %s, n = %d"
             % (_руб(выручка), когда, место, оквэд, где, размер, данные["n"]))
    наблюдения = {имя: данные.get(сч) for имя, сч in ПОКАЗАТЕЛИ if сч in данные}
    return {
        "статус": ПРОВЕРЕНО,
        "запрос": запрос,
        "код_региона": код,
        "размерная_группа": размер,
        "предупреждение": ПРЕДУПРЕЖДЕНИЕ_КРУПНЫЕ if размер in
                          ("среднее", "крупное") else None,
        "группа": {"ключ": ключ, "уровень": уровень, "n": данные["n"],
                   "регион_наименование": регион_имя},
        "перцентиль_выручки": место,
        "оговорка": оговорка,
        "фраза": фраза,
        "нормы": данные,
        # Сколько компаний стоит за КАЖДЫМ показателем: «n» — это только про
        # перцентили дохода, и потребитель обязан это видеть.
        "наблюдений": наблюдения,
        "порог_n_показателя": таблица.get("порог_n_показателя"),
        "база_сравнения": ОГОВОРКА_БАЗЫ,
        "год_отчётности": год,
        "год_норм": год_норм,
        "разрыв_лет": разрыв,
        "оговорка_периода": (None if год else
                             "год отчётности не передан — сравнимость периода "
                             "выручки с отчётным периодом норм (%s) не "
                             "проверена" % (год_норм or "неизвестен")),
        "дата_дампов": таблица.get("дата_дампов"),
        "порог_n": таблица.get("порог_n"),
        "источник": "открытые данные ФНС (file.nalog.ru/opendata), "
                    "таблица собрана benchmarks.py --построить",
        "дата_проверки": time.strftime("%Y-%m-%d"),
    }


# ГИР БО отдаёт суммы в тысячах рублей (проверено на 5036045205: стр. 2110 за
# 2025 = 396 350 822 = 396 млрд руб.), дампы ФНС — в рублях.
ГИРБО_В_РУБЛИ = 1000



class Выборка(tuple):
    """(инн, оквэд, регион, выручка) + год отчётности отдельным атрибутом.

    Кортеж из ЧЕТЫРЁХ элементов намеренно: `инн, оквэд, регион, выручка =
    из_fetch(...)` — публичный контракт, на нём стоит paper_vat.py. Год едет
    атрибутом `.год`, а не пятым элементом, чтобы добавить его, ничего не
    сломав: он нужен оценить(), которая обязана отказаться сравнивать
    отчётность 2021 года с нормами 2025-го."""

    # __slots__ у подкласса tuple не бывает непустым, поэтому год живёт в
    # обычном __dict__ экземпляра; на четыре элемента кортежа это не влияет.

    def __new__(cls, инн, оквэд, регион, выручка, год=None):
        сам = super().__new__(cls, (инн, оквэд, регион, выручка))
        сам.год = год
        return сам


def из_fetch(данные):
    """Вывод fetch_counterparty.py -> Выборка(инн, оквэд, регион, выручка), .год.

    Выручка — в рублях (ГИР БО отдаёт тысячи). Год берётся САМЫЙ СВЕЖИЙ явной
    сортировкой, а не первым элементом списка: порядок сортировки — деталь
    чужого модуля, полагаться на неё нельзя (тот же приём, что и
    paper_vat._последний_год)."""
    инн = данные.get("инн")
    риски = данные.get("риски") or {}
    егрюл = данные.get("егрюл") or {}
    финансы = данные.get("финансы") or {}
    оквэд = риски.get("оквэд") or финансы.get("okved2")
    # ЕГРЮЛ отдаёт «Краснодарский край», pb — «КРАСНОДАРСКИЙ КРАЙ»,
    # а в снимках встречается и числовой код: отдаём как есть, код вытащит
    # оценить() по справочнику регионов самой таблицы.
    регион = егрюл.get("регион") or риски.get("регион")
    годы = [г for г in (финансы.get("отчётность_по_годам") or [])
            if isinstance(г, dict) and г.get("выручка") is not None]

    def ключ(г):
        try:
            return int(г.get("год"))
        except (TypeError, ValueError):
            return 0

    годы.sort(key=ключ, reverse=True)
    if not годы:
        return Выборка(инн, оквэд, регион, None, None)
    свежий = годы[0]
    return Выборка(инн, оквэд, регион,
                   float(свежий["выручка"]) * ГИРБО_В_РУБЛИ,
                   ключ(свежий) or None)


