def _медиана_если_хватает(значения, знаков, порог):
    """(медиана или None, сколько было наблюдений).

    Пустая куча даёт (None, 0), а не 0.0: «данных нет» и «норма равна нулю» —
    разные утверждения, и подменять первое вторым нельзя. Одно-два наблюдения
    тоже дают None: это не медиана отрасли, а конкретная компания."""
    n = len(значения)
    if n < порог:
        return None, n
    м = медиана(значения)
    return (round(м, знаков) if знаков else round(м)), n


def _статистики(куча, порог_показателя=ПОРОГ_N_ПОКАЗАТЕЛЯ):
    выручки = sorted(куча["выручка"])
    нагрузка, n_нагрузка = _медиана_если_хватает(куча["нагрузка"], 4,
                                                 порог_показателя)
    ссч, n_ссч = _медиана_если_хватает(куча["ссч"], 1, порог_показателя)
    на_сотр, n_на_сотр = _медиана_если_хватает(куча["на_сотрудника"], 0,
                                               порог_показателя)
    ндс, n_ндс = _медиана_если_хватает(куча["ндс"], 4, порог_показателя)
    n_усн = куча["усн_знаменатель"]
    доля_усн = (round(куча["усн"] / n_усн, 3)
                if n_усн >= порог_показателя else None)
    return [
        len(выручки),
        round(перцентиль(выручки, 10)),
        round(перцентиль(выручки, 25)),
        round(перцентиль(выручки, 50)),
        round(перцентиль(выручки, 75)),
        round(перцентиль(выручки, 90)),
        нагрузка, n_нагрузка,
        ссч, n_ссч,
        на_сотр, n_на_сотр,
        доля_усн, n_усн,
        ндс, n_ндс,
    ]


