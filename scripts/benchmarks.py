#!/usr/bin/env python3
"""
benchmarks.py — отраслевые нормы из открытых дампов ФНС. Только stdlib.

Вторая ось вердикта: не «выручка такая-то», а «положение относительно нормы».
Отрицательные чистые активы у клиники на третьем году — норма отрасли или
аномалия: ответ даёт таблица норм, а не интуиция.

Использование:
    python3 benchmarks.py --построить                  # собрать таблицу из дампов
    python3 benchmarks.py --построить --в data/benchmarks_ru.json
    python3 benchmarks.py --инн 2309085638 --оквэд 47.11 --регион 23 \
                          --выручка 59206475000
    python3 fetch_counterparty.py --инн 5036045205 | python3 benchmarks.py --stdin

ГРУППА (спек волны 3, §1.2): (ОКВЭД2 — два первых знака, код региона,
размерная группа по доходу). Границы размерных групп — из data/canon_ru.json
(ПП РФ от 04.04.2016 N 265), а не из констант кода; канона нет -> «не проверено».

ПОРОГ ПУБЛИКАЦИИ n < 20: группа с меньшим числом компаний не попадает в таблицу
(и статистически пусто, и деанонимизирует конкретные компании) и схлопывается
на уровень (ОКВЭД2, размер) без региона; если и там n < 20 — группы нет, и
lookup честно отвечает «нормы по этой отрасли и размеру не построены».

ОТКУДА ЧТО БЕРЁТСЯ (проверено по живым дампам 19.09.2026, см. opendata_refresh):
    доход, расход        revexp   (ОТКРДАННЫЕ5, рубли, период 31.12.2025)
    уплаченные налоги    paytax   (ОТКРДАННЫЕ4, рубли, период 31.12.2025)
    ССЧ                  sshr2019 (ОТКРДАННЫЕ3, период 31.12.2025)
    признак УСН          snr      (ОТКРДАННЫЕ1, состояние 01.08.2026)
    ОКВЭД и код региона  rsmp     (РЕЕСТРМСП, состояние 10.09.2026)

РАСХОЖДЕНИЕ СО СПЕКОМ, КОТОРОЕ НАДО ЗНАТЬ. Спек §1.2 строит группу по ОКВЭД2,
но НИ В ОДНОМ из четырёх датасетов §0 ОКВЭД нет: revexp/paytax/sshr2019/snr
отдают только ИНН, наименование и свою метрику. Каталог открытых данных ФНС
(https://www.nalog.gov.ru/opendata/, 96 наборов, проверено 19.09.2026) содержит
ровно один набор с ОКВЭД по ИНН — реестр МСП (`7707329152-rsmp`). Поэтому
отраслевой разрез строится по нему, и отсюда ГЛАВНОЕ ОГРАНИЧЕНИЕ ТАБЛИЦЫ:
в реестр МСП не входят крупный бизнес, банки, бюджетные учреждения — по ним
ОКВЭД неизвестен, они в норму не попадают, и размерная группа «крупное»
заполнена слабо. Это ограничение записано в самой таблице (`покрытие`), а
lookup по непостроенной группе отвечает «не проверено», а не медианой наугад.

НАЛОГОВАЯ НАГРУЗКА считается как (налоги и сборы) / доход. Из суммы paytax
исключены страховые взносы, пени, проценты и «НЕНАЛОГОВЫЕ ДОХОДЫ» — так же,
как их исключает методика ФНС (Приказ ММВ-3-06/333@); список исключаемых
наименований взят из реальных данных (НАИМЕНОВАНИЯ_НЕ_НАЛОГ), потому что вид
платежа в дампе записан ТЕКСТОМ, кодов там нет.

ЕДИНИЦЫ. Дампы — рубли. ГИР БО (`--stdin`, блок `финансы`) — ТЫСЯЧИ рублей
(проверено на АО «ДИКСИ ЮГ» 5036045205: стр. 2110 за 2025 = 396 350 822, то
есть 396 млрд руб.), поэтому при чтении stdin выручка умножается на 1000.
`--выручка` в аргументах — всегда рубли.
"""

