def _арг(args, имя):
    if имя in args:
        i = args.index(имя)
        if i + 1 < len(args):
            return args[i + 1]
    return None


def _пути_из_кэша(каталог):
    пути = {}
    for ид in ДАТАСЕТЫ_НОРМ:
        путь = od.путь_дампа(ид, каталог=os.path.join(каталог, ид))
        if путь:
            пути[ид] = путь
    return пути


def _команда_построить(args):
    кэш = _арг(args, "--кэш")
    пути = (_пути_из_кэша(кэш) if кэш
            else {ид: п for ид in ДАТАСЕТЫ_НОРМ
                  for п in [od.путь_дампа(ид)] if п})
    нет = [ид for ид in ДАТАСЕТЫ_НОРМ if ид not in пути]
    if нет:
        return _out({"статус": НЕ_ПРОВЕРЕНО,
                     "причина": "нет дампов в кэше: %s" % ", ".join(нет),
                     "что_делать": "opendata_refresh.py --refresh (и --датасет "
                                   "rsmp отдельно: 2,1 ГБ)"}, 1)
    try:
        порог = int(_арг(args, "--порог-n") or ПОРОГ_N)
    except ValueError:
        порог = ПОРОГ_N
    лимит = _арг(args, "--лимит")
    try:
        лимит = int(лимит) if лимит else None
    except ValueError:
        return _out({"статус": НЕ_ПРОВЕРЕНО,
                     "причина": "--лимит не число"}, 2)
    явная_цель = _арг(args, "--в")
    # Урезанная сборка не имеет права попасть в путь по умолчанию. Лимит режет
    # каждый дамп независимо, джойн разваливается, и получается таблица с
    # правдоподобными n, которую никто не отличит от настоящей.
    if лимит and not явная_цель:
        return _out({"статус": НЕ_ПРОВЕРЕНО,
                     "причина": "--лимит %d строит заведомо неполную таблицу "
                                "(каждый дамп урезается независимо, джойн "
                                "разваливается) и в %s не пишется"
                                % (лимит, ТАБЛИЦА_ПУТЬ),
                     "что_делать": "для отладки укажите путь явно: --лимит %d "
                                   "--в /tmp/проба.json; такая таблица помечена "
                                   "ключом «лимит», и lookup по ней откажется "
                                   "работать" % лимит}, 2)
    начало = time.time()
    таблица, причина = построить(пути, порог_n=порог, тихо="--тихо" in args,
                                 лимит=лимит)
    if таблица is None:
        return _out({"статус": НЕ_ПРОВЕРЕНО, "причина": причина}, 1)
    цель = явная_цель or ТАБЛИЦА_ПУТЬ
    with open(цель, "w", encoding="utf-8") as fh:
        fh.write(_сериализовать(таблица) + "\n")
    сводка = {k: таблица[k] for k in
              ("версия_таблицы", "дата_дампов", "версия_структуры", "порог_n",
               "порог_n_показателя", "лимит", "групп", "статистика",
               "покрытие", "урезано", "размер_байт")}
    сводка["файл"] = цель
    сводка["секунд"] = round(time.time() - начало, 1)
    if лимит:
        сводка["статус"] = НЕ_ПРОВЕРЕНО
        сводка["причина"] = причина_урезанной_сборки(таблица)
        return _out(сводка, 1)
    сводка["статус"] = ПРОВЕРЕНО
    return _out(сводка)


def main(argv):
    args = argv[1:]
    if not args:
        sys.stderr.write(__doc__)
        return 2
    if "--построить" in args:
        return _команда_построить(args)
    путь = _арг(args, "--таблица") or ТАБЛИЦА_ПУТЬ
    if "--stdin" in args:
        try:
            данные = json.loads(sys.stdin.read())
        except ValueError as e:
            return _out({"статус": НЕ_ПРОВЕРЕНО,
                         "причина": "на stdin не JSON вывода fetch_counterparty "
                                    "(%s)" % e}, 2)
        выборка = из_fetch(данные)
        инн, оквэд, регион, выручка = выборка
        год = выборка.год
    else:
        инн = _арг(args, "--инн")
        оквэд = _арг(args, "--оквэд")
        регион = _арг(args, "--регион")
        выручка = _арг(args, "--выручка")
        год = _арг(args, "--год")
        if год is not None:
            try:
                год = int(год)
            except ValueError:
                return _out({"статус": НЕ_ПРОВЕРЕНО,
                             "причина": "--год не число"}, 2)
        if выручка is not None:
            try:
                выручка = float(выручка.replace(" ", "").replace(",", "."))
            except ValueError:
                return _out({"статус": НЕ_ПРОВЕРЕНО,
                             "причина": "--выручка не число (ждём рубли)"}, 2)
        if оквэд is None and выручка is None:
            sys.stderr.write("Укажите --построить, --stdin или "
                             "--инн/--оквэд/--регион/--выручка\n")
            return 2
    res = оценить(инн, оквэд, регион, выручка, путь, год=год)
    return _out(res, 0 if res["статус"] == ПРОВЕРЕНО else 1)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
