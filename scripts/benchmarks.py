def пороги_размера(path=CANON_PATH):
    """{'микро': 120e6, 'малое': 800e6, 'среднее': 2e9} + источник, или None."""
    текст = _читать_канон_текст(path)
    if текст is None:
        return None
    try:
        пороги = json.loads(текст).get("пороги") or {}
    except (ValueError, AttributeError):
        return None
    ключи = (("микро", "размер_микро_доход"), ("малое", "размер_малое_доход"),
             ("среднее", "размер_среднее_доход"))
    out = {}
    for имя, ключ in ключи:
        зап = пороги.get(ключ) or {}
        зн = зап.get("значение")
        if not isinstance(зн, (int, float)):
            return None
        out[имя] = float(зн)
        out.setdefault("_источники", {})[имя] = {
            "значение": зн, "единица": зап.get("единица"),
            "источник": зап.get("источник"),
            "источник_url": зап.get("источник_url"),
            "дата_проверки": зап.get("дата_проверки"),
        }
    return out


def размерная_группа(доход, пороги):
    """Граница НЕСТРОГАЯ: ПП РФ N 265 говорит «не превышает», поэтому доход
    ровно 120 млн — это микропредприятие, а не малое."""
    if доход is None or пороги is None:
        return None
    if доход <= пороги["микро"]:
        return "микро"
    if доход <= пороги["малое"]:
        return "малое"
    if доход <= пороги["среднее"]:
        return "среднее"
    return "крупное"


