def перцентиль(отсортированные, q):
    """Линейная интерполяция по отсортированному списку (метод numpy 'linear')."""
    n = len(отсортированные)
    if n == 0:
        return None
    if n == 1:
        return float(отсортированные[0])
    поз = (q / 100.0) * (n - 1)
    низ = int(поз)
    верх = min(низ + 1, n - 1)
    доля = поз - низ
    return отсортированные[низ] + (отсортированные[верх] - отсортированные[низ]) * доля


def медиана(значения):
    if not значения:
        return None
    s = sorted(значения)
    return перцентиль(s, 50)


def позиция_перцентиля(значение, точки):
    """Обратная задача: где значение среди опубликованных перцентилей.

    `точки` — [(перцентиль, значение), ...] по возрастанию значения. Возвращает
    (перцентиль, оговорка). Между точками — линейная интерполяция; за краями
    честно говорится, что оценка граничная: p10/p90 — всё, что опубликовано."""
    точки = [(p, v) for p, v in точки if v is not None]
    if not точки:
        return None, "в группе нет опубликованных перцентилей"
    точки.sort(key=lambda t: t[1])
    if значение <= точки[0][1]:
        return точки[0][0], ("не выше %d-го перцентиля: ниже опубликованного "
                             "края группы" % точки[0][0])
    if значение >= точки[-1][1]:
        return точки[-1][0], ("не ниже %d-го перцентиля: выше опубликованного "
                              "края группы" % точки[-1][0])
    for i in range(len(точки) - 1):
        (p1, v1), (p2, v2) = точки[i], точки[i + 1]
        if v1 <= значение <= v2:
            if v2 == v1:
                return p2, None
            доля = (значение - v1) / (v2 - v1)
            return round(p1 + (p2 - p1) * доля), None
    return точки[-1][0], None


