def _добавить(куча, зап):
    доход = зап["доход"]
    куча["выручка"].append(доход)
    if зап.get("налоги") is not None and доход > 0:
        куча["нагрузка"].append(зап["налоги"] / доход)
    # В норму НДС попадает только тот, у кого обязанность есть: «ндс_обязан»
    # обязан быть выставлен явно источником записей. Отсутствие ключа — это
    # «население нормы неизвестно», и тогда нормы НДС просто нет; молча
    # считать её по всем подряд (включая УСН с нулём по закону) нельзя.
    if зап.get("ндс") is not None and доход > 0 and зап.get("ндс_обязан") is True:
        куча["ндс"].append(зап["ндс"] / доход)
    ссч = зап.get("ссч")
    if ссч is not None:
        куча["ссч"].append(float(ссч))
        # Ноль сотрудников — не «один сотрудник». Делить на ноль нечего, и
        # подменять его единицей значит опубликовать выдуманную норму.
        if ссч > 0:
            куча["на_сотрудника"].append(доход / ссч)
    усн = зап.get("усн")
    # усн is False — это подтверждённое «спецрежима нет» (компании нет в snr,
    # а в snr не бывает записей со всеми выключенными признаками), и в
    # знаменатель доли она входит. None — это «неизвестно», и только оно из
    # знаменателя выпадает.
    if усн is not None:
        куча["усн_знаменатель"] += 1
        куча["усн"] += 1 if усн else 0


def агрегировать(компании, пороги, порог_n=ПОРОГ_N,
                 порог_показателя=ПОРОГ_N_ПОКАЗАТЕЛЯ):
    """Поток записей о компаниях -> (группы, группы_без_региона, статистика).

    Запись: {"оквэд2","регион","доход","налоги","ндс","ссч","усн"}. Функция
    вынесена отдельно от чтения дампов именно затем, чтобы eval проверял
    агрегацию на синтетике с известным ответом."""
    с_регионом = {}
    без_региона = {}
    всего = 0
    for зап in компании:
        оквэд2, регион, доход = зап.get("оквэд2"), зап.get("регион"), зап.get("доход")
        if not оквэд2 or доход is None or доход <= 0:
            continue
        размер = размерная_группа(доход, пороги)
        if размер is None:
            continue
        всего += 1
        if регион:
            ключ = "%s|%s|%s" % (оквэд2, регион, размер)
            _добавить(с_регионом.setdefault(ключ, _новая_куча()), зап)
        ключ2 = "%s|%s" % (оквэд2, размер)
        _добавить(без_региона.setdefault(ключ2, _новая_куча()), зап)

    групп_всего = len(с_регионом)
    группы = {k: _статистики(v, порог_показателя) for k, v in с_регионом.items()
              if len(v["выручка"]) >= порог_n}
    схлопнутые = {k: _статистики(v, порог_показателя)
                  for k, v in без_региона.items()
                  if len(v["выручка"]) >= порог_n}
    статистика = {
        "компаний_в_агрегации": всего,
        "групп_оквэд_регион_размер_всего": групп_всего,
        "групп_опубликовано": len(группы),
        "групп_отсеяно_порогом": групп_всего - len(группы),
        "групп_без_региона_всего": len(без_региона),
        "групп_без_региона_опубликовано": len(схлопнутые),
        "групп_без_региона_отсеяно_порогом": len(без_региона) - len(схлопнутые),
        "порог_n_показателя": порог_показателя,
    }
    статистика.update(_счёт_пустых(группы, схлопнутые))
    return группы, схлопнутые, статистика


def _счёт_пустых(*блоки, поля=None):
    """Сколько опубликованных групп не несут того или иного показателя.

    Это единственное место, где видно, что норма «есть у всех» — и это
    честнее, чем нули, которых в данных не было."""
    поля = поля or ПОЛЯ
    индексы = {имя: поля.index(имя) for имя, _ in ПОКАЗАТЕЛИ if имя in поля}
    пустых = dict.fromkeys(индексы, 0)
    всего = 0
    for блок in блоки:
        for значения in блок.values():
            всего += 1
            for имя, i in индексы.items():
                if значения[i] is None:
                    пустых[имя] += 1
    return {"групп_всего_опубликовано": всего,
            "показателей_null_в_группах": пустых}


