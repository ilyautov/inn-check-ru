def _сериализовать(таблица):
    return json.dumps(таблица, ensure_ascii=False, separators=(",", ":"))


def _ужать(таблица, целевой_размер):
    """Целевой размер 3 МБ (спек §1.2): не влезает — сначала редкие регионы,
    затем только p25/p50/p75. Что урезано — записано в саму таблицу.

    Схлопывание обязано ехать по ОБОИМ блокам и обязано переписать статистику:
    иначе в таблице остаётся «групп_опубликовано: 5244» при 1800 реально
    опубликованных — то есть правдоподобное число вместо правды."""
    урезано = []
    размер = len(_сериализовать(таблица).encode("utf-8"))
    порог_редкости = таблица["порог_n"]
    while размер > целевой_размер and таблица["группы"]:
        порог_редкости *= 2
        for блок in ("группы", "группы_без_региона"):
            таблица[блок] = {k: v for k, v in таблица[блок].items()
                             if v[0] >= порог_редкости}
        урезано.append("редкие группы: оставлены группы с n >= %d в обоих блоках"
                       % порог_редкости)
        размер = len(_сериализовать(таблица).encode("utf-8"))
    if размер > целевой_размер:
        оставить = [ПОЛЯ.index(f) for f in ПОЛЯ_УРЕЗАННЫЕ]
        for блок in ("группы", "группы_без_региона"):
            таблица[блок] = {k: [v[i] for i in оставить]
                             for k, v in таблица[блок].items()}
        таблица["поля"] = ПОЛЯ_УРЕЗАННЫЕ
        урезано.append("оставлены p25/p50/p75: p10 и p90 убраны ради размера")
        размер = len(_сериализовать(таблица).encode("utf-8"))
    if урезано:
        стат = таблица.setdefault("статистика", {})
        было = стат.get("групп_опубликовано")
        стат["групп_опубликовано"] = len(таблица["группы"])
        стат["групп_без_региона_опубликовано"] = len(таблица["группы_без_региона"])
        всего = стат.get("групп_оквэд_регион_размер_всего")
        if всего is not None:
            стат["групп_отсеяно_порогом"] = всего - len(таблица["группы"])
        безрег = стат.get("групп_без_региона_всего")
        if безрег is not None:
            стат["групп_без_региона_отсеяно_порогом"] = (
                безрег - len(таблица["группы_без_региона"]))
        стат["групп_опубликовано_до_ужатия"] = было
        стат.update(_счёт_пустых(таблица["группы"], таблица["группы_без_региона"],
                                 поля=таблица["поля"]))
    таблица["групп"] = len(таблица["группы"]) + len(таблица["группы_без_региона"])
    таблица["урезано"] = урезано
    таблица["размер_байт"] = 0
    таблица["размер_байт"] = len(_сериализовать(таблица).encode("utf-8"))
    return таблица


