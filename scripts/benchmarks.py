def _арг(args, имя):
    if имя in args:
        i = args.index(имя)
        if i + 1 < len(args):
            return args[i + 1]
    return None


def _пути_из_кэша(каталог):
    пути = {}
    for ид in od.ДАТАСЕТЫ:
        путь = od.путь_дампа(ид, каталог=os.path.join(каталог, ид))
        if путь:
            пути[ид] = путь
    return пути


def _команда_построить(args):
    кэш = _арг(args, "--кэш")
    пути = (_пути_из_кэша(кэш) if кэш
            else {ид: п for ид in od.ДАТАСЕТЫ
                  for п in [od.путь_дампа(ид)] if п})
    нет = [ид for ид in od.ДАТАСЕТЫ if ид not in пути]
    if нет:
        return _out({"статус": НЕ_ПРОВЕРЕНО,
                     "причина": "нет дампов в кэше: %s" % ", ".join(нет),
                     "что_делать": "opendata_refresh.py --refresh (и --датасет "
                                   "rsmp отдельно: 2,1 ГБ)"}, 1)
    try:
        порог = int(_арг(args, "--порог-n") or ПОРОГ_N)
    except ValueError:
        порог = ПОРОГ_N
    лимит = _арг(args, "--лимит")
    начало = time.time()
    таблица, причина = построить(пути, порог_n=порог, тихо="--тихо" in args,
                                 лимит=int(лимит) if лимит else None)
    if таблица is None:
        return _out({"статус": НЕ_ПРОВЕРЕНО, "причина": причина}, 1)
    цель = _арг(args, "--в") or ТАБЛИЦА_ПУТЬ
    with open(цель, "w", encoding="utf-8") as fh:
        fh.write(_сериализовать(таблица) + "\n")
    сводка = {k: таблица[k] for k in
              ("версия_таблицы", "дата_дампов", "версия_структуры", "порог_n",
               "групп", "статистика", "покрытие", "урезано", "размер_байт")}
    сводка["статус"] = ПРОВЕРЕНО
    сводка["файл"] = цель
    сводка["секунд"] = round(time.time() - начало, 1)
    return _out(сводка)


def main(argv):
    args = argv[1:]
    if not args:
        sys.stderr.write(__doc__)
        return 2
    if "--построить" in args:
        return _команда_построить(args)
    путь = _арг(args, "--таблица") or ТАБЛИЦА_ПУТЬ
    if "--stdin" in args:
        try:
            данные = json.loads(sys.stdin.read())
        except ValueError as e:
            return _out({"статус": НЕ_ПРОВЕРЕНО,
                         "причина": "на stdin не JSON вывода fetch_counterparty "
                                    "(%s)" % e}, 2)
        инн, оквэд, регион, выручка = из_fetch(данные)
    else:
        инн = _арг(args, "--инн")
        оквэд = _арг(args, "--оквэд")
        регион = _арг(args, "--регион")
        выручка = _арг(args, "--выручка")
        if выручка is not None:
            try:
                выручка = float(выручка.replace(" ", "").replace(",", "."))
            except ValueError:
                return _out({"статус": НЕ_ПРОВЕРЕНО,
                             "причина": "--выручка не число (ждём рубли)"}, 2)
        if оквэд is None and выручка is None:
            sys.stderr.write("Укажите --построить, --stdin или "
                             "--инн/--оквэд/--регион/--выручка\n")
            return 2
    res = оценить(инн, оквэд, регион, выручка, путь)
    return _out(res, 0 if res["статус"] == ПРОВЕРЕНО else 1)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
