def _ячейка(v):
    return str(v if v not in (None, "") else "—").replace("|", "\\|").replace("\n", " ")


def в_markdown(строки, шапка=None, сноски=()):
    колонки = ("ИНН", "Название", "Светофор", "Сигналы", "Проверка", "Не проверено")
    линии = []
    if шапка:
        линии += [шапка, ""]
    линии.append("| " + " | ".join(колонки) + " |")
    линии.append("|" + "|".join(["---"] * len(колонки)) + "|")
    for s in строки:
        проверка = {True: "состоялась", False: "не состоялась"}.get(
            s.get("проверка_состоялась"), s.get("статус") or "—")
        # для непроверенной строки последняя колонка несёт причину: читателю
        # нужна она, а не пустой список источников
        хвост = "; ".join(s.get("не_проверено") or []) or (
            s.get("причина") if s.get("статус") != "проверено" else "")
        линии.append("| " + " | ".join([
            _ячейка(s.get("инн")),
            _ячейка(s.get("название")),
            _ячейка(s.get("светофор")),
            _ячейка("; ".join(s.get("сигналы") or [])),
            _ячейка(проверка),
            _ячейка(хвост),
        ]) + " |")
    for сноска in сноски:
        if сноска:
            линии += ["", "> %s" % сноска]
    return "\n".join(линии)


def счётчики(строки):
    """Разложение батча по итогу — так, чтобы каждая строка попала ровно в один
    счётчик. Светофора нет при состоявшейся проверке только в профилях без
    вердикта («нейтрально», «факты») — это «без вердикта». Светофора нет при
    НЕсостоявшейся проверке — это «проверка не состоялась»: строка с такой
    дырой не должна теряться между 🟢 и «не проверено».
    """
    c = {"🔴": 0, "🟡": 0, "🟢": 0, "без_вердикта": 0,
         "проверка_не_состоялась": 0, "не_проверено": 0, "некорректных_инн": 0}
    for s in строки:
        статус = s.get("статус")
        светофор = s.get("светофор")
        if статус == "некорректный ИНН":
            c["некорректных_инн"] += 1
        elif статус != "проверено":
            c["не_проверено"] += 1
        elif светофор in ("🔴", "🟡", "🟢"):
            c[светофор] += 1
        elif s.get("проверка_состоялась") is True:
            c["без_вердикта"] += 1
        else:
            c["проверка_не_состоялась"] += 1
    return c


def шапка_markdown(c, всего, профиль, режим):
    """Шапка таблицы. Нулевые «без вердикта» и «проверка не состоялась» не
    печатаются, ненулевые — обязательно: иначе батч, где не состоялась ни одна
    проверка, читается как «🔴 0 · 🟡 0 · 🟢 0 · не проверено 0», то есть
    «всё в порядке»."""
    части = ["**Батч по %d ИНН**" % всего, "профиль `%s`" % профиль,
             "режим `%s`" % режим,
             "🔴 %d" % c["🔴"], "🟡 %d" % c["🟡"], "🟢 %d" % c["🟢"]]
    if c["без_вердикта"]:
        части.append("без вердикта %d" % c["без_вердикта"])
    if c["проверка_не_состоялась"]:
        части.append("проверка НЕ состоялась %d" % c["проверка_не_состоялась"])
    части.append("не проверено %d" % (c["не_проверено"] + c["некорректных_инн"]))
    return " · ".join(части)


СТАТУС_НЕИЗВЕСТЕН = "неизвестно"


def _ключ(row):
    """Строка CSV с ключами в нижнем регистре и без пробелов по краям:
    «ИНН», «Инн» и «инн » — одна и та же колонка."""
    return {str(k or "").strip().lower(): v for k, v in row.items() if k is not None}


def читать_csv(path):
    """Ранее собранные строки из CSV (`--продолжить`).

    -> ({инн: строка} в порядке файла, проблема с форматом или None).

    Статус берётся из файла КАК ЕСТЬ: пустая ячейка или отсутствие колонки
    «статус» — это «неизвестно», а не «проверено». Иначе строка, которая в
    прошлый раз не проверилась (таймаут, сбой сети), навсегда осталась бы
    непроверенной, выглядя проверенной, — а батч читают, чтобы решить, с кем
    работать.
    """
    готовые = {}
    try:
        with open(path, encoding="utf-8-sig", newline="") as fh:
            чтец = csv.DictReader(fh)
            поля = [str(f or "").strip().lower() for f in (чтец.fieldnames or [])]
            if поля and "статус" not in поля:
                return {}, ("нет колонки «статус» — это не файл результатов батча "
                            "(колонки: %s)" % ", ".join(поля[:8]))
            for row in чтец:
                row = _ключ(row)
                inn = str(row.get("инн") or "").strip()
                if not inn:
                    continue
                готовые[inn] = {
                    "инн": inn, "название": row.get("название") or None,
                    "светофор": row.get("светофор") or None,
                    "статус": (row.get("статус") or "").strip() or СТАТУС_НЕИЗВЕСТЕН,
                    "сигналы": [x for x in (row.get("сигналы") or "").split("; ") if x],
                    "проверка_состоялась": {"да": True, "нет": False}.get(
                        (row.get("проверка_состоялась") or "").strip()),
                    "не_проверено": [x for x in (row.get("не_проверено") or "").split("; ") if x],
                    "рекомендация": row.get("рекомендация") or None,
                    "причина": None, "секунд": None, "режим": None, "вердикт": None,
                    "из_файла": True,
                }
    except FileNotFoundError:
        return {}, None
    except (OSError, csv.Error, UnicodeDecodeError) as e:
        sys.stderr.write("ВНИМАНИЕ: --продолжить: файл не прочитан (%s), "
                         "начинаем с нуля\n" % e)
        return {}, None
    return готовые, None


class Журнал:
    """Файл результатов `--продолжить`, который пишется по ходу прогона.

    Заголовок и сохраняемые строки кладутся в файл ДО первой проверки, каждая
    готовая строка попадает в него сразу по готовности — обрыв батча на сотню
    контрагентов не теряет то, что уже собрано. Повторно проверенный ИНН
    ПЕРЕЗАПИСЫВАЕТ свою строку, а не добавляет вторую.

    `наш_формат=False` — файл не наш (нет колонки «статус», обычно это входной
    список контрагентов, указанный в `--продолжить` по ошибке). Тогда его
    содержимое не трогается вообще: результаты дописываются в конец отдельным
    блоком с заголовком.
    """

    def __init__(self, path, сохранить=(), наш_формат=True):
        self.path = path
        self.наш_формат = наш_формат
        self.сбоев = 0
        self._замок = threading.Lock()
        self._строки = {}
        for s in сохранить:
            inn = str(s.get("инн") or "").strip()
            if inn:
                self._строки[inn] = s
        if наш_формат:
            self._переписать()
        else:
            self._дописать([], заголовок=True)

    def записать(self, строка):
        """Одна готовая строка в файл. Потокобезопасно: `прогон` зовёт это
        из своего цикла, `--дальше` — из своего."""
        inn = str((строка or {}).get("инн") or "").strip()
        if not inn:
            return
        with self._замок:
            повтор = inn in self._строки
            self._строки[inn] = строка
            if повтор and self.наш_формат:
                self._переписать()      # строка уже есть в файле — не дубль, а замена
            else:
                self._дописать([строка])

    def _жалоба(self, e):
        self.сбоев += 1
        if self.сбоев <= 3:
            sys.stderr.write("ВНИМАНИЕ: результаты не записаны в %s (%s)\n"
                             % (self.path, e))

    def _дописать(self, строки, заголовок=False):
        try:
            пустой = not os.path.exists(self.path) or os.path.getsize(self.path) == 0
            with open(self.path, "a", encoding="utf-8", newline="") as fh:
                в_csv(строки, fh, заголовок=заголовок or пустой)
        except OSError as e:
            self._жалоба(e)

    def _переписать(self):
        """Полная перезапись через временный файл и os.replace: обрыв на записи
        оставляет прежнюю целую версию файла, а не половину новой."""
        врем = self.path + ".tmp"
        try:
            with open(врем, "w", encoding="utf-8", newline="") as fh:
                в_csv(list(self._строки.values()), fh, заголовок=True)
            os.replace(врем, self.path)
        except OSError as e:
            self._жалоба(e)
            try:
                os.unlink(врем)
            except OSError:
                pass


