#!/usr/bin/env python3
"""
batch_check.py — батч-проверка списка контрагентов по ИНН (волна 2, задача 8).

Один прогон по списку: быстрый сбор движком (fetch_counterparty.py) + резолвер
профиля (profiles.resolve) → таблица «кому нельзя отгружать» сверху вниз.
Только стандартная библиотека.

Использование:
    python3 batch_check.py контрагенты.csv [--профиль отсрочка]
    python3 batch_check.py 7707083893 5036045205 --csv
    cat инны.txt | python3 batch_check.py --stdin --json
    python3 batch_check.py большой.csv --продолжить результаты.csv

Вход (любой из трёх, можно сочетать файл и ИНН аргументами):
  * CSV/TSV-файл — разделитель определяется сам (, ; таб |), колонка с ИНН —
    по заголовку («ИНН», «inn», «ИНН контрагента»…) либо `--колонка N` (с 1),
    либо по содержимому (колонка, где больше всего 10/12-значных чисел);
  * ИНН списком в аргументах;
  * `--stdin` — по ИНН на строку.

Дубли схлопываются (остаётся первое вхождение). Невалидный ИНН не отбрасывается
молча: попадает в вывод со статусом «некорректный ИНН».

Опции:
    --профиль <id>      профиль цели (profiles.py --list), по умолчанию нейтрально
    --колонка N         номер колонки с ИНН (с 1), если заголовок не распознан
    --stdin             читать ИНН из stdin
    --режим <р>         quick (по умолчанию) | полный | всё — передаётся движку
    --дальше            вторым проходом догрузить досье по тем, кто НЕ 🔴
    --потоков N         сколько ИНН собирать одновременно (по умолчанию 3)
    --csv               вывод CSV вместо markdown
    --json              вывод полного JSON (с вердиктом по каждому ИНН)
    --продолжить <файл> писать результаты в CSV по ходу прогона, пропуская уже
                        проверенные ИНН (батч на сотню переживает обрыв)
    --тихо              без прогресса в stderr

Параллельность ограничена 3 ИНН (`--потоков`) — уважение к ФНС: батч не должен
выглядеть как нагрузочное тестирование бесплатных эндпоинтов.

`--продолжить`: что считается «уже проверено». Только строка со статусом
`проверено` в файле результатов. Строка «не проверено», «некорректный ИНН» или
без отметки статуса перепроверяется, а её строка в файле ПЕРЕЗАПИСЫВАЕТСЯ (не
дублируется). Файл с заголовком создаётся ДО начала прогона, каждая готовая
строка пишется в него сразу — обрыв (Ctrl-C, потеря сети) не теряет собранное.
Если в файле нет колонки «статус» (частая опечатка: тот же файл на входе и в
`--продолжить`), он не считается файлом результатов: его содержимое не трогается,
результаты дописываются в конец своим блоком, все ИНН проверяются заново.

Режим сбора. Движку передаётся `--режим quick` (ранний выход по deal-killer,
поток F волны 2). Отсутствие флага у движка и сбой прогона различаются: ненулевой
код + USAGE в stderr — флага нет (повтор без флага, пометка «быстрый режим
недоступен» на весь батч); всё остальное (таймаут, не-JSON, падение) — сбой по
этому ИНН, строка «не проверено», быстрый режим остаётся включённым.

Устойчивость: сбой по одному ИНН (таймаут, не-JSON, исключение) не роняет батч —
строка со статусом «не проверено» и причиной. Сам скрипт не падает traceback'ом.

Сортировка вывода: 🔴 → «проверка не состоялась» (null) → 🟡 → 🟢. Опасное и
непроверенное сверху: батч читают глазами и сверху вниз.
"""

