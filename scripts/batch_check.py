USAGE = __doc__


_СЛЕД = object()   # маркер «значение флага идёт следующим аргументом»
_РАСШИРЕНИЯ_ТАБЛИЦ = (".csv", ".tsv", ".txt", ".tab")


def _похоже_на_файл(a):
    """Позиционный аргумент — файл, а не ИНН? Существующий путь, путь с
    разделителем каталогов или знакомое расширение таблицы."""
    s = str(a)
    return (os.path.exists(s) or os.sep in s or "/" in s
            or s.lower().endswith(_РАСШИРЕНИЯ_ТАБЛИЦ))


def _значение(след, it):
    """Значение флага: либо из `--флаг=значение`, либо следующим аргументом."""
    return next(it, None) if след is _СЛЕД else след


def _разобрать_аргументы(argv):
    """-> (опции, ошибка). Ручной разбор: флаги русские, значения через пробел и =."""
    o = {"файлы": [], "инны": [], "профиль": None, "колонка": None, "stdin": False,
         "режим": "quick", "дальше": False, "потоков": ПОТОКОВ_ПО_УМОЛЧАНИЮ,
         "формат": "markdown", "продолжить": None, "тихо": False, "помощь": False}
    it = iter(argv[1:])
    for a in it:
        зн = None
        if a.startswith("--") and "=" in a:
            a, зн = a.split("=", 1)
        след = зн if зн is not None else _СЛЕД

        if a in ("-h", "--help", "--помощь"):
            o["помощь"] = True
        elif a in ("--профиль", "--profile"):
            o["профиль"] = _значение(след, it)
        elif a in ("--колонка", "--column"):
            v = _значение(след, it)
            try:
                o["колонка"] = int(v)
            except (TypeError, ValueError):
                return o, "--колонка ожидает номер колонки (с 1), получено %r" % v
            if o["колонка"] < 1:
                return o, "--колонка нумеруется с 1"
        elif a == "--stdin":
            o["stdin"] = True
        elif a in ("--режим", "--mode"):
            o["режим"] = _значение(след, it)
            if o["режим"] not in РЕЖИМЫ:
                return o, "--режим: допустимо %s" % ", ".join(РЕЖИМЫ)
        elif a in ("--дальше", "--next"):
            o["дальше"] = True
        elif a in ("--потоков", "--workers"):
            v = _значение(след, it)
            try:
                o["потоков"] = max(1, int(v))
            except (TypeError, ValueError):
                return o, "--потоков ожидает число, получено %r" % v
        elif a == "--csv":
            o["формат"] = "csv"
        elif a == "--json":
            o["формат"] = "json"
        elif a in ("--продолжить", "--resume"):
            o["продолжить"] = _значение(след, it)
            if not o["продолжить"]:
                return o, "--продолжить ожидает путь к CSV"
        elif a in ("--тихо", "--quiet"):
            o["тихо"] = True
        elif a.startswith("-"):
            return o, "неизвестный аргумент %s" % a
        elif _похоже_на_файл(a):
            o["файлы"].append(a)
        else:
            # всё остальное — значение ИНН (возможно с опечаткой): такое не
            # отбрасывается молча, а попадает в вывод как «некорректный ИНН»
            o["инны"].append(str(a).strip())
    return o, None


def _собрать_вход(o):
    """-> (список ИНН, пояснения как разобрали, сколько дублей схлопнуто, ошибка)."""
    значения, пояснения = [], []
    for путь in o["файлы"]:
        try:
            text = Path(путь).read_text(encoding="utf-8-sig")
        except OSError as e:
            return [], пояснения, 0, "файл не читается: %s (%s)" % (путь, e)
        часть, как = разобрать_таблицу(text, o["колонка"])
        значения += часть
        пояснения.append("%s: %s, строк %d" % (путь, как, len(часть)))
    if o["stdin"]:
        текст = sys.stdin.read()
        часть = [s.strip() for s in текст.splitlines() if s.strip()]
        значения += часть
        пояснения.append("stdin: строк %d" % len(часть))
    значения += o["инны"]
    if o["инны"]:
        пояснения.append("аргументами: %d" % len(o["инны"]))
    инны, дублей = схлопнуть(значения)
    return инны, пояснения, дублей, None


def main(argv):
    o, ошибка = _разобрать_аргументы(argv)
    if o["помощь"]:
        sys.stderr.write(USAGE)
        return 0
    if ошибка:
        sys.stderr.write(ошибка + "\n\n" + USAGE)
        return 2
    if not (o["файлы"] or o["инны"] or o["stdin"]):
        sys.stderr.write("нечего проверять: укажите CSV/TSV-файл, ИНН аргументами "
                         "или --stdin\n\n" + USAGE)
        return 2
    профиль = o["профиль"] or "нейтрально"
    инны, пояснения, дублей, ошибка = _собрать_вход(o)
    if ошибка:
        sys.stderr.write(ошибка + "\n")
        return 2
    if not инны:
        sys.stderr.write("во входе нет ни одного значения ИНН (%s)\n"
                         % ("; ".join(пояснения) or "вход пуст"))
        return 2

    готовые, проблема_файла = (читать_csv(o["продолжить"]) if o["продолжить"]
                               else ({}, None))
    наш_формат = проблема_файла is None
    if проблема_файла:
        sys.stderr.write(
            "ВНИМАНИЕ: --продолжить: %s: %s.\n"
            "Ни один ИНН не считается проверенным — проверяем все заново, "
            "содержимое файла не трогаем, результаты допишем в конец.\n"
            % (o["продолжить"], проблема_файла))
    # «Уже проверено» — ТОЛЬКО явный статус «проверено». Строка «не проверено»,
    # «некорректный ИНН» или без статуса перепроверяется: иначе таймаут первого
    # прогона навсегда оставил бы контрагента непроверенным, но с виду готовым.
    пропущено = [i for i in инны
                 if (готовые.get(i) or {}).get("статус") == "проверено"]
    отложенные = set(пропущено)
    к_проверке = [i for i in инны if i not in отложенные]
    перепроверяем = [i for i in к_проверке if i in готовые]
    if o["продолжить"]:
        if пропущено:
            sys.stderr.write("--продолжить: уже проверено %d из %d, пропускаем\n"
                             % (len(пропущено), len(инны)))
        if перепроверяем:
            sys.stderr.write("--продолжить: перепроверяем %d строк без отметки "
                             "«проверено» (%s)\n"
                             % (len(перепроверяем), ", ".join(перепроверяем[:5])
                                + ("…" if len(перепроверяем) > 5 else "")))

    # Журнал открывается ДО прогона: файл с заголовком и уже известными
    # строками существует с самого начала, дальше каждая готовая строка
    # дописывается сразу.
    журнал = None
    if o["продолжить"]:
        сохранить = [s for inn, s in готовые.items() if inn not in set(к_проверке)]
        журнал = Журнал(o["продолжить"], сохранить, наш_формат=наш_формат)

    прогресс = None if o["тихо"] else _прогресс_в_stderr
    новые = []
    if к_проверке:
        if прогресс:
            sys.stderr.write("батч: %d ИНН, профиль %s, режим %s, потоков %d\n"
                             % (len(к_проверке), профиль, o["режим"], o["потоков"]))
        новые = прогон(к_проверке, профиль=профиль, режим=o["режим"],
                       потоков=o["потоков"], прогресс=прогресс,
                       на_готовую=журнал.записать if журнал else None)
    досье = 0
    if o["дальше"] and новые:
        новые, досье = догрузить_досье(
            новые, профиль, потоков=o["потоков"], прогресс=прогресс,
            на_готовую=журнал.записать if журнал else None)
        if not досье and замечание_о_режиме() and прогресс:
            sys.stderr.write("--дальше: догружать нечего — движок без флага "
                             "--режим собрал досье первым проходом\n")

    все = [готовые[i] for i in пропущено] + новые
    все = отсортировать(все)
    замечание = замечание_о_режиме()
    c = счётчики(все)
    сводка = {
        "статус": "ок",
        "профиль": профиль,
        "режим": o["режим"],
        "быстрый_режим": замечание or "доступен",
        "всего": len(все),
        "проверено": sum(1 for s in все if s.get("статус") == "проверено"),
        "не_проверено": c["не_проверено"],
        "некорректных_инн": c["некорректных_инн"],
        "без_вердикта": c["без_вердикта"],
        "проверка_не_состоялась": c["проверка_не_состоялась"],
        "красных": c["🔴"], "жёлтых": c["🟡"], "зелёных": c["🟢"],
        "дублей_схлопнуто": дублей,
        "пропущено_по_продолжить": len(пропущено),
        "перепроверено_по_продолжить": len(перепроверяем),
        "досье_догружено": досье,
        "как_разобран_вход": пояснения,
    }
    if o["формат"] == "json":
        sys.stdout.write(json.dumps(dict(сводка, результаты=все),
                                    ensure_ascii=False, indent=2) + "\n")
    elif o["формат"] == "csv":
        в_csv(все, sys.stdout)
    else:
        шапка = шапка_markdown(c, сводка["всего"], профиль, o["режим"])
        сноски = [замечание]
        if проблема_файла:
            сноски.append("--продолжить: %s — все ИНН проверены заново, файл не "
                          "переписан, результаты дописаны в конец" % проблема_файла)
        if дублей:
            сноски.append("дублей схлопнуто: %d" % дублей)
        if пропущено:
            сноски.append("пропущено как уже проверенные (--продолжить): %d" % len(пропущено))
        if перепроверяем:
            сноски.append("перепроверено (в файле не было отметки «проверено»): %d"
                          % len(перепроверяем))
        сноски.append("сортировка: 🔴 → проверка не состоялась → 🟡 → 🟢; "
                      "пустой светофор = вердикт не выдаётся (профиль «факты» "
                      "или не проверены deal-killer-источники)")
        sys.stdout.write(в_markdown(все, шапка, сноски) + "\n")
    return 0 if сводка["проверено"] or not к_проверке else 1


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except KeyboardInterrupt:
        sys.stderr.write("\nпрервано пользователем\n")
        sys.exit(130)
    except Exception as e:  # батч не падает traceback'ом
        sys.stdout.write(json.dumps({"статус": "не проверено",
                                     "причина": "внутренняя ошибка: %s: %s"
                                                % (type(e).__name__, e)},
                                    ensure_ascii=False, indent=2) + "\n")
        sys.exit(1)
