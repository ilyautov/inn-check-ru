#!/usr/bin/env python3
"""
minpromtorg.py — реестры Минпромторга по ИНН, офлайн. Только stdlib.

Открытые данные minpromtorg.gov.ru/opendata — CSV со страниц-паспортов наборов.
Сайт закрыт для не-РФ адресов (403): скачивание через сеть пользователя
(INN_CHECK_PROXY, в т. ч. iface://en0; см. dump_tools.py). Живьём 28.09.2026:

    0000000001-LicenziLekarstvaMinpromtorg  лицензии на производство лекарственных
                                            средств: 496 лицензий, ИНН у всех;
                                            «действующая» и «приостановлена…»
                                            (прекращённых в наборе нет)
    1000000011-ReestrOrgs                   производители российской промышленной
                                            продукции по ПП РФ № 719: 8 076 организаций
    1000000010-resolutions                  заключения о подтверждении производства
                                            на территории РФ (ПП 719): 44 139 строк,
                                            22 215 номеров, 10 570 ИНН, срок действия

Паспорт набора перечисляет версии «data-ГГГГММДД-structure-….csv». Бывает, что
самая свежая из перечисленных отдаёт 404 (живьём: 27.09 исчезла, когда вышла
28.09) — тогда берётся следующая перечисленная, но не больше ВЕРСИЙ_ПОПРОБОВАТЬ,
и дата взятой версии попадает в ответ. Адреса версий не угадываются.

В индекс не попадают наименования (у ИП — ФИО), адреса и ответственные лица:
только ИНН, номера, даты, статусы и виды работ (обрезаны). Ссылки на PDF
заключений не берутся: в имени файла — наименование, у ИП это ФИО.

    python3 minpromtorg.py --refresh      # нужен РФ-IP или INN_CHECK_PROXY
    python3 minpromtorg.py --inn 0721009345
"""

import csv
import datetime as dt
import html
import io
import json
import os
import re
import sys
import urllib.error

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_tools

CACHE_DIR = os.path.expanduser(os.path.join("~", ".cache", "inn-check-ru", "minpromtorg"))
CACHE_DIR_ВИДИМЫЙ = "~/.cache/inn-check-ru/minpromtorg"
ИНДЕКС = "индекс.json.gz"
САЙТ = "https://minpromtorg.gov.ru"
ОТКРЫТЫЕ_ДАННЫЕ = САЙТ + "/opendata"
НАБОРЫ = {
    "лекарства": {"набор": "0000000001-LicenziLekarstvaMinpromtorg",
                  "название": "Реестр лицензий на производство лекарственных средств",
                  "колонки": ("ИНН", "Регистрационный номер лицензии", "Статус лицензии",
                              "Дата внесения сведений в реестр", "Дата начала действия",
                              "Дата решения", "Номер решения",
                              "Наименования выполняемых работ",
                              "Регистрационный номер лицензии (до 01.03.2022)"),
                  "лимит": 100 << 20},
    "производители": {"набор": "1000000011-ReestrOrgs",
                      "название": "Производители российской промышленной продукции (ПП 719)",
                      "колонки": ("INN",),
                      "лимит": 100 << 20},
    "заключения": {"набор": "1000000010-resolutions",
                   "название": "Заключения о подтверждении производства промышленной "
                               "продукции на территории РФ (ПП 719)",
                   "колонки": ("INN", "Numberofcon", "Dateofcon", "Expirationdate", "Document"),
                   "лимит": 500 << 20},
}
ВЕРСИЙ_ПОПРОБОВАТЬ = 3
ДОЛЯ_ПАДЕНИЯ = 0.8
ДОЛЯ_БЕЗ_ИНН = 0.01
СВЕЖЕСТЬ_ДНЕЙ = 30
РАБОТЫ_СИМВОЛОВ = 300
ПОКАЗАТЬ = 10


def страница(набор):
    return "%s/%s" % (ОТКРЫТЫЕ_ДАННЫЕ, НАБОРЫ[набор]["набор"])


def версии(html_паспорта, набор):
    """Паспорт -> [(дата ISO, url CSV)] перечисленных версий, свежие первыми."""
    код = re.escape(НАБОРЫ[набор]["набор"])
    найдено = set(re.findall(r'href="(/opendata/%s/data-(\d{8})-structure-(\d{8})\.csv)"' % код,
                             html_паспорта))
    if not найдено:
        raise ValueError("схема: в паспорте %s нет ссылок data-*.csv" % набор)
    # у одной даты бывает несколько структур — в списке остаются все (ревью Codex)
    return [("%s-%s-%s" % (д[:4], д[4:6], д[6:]), САЙТ + путь)
            for путь, д, _ in sorted(найдено, key=lambda x: (x[1], x[2]), reverse=True)]


def _дата(s):
    """«20-04-2017» или «2017-04-20» -> ISO; иначе None."""
    s = (s or "").strip()
    m = re.fullmatch(r"(\d{2})-(\d{2})-(\d{4})", s)
    г, м, д = (m.group(3), m.group(2), m.group(1)) if m else (s[:4], s[5:7], s[8:10])
    if not (m or re.fullmatch(r"\d{4}-\d{2}-\d{2}", s)):
        return None
    try:
        return dt.date(int(г), int(м), int(д)).isoformat()
    except ValueError:
        return None


def _строки(данные, колонки):
    """CSV (UTF-8, запятая) -> (шапка→номер, строки). Нет нужной колонки — схема."""
    csv.field_size_limit(1 << 26)
    # strict: незакрытая кавычка — отказ, а не склейка строк в одно поле (ревью Codex)
    r = csv.reader(io.StringIO(данные.decode("utf-8-sig")), strict=True)
    try:
        шапка = [к.strip() for к in next(r)]
        строки = [row for row in r if row]
    except StopIteration:
        raise ValueError("схема: пустой CSV") from None
    except csv.Error as e:
        raise ValueError("схема: битый CSV (%s)" % e) from None
    нет = [к for к in колонки if к not in шапка]
    if нет:
        raise ValueError("схема: в CSV нет колонок %s" % ", ".join(нет))
    номера = {к: шапка.index(к) for к in колонки}
    if any(len(row) != len(шапка) for row in строки):
        raise ValueError("схема: строки не по шапке")
    if not строки:
        raise ValueError("схема: в CSV нет строк")
    return номера, строки


def _инн(s):
    s = (s or "").strip()
    return s if re.fullmatch(r"\d{10}|\d{12}", s) else None


def разобрать(набор, данные):
    """-> ({инн: [записи]}, строк, без_инн)."""
    к, строки = _строки(данные, НАБОРЫ[набор]["колонки"])
    по_инн, без = {}, 0
    for row in строки:
        инн = _инн(row[к[НАБОРЫ[набор]["колонки"][0]]])
        if not инн:
            без += 1
            continue
        if набор == "лекарства":
            статус = " ".join(row[к["Статус лицензии"]].split()).lower()
            if not (статус == "действующая" or статус.startswith("приостановлена")):
                raise ValueError("схема: статус лицензии %r" % статус[:40])
            работы = " ".join(html.unescape(row[к["Наименования выполняемых работ"]])
                              .split()).strip(" ;") or None
            if работы and len(работы) > РАБОТЫ_СИМВОЛОВ:
                работы = работы[:РАБОТЫ_СИМВОЛОВ - 1] + "…"
            запись = {"номер": row[к["Регистрационный номер лицензии"]].strip(),
                      "прежний_номер": row[к["Регистрационный номер лицензии (до 01.03.2022)"]]
                      .strip() or None,
                      "статус": статус,
                      "внесена": _дата(row[к["Дата внесения сведений в реестр"]]),
                      "действует_с": _дата(row[к["Дата начала действия"]]),
                      "решение": row[к["Номер решения"]].strip() or None,
                      "решение_от": _дата(row[к["Дата решения"]]),
                      "работы": работы}
            if not запись["номер"]:
                raise ValueError("схема: лицензия без номера")
        elif набор == "производители":
            запись = True
        else:
            # живьём 371 строка из 44 139 без номера — строка остаётся, номер None
            номер = row[к["Numberofcon"]].strip() or None
            # ссылку на PDF не храним: в имени файла наименование, у ИП — ФИО; она
            # нужна только, чтобы не склеить разные заключения без номера
            запись = {"номер": номер, "дата": _дата(row[к["Dateofcon"]]),
                      "действует_до": _дата(row[к["Expirationdate"]]),
                      "_ключ": номер or "|".join(row)}
        по_инн.setdefault(инн, []).append(запись)
    if без > len(строки) * ДОЛЯ_БЕЗ_ИНН:
        raise ValueError("схема: без ИНН %d строк из %d" % (без, len(строки)))
    if набор == "производители":
        по_инн = {инн: True for инн in по_инн}
    elif набор == "заключения":
        # одно заключение бывает в нескольких строках (живьём 44 139 строк на 22 215
        # номеров) — остаётся строка с самым поздним сроком
        for инн, записи in по_инн.items():
            лучшие = {}
            for з in записи:
                ключ = з.pop("_ключ")
                было = лучшие.get(ключ)
                if было is None or (з["действует_до"] or "") > (было["действует_до"] or ""):
                    лучшие[ключ] = з
            по_инн[инн] = list(лучшие.values())
    return по_инн, len(строки), без


def скачать(набор, get):
    """-> (дата версии, байты CSV, пропущенные версии). 404 у перечисленной
    версии — следующая перечисленная; другой отказ — наверх."""
    паспорт = get(страница(набор), ОТКРЫТЫЕ_ДАННЫЕ, 5 << 20).decode("utf-8", "replace")
    пропущены = []
    for дата, url in версии(паспорт, набор)[:ВЕРСИЙ_ПОПРОБОВАТЬ]:
        try:
            return дата, get(url, страница(набор), НАБОРЫ[набор]["лимит"]), пропущены
        except urllib.error.HTTPError as e:
            if e.code != 404:
                raise
            пропущены.append(дата)
    raise ValueError("перечисленные в паспорте %s версии %s отдают 404"
                     % (набор, ", ".join(пропущены)))


def refresh(cache_dir=None, get=None, сегодня=None):
    """Качает три набора, пересобирает индекс; сбой любого — старый индекс цел.
    get(url, referer, лимит) — для тестов."""
    cache_dir = cache_dir or CACHE_DIR
    os.makedirs(cache_dir, exist_ok=True)
    путь = os.path.join(cache_dir, ИНДЕКС)
    сегодня = сегодня or dump_tools.сегодня()
    if get is None:
        try:
            op = dump_tools.opener()
        except ValueError as e:
            return {"статус": "индекс не обновлён: %s" % e}

        def get(url, referer, лимит, в_файл=None):
            return dump_tools.get(url, referer, лимит, timeout=600, в_файл=в_файл, op=op)
    try:
        блок = dump_tools.Блокировка(cache_dir).__enter__()
    except FileExistsError:
        return {"статус": "индекс не обновлён: другой refresh уже идёт"}
    try:
        try:
            прежний = dump_tools.прочитать_индекс(путь) if os.path.exists(путь) else {}
        except Exception:
            прежний = {}
        наборы = {}
        try:
            for набор in НАБОРЫ:
                дата, данные, пропущены = скачать(набор, get)
                по_инн, строк, без = разобрать(набор, данные)
                было = (прежний.get("наборы") or {}).get(набор, {}).get("строк") or 0
                if строк < было * ДОЛЯ_ПАДЕНИЯ:
                    raise ValueError("схема: в наборе %s %d строк (было %d)" % (набор, строк, было))
                наборы[набор] = {"выгрузка": дата, "строк": строк, "без_инн": без,
                                 "пропущены_404": пропущены, "по_инн": по_инн}
        except Exception as e:
            return {"статус": "индекс не обновлён: %s: %s" % (type(e).__name__, str(e)[:200])}
        dump_tools.записать_индекс(путь, {"скачан": сегодня, "наборы": наборы})
        return {"статус": "обновлено",
                "наборы": {н: {к: в for к, в in д.items() if к != "по_инн"}
                           for н, д in наборы.items()}}
    finally:
        блок.__exit__(None, None, None)


def устарел(индекс, сегодня):
    out = []
    for набор, д in sorted(индекс["наборы"].items()):
        if dump_tools.старше(д["выгрузка"], сегодня, СВЕЖЕСТЬ_ДНЕЙ):
            out.append("выгрузка Минпромторга «%s» от %s — старше %d дней; обновите: "
                       "minpromtorg.py --refresh (нужен РФ-IP или INN_CHECK_PROXY)"
                       % (набор, д["выгрузка"], СВЕЖЕСТЬ_ДНЕЙ))
    return out


def lookup(inn, cache_dir=None, сегодня=None):
    """-> (dict|None, заметка). None — индекса нет."""
    cache_dir = cache_dir or CACHE_DIR
    try:
        индекс = dump_tools.прочитать_индекс(os.path.join(cache_dir, ИНДЕКС))
    except FileNotFoundError:
        return None, ("индекса нет (%s) — сначала minpromtorg.py --refresh (нужен РФ-IP или "
                      "INN_CHECK_PROXY)" % (CACHE_DIR_ВИДИМЫЙ if cache_dir == CACHE_DIR
                                            else cache_dir))
    сегодня = сегодня or dump_tools.сегодня()
    н = индекс["наборы"]
    лицензии = н["лекарства"]["по_инн"].get(str(inn), [])
    заключения = sorted(н["заключения"]["по_инн"].get(str(inn), []),
                        key=lambda з: (з["действует_до"] or "", з["номер"] or ""), reverse=True)
    действующие = [з for з in заключения if з["действует_до"] and з["действует_до"] >= сегодня]
    срок_неизвестен = sum(not з["действует_до"] for з in заключения)
    производитель = bool(н["производители"]["по_инн"].get(str(inn)))
    return {
        "в_реестрах": bool(лицензии or заключения or производитель),
        "лицензии_лекарства": лицензии,
        "производитель_пп719": производитель,
        "заключений_пп719": len(заключения),
        "действующих_заключений": len(действующие),
        # срок не распознан — ни действующим, ни истёкшим не считается (ревью Codex)
        "заключений_срок_неизвестен": срок_неизвестен,
        "заключения_показаны": заключения[:ПОКАЗАТЬ],
        "выгрузки": {набор: {"дата": д["выгрузка"], "пропущены_404": д["пропущены_404"]}
                     for набор, д in н.items()},
        "оговорка": "в реестре лицензий на лекарства только действующие и приостановленные "
                    "лицензии — прекращённая лицензия там не видна; «производитель» и "
                    "заключения — по ПП РФ № 719 (подтверждение российского производства)",
        "скачан": индекс["скачан"],
        "предупреждения": устарел(индекс, сегодня),
        "источник": ОТКРЫТЫЕ_ДАННЫЕ,
    }, "ok"


def main(argv):
    args = argv[1:]
    if args == ["--refresh"]:
        res = refresh()
        print(json.dumps(res, ensure_ascii=False, indent=2))
        return 0 if res["статус"].startswith("обновлено") else 1
    if len(args) == 2 and args[0] == "--inn":
        res, note = lookup(args[1])
        print(json.dumps(res if res is not None else {"статус": "не проверено",
                                                      "причина": note},
                         ensure_ascii=False, indent=2))
        return 0 if res is not None else 1
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
