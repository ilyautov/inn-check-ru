def _источники_поля(d):
    """Источники поля всегда кортежем: одиночный id тоже."""
    источник = d.get("источник")
    if источник is None:
        return ()
    return источник if isinstance(источник, tuple) else (источник,)


ИСТОЧНИК_ПОЛЯ = {d["поле"]: _источники_поля(d) for d in ОТСЛЕЖИВАЕМЫЕ_ПОЛЯ}


def это_отпечаток(snap):
    """True, если это нормализованный отпечаток snapshot.py, а не полный слепок."""
    return isinstance(snap, dict) and snap.get("версия_формата") is not None


def состояние_блока(av):
    """Состояние блока из _доступность: словарь §1.1 или старая строка-статус."""
    if isinstance(av, dict):
        st = av.get("состояние")
        return st if st in СОСТОЯНИЯ else "не проверено"
    if isinstance(av, str):
        s = av.strip().lower()
        if s.startswith(("ok", "ок", "проверено", "собрано")):
            return "ok"
        if s.startswith("пусто"):
            return "пусто"
        return "не проверено"
    return "не проверено"


def состояния_снимка(snap):
    """{id источника: ok|пусто|не проверено} из отпечатка или полного слепка.

    Пустой словарь означает «состояния неизвестны»: полный снимок формата до
    1.7.0 без `_доступность`. Это НЕ то же самое, что «всё проверено», поэтому
    карточка про такие снимки говорит отдельно.
    """
    if not isinstance(snap, dict):
        return {}
    if это_отпечаток(snap):
        st = snap.get("состояния")
        if not isinstance(st, dict):
            return {}
        return {sid: (v if v in СОСТОЯНИЯ else "не проверено")
                for sid, v in st.items()}
    av_map = snap.get("_доступность")
    if not isinstance(av_map, dict):
        return {}
    return {sid: состояние_блока(av) for sid, av in av_map.items()}


def итог_снимка(snap):
    """Вердикт полноты проверки по снимку или None, если состояния неизвестны.

    {"проверка_состоялась": True|False|None,   None — снимок вердикта не принёс
     "не_проверено": [...],                    все молчащие источники
     "не_проверено_deal_killer": [...],        из них deal-killer'ы
     "не_ответили_deal_killer": [...],         из них те, что движок умеет собирать
     "не_покрыты_deal_killer": [...]}          постоянный предел (требует: браузер)
    """
    сост = состояния_снимка(snap)
    if not сост:
        return None
    блок = (snap.get("_итог") if это_отпечаток(snap)
            else snap.get("_итог_проверки"))
    пс = блок.get("проверка_состоялась") if isinstance(блок, dict) else None
    не_проверено = sorted(s for s, v in сост.items() if v == "не проверено")
    dk = [s for s in deal_killers() if сост.get(s) == "не проверено"]
    непокрытые = set(не_покрыты_скриптом())
    return {
        "проверка_состоялась": None if пс is None else bool(пс),
        "не_проверено": не_проверено,
        "не_проверено_deal_killer": dk,
        "не_ответили_deal_killer": [s for s in dk if s not in непокрытые],
        "не_покрыты_deal_killer": [s for s in dk if s in непокрытые],
    }


def условия_сбора(snap):
    """{режим, профиль} — чем собран снимок (None, если снимок этого не хранит).

    Снимок, собранный `--профиль отсрочка` или с ранним выходом, содержит меньше
    источников, чем полный: сравнивать их как равные — значит выдавать артефакт
    сбора за изменение у контрагента.
    """
    if not isinstance(snap, dict):
        return {"режим": None, "профиль": None}
    if это_отпечаток(snap):
        сбор = snap.get("сбор")
        сбор = сбор if isinstance(сбор, dict) else {}
        return {"режим": сбор.get("режим"), "профиль": сбор.get("профиль")}
    return {"режим": _g(snap, "_сбор", "режим"), "профиль": snap.get("профиль")}


def _год(значение):
    """Год отчётности приводится к int: «2025» и 2025 — один и тот же год."""
    try:
        return int(str(значение).strip())
    except (TypeError, ValueError):
        return значение


def _строка_года(rec, code):
    """Строка баланса года. Обычно через fin_scoring (единое место имён строк);
    без него — минимальный запасной разбор, чтобы отпечаток не терял данные."""
    if _fin is not None:
        return _fin._строка(rec, code)
    строки = rec.get("строки") if isinstance(rec.get("строки"), dict) else {}
    val = строки.get(code)
    if val is None:
        val = rec.get({"2110": "выручка", "1300": "чистые_активы"}.get(code))
    try:
        return float(val) if val is not None else None
    except (TypeError, ValueError):
        return None


def _годы_отчётности(блок):
    """Последние ЛЕТ_ОТЧЁТНОСТИ лет в нормализованном виде (по возрастанию года)."""
    годы = {}
    for rec in (блок or []):
        if isinstance(rec, dict):
            годы[_год(rec.get("год"))] = rec
    ключи = sorted((g for g in годы if g is not None), key=lambda g: str(g))
    out = []
    for g in ключи[-ЛЕТ_ОТЧЁТНОСТИ:]:
        out.append({"год": g,
                    "чистые_активы": _строка_года(годы[g], "1300"),
                    "выручка": _строка_года(годы[g], "2110")})
    return out


def поля_снимка(snap):
    """Нормализованный вид снимка: {поле: значение} по ОТСЛЕЖИВАЕМЫЕ_ПОЛЯ.

    Полный слепок разбирается по путям, отпечаток отдаёт готовый блок «поля».
    Именно по этому виду работает diff(), поэтому оба формата сравнимы между
    собой (полный слепок ↔ отпечаток тоже).
    """
    if not isinstance(snap, dict):
        return {}
    if это_отпечаток(snap):
        поля = snap.get("поля")
        return dict(поля) if isinstance(поля, dict) else {}
    out = {}
    for d in ОТСЛЕЖИВАЕМЫЕ_ПОЛЯ:
        вид = d["вид"]
        if вид == "значение":
            out[d["поле"]] = _g(snap, *d["путь"])
        elif вид == "годы":
            out[d["поле"]] = _годы_отчётности(_g(snap, *d["путь"]))
        elif вид == "статусы":
            блок = _g(snap, *d["путь"])
            out[d["поле"]] = ({k: _g(блок, k, "статус") for k in блок}
                              if isinstance(блок, dict) else None)
    статус = out.get("статус")
    out["ликвидация"] = bool(
        (статус and any(h in str(статус).lower() for h in RED_STATUS_HINTS))
        or out.get("дата_прекращения"))
    последний = (out.get("финансы_годы") or [{}])[-1]
    out["год_отчётности"] = последний.get("год")
    out["чистые_активы"] = последний.get("чистые_активы")
    out["выручка"] = последний.get("выручка")
    return out


def _load(path):
    """Снимок с диска или None. Путь None/пустой — тоже None, а не TypeError:
    выше по течению snapshot.save() возвращает None при сбое записи, и прогон
    по списку наблюдения не имеет права падать из-за одного не записавшегося
    файла (тишина в кроне читается как «всё спокойно»)."""
    if not path or not isinstance(path, (str, bytes, os.PathLike)):
        return None
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError, TypeError):
        return None


def _g(d, *path):
    cur = d
    for key in path:
        if isinstance(cur, dict):
            cur = cur.get(key)
        else:
            return None
    return cur


def _snap_date(path):
    return os.path.splitext(os.path.basename(path))[0].replace("_", " ")


def _snapshots(inn):
    snap_dir = os.path.join(CACHE_DIR, "snapshots", inn)
    return sorted(glob.glob(os.path.join(snap_dir, "*.json")))


def _изм(поле, было, стало, severity, дата_было, дата_стало, пояснение=None,
         год=None):
    out = {"поле": поле, "было": было, "стало": стало, "severity": severity,
           "дата_было": дата_было, "дата_стало": дата_стало}
    if пояснение:
        out["пояснение"] = пояснение
    if год is not None:
        out["год"] = год
    return out


