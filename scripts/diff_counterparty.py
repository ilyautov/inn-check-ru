#!/usr/bin/env python3
"""
diff_counterparty.py — мониторинг изменений контрагента по снимкам
fetch_counterparty.py --save. Офлайн: сравниваются файлы, сеть не нужна.

Читает два формата снимков (спек волны 2, §3.1):
  * полный слепок вывода fetch_counterparty.py (как было);
  * нормализованный отпечаток scripts/snapshot.py (ключ «версия_формата»).
Дифф идёт по одному и тому же перечню полей ОТСЛЕЖИВАЕМЫЕ_ПОЛЯ, поэтому
переход, поданный полным снимком и отпечатком, даёт один и тот же результат.

Использование:
    python3 diff_counterparty.py <ИНН>                 # два последних снимка из кэша
    python3 diff_counterparty.py --a old.json --b new.json
    python3 diff_counterparty.py <ИНН> --human          # светофорная карточка

Выход JSON:
    {
      "статус": "сравнено" | "изменений нет" | "проверка не состоялась"
                | "сравнивать не с чем" | "нет снимков",
      "изменения": [
        {"поле": ..., "было": ..., "стало": ..., "severity": "🔴"/"🟡"/"ℹ️",
         "дата_было": ..., "дата_стало": ...}
      ]
    }
Один снимок — честное «сравнивать не с чем, снимок сохранён, вернитесь позже».

Состояния источников сравниваются ПЕРЕД значениями (спек волны 1, §1):
источник, ушедший из `ok|пусто` в `не проверено`, даёт отдельную запись
«источник перестал проверяться», а его поля в сравнение значений не идут вовсе
— иначе молчание источника читалось бы как «руководитель → None» и, хуже,
как «отметка о недостоверности снята». Обратный переход — тоже запись, и
значения сравниваются только со следующего снимка. Снимки без `_доступность`
(полный формат до 1.7.0) — «состояния неизвестны»: поведение прежнее, но в
карточке об этом сказано прямо.

Пороги финансового ухудшения не дублируются: импортируются из fin_scoring.py
(единое место констант). Leading indicators: смена статуса на ликвидацию/
реорганизацию 🔴, недостоверность сведений 🔴, смена директора/адреса 🟡,
налоговая задолженность 🟡, ЧА < 0 🔴 или падение выручки > порога 🟡 — и для
нового года отчётности, и для уже известного года (пересдача/дозагрузка форм
— обычное дело, ухудшение внутри известного года молчать не должно).
"""

