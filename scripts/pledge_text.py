#!/usr/bin/env python3
"""
pledge_text.py — разбор текста страницы результатов reestr-zalogov.ru (поиск по
залогодателю), скопированного пользователем (Ctrl+A, Ctrl+C). Страница под
reCAPTCHA v3: поиск запускает сам пользователь, код только читает вставленный
текст.

    python3 scripts/pledge_text.py --инн 1650032058 < страница.txt

Разбирается то, что видели живьём (28.09.2026, ИНН 1650032058): строка
«Параметры поиска: … ИНН: N», строки уведомлений «№ ДД.ММ.ГГГГ номер», стороны,
пагинация. Чего не видели — не угадываем: нет строк уведомлений — ValueError
(«ничего не найдено» отмечается формой вручную), страниц больше одной —
разбор помечается неполным.

Имена залогодержателей записываются, только если это организация (ООО, АО,
банк, госкорпорация…): залогодержатель-физлицо и ИП не записываются вовсе.
Имена залогодателей не записываются: это сама проверяемая компания или
созалогодатели, среди которых бывают физлица.
"""

import datetime
import json
import re
import sys

МАКС_ТЕКСТ = 512 * 1024
МАКС_ИМЯ = 200
СКРЫТ = "скрыт"
НЕ_ОРГАНИЗАЦИЯ = "не организация — не записан"

_СТРОКА = re.compile(r"^\s*(\d{1,4})\s+(\d{2})\.(\d{2})\.(\d{4})\s+(\d{4}-\d{3}-\d{6}-\d{3})\s*$")
_ПАРАМЕТРЫ = re.compile(r"Параметры поиска:([^\n]*)")
_ИНН_ПОИСКА = re.compile(r"ИНН:\s*(\d*)")
_СТРАНИЦЫ = re.compile(r"^\s*\d+(?:\s+(?:\d+|…|\.\.\.))*\s*$")
_КОНЕЦ = re.compile(r"^\s*(Внимание!|Рекомендации по повышению)")
_ИМУЩЕСТВО = re.compile(r"^\s*(История изменений\s*)?(Номер имущества:.*|Данные не представлены\s*)?$")
# Организация — по целому слову: подстрока пропустила бы фамилию («Банков»,
# «Фондов») с ФИО залогодержателя-физлица (ревью Codex, P1).
_ОРГАНИЗАЦИЯ = re.compile(
    r"\b(ООО|ОАО|ЗАО|ПАО|НАО|АО|АКБ|КБ|МФК|МКК|ГУП|МУП|ФГУП|НКО|"
    r"обществ[оа]|банк[аеу]?|корпораци[яи]|компани[яи]|фонд[аеу]?|предприяти[ея]|"
    r"учреждени[ея]|товариществ[оа]|кооператив[аеу]?|министерств[оа]|администраци[яи]|"
    r"агентств[оа])\b", re.IGNORECASE)
_ИП = re.compile(r"(\bИП\b|индивидуальный предприниматель)", re.IGNORECASE)


def _залогодержатель(строки):
    текст = " ".join(s.strip() for s in строки if s.strip())
    if not текст:
        return None
    if "скрыта от публикации" in текст.lower():
        return СКРЫТ
    if _ИП.search(текст) or not _ОРГАНИЗАЦИЯ.search(текст):
        return НЕ_ОРГАНИЗАЦИЯ
    return текст[:МАКС_ИМЯ]


def разобрать(текст, инн):
    """-> {"уведомлений", "уведомления": [{дата, номер, залогодержатель}],
    "залогодержатели": {имя: число}, "последнее", "полно", "примечание"}.
    ValueError — текст не страница результатов по этому ИНН или не разобран."""
    if not isinstance(текст, str) or not текст.strip():
        raise ValueError("текст страницы пуст")
    if len(текст) > МАКС_ТЕКСТ:
        raise ValueError("текст длиннее %d КБ — скопируйте только страницу результатов"
                         % (МАКС_ТЕКСТ // 1024))
    текст = текст.replace("\r\n", "\n").replace("\r", "\n").replace("\xa0", " ")
    параметры = _ПАРАМЕТРЫ.findall(текст)
    if not параметры:
        raise ValueError("нет строки «Параметры поиска» — это не страница результатов "
                         "reestr-zalogov.ru")
    for п in параметры:
        m = _ИНН_ПОИСКА.search(п)
        # наименование или ОГРН рядом с ИНН сужают поиск: выдача была бы неполной
        лишнее = re.search(r"(Наименование|ОГРН):\s*[^,\s]", п)
        if not m or m.group(1) != инн or лишнее:
            raise ValueError("поиск шёл не по ИНН %s: «Параметры поиска:%s»"
                             % (инн, п.strip()[:120]))
    строки = текст.split("\n")
    начала = [i for i, s in enumerate(строки) if _СТРОКА.match(s)]
    if not начала:
        raise ValueError("строк уведомлений не найдено: если реестр ответил «ничего не "
                         "найдено», отметьте итог в форме вручную (уведомлений 0)")
    конец = len(строки)
    for i in range(начала[-1] + 1, len(строки)):
        if _КОНЕЦ.match(строки[i]):
            конец = i
            break
    уведомления, страницы = [], None
    for k, начало in enumerate(начала):
        m = _СТРОКА.match(строки[начало])
        if int(m.group(1)) != k + 1:
            raise ValueError("уведомления не по порядку (строка %s вместо %d) — текст "
                             "скопирован не целиком" % (m.group(1), k + 1))
        try:
            дата = datetime.date(int(m.group(4)), int(m.group(3)), int(m.group(2)))
        except ValueError:
            raise ValueError("дата уведомления %s не разобрана" % строки[начало].strip())
        до = начала[k + 1] if k + 1 < len(начала) else конец
        тело = строки[начало + 1:до]
        if k + 1 == len(начала):
            # хвост после последнего уведомления: строка пагинации
            for j, s in enumerate(тело):
                if s.strip() and _СТРАНИЦЫ.match(s):
                    страницы = s.split()
                    тело = тело[:j]
                    break
        стороны = [s for s in тело if s.strip() and not _ИМУЩЕСТВО.match(s)]
        if len(стороны) != 2:
            # залогодатель + залогодержатель; иначе (созалогодатели, перенос строки)
            # стороны не угадываем
            держатель = None
        else:
            держатель = _залогодержатель(стороны[1:])
        уведомления.append({"дата": дата.isoformat(), "номер": m.group(5),
                            "залогодержатель": держатель or "стороны не разобраны"})
    if страницы is None or конец == len(строки):
        # страница копируется целиком: после пагинации — «Внимание!» реестра
        raise ValueError("нет строки со страницами или предупреждения «Внимание!» "
                         "после списка — текст скопирован не целиком")
    полно = страницы == ["1"]
    держатели = {}
    for у in уведомления:
        держатели[у["залогодержатель"]] = держатели.get(у["залогодержатель"], 0) + 1
    return {
        "уведомлений": len(уведомления),
        "уведомления": уведомления,
        "залогодержатели": держатели,
        "последнее": max(у["дата"] for у in уведомления),
        "полно": полно,
        "примечание": (
            "реестр сам предупреждает: результаты поиска могут быть неполными; "
            "юридически значимо — выписка у нотариуса" if полно else
            "страниц результатов %s, разобрана одна — вставьте все страницы или "
            "отметьте итог вручную" % страницы[-1]),
    }


def main(argv):
    args = argv[1:]
    if len(args) != 2 or args[0] != "--инн":
        sys.stdout.write(__doc__)
        return 2
    try:
        out = разобрать(sys.stdin.read(), args[1])
    except ValueError as e:
        sys.stderr.write("не разобрано: %s\n" % e)
        return 1
    sys.stdout.write(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
