_RE_LI = re.compile(r"<li>(.*?)</li>", re.DOTALL)
_RE_ТЕГ = re.compile(r"<[^>]+>")
_RE_НОМЕР = re.compile(r"^(\d+)\.\s*")
_RE_ИНН = re.compile(r"ИНН:\s*(\d{10}|\d{12})")
_RE_ОГРН = re.compile(r"ОГРН:\s*(\d{13}|\d{15})")
_RE_ДАТА_РОЖДЕНИЯ = re.compile(r"(\d{2}\.\d{2}\.\d{4})\s*г\.\s*р\.")
# Дата в хвосте организации идёт сразу за ОГРН; в источнике она не подписана
# (по виду — дата решения суда о ликвидации/запрете), поэтому поле нейтральное.
_RE_ДАТА_ОРГ = re.compile(r"ОГРН:\s*\d+\s*,\s*(\d{2}\.\d{2}\.\d{4})")
_RE_СКОБКИ = re.compile(r"\(([^()]*)\)")
_RE_ХВОСТ_ИНН = re.compile(r",?\s*,\s*ИНН:")
# «ОБЪЕДИНЕНИЕ, ВКЛЮЧАЮЩЕЕ: ФАМИЛИЯ ИМЯ ОТЧЕСТВО, РОДИВШЕГОСЯ ДД.ММ.ГГГГ В <место>, …»
_RE_УЧАСТНИК = re.compile(
    r"([^,:]+),\s*РОДИВШ\w+\s*(\d{2}\.\d{2}\.\d{4})?(?:\s*В\s+([^,]+))?")


def _текст_записи(li):
    """<li>…</li> -> плоская строка: теги вон, сущности развёрнуты,
    пробелы схлопнуты. Записи перечня разметки внутри не содержат."""
    text = _html.unescape(_RE_ТЕГ.sub(" ", li)).replace("\xa0", " ")
    return " ".join(text.split())


def _имя_и_алиасы(head, тип):
    """Голова записи -> (имя, [алиасы]). Алиасы в перечне идут в скобках через
    «;». У организаций скобки бывают и частью названия (ZUKUNFT MEMORIAL E.V.
    (БУДУЩЕЕ. МЕМОРИАЛ), ГЕРМАНИЯ (АССОЦИАЦИЯ …)), поэтому алиасами считается
    только последняя группа скобок, закрывающая голову."""
    h = head.strip().strip(",").strip()
    алиасы = []
    if тип == "организация":
        if h.endswith(")"):
            i = h.rfind("(")
            if i > 0:
                алиасы = [a.strip() for a in h[i + 1:-1].split(";") if a.strip()]
                h = h[:i].strip().strip(",").strip()
        имя = h.strip().strip("*").strip()
    else:
        for группа in _RE_СКОБКИ.findall(h):
            алиасы += [a.strip() for a in группа.split(";") if a.strip()]
        имя = h.split("(")[0].split(",")[0].strip().strip("*").strip()
    return (имя or None), алиасы


def _разобрать_запись_рфм(li, часть, тип):
    """Одна <li> перечня -> запись. Форматы (живая страница 19.09.2026):
        организация: «N. НАЗВАНИЕ [ (алиасы)], [, ИНН: …, ОГРН: …[, ДД.ММ.ГГГГ]];»
        физлицо:     «N. ФАМИЛИЯ ИМЯ ОТЧЕСТВО*[,  (алиасы)], ДД.ММ.ГГГГ г.р. , МЕСТО;»
        объединение: «N. ОБЪЕДИНЕНИЕ, ВКЛЮЧАЮЩЕЕ: ФИО, РОДИВШЕГОСЯ ДД.ММ.ГГГГ В …, …;»
    Звёздочка у названия — пометка источника, в имя не входит."""
    текст = _текст_записи(li)
    m = _RE_НОМЕР.match(текст)
    номер = int(m.group(1)) if m else None
    тело = (текст[m.end():] if m else текст).strip().rstrip(";").strip()
    if not тело:
        return None

    инн = _RE_ИНН.findall(тело)
    огрн = _RE_ОГРН.findall(тело)
    m_рожд = _RE_ДАТА_РОЖДЕНИЯ.search(тело)
    дата_рождения = m_рожд.group(1) if m_рожд else None

    if инн:
        head = _RE_ХВОСТ_ИНН.split(тело, 1)[0]
    elif m_рожд:
        head = тело[:m_рожд.start()]
    else:
        head = тело
    имя, алиасы = _имя_и_алиасы(head, тип)

    место = None
    if m_рожд:
        место = тело[m_рожд.end():].strip().lstrip(",").strip() or None
    elif тип == "физлицо" and "," in тело:
        место = тело.rsplit(",", 1)[1].strip() or None

    m_дата = _RE_ДАТА_ОРГ.search(тело) if тип == "организация" else None
    дата = m_дата.group(1) if m_дата else None

    участники = []
    if "ВКЛЮЧАЮЩЕЕ" in тело:
        хвост = тело.split("ВКЛЮЧАЮЩЕЕ", 1)[1].lstrip(": ")
        for m_у in _RE_УЧАСТНИК.finditer(хвост):
            имя_у = m_у.group(1).strip().strip("*").strip()
            if имя_у:
                участники.append({"имя": имя_у,
                                  "дата_рождения": m_у.group(2),
                                  "место_рождения": (m_у.group(3) or "").strip() or None})

    все_имена = [имя] + алиасы + [у["имя"] for у in участники]
    запись = {
        "имя": имя,
        "все_имена": [n for n in все_имена if n],
        "алиасы": алиасы,
        "инн": инн,
        "огрн": огрн,
        "дата_рождения": дата_рождения,
        "место_рождения": место,
        "дата": дата,
        "номер": номер,
        "часть": часть,
        "тип_записи": тип,
        "раздел": "%s / %s" % (часть, "организации" if тип == "организация"
                               else "физические лица"),
    }
    if участники:
        запись["участники"] = участники
    return запись


def _прочитать_текст(path):
    """Кэш -> (текст, доля_замен, проблема). Доля символов-замен выше порога
    означает, что файл не в UTF-8: латиница уцелеет, кириллица станет мусором,
    и сверка по ФИО молча даст 0 совпадений — поэтому это «не проверено»,
    а не предупреждение."""
    try:
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError:
        return None, None, "кэш: не читается"
    текст = data.decode("utf-8", errors="replace")
    if not текст:
        return None, None, "кэш: пустой файл"
    доля = текст.count("�") / len(текст)
    if доля > ПОРОГ_ЗАМЕН:
        return None, доля, (
            "кодировка: %.1f%% символов не декодировались как UTF-8 (порог %.1f%%) "
            "— файл не в UTF-8, имена кириллицей не сверить; обновите: --refresh"
            % (доля * 100, ПОРОГ_ЗАМЕН * 100))
    return текст, доля, None


def _entries_rfm(path):
    """Перечень РФМ (HTML полного списка) -> ([записи], статус, причина).

    Страница ≈4 МБ: режется один раз по маркерам разделов id="russianUL" и
    далее, внутри каждого раздела берётся единственный <ol class="terrorist-list">
    — квадратичных проходов нет, разбор всех ≈23 800 записей укладывается в
    доли секунды. <li> шапки-хлебных крошек имеют атрибуты и под «<li>» без
    атрибутов не попадают. Схема проверена на живом файле 19.09.2026.

    Ни одной записи -> (None, «не проверено», причина): структура страницы
    изменилась, и честнее сказать «не проверено», чем показать пустой перечень
    как проверенный.

    Пропал раздел -> «проверено частично»: человек из потерянного раздела просто
    не найдётся, а «проверено, совпадений 0» об этом молчит. Различаются два
    случая: маркер раздела не найден вовсе (дефект разбора) и раздел найден,
    а записей в нём ноль с пометкой источника «Сведения о субъектах отсутствуют»
    (факт: на 19.09.2026 так помечена вся международная часть)."""
    страница, _доля, проблема = _прочитать_текст(path)
    if страница is None:
        return None, НЕ_ПРОВЕРЕНО, проблема

    позиции = [(страница.find('id="%s"' % ident), ident, часть, тип)
               for ident, часть, тип in RFM_РАЗДЕЛЫ]
    найдены = sorted(p for p in позиции if p[0] >= 0)
    пропущены = [p[1] for p in позиции if p[0] < 0]
    if not найдены:
        return None, НЕ_ПРОВЕРЕНО, (
            "схема: в HTML нет ни одного раздела перечня (russianUL/russianFL/"
            "foreignUL/foreignFL) — структура страницы изменилась")

    entries = []
    пустые, без_списка = [], []
    for i, (начало, ident, часть, тип) in enumerate(найдены):
        конец = найдены[i + 1][0] if i + 1 < len(найдены) else len(страница)
        кусок = страница[начало:конец]
        j = кусок.find('<ol class="terrorist-list"')
        if j < 0:
            # Раздел без списка: либо источник прямо сказал «субъектов нет»
            # (факт), либо разметка съехала (дефект) — это разные вещи.
            (пустые if МАРКЕР_ПУСТОГО_РАЗДЕЛА in кусок else без_списка).append(ident)
            continue
        k = кусок.find("</ol>", j)
        for li in _RE_LI.findall(кусок[j:k if k > 0 else len(кусок)]):
            запись = _разобрать_запись_рфм(li, часть, тип)
            if запись:
                entries.append(запись)

    if not entries:
        return None, НЕ_ПРОВЕРЕНО, (
            "схема: разделы перечня найдены, но ни одной записи не разобрано "
            "— структура страницы изменилась")
    оговорки = []
    if пропущены:
        оговорки.append("схема: в HTML не найдены разделы: %s — записи из них "
                        "НЕ сверялись" % ", ".join(пропущены))
    if без_списка:
        оговорки.append("схема: в разделах %s нет ни списка записей, ни пометки "
                        "«%s» — записи из них НЕ сверялись"
                        % (", ".join(без_списка), МАРКЕР_ПУСТОГО_РАЗДЕЛА))
    if оговорки:
        return entries, ЧАСТИЧНО, "; ".join(оговорки)
    if пустые:
        return entries, ПРОВЕРЕНО, ("разделы %s пусты по данным источника («%s») "
                                    "— это факт перечня, а не сбой разбора"
                                    % (", ".join(пустые), МАРКЕР_ПУСТОГО_РАЗДЕЛА))
    return entries, ПРОВЕРЕНО, None


def _entries_ofac(path):
    """OFAC sdn.csv (CSV без заголовка: поле 1 = id, поле 2 = имя CAPS)
    -> ([записи], статус, причина). ИНН в файле нет — сверка только по имени.
    Схема проверена на живом файле 19.09.2026."""
    текст, _доля, проблема = _прочитать_текст(path)
    if текст is None:
        return None, НЕ_ПРОВЕРЕНО, проблема
    entries = []
    for row in csv.reader(io.StringIO(текст, newline="")):
        if len(row) < 2 or not row[1].strip():
            continue
        entries.append({"имя": row[1].strip(), "инн": [],
                        "подробности": row[-1].strip() or None,
                        "id_списка": row[0].strip()})
    if not entries:
        return None, НЕ_ПРОВЕРЕНО, ("схема: в CSV не разобрано ни одной записи "
                                    "— формат файла изменился")
    return entries, ПРОВЕРЕНО, None


def _entries_eu(path):
    """EU Consolidated list (XML, ~20 МБ): sanctionEntity -> nameAlias
    (атрибут wholeName) + identification (атрибут number) -> ([записи], статус,
    причина). Схема проверена на живом файле 19.09.2026. Файл может быть обрезан
    недокачанным — iterparse + ParseError: сохраняем разобранное и честно
    отдаём «проверено частично», потому что хвост списка не сверялся."""
    entries = []
    truncated = False
    current = None
    сбой = None
    try:
        for _, el in ET.iterparse(path, events=("end",)):
            name = _local(el.tag)
            if name == "sanctionentity":
                if current and (current["имена"] or current["номера"]):
                    entries.append(current)
                current = None
                el.clear()
            elif name == "namealias" and current is not None:
                whole = (el.get("wholeName") or "").strip()
                if whole:
                    current["имена"].append(whole)
                el.clear()
            elif name == "identification" and current is not None:
                num = (el.get("number") or "").strip()
                if num:
                    current["номера"].append(num)
                el.clear()
            elif name == "subjecttype" and current is None:
                current = {"имена": [], "номера": [],
                           "тип": el.get("code") or None}
                el.clear()
    except Exception as e:
        truncated = bool(entries)
        сбой = type(e).__name__
        if not entries:
            return None, НЕ_ПРОВЕРЕНО, (
                "схема: XML перечня не разобран (%s) — файл битый или в этой "
                "сборке Python не грузится pyexpat" % сбой)
    out = [{"имя": e["имена"][0] if e["имена"] else None,
            "все_имена": e["имена"], "инн": [], "номера": e["номера"],
            "тип": e["тип"]} for e in entries]
    if truncated:
        return out, ЧАСТИЧНО, ("схема: файл обрезан (недокачан, %s) — разобрана "
                               "только часть списка, обновите: --refresh" % сбой)
    return out, ПРОВЕРЕНО, None


def _load(src):
    """Кэш одного перечня -> (записи, статус, причина).

    Свежесть — гейт, а не предупреждение (спек волны 1 §10): по кэшу годичной
    давности «совпадений 0» не значит «чисто», поэтому устаревший кэш даёт
    «не проверено», а не «проверено» с припиской."""
    path = SOURCES[src]["file"]
    if not os.path.exists(path):
        return None, НЕ_ПРОВЕРЕНО, "кэш: отсутствует"
    возраст = _cache_age_days(src)
    if возраст is not None and возраст > CACHE_TTL_DAYS:
        return None, НЕ_ПРОВЕРЕНО, (
            "кэш: устарел (%.0f дн., норма %d) — по такому перечню «совпадений 0» "
            "не означает «чисто»; обновите: --refresh" % (возраст, CACHE_TTL_DAYS))
    if src == "рфм":
        return _entries_rfm(path)
    if src == "ofac":
        return _entries_ofac(path)
    return _entries_eu(path)


def _вера(hit):
    """Насколько совпадению можно верить. Совпадение по ИНН — уникальный
    идентификатор. Совпадение по «номеру идентификации» в EU — это ЛЮБОЙ номер
    записи (паспорт, удостоверение, налоговый номер страны ЕС): тип номера
    источник не уточняет, поэтому «высокая вера» тут неуместна."""
    if "ИНН" in hit:
        return ("высокая — идентификатор уникален, но сверьте имя перед выводами")
    if "номеру" in hit:
        return ("требует ручной сверки: совпал идентификационный номер, тип "
                "которого не уточнён (в EU это паспорт/удостоверение/налоговый "
                "номер страны ЕС, а не российский ИНН)")
    return ("требует ручной сверки по дате рождения — однофамильцы в перечнях "
            "часты, это НЕ доказательство")


def _релевантные_списки(inn_q, name_q):
    """Какие перечни обязаны быть проверены, чтобы ответ на ЭТОТ запрос значил
    «чисто». Российские ИНН есть только в перечне РФМ, поэтому сверка по ИНН без
    него не сверяется ни с чем; имя ищется во всех трёх."""
    if name_q:
        return list(SOURCES)
    if inn_q:
        return [s for s in SOURCES if s in СПИСКИ_С_ИНН]
    return list(SOURCES)


def сверить(inn=None, name=None):
    """Сверка по кэшам -> (результат, проверено_полностью).
    Печать отделена от логики: этим же пользуется офлайн-eval."""
    inn_q = (inn or "").strip()
    name_q = _normalize(name)
    релевантные = _релевантные_списки(inn_q, name_q)
    совпадения = []
    по_спискам = {}

    for src, info in SOURCES.items():
        entries, статус, причина = _load(src)
        age = _cache_age_days(src)
        блок = {"список": info["название"], "url": info["url"],
                "возраст_кэша_дней": round(age, 1) if age is not None else None,
                "релевантен_запросу": src in релевантные,
                "статус": статус,
                "предупреждения": []}
        if entries is None:
            блок["причина"] = ("%s; при необходимости скачайте вручную с "
                               "подходящего IP: %s и положите в %s, затем "
                               "повторите сверку"
                               % (причина, info["url"], info["file"]))
        else:
            блок["записей"] = len(entries)
            if причина:
                (блок["предупреждения"] if статус == ЧАСТИЧНО
                 else блок.setdefault("примечания", [])).append(причина)
            for e in entries:
                hit = None
                совпавшее_имя = None
                if inn_q and inn_q in [i.strip() for i in e.get("инн", [])]:
                    hit = "по ИНН (точное)"
                elif inn_q and inn_q in e.get("номера", []):
                    hit = "по номеру идентификации (точное)"
                elif name_q:
                    for n in (e.get("все_имена") or [e.get("имя")]):
                        if n and _normalize(n) == name_q:
                            hit = "по имени (точное, нормализованное)"
                            совпавшее_имя = n
                            break
                if hit:
                    совпадение = {
                        "список": info["название"],
                        "совпадение": hit,
                        "имя": e.get("имя"),
                        "дата_рождения": e.get("дата_рождения"),
                        "вера": _вера(hit),
                    }
                    if совпавшее_имя and совпавшее_имя != e.get("имя"):
                        совпадение["совпавшее_имя"] = совпавшее_имя
                    if e.get("раздел"):
                        # У разделов разный юридический вес — раздел обязателен.
                        совпадение["раздел"] = e["раздел"]
                        совпадение["номер_в_перечне"] = e.get("номер")
                        if e.get("инн"):
                            совпадение["инн"] = e["инн"]
                        if e.get("огрн"):
                            совпадение["огрн"] = e["огрн"]
                        if e.get("участники"):
                            совпадение["участники"] = e["участники"]
                    совпадения.append(совпадение)
        по_спискам[src] = блок

    def _перечень(статус_списка):
        return [{"список": src, "название": SOURCES[src]["название"],
                 "причина": по_спискам[src].get("причина") or
                            "; ".join(по_спискам[src]["предупреждения"]) or None}
                for src in релевантные if по_спискам[src]["статус"] == статус_списка]

    не_проверено = _перечень(НЕ_ПРОВЕРЕНО)
    частично = _перечень(ЧАСТИЧНО)
    if len(не_проверено) == len(релевантные):
        статус = НЕ_ПРОВЕРЕНО
    elif не_проверено or частично:
        статус = ЧАСТИЧНО
    else:
        статус = ПРОВЕРЕНО

    результат = {
        # Верхний уровень — то, на что смотрят потребители (profiles.py, MCP):
        # «совпадений 0» при статусе ниже «проверено» НЕ означает «чисто».
        "статус": статус,
        "запрос": {"инн": inn or None, "имя": name or None},
        "совпадений": len(совпадения),
        "совпадения": совпадения,
        "релевантные_списки": релевантные,
        "не_проверено": не_проверено,
        "проверено_частично": частично,
        "по_спискам": по_спискам,
        "дата_проверки": time.strftime("%Y-%m-%d"),
        "примечание": "совпадение в списках ЕС/США — риск вторичных санкций "
                      "и валютных платежей для экспортных сделок",
    }
    if статус != ПРОВЕРЕНО:
        чего_нет = ", ".join(x["список"] for x in не_проверено + частично)
        по_инн = (inn_q and not name_q)
        результат["оговорка"] = (
            "статус «%s»: %s — %s«совпадений: %d» НЕ означает «чисто», сверка "
            "неполная" % (статус, "не сверены/сверены частично перечни: %s" % чего_нет,
                          "сверка по ИНН идёт только по перечню РФМ (в OFAC/EU "
                          "российских ИНН в данных нет), поэтому " if по_инн else "",
                          len(совпадения)))
    return результат, статус == ПРОВЕРЕНО


def check(inn=None, name=None):
    результат, проверено = сверить(inn=inn, name=name)
    return _out(результат, 0 if проверено else 1)


def main(argv):
    args = argv[1:]
    if not args:
        sys.stderr.write(__doc__)
        return 2
    if "--refresh" in args:
        return refresh()
    inn = name = None
    for i, a in enumerate(args):
        if a == "--inn" and i + 1 < len(args):
            inn = args[i + 1]
        elif a == "--name" and i + 1 < len(args):
            name = args[i + 1]
    if inn is None and name is None:
        sys.stderr.write(
            "Укажите --inn <ИНН> и/или --name \"ФИО\" (или --refresh)\n")
        return 2
    return check(inn=inn, name=name)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
