_RE_CHARSET_HEADER = re.compile(r"charset\s*=\s*[\"']?([A-Za-z0-9_.:+-]+)", re.IGNORECASE)
_RE_CHARSET_META = re.compile(rb"charset\s*=\s*[\"']?\s*([A-Za-z0-9_.:+-]+)", re.IGNORECASE)


def _объявленная_кодировка(headers, data):
    """Кодировка, которую объявил сам источник: Content-Type, затем
    <meta charset>/<?xml encoding?> в первых килобайтах. -> (имя, откуда)."""
    ct = ""
    try:
        ct = headers.get("Content-Type") or ""
    except Exception:
        ct = ""
    m = _RE_CHARSET_HEADER.search(ct)
    if m:
        return m.group(1), "Content-Type"
    m2 = _RE_CHARSET_META.search(data[:4096])
    if m2:
        try:
            return m2.group(1).decode("ascii"), "<meta charset>/<?xml?>"
        except UnicodeDecodeError:
            return None, None
    return None, None


def _в_utf8(data, объявлена):
    """Байты ответа -> байты UTF-8. Возвращает (байты, описание кодировки,
    предупреждение, проблема). Источник сменил кодировку молча — без этого шага
    кириллица превращается в мусор, а сверка по ФИО тихо даёт 0 совпадений."""
    канон = (объявлена or "").strip().lower().replace("_", "-")
    if канон in ("", "utf-8", "utf8"):
        try:
            data.decode("utf-8")
        except UnicodeDecodeError as e:
            if объявлена:
                return None, объявлена, None, (
                    "источник объявил %s, но байты ей не соответствуют (%s)"
                    % (объявлена, e.reason))
            try:
                подобрана = data.decode("cp1251").encode("utf-8")
            except UnicodeDecodeError:
                return None, None, None, (
                    "кодировка не объявлена и не UTF-8, cp1251 тоже не подошла")
            return подобрана, "cp1251 (подобрана)", (
                "источник не объявил кодировку и отдал не UTF-8; байты разобраны "
                "как cp1251 и перекодированы — сверьте имена в выводе"), None
        return data, объявлена or "utf-8 (не объявлена, проверена)", None, None
    try:
        return data.decode(канон).encode("utf-8"), объявлена, None, None
    except (UnicodeDecodeError, LookupError) as e:
        return None, объявлена, None, ("кодировка %s не разбирается (%s)"
                                       % (объявлена, type(e).__name__))


def _download(src):
    """Скачивает один список в кэш. TLS включён. Не падает при сбое сети.
    В кэш кладётся ТОЛЬКО UTF-8: кодировка берётся из Content-Type/<meta>,
    иначе файл не сохраняется — лучше «не скачан», чем мусор вместо имён."""
    info = SOURCES[src]
    os.makedirs(CACHE_DIR, exist_ok=True)
    ctx = _ssl_context()
    req = urllib.request.Request(info["url"], headers={"User-Agent": UA})
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT, context=ctx) as resp:
            data = resp.read()
            headers = resp.headers
    except Exception as e:
        return {"список": info["название"], "статус": "не скачан",
                "причина": "%s — скачайте вручную: %s и положите в %s"
                           % (type(e).__name__, info["url"], info["file"])}
    if len(data) < 1000:
        return {"список": info["название"], "статус": "не скачан",
                "причина": "источник вернул %d байт — структура изменилась "
                           "или блокировка" % len(data)}
    объявлена, откуда = _объявленная_кодировка(headers, data)
    данные, кодировка, предупреждение, проблема = _в_utf8(data, объявлена)
    if данные is None:
        return {"список": info["название"], "статус": "не скачан",
                "причина": "кодировка: %s — файл не сохранён, иначе кириллица "
                           "стала бы мусором и сверка по имени молча дала бы 0 "
                           "совпадений" % проблема}
    with open(info["file"], "wb") as fh:
        fh.write(данные)
    meta = {"скачан": time.strftime("%Y-%m-%d %H:%M:%S"),
            "источник": info["url"], "байт": len(данные),
            "кодировка": кодировка,
            "кодировка_объявлена": откуда or "не объявлена"}
    if предупреждение:
        meta["предупреждение"] = предупреждение
    with open(_meta_path(src), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, ensure_ascii=False, indent=2)
    return {"список": info["название"], "статус": "ок",
            "файл": info["file"], **meta}


