#!/usr/bin/env python3
"""
extract_inn.py — извлечение ИНН из входящего документа (волна 3, задача 7:
«проверка без запроса»). Только стандартная библиотека.

    python3 extract_inn.py счёт.txt договор.html выгрузка.csv
    cat письмо.eml | python3 extract_inn.py --stdin --только-новые
    python3 extract_inn.py счёт.txt --проверить --профиль отсрочка

Зачем. Раньше триггер проверки был один — фраза человека. Теперь: пришёл счёт
от нового ИНН, появился контрагент в выгрузке, договор пришёл на подпись —
ИНН вынимается из текста сам, отсеивается уже проверенное, а новое уходит в
`batch_check.py --режим quick`, и человек узнаёт о 🔴 до оплаты.

Вход: файлы аргументами и/или `--stdin`. Форматы:
  * текст, CSV/TSV — разбираются как текст (разделители колонок учитываются
    только как границы поля, см. «пробелы внутри числа» ниже);
  * HTML — теги снимаются, сущности (`&nbsp;`) раскрываются; значимые атрибуты
    (`value`, `title`, `alt`, `placeholder`, `content`, `href`, `data-*`)
    читаются вместе с текстом: в карточке ЕГРЮЛ и веб-1С ИНН лежит именно в
    атрибуте, и срезать его вместе с тегом значило бы «найдено 0» молча;
  * письмо (.eml, MIME) — разбирается стандартным `email`: base64 и
    quoted-printable раскодируются, текстовые части (text/plain, text/html)
    склеиваются, вложения НЕ разбираются, но перечисляются в пометке;
  * JSON — разбирается и разворачивается в строки `путь: значение`, поэтому
    контекст показывает, В КАКОМ поле нашёлся ИНН; битый JSON не роняет разбор,
    а честно уходит в текстовый режим с пометкой;
  * DOCX — это ZIP с XML: читается `word/document.xml` И колонтитулы
    (`header*.xml`, `footer*.xml`), сноски; какие части прочитаны, а какие
    остались непрочитанными, написано в пометке файла;
  * PDF — НЕ поддерживается (stdlib не читает), честная строка «передайте текст»;
  * двоичный файл — «двоичный файл, не текст», без попыток угадать.
Кодировка: UTF-8 (в т.ч. с BOM), при сбое — CP1251 (выгрузки из 1С).

Ложные срабатывания режутся контрольным числом ФНС (`fetch_counterparty.
validate_inn` — импорт, не копия) плюс правилом длины цельного числа:
кандидатом считается ТОЛЬКО максимальный ряд цифр длиной 10 или 12. Поэтому
мимо проходят номер счёта, телефон, расчётный счёт (20 цифр), ОГРН (13/15),
КПП (9), дата, «КПП+ИНН слитно» (19) и случайные 10/12 цифр с неверной
контрольной суммой, а также число, слитое с буквами («7707083893AB» из
колонки «Артикул»; слитный маркер «ИНН7707083893» при этом допускается).
Третье правило — код региона: он должен быть в диапазоне 01…92 либо 99
(межрайонные и иностранные), поэтому «0000000000» (контрольное число сходится!)
и «9326549561» — не ИНН. Отбракованные кандидаты не молчат: их число всегда в
сводке, а `--отбракованные` печатает их списком с причиной — «ничего не
нашли» и «нашли и отбросили» это разные новости.

Разрывы внутри числа («ИНН 7707 083893», неразрывный пробел из вёрстки, мягкий
перенос U+00AD и zero-width space U+200B из Word/HTML, перенос строки)
склеиваются, но по разным правилам — склейка сама по себе порождает ложные ИНН
из соседних чисел таблицы:
  * невидимый разделитель (U+00AD, U+200B/200C/200D, U+2060, BOM) — всегда:
    между двумя РАЗНЫМИ числами такого символа не бывает;
  * видимый пробел — только рядом с маркером «ИНН» (40 символов слева) или
    когда число занимает поле целиком И не выглядит денежной суммой: ячейка
    1С «7 707 083 893» — это рубли, а контрольное число ФНС проходят 10% любых
    десятизначных, поэтому одной контрольной суммы тут мало;
  * перенос строки — только рядом с маркером «ИНН»: соседние строки колонки
    иначе слипались бы в ИНН, которого в документе нет.
Отказ склейки не молчит: кандидат уходит в отбраковку с причиной.

Выход по каждому найденному ИНН: контекст (±80 символов), тип (ЮЛ/ИП по длине),
файл и строка (для HTML/JSON/DOCX — строка ПРИВЕДЁННОГО текста, а не исходной
вёрстки), число вхождений и пометка:
  * `новый` — ни снимка, ни записи в списке наблюдения;
  * `уже проверялся` — есть ЧИТАЕМЫЙ снимок этого ИНН в
    ~/.cache/inn-check-ru/snapshots/<ИНН>/ (`INN_CHECK_CACHE` / `--каталог`)
    или запись в списке наблюдения (`INN_CHECK_WATCHLIST` /
    `--список-наблюдения`);
  * `снимок устарел` — снимок есть, но старше 90 дней: в батч такой ИНН идёт
    наравне с новым, молча исключать его из проверки нельзя.
Пустой файл, битый JSON, снимок с чужим ИНН внутри за проверку не считаются:
оборванный прогон или полный диск не должны выглядеть как «уже проверяли».
Недоступный каталог снимков или нечитаемый список наблюдения — предупреждение
в выводе, а не тихое «все новые».
Пометка — не «этот ИНН безопасен», а «его уже видели»: свежесть снимка стоит
рядом с датой, решение о перепроверке остаётся за человеком.

Флаги:
    --stdin                  читать документ из stdin
    --только-новые           в выводе только те, кого раньше не видели
    --json                   JSON вместо человекочитаемого отчёта
    --отбракованные          показать отброшенных кандидатов с причиной
    --проверить              новые ИНН → batch_check.py --режим quick
    --профиль <id>           профиль цели для --проверить
    --подтверждаю            согласие на батч больше порога (20 ИНН)
    --каталог <путь>         каталог кэша со снимками
    --список-наблюдения <ф>  файл списка наблюдения

`--проверить` дёргает ФНС, поэтому автопрогон ограничен: больше 20 новых ИНН —
батч НЕ запускается без `--подтверждаю` (SKILL.md: «выгрузка на сотни ИНН — не
повод для автопрогона»). Проверенные батчем ИНН попадают в кэш снимков
(`batch_check.py --снимки`), иначе следующий счёт того же поставщика снова
считался бы новым и снова шёл в сеть.

Код возврата: 0 — сделано; 1 — запрошенная работа не состоялась (ни один
документ не разобран; батч не запустился, упал или не сказал ни слова);
2 — ошибка в аргументах.

Сеть не дёргается: без `--проверить` скрипт полностью офлайновый.
"""

