#!/usr/bin/env python3
"""
extract_inn.py — извлечение ИНН из входящего документа (волна 3, задача 7:
«проверка без запроса»). Только стандартная библиотека.

    python3 extract_inn.py счёт.txt договор.html выгрузка.csv
    cat письмо.eml | python3 extract_inn.py --stdin --только-новые
    python3 extract_inn.py счёт.txt --проверить --профиль отсрочка

Зачем. Раньше триггер проверки был один — фраза человека. Теперь: пришёл счёт
от нового ИНН, появился контрагент в выгрузке, договор пришёл на подпись —
ИНН вынимается из текста сам, отсеивается уже проверенное, а новое уходит в
`batch_check.py --режим quick`, и человек узнаёт о 🔴 до оплаты.

Вход: файлы аргументами и/или `--stdin`. Форматы:
  * текст, CSV/TSV — разбираются как текст (разделители колонок учитываются
    только как границы поля, см. «пробелы внутри числа» ниже);
  * HTML — теги снимаются, сущности (`&nbsp;`) раскрываются;
  * JSON — разбирается и разворачивается в строки `путь: значение`, поэтому
    контекст показывает, В КАКОМ поле нашёлся ИНН; битый JSON не роняет разбор,
    а честно уходит в текстовый режим с пометкой;
  * DOCX — это ZIP с XML, текст берётся из `word/document.xml` чистым stdlib;
  * PDF — НЕ поддерживается (stdlib не читает), честная строка «передайте текст»;
  * двоичный файл — «двоичный файл, не текст», без попыток угадать.
Кодировка: UTF-8 (в т.ч. с BOM), при сбое — CP1251 (выгрузки из 1С).

Ложные срабатывания режутся контрольным числом ФНС (`fetch_counterparty.
validate_inn` — импорт, не копия) плюс правилом длины цельного числа:
кандидатом считается ТОЛЬКО максимальный ряд цифр длиной 10 или 12. Поэтому
мимо проходят номер счёта, телефон, расчётный счёт (20 цифр), ОГРН (13/15),
КПП (9), дата, «КПП+ИНН слитно» (19) и случайные 10/12 цифр с неверной
контрольной суммой, а также число, слитое с буквами («7707083893AB» из
колонки «Артикул»; слитный маркер «ИНН7707083893» при этом допускается).
Третье правило — код региона: первые две цифры «00» не
существуют, поэтому «0000000000» (контрольное число сходится!) тоже не ИНН. Отбракованные кандидаты не молчат: их число всегда в
сводке, а `--отбракованные` печатает их списком с причиной — «ничего не
нашли» и «нашли и отбросили» это разные новости.

Пробелы внутри числа («ИНН 7707 083893», неразрывный пробел из вёрстки)
склеиваются, но только когда рядом есть маркер «ИНН» (40 символов до числа)
или число занимает поле целиком (между границами строки/колонки). Без этого
условия склейка сама порождала бы ложные ИНН из соседних чисел в таблице.

Выход по каждому найденному ИНН: контекст (±80 символов), тип (ЮЛ/ИП по длине),
файл и строка (для HTML/JSON/DOCX — строка ПРИВЕДЁННОГО текста, а не исходной
вёрстки), число вхождений и пометка:
  * `новый` — ни снимка, ни записи в списке наблюдения;
  * `уже проверялся` — есть снимок в ~/.cache/inn-check-ru/snapshots/<ИНН>/
    (`INN_CHECK_CACHE` / `--каталог`) или запись в списке наблюдения
    (`INN_CHECK_WATCHLIST` / `--список-наблюдения`).
Пометка — не «этот ИНН безопасен», а «его уже видели»: свежесть снимка стоит
рядом с датой, решение о перепроверке остаётся за человеком.

Флаги:
    --stdin                  читать документ из stdin
    --только-новые           в выводе только те, кого раньше не видели
    --json                   JSON вместо человекочитаемого отчёта
    --отбракованные          показать отброшенных кандидатов с причиной
    --проверить              новые ИНН → batch_check.py --режим quick
    --профиль <id>           профиль цели для --проверить
    --каталог <путь>         каталог кэша со снимками
    --список-наблюдения <ф>  файл списка наблюдения

Сеть не дёргается: без `--проверить` скрипт полностью офлайновый.
"""

