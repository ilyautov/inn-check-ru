def _батч():
    """Путь к батчу. INN_CHECK_EXTRACT_BATCH — шов для офлайн-eval."""
    return (os.environ.get("INN_CHECK_EXTRACT_BATCH")
            or os.path.join(_HERE, "batch_check.py"))


def проверить(инны, профиль=None, json_режим=False, каталог=None,
              подтверждено=False, разобрано=None, порог=ПОРОГ_БАТЧА):
    """Новые ИНН -> batch_check.py --режим quick. Возвращает блок для отчёта.

    Блок всегда отвечает на вопрос «состоялась ли проверка» (`состоялась`), и
    ответ не выводится из факта запуска: батч с кодом 0 и пустым stdout — это
    молчание, а не чистый результат. stderr читается ВСЕГДА, а не только при
    ненулевом коде: батч пишет туда предупреждения о деградации («--продолжить:
    файл не прочитан», «результаты не записаны») ровно с кодом 0.

    Батчу передаётся `--снимки`: без этого каждый следующий счёт того же
    поставщика снова считался бы новым и снова шёл в сеть, а правило «порог —
    новый контрагент» было бы неисполнимо.
    """
    if not инны:
        причина = ("ни один документ не разобран — новых ИНН не могло быть "
                   "найдено, батч не запускался"
                   if разобрано == 0 else
                   "новых ИНН нет — батч не запускался")
        return {"запущен": False, "состоялась": False, "причина": причина}
    if len(инны) > порог and not подтверждено:
        return {"запущен": False, "состоялась": False, "инны": list(инны),
                "порог": порог,
                "причина": ("новых ИНН %d — больше порога %d, батч НЕ запускался: "
                            "это %d запросов к ФНС, а выгрузка на сотни ИНН не "
                            "повод для автопрогона. Нужен прогон — повторите с "
                            "--подтверждаю (или сузьте документ)"
                            % (len(инны), порог, len(инны)))}
    cmd = [sys.executable, _батч()] + list(инны) + ["--режим", "quick", "--снимки"]
    if профиль:
        cmd += ["--профиль", профиль]
    if каталог:
        cmd += ["--каталог", каталог]
    if json_режим:
        cmd += ["--json"]
    try:
        p = subprocess.run(cmd, capture_output=True, text=True,
                           timeout=ТАЙМАУТ_БАТЧА, check=False)
    except subprocess.TimeoutExpired:
        return {"запущен": True, "состоялась": False,
                "причина": "батч не уложился в таймаут %.0f с "
                           "(INN_CHECK_EXTRACT_TIMEOUT)" % ТАЙМАУТ_БАТЧА,
                "инны": list(инны)}
    except (OSError, subprocess.SubprocessError) as e:
        return {"запущен": False, "состоялась": False,
                "причина": "батч не запустился: %s" % e}
    вывод = p.stdout or ""
    блок = {"запущен": True, "код": p.returncode, "инны": list(инны),
            "пусто": not вывод.strip()}
    stderr = (p.stderr or "").strip()
    if stderr:
        блок["stderr"] = stderr[-2000:]
    if json_режим:
        try:
            блок["результат"] = json.loads(вывод)
        except ValueError:
            блок["результат"] = None
            блок["вывод"] = вывод
            блок["причина"] = "батч вернул не JSON"
    else:
        блок["вывод"] = вывод
    блок["состоялась"] = bool(
        p.returncode == 0 and not блок["пусто"]
        and (блок.get("результат") is not None if json_режим else True))
    if not блок["состоялась"] and "причина" not in блок:
        блок["причина"] = ("батч не напечатал ни строки (код %s) — считать это "
                           "проверкой нельзя" % p.returncode if блок["пусто"]
                           else "батч завершился с кодом %s" % p.returncode)
    return блок


def печать_проверки(блок):
    """Блок проверки -> строки отчёта. Молчание батча называется молчанием."""
    строки = []
    if not блок.get("запущен") or not блок.get("состоялась"):
        строки.append("⚠️  Быстрая проверка НЕ состоялась: %s"
                      % (блок.get("причина") or "причина не указана"))
    if блок.get("запущен"):
        строки.append("Быстрая проверка (batch_check.py --режим quick, %d ИНН):"
                      % len(блок.get("инны") or []))
        вывод_батча = (блок.get("вывод") or "").rstrip()
        if вывод_батча:
            строки.append(вывод_батча)
        elif блок.get("пусто"):
            строки.append("  (батч не сказал ни слова — ни таблицы, ни строки "
                          "про 🟢: это не «проверено, чисто»)")
        if блок.get("stderr"):
            строки.append("предупреждения батча (stderr): %s" % блок["stderr"])
        if блок.get("код"):
            строки.append("батч завершился с кодом %d" % блок["код"])
    return строки


# --- CLI --------------------------------------------------------------------------

def _значение(флаг, it):
    """Значение опции. Пропущенное значение — ошибка, а не тихий None:
    `--профиль` без значения уводил батч в профиль «нейтрально», который не
    выносит светофор никогда, и правило «сообщить, если 🔴» гасло целиком."""
    v = next(it, None)
    if v is None or (v.startswith("-") and v != "-"):
        return None, "%s ожидает значение, а его нет" % флаг
    return v, None


def _разобрать_аргументы(argv):
    o = {"файлы": [], "stdin": False, "только_новые": False, "json": False,
         "отбракованные": False, "проверить": False, "профиль": None,
         "каталог": None, "список": None, "подтверждаю": False}
    it = iter(argv[1:])
    for a in it:
        ошибка = None
        if a in ("--помощь", "--help", "-h"):
            return o, "помощь"
        elif a == "--stdin":
            o["stdin"] = True
        elif a in ("--только-новые", "--only-new"):
            o["только_новые"] = True
        elif a == "--json":
            o["json"] = True
        elif a in ("--отбракованные", "--rejected"):
            o["отбракованные"] = True
        elif a in ("--проверить", "--check"):
            o["проверить"] = True
        elif a in ("--подтверждаю", "--yes"):
            o["подтверждаю"] = True
        elif a in ("--профиль", "--profile"):
            o["профиль"], ошибка = _значение(a, it)
        elif a in ("--каталог", "--dir"):
            o["каталог"], ошибка = _значение(a, it)
        elif a in ("--список-наблюдения", "--watchlist"):
            o["список"], ошибка = _значение(a, it)
        elif a.startswith("-"):
            return o, "неизвестный флаг: %s" % a
        else:
            o["файлы"].append(a)
        if ошибка:
            return o, ошибка
    if not o["файлы"] and not o["stdin"]:
        return o, "нужен хотя бы один файл или --stdin"
    return o, None


def main(argv):
    o, ошибка = _разобрать_аргументы(argv)
    if ошибка == "помощь":
        print(__doc__.strip())
        return 0
    if ошибка:
        sys.stderr.write("%s\n\n%s\n" % (ошибка, USAGE))
        return 2

    читаемые, файлы_с_ошибкой = [], []
    for путь in o["файлы"]:
        try:
            with open(путь, "rb") as fh:
                читаемые.append((путь, fh.read()))
        except OSError as e:
            файлы_с_ошибкой.append({"файл": путь, "формат": "—",
                                    "статус": "не прочитан",
                                    "причина": "файл не прочитан (%s)" % e})
    if o["stdin"]:
        читаемые.append(("<stdin>", sys.stdin.buffer.read()))

    результат = собрать(читаемые, o["каталог"], o["список"])
    результат["файлы"] = файлы_с_ошибкой + результат["файлы"]
    результат["итого"]["не_прочитано_документов"] = len(файлы_с_ошибкой)
    результат["итого"]["документов"] += len(файлы_с_ошибкой)
    разобрано = результат["итого"]["разобрано_документов"]

    if o["проверить"]:
        результат["проверка"] = проверить(
            к_проверке(результат), o["профиль"], o["json"], o["каталог"],
            подтверждено=o["подтверждаю"], разобрано=разобрано)

    блок = результат.get("проверка") or {}
    # Код возврата отвечает на вопрос «работа состоялась?»: упавший или вовсе
    # не запустившийся батч снаружи не должен выглядеть как успех.
    код = 0
    if o["проверить"] and not блок.get("состоялась"):
        код = 1
    if результат["итого"]["документов"] and not разобрано:
        код = 1

    if o["json"]:
        вывод = dict(результат)
        if o["только_новые"]:
            вывод["найдено"] = [z for z in вывод["найдено"]
                                if z["статус"] != СТАТУС_ПРОВЕРЯЛСЯ]
        if not o["отбракованные"]:
            вывод.pop("отбракованные", None)
        print(json.dumps(вывод, ensure_ascii=False, indent=2))
    else:
        print(отчёт(результат, o["только_новые"], o["отбракованные"]))
        if блок:
            print()
            print("\n".join(печать_проверки(блок)))
    for f in файлы_с_ошибкой:
        sys.stderr.write("ВНИМАНИЕ: %s\n" % f["причина"])
    for п in результат.get("предупреждения") or []:
        sys.stderr.write("ВНИМАНИЕ: %s\n" % п)
    if o["проверить"] and not блок.get("состоялась"):
        sys.stderr.write("ВНИМАНИЕ: быстрая проверка не состоялась: %s\n"
                         % (блок.get("причина") or "причина не указана"))
    return код


