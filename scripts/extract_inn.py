def собрать(документы, каталог=None, файл_наблюдения=None):
    """documents = [(имя, байты)] -> результат разбора (структура для --json)."""
    файлы, все_найденные, все_отбракованные, причины = [], [], [], {}
    разобрано = 0
    for имя, данные in документы:
        разбор = прочитать_документ(имя, данные)
        строка = {"файл": имя, "формат": разбор["формат"]}
        if разбор["текст"] is None:
            строка["статус"] = "не поддерживается"
            строка["причина"] = разбор["причина"]
            файлы.append(строка)
            continue
        найденные, отбракованные, причины_файла = разобрать_текст(
            разбор["текст"], имя)
        строка["статус"] = "разобран"
        разобрано += 1
        if разбор["причина"]:
            строка["причина"] = разбор["причина"]
        строка["найдено"] = len(найденные)
        строка["отбраковано"] = sum(причины_файла.values())
        файлы.append(строка)
        все_найденные.extend(найденные)
        все_отбракованные.extend(отбракованные)
        for ключ, n in причины_файла.items():
            причины[ключ] = причины.get(ключ, 0) + n

    # дедуп: остаётся первое вхождение, счётчик повторов рядом
    уникальные = {}
    for запись in все_найденные:
        inn = запись["инн"]
        if inn in уникальные:
            уникальные[inn]["вхождений"] += 1
            continue
        запись = dict(запись)
        запись["вхождений"] = 1
        уникальные[inn] = запись

    пометки, предупреждения = известные(list(уникальные), каталог,
                                        файл_наблюдения)
    for inn, запись in уникальные.items():
        пометка = пометки.get(inn) or {}
        запись["статус"] = пометка.get("статус") or СТАТУС_НОВЫЙ
        запись["почему"] = пометка.get("почему")

    найдено = list(уникальные.values())
    новых = [z for z in найдено if z["статус"] == СТАТУС_НОВЫЙ]
    устарели = [z for z in найдено if z["статус"] == СТАТУС_УСТАРЕЛ]
    return {
        "файлы": файлы,
        "предупреждения": предупреждения,
        "найдено": найдено,
        "отбракованные": все_отбракованные,
        "итого": {
            "всего": len(найдено),
            "новых": len(новых),
            "устарели": len(устарели),
            "уже_проверялись": len(найдено) - len(новых) - len(устарели),
            "вхождений": len(все_найденные),
            "отбраковано": sum(причины.values()),
            "причины_отбраковки": причины,
            "документов": len(документы),
            "разобрано_документов": разобрано,
        },
    }


