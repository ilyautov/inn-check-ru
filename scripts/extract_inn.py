тип_контрагента = fetch_counterparty._тип_контрагента

КОНТЕКСТ = 80          # символов слева и справа от найденного ИНН
МАРКЕР_СЛЕВА = 40      # где искать слово «ИНН» перед числом с пробелами
ОТБРАКОВКА_ПОКАЗ = 50      # сколько отброшенных кандидатов печатать
ПРЕДЕЛ_ОТБРАКОВКИ = 500    # сколько отброшенных кандидатов хранить (считаются все)
ТАЙМАУТ_БАТЧА = float(os.environ.get("INN_CHECK_EXTRACT_TIMEOUT", "1800"))

# Пробелы, которые вёрстка и 1С вставляют внутрь числа.
_СЕП = "[     ⁠]"
# Кандидат = максимальный ряд цифр от 9 знаков: короче — шум, не о чем сообщать.
_РЯД = re.compile(r"(?<![0-9])[0-9]{9,}(?![0-9])")
_РЯД_С_ПРОБЕЛАМИ = re.compile(
    r"(?<![0-9])[0-9]{1,11}(?:%s[0-9]{1,11}){1,3}(?![0-9])" % _СЕП)
_МАРКЕР = re.compile(r"инн|inn", re.IGNORECASE)
_БУКВА = re.compile(r"[^\W\d_]", re.UNICODE)
_МАРКЕР_СЛИТНО = re.compile(r"(?:инн|inn)$", re.IGNORECASE)
_ГРАНИЦЫ_ПОЛЯ = set(",;|\t\n\r\"'")
_ПРОБЕЛЫ = re.compile(r"[\s ]+")

