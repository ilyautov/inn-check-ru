_ЗНАЧОК = {СТАТУС_НОВЫЙ: "🆕", СТАТУС_УСТАРЕЛ: "🕒", СТАТУС_ПРОВЕРЯЛСЯ: "✓ "}


def отчёт(результат, только_новые=False, показать_отбракованные=False):
    строки = []
    for f in результат["файлы"]:
        if f["статус"] in ("не поддерживается", "не прочитан"):
            строки.append("⚠️  %s — %s" % (f["файл"], f["причина"]))
        elif f.get("причина"):
            строки.append("• %s — %s, %s" % (f["файл"], f["формат"], f["причина"]))
    for п in результат.get("предупреждения") or []:
        строки.append("⚠️  %s" % п)
    итого = результат["итого"]
    записи = результат["найдено"]
    if только_новые:
        записи = [z for z in записи if z["статус"] != СТАТУС_ПРОВЕРЯЛСЯ]
    сводка = ("Найдено ИНН: %d (новых %d, уже проверялись %d"
              % (итого["всего"], итого["новых"], итого["уже_проверялись"]))
    if итого.get("устарели"):
        сводка += ", снимок устарел %d" % итого["устарели"]
    строки.append(сводка + "). Отбраковано кандидатов: %d." % итого["отбраковано"])
    if итого.get("разобрано_документов") == 0 and итого.get("документов"):
        строки.append("  (ни один документ не разобран — «ИНН не найдено» здесь "
                      "не утверждение о документах)")
    if not записи:
        строки.append("  (в выводе пусто%s)"
                      % (" — новых нет" if только_новые and итого["всего"] else ""))
    for z in записи[:НАХОДКИ_ПОКАЗ]:
        значок = _ЗНАЧОК.get(z["статус"], "• ")
        хвост = "" if z["статус"] == СТАТУС_НОВЫЙ else " — %s" % (z["почему"] or "")
        повтор = "" if z["вхождений"] == 1 else " ×%d" % z["вхождений"]
        строки.append("%s %s — %s — %s%s%s"
                      % (значок, z["инн"], z["тип"], z["статус"], хвост, повтор))
        строки.append("     %s:%d  %s" % (z["источник"], z["строка"], z["контекст"]))
    if len(записи) > НАХОДКИ_ПОКАЗ:
        # Счётчики в сводке полные: обрезается печать, а не подсчёт.
        строки.append("  … и ещё %d ИНН не напечатано (показаны первые %d; "
                      "полный список — --json)"
                      % (len(записи) - НАХОДКИ_ПОКАЗ, НАХОДКИ_ПОКАЗ))
    if показать_отбракованные and результат["отбракованные"]:
        строки.append("")
        строки.append("Отброшено (не ИНН):")
        for z in результат["отбракованные"][:ОТБРАКОВКА_ПОКАЗ]:
            строки.append("  ✗ %s — %s [%s:%d]"
                          % (z["как_записано"].strip(), z["причина"],
                             z["источник"], z["строка"]))
        осталось = итого["отбраковано"] - ОТБРАКОВКА_ПОКАЗ
        if осталось > 0:
            строки.append("  … и ещё %d" % осталось)
    elif результат["итого"]["причины_отбраковки"]:
        строки.append("Причины отбраковки: %s (подробно — --отбракованные)"
                      % ", ".join("%s — %d" % (k, v) for k, v
                                  in sorted(результат["итого"]["причины_отбраковки"].items())))
    return "\n".join(строки)


