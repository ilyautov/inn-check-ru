def _есть_маркер(текст, начало):
    окно = текст[max(0, начало - МАРКЕР_СЛЕВА):начало]
    return bool(_МАРКЕР.search(окно))


def _целое_поле(текст, начало, конец):
    слева = текст[начало - 1] if начало else "\n"
    справа = текст[конец] if конец < len(текст) else "\n"
    return слева in _ГРАНИЦЫ_ПОЛЯ and справа in _ГРАНИЦЫ_ПОЛЯ


# Причины, по которым склейка не разрешена. Это не «мимо» и не «ничего не
# нашли»: такие кандидаты уходят в отбраковку и видны в `--отбракованные`.
ОТКАЗ_СУММА = ("похоже на денежную сумму (разряды по три цифры), "
               "маркера «ИНН» рядом нет")
ОТКАЗ_ПЕРЕНОС = ("число разорвано переносом строки, маркера «ИНН» рядом нет "
                 "(соседние строки колонки не склеиваются)")
ОТКАЗ_СОСЕДИ = ("склейка соседних чисел без маркера «ИНН» и вне границ поля")


def _склейка(текст, m, как):
    """Можно ли считать разорванное число одним ИНН -> (можно, причина отказа).

    Три правила, по убыванию надёжности разделителя:
      * невидимый разделитель (мягкий перенос, zero-width) — всегда можно:
        между двумя разными числами такого символа не бывает;
      * маркер «ИНН» слева — можно при любом разделителе;
      * иначе: перенос строки — нельзя (это две ячейки колонки), пробел —
        можно, только если число занимает поле целиком И не записано как
        денежная сумма («7 707 083 893» в колонке 1С — это рубли; контрольное
        число ФНС проходит каждое десятое случайное десятизначное, поэтому
        охрана склейки и есть то, что отделяет сумму от ИНН).
    """
    разделители = set(re.sub(r"[0-9]", "", как))
    if разделители and разделители <= set(_СЕП_НЕВИДИМЫЙ):
        return True, None
    if _есть_маркер(текст, m.start()):
        return True, None
    if разделители & set(_СЕП_ПЕРЕНОС):
        return False, ОТКАЗ_ПЕРЕНОС
    if not _целое_поле(текст, m.start(), m.end()):
        return False, ОТКАЗ_СОСЕДИ
    if _СУММА.match(как):
        return False, ОТКАЗ_СУММА
    return True, None


def кандидаты(текст):
    """Все места, похожие на ИНН: [(цифры, начало, конец, как_записано, отказ)].

    `отказ` не None — склейка запрещена правилом: кандидат не исчезает, а идёт
    в отбраковку с этой причиной.
    """
    найдено = []
    for m in _РЯД.finditer(текст):
        найдено.append((m.group(), m.start(), m.end(), m.group(), None))
    for m in _РЯД_С_ПРОБЕЛАМИ.finditer(текст):
        цифры = re.sub(r"[^0-9]", "", m.group())
        if len(цифры) not in (10, 12):
            continue
        можно, отказ = _склейка(текст, m, m.group())
        найдено.append((цифры, m.start(), m.end(), m.group(),
                        None if можно else отказ))
    найдено.sort(key=lambda t: t[1])
    return найдено


def контекст(текст, начало, конец):
    """±КОНТЕКСТ символов вокруг находки, пробелы схлопнуты, обрезки — многоточием."""
    слева_от = max(0, начало - КОНТЕКСТ)
    справа_до = min(len(текст), конец + КОНТЕКСТ)
    кусок = _ПРОБЕЛЫ.sub(" ", текст[слева_от:справа_до]).strip()
    if слева_от > 0:
        кусок = "…" + кусок
    if справа_до < len(текст):
        кусок = кусок + "…"
    return кусок


def карта_строк(текст):
    """Смещения переносов строк — чтобы номер строки искался бинарно.

    `текст.count("\n", 0, начало)` на каждого кандидата превращал разбор
    выгрузки в квадратичный: на 2-мегабайтном CSV это десятки секунд.
    """
    return [m.start() for m in re.finditer(r"\n", текст)]


def строка_номер(карта, начало):
    return bisect.bisect_right(карта, начало - 1) + 1


def _границы_ок(текст, начало, конец):
    """Число не слито с буквами — иначе это артикул или серийник, а не ИНН.

    Справа буква запрещена всегда («7707083893AB» из колонки «Артикул»).
    Слева буквы допустимы, только если они и есть маркер («ИНН7707083893»
    без пробела — частая запись в плотных таблицах).
    """
    справа = текст[конец] if конец < len(текст) else " "
    if _БУКВА.match(справа):
        return False
    # Окно, а не весь префикс: `текст[:начало]` копировал документ целиком на
    # КАЖДОГО кандидата — 17-мегабайтная выгрузка разбиралась 141 секунду и
    # съедала 2,5 ГБ. Соседние строки объясняли, почему split по всему тексту
    # недопустим, а срез прямо над ними делал ровно это.
    слева = текст[max(0, начало - МАРКЕР_СЛЕВА):начало]
    if слева and _БУКВА.match(слева[-1]):
        хвост = re.split(r"[^\w]", слева)[-1]
        return bool(_МАРКЕР_СЛИТНО.search(хвост))
    return True


def _код_региона_есть(цифры):
    """Первые две цифры ИНН — код субъекта РФ: 01…92 либо 99 (межрайонные
    инспекции и иностранные организации, 9909…). Кодов «00» и 93…98 не бывает,
    поэтому «0000000000» (контрольное число у него сходится!), «9326549561» и
    «9812859280» — не ИНН, а число из колонки выгрузки. Полная проверка
    префикса снимает около 6% ложных срабатываний, которые контрольное число
    пропускает."""
    код = цифры[:2]
    if not код.isdigit():
        return False
    номер = int(код)
    return 1 <= номер <= 92 or номер == 99


def разобрать_текст(текст, источник, предел=ПРЕДЕЛ_ОТБРАКОВКИ):
    """Текст -> (найденные, отбракованные, причины отбраковки со счётчиками).

    Отбракованные СЧИТАЮТСЯ все, а хранятся первые `предел`: на выгрузке в сотню
    тысяч строк список мусора весил бы больше самого документа. Сводка при этом
    остаётся полной — «нашли и отбросили» видно всегда.
    """
    найденные, отбракованные, причины = [], [], {}
    карта = карта_строк(текст)

    def запись(цифры, как, начало, конец):
        return {"инн": цифры, "как_записано": как, "источник": источник,
                "строка": строка_номер(карта, начало),
                "контекст": контекст(текст, начало, конец)}

    def отбраковать(причина, цифры, как, начало, конец):
        # «не 10 и не 12 цифр (20)» и «(9)» — одна причина: длина.
        ключ = re.sub(r"\s*\(\d+\)$", "", причина)
        причины[ключ] = причины.get(ключ, 0) + 1
        if len(отбракованные) < предел:
            з = запись(цифры, как, начало, конец)
            з["причина"] = причина
            отбракованные.append(з)

    for цифры, начало, конец, как, отказ in кандидаты(текст):
        if len(цифры) not in (10, 12):
            отбраковать("не 10 и не 12 цифр (%d)" % len(цифры),
                        цифры, как, начало, конец)
        elif отказ:
            отбраковать(отказ, цифры, как, начало, конец)
        elif not _границы_ок(текст, начало, конец):
            отбраковать("число слито с буквами (артикул, серийный номер)",
                        цифры, как, начало, конец)
        elif not _код_региона_есть(цифры):
            отбраковать("кода региона %r не существует (бывают 01…92 и 99)"
                        % цифры[:2], цифры, как, начало, конец)
        elif валидный_инн(цифры) is None:
            отбраковать("контрольное число не сошлось (алгоритм ФНС)",
                        цифры, как, начало, конец)
        else:
            з = запись(цифры, как, начало, конец)
            з["тип"] = тип_контрагента(цифры)
            найденные.append(з)
    return найденные, отбракованные, причины


# --- «новый» против «уже проверялся» ------------------------------------------

СТАТУС_НОВЫЙ = "новый"
СТАТУС_ПРОВЕРЯЛСЯ = "уже проверялся"
СТАТУС_УСТАРЕЛ = "снимок устарел"


def _дата_снимка(путь, данные=None):
    """Дата снимка: из содержимого (поле «дата»), иначе из имени файла."""
    if isinstance(данные, dict):
        дата = str(данные.get("дата") or "")
        m = re.match(r"(\d{4}-\d{2}-\d{2})", дата)
        if m:
            return m.group(1)
    имя = os.path.basename(путь)
    m = re.match(r"(\d{4}-\d{2}-\d{2})", имя)
    return m.group(1) if m else имя


def _возраст_дней(дата):
    """Сколько дней снимку. None — дату разобрать не удалось."""
    try:
        когда = time.mktime(time.strptime(дата, "%Y-%m-%d"))
    except (ValueError, OverflowError):
        return None
    return (time.time() - когда) / 86400.0


def _снимки_инн(inn, каталог):
    """Снимки ИНН -> (годные [(дата, путь, данные)], претензии к негодным).

    Файл на диске сам по себе не доказательство проверки: пустой файл после
    обрыва, битый JSON после полного диска и снимок с ЧУЖИМ ИНН внутри — всё
    это раньше давало «уже проверялся», и ИНН молча выпадал из проверки перед
    оплатой. Снимок засчитывается, только если он читается и относится к
    этому ИНН.
    """
    каталог_инн = snapshot.snapshots_dir(inn, каталог)
    try:
        пути = sorted(glob.glob(os.path.join(каталог_инн, "*.json")))
    except OSError as e:
        return [], ["каталог снимков %s не прочитан (%s)" % (каталог_инн, e)]
    годные, претензии = [], []
    for путь in пути:
        данные = snapshot.load(путь)
        имя = os.path.basename(путь)
        if данные is None:
            претензии.append("снимок %s не читается (пустой или битый JSON)" % имя)
            continue
        свой = str(данные.get("инн") or "").strip()
        if свой and свой != str(inn):
            претензии.append("снимок %s — о другом ИНН (%s)" % (имя, свой))
            continue
        if not свой:
            претензии.append("снимок %s без поля «инн» — за проверку не считается"
                             % имя)
            continue
        годные.append((_дата_снимка(путь, данные), путь, данные))
    return годные, претензии


def _пометка_по_снимкам(inn, годные):
    """(статус, пояснение) по годным снимкам ИНН."""
    дата, _путь, данные = годные[-1]
    хвост = "снимок от %s (всего %d)" % (дата, len(годные))
    сбор = данные.get("сбор") if isinstance(данные.get("сбор"), dict) else {}
    режим = сбор.get("режим")
    if режим and режим != "всё":
        # Отпечаток быстрой фазы не видел ФССП, судов и банкротства: «его уже
        # видели» — да, «его проверили целиком» — нет.
        хвост += ", неполный (режим %s)" % режим
    возраст = _возраст_дней(дата)
    if возраст is None:
        return СТАТУС_ПРОВЕРЯЛСЯ, хвост + ", дату снимка разобрать не удалось"
    if возраст > СНИМОК_СВЕЖ_ДНЕЙ:
        return СТАТУС_УСТАРЕЛ, ("%s — это %d дней назад (свежим считается %d), "
                               "идёт в проверку наравне с новым"
                               % (хвост, int(возраст), int(СНИМОК_СВЕЖ_ДНЕЙ)))
    return СТАТУС_ПРОВЕРЯЛСЯ, хвост


def _каталог_снимков_доступен(каталог):
    """Предупреждения о самом каталоге кэша: опечатка в `--каталог` и полный
    отказ доступа не должны выглядеть как «кэш пуст, все ИНН новые»."""
    корень = os.path.join(каталог, "snapshots")
    if not os.path.exists(корень):
        return ["каталога снимков нет: %s — сравнивать не с чем, все ИНН "
                "считаются новыми (опечатка в --каталог выглядит так же)" % корень]
    if not os.path.isdir(корень):
        return ["%s — не каталог: снимки не читаются, все ИНН считаются новыми"
                % корень]
    if not os.access(корень, os.R_OK | os.X_OK):
        return ["нет прав на чтение каталога снимков %s — все ИНН считаются "
                "новыми" % корень]
    return []


def _список_наблюдения(файл_наблюдения):
    """({инн: запись}, предупреждения). Битый и недоступный список — не пустой."""
    путь = watchlist.путь_файла(файл_наблюдения)
    явный = bool(файл_наблюдения or os.environ.get("INN_CHECK_WATCHLIST"))
    try:
        with open(путь, encoding="utf-8") as fh:
            данные = json.load(fh)
    except FileNotFoundError:
        if явный:
            return {}, ["списка наблюдения нет: %s — записи о наблюдении "
                        "не учитываются" % путь]
        return {}, []
    except (OSError, ValueError, UnicodeDecodeError) as e:
        return {}, ["список наблюдения не прочитан: %s (%s) — записи о "
                    "наблюдении не учитываются, ИНН из него будут показаны "
                    "как новые" % (путь, e)]
    контрагенты = данные.get("контрагенты") if isinstance(данные, dict) else None
    if not isinstance(контрагенты, list):
        return {}, ["список наблюдения %s не распознан (нет списка "
                    "«контрагенты») — записи о наблюдении не учитываются" % путь]
    return ({str(з.get("инн")): з for з in контрагенты if isinstance(з, dict)},
            [])


def известные(инны, каталог=None, файл_наблюдения=None):
    """ИНН -> пометка о прошлых проверках.

    -> ({инн: {"статус": …, "почему": …}}, предупреждения). Отсутствие ИНН в
    словаре значит «новый». Предупреждения — обо всём, что помешало ответить
    на вопрос «видели ли мы его раньше»: недоступный кэш, битый список
    наблюдения, нечитаемый снимок. Молчание здесь и есть тихая деградация:
    «новых 2, предупреждений 0» на несуществующем каталоге неотличимо от
    честного пустого кэша.
    """
    каталог = watchlist.каталог_кэша(каталог)
    предупреждения = list(_каталог_снимков_доступен(каталог))
    итог = {}
    for inn in инны:
        годные, претензии = _снимки_инн(inn, каталог)
        предупреждения += ["ИНН %s: %s" % (inn, п) for п in претензии]
        if годные:
            статус, почему = _пометка_по_снимкам(inn, годные)
            итог[inn] = {"статус": статус, "почему": почему}
        elif претензии:
            предупреждения.append(
                "ИНН %s: снимки есть, но ни один не засчитан — считаем новым"
                % inn)
    наблюдаемые, жалобы = _список_наблюдения(файл_наблюдения)
    предупреждения += жалобы
    for inn in инны:
        if inn not in наблюдаемые:
            continue
        хвост = "в списке наблюдения"
        профиль = наблюдаемые[inn].get("профиль")
        if профиль:
            хвост += " (профиль %s)" % профиль
        было = итог.get(inn)
        if было:
            было["почему"] = "%s; %s" % (было["почему"], хвост)
            # запись в списке наблюдения свежести снимку не добавляет, но и
            # «устарел» не отменяет: мониторинг — отдельная петля
        else:
            итог[inn] = {"статус": СТАТУС_ПРОВЕРЯЛСЯ, "почему": хвост}
    return итог, предупреждения


