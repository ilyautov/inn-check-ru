# --- чтение и приведение к тексту --------------------------------------------

def _декодировать(данные):
    """Байты -> (текст, кодировка). UTF-8 (с BOM), иначе CP1251 (выгрузки 1С)."""
    for кодировка in ("utf-8-sig", "cp1251"):
        try:
            return данные.decode(кодировка), кодировка
        except UnicodeDecodeError:
            continue
    return данные.decode("utf-8", "replace"), "utf-8 (с потерями)"


# Байты, которых в тексте не бывает: управляющие, кроме tab/LF/CR/FF и ESC.
_УПРАВЛЯЮЩИЕ = bytes(b for b in range(32) if b not in (9, 10, 12, 13, 27)) + b"\x7f"


def _похоже_на_двоичный(данные):
    """Нулевой байт или больше 5% управляющих в начале файла — это не текст.

    Только по `\x00` судить нельзя: короткий бинарник (обрезанный PDF, картинка,
    дамп) нулей может не содержать, но «разобрать как cp1251» и промолчать —
    ровно тот случай, когда инструмент делает вид, что прочитал документ.
    """
    голова = данные[:4096]
    if not голова:
        return False
    if b"\x00" in голова:
        return True
    плохих = sum(голова.count(bytes([b])) for b in _УПРАВЛЯЮЩИЕ)
    return плохих > len(голова) * 0.05


# Атрибуты, в которых лежит значение, а не оформление: сохранённая карточка
# ЕГРЮЛ и веб-1С кладут ИНН именно в них — в `value`, `data-inn`, `title`.
_ЗНАЧИМЫЕ_АТРИБУТЫ = ("value", "title", "alt", "placeholder", "content",
                      "href", "aria-label", "label", "summary")
_АТРИБУТ = re.compile(
    r"""([A-Za-z_:][-\w:.]*)\s*=\s*("([^"]*)"|'([^']*)'|([^\s"'>`=]+))""")


def _значимые_атрибуты(тег):
    """Значения атрибутов тега, которые несут данные, а не вёрстку."""
    куски = []
    for m in _АТРИБУТ.finditer(тег):
        имя = m.group(1).lower()
        if имя in _ЗНАЧИМЫЕ_АТРИБУТЫ or имя.startswith("data-"):
            значение = (m.group(3) if m.group(3) is not None else
                        m.group(4) if m.group(4) is not None else
                        m.group(5) or "")
            if значение.strip():
                куски.append("%s=%s" % (имя, значение.strip()))
    return куски


def текст_из_html(text):
    """HTML -> текст: скрипты/стили вон, теги в пробел, значимые атрибуты
    остаются, сущности раскрываются.

    Атрибуты вынимаются намеренно: `re.sub("<[^>]+>", " ")` срезает `value` и
    `data-inn` вместе с тегом, и сохранённая карточка ЕГРЮЛ даёт «Найдено ИНН:
    0» при нуле отбракованных — то есть выглядит как документ без ИНН.
    """
    text = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", " ", text)
    text = re.sub(r"(?i)<(br|/p|/tr|/div|/h[1-6])[^>]*>", "\n", text)

    def _тег(m):
        куски = _значимые_атрибуты(m.group())
        return " %s " % " ".join(куски) if куски else " "

    text = re.sub(r"(?s)<[^>]+>", _тег, text)
    return _html.unescape(text)


def текст_из_json(данные, путь=""):
    """JSON -> строки «путь: значение»: контекст показывает поле, а не голое число."""
    строки = []

    def обойти(узел, путь):
        if isinstance(узел, dict):
            for k, v in узел.items():
                обойти(v, "%s.%s" % (путь, k) if путь else str(k))
        elif isinstance(узел, list):
            for i, v in enumerate(узел):
                обойти(v, "%s[%d]" % (путь, i))
        elif узел is not None and not isinstance(узел, bool):
            строки.append("%s: %s" % (путь or "значение", узел))

    обойти(данные, путь)
    return "\n".join(строки)


# Части DOCX, в которых бывает текст контрагента. Колонтитул — не экзотика:
# в счёте из 1С реквизиты поставщика часто стоят именно в footer1.xml, и читать
# один document.xml значило бы терять ИНН без единого слова об этом.
_ЧАСТИ_DOCX = re.compile(
    r"(?i)^word/(document\d*|header\d*|footer\d*|footnotes|endnotes|comments)\.xml$")
# Служебная разметка: стилей и нумерации в отчёте ждать нечего, молчать о них
# не обман.
_СЛУЖЕБНЫЕ_DOCX = re.compile(
    r"(?i)^(\[content_types\]\.xml|_rels/.*|docprops/.*|customxml/.*"
    r"|word/_rels/.*|word/media/.*|word/theme/.*"
    r"|word/(styles|stylesWithEffects|settings|webSettings|fontTable|numbering"
    r"|people|commentsExtended|commentsIds)\.xml)$")


def _текст_из_xml(xml):
    xml = re.sub(r"(?i)</w:p>", "\n", xml)
    xml = re.sub(r"(?i)<w:tab[^>]*/>", "\t", xml)
    xml = re.sub(r"(?i)<w:br[^>]*/>", "\n", xml)
    xml = re.sub(r"(?s)<[^>]+>", "", xml)
    return _html.unescape(xml)


def текст_из_docx(данные):
    """DOCX -> (текст, прочитанные части, непрочитанные части).

    Это ZIP с XML, stdlib его открывает. Читается тело И колонтитулы со
    сносками; всё, что осталось непрочитанным, возвращается списком —
    имена файлов архива уже в руках, промолчать о них стоило бы дороже.
    """
    прочитано, пропущено, куски = [], [], []
    with zipfile.ZipFile(io.BytesIO(данные)) as z:
        имена = sorted(z.namelist(),
                       key=lambda и: (not и.lower().startswith("word/document"), и))
        for имя in имена:
            if _ЧАСТИ_DOCX.match(имя):
                try:
                    xml = z.read(имя).decode("utf-8", "replace")
                except (KeyError, OSError, RuntimeError, zipfile.BadZipFile) as e:
                    пропущено.append("%s (%s)" % (имя, e))
                    continue
                текст = _текст_из_xml(xml)
                if текст.strip():
                    куски.append(текст)
                прочитано.append(имя)
            elif имя.lower().endswith(".xml") and not _СЛУЖЕБНЫЕ_DOCX.match(имя):
                пропущено.append(имя)
    return "\n".join(куски), прочитано, пропущено


# Заголовки, по которым текст опознаётся как письмо. Двух достаточно: одинокое
# «Subject:» бывает и в обычной заметке.
_ЗАГОЛОВКИ_ПИСЬМА = frozenset((
    "from", "to", "cc", "bcc", "subject", "date", "message-id", "mime-version",
    "content-type", "content-transfer-encoding", "received", "return-path",
    "delivered-to", "reply-to", "sender", "x-mailer"))
_ЗАГОЛОВОК = re.compile(r"([A-Za-z][A-Za-z0-9-]*)[ \t]*:")


def _похоже_на_письмо(имя, данные):
    """Письмо (RFC 822/MIME)? По расширению либо по шапке из заголовков."""
    if os.path.splitext(имя or "")[1].lower() in (".eml", ".mht", ".mhtml", ".msg"):
        return True
    голова = данные[:8192].decode("latin-1", "replace")
    найдено = set()
    # split("\n"), а не splitlines(): кириллица в заголовке From, прочитанная
    # как latin-1, содержит байт 0x85 (NEL), и splitlines рвёт по нему строку —
    # письмо переставало опознаваться письмом.
    for строка in голова.split("\n")[:60]:
        строка = строка.rstrip("\r")
        if not строка.strip():
            break
        m = _ЗАГОЛОВОК.match(строка)
        if m:
            найдено.add(m.group(1).lower())
        elif not строка[:1].isspace():
            return False   # не заголовок и не его продолжение — это просто текст
    return len(найдено & _ЗАГОЛОВКИ_ПИСЬМА) >= 2


def _текст_части(часть):
    """Тело MIME-части текстом: base64/quoted-printable уже раскодированы."""
    сырые = часть.get_payload(decode=True)
    if сырые is None:                      # не удалось раскодировать
        значение = часть.get_payload()
        return значение if isinstance(значение, str) else None
    кодировка = часть.get_content_charset()
    if кодировка:
        try:
            return сырые.decode(кодировка, "replace")
        except (LookupError, UnicodeDecodeError):
            pass
    return _декодировать(сырые)[0]


def _шапка_письма(msg):
    """From/To/Subject человекочитаемо: ИНН бывает и в теме письма."""
    строки = []
    for поле in ("From", "To", "Subject"):
        значение = msg.get(поле)
        if not значение:
            continue
        try:
            значение = str(email.header.make_header(
                email.header.decode_header(значение)))
        except (ValueError, UnicodeDecodeError, LookupError):
            pass
        строки.append("%s: %s" % (поле, значение))
    return строки


def текст_из_письма(данные):
    """Письмо -> (текст, пометка). Разбор — стандартным `email`.

    Тело в base64 — чистый ASCII: под двоичный детектор оно не попадает, а без
    разбора MIME даёт «Найдено ИНН: 0» при живых ИНН внутри. Quoted-printable
    с мягким переносом (`=\n` посреди числа) раскодируется там же.

    Вложения (PDF, DOCX, картинки) НЕ разбираются — и не замалчиваются: их
    имена уходят в пометку, иначе «в письме ИНН нет» читалось бы как факт,
    когда ИНН лежит в приложенном счёте.
    """
    msg = email.message_from_bytes(данные, policy=email.policy.compat32)
    куски = _шапка_письма(msg)
    текстовых, вложения, сбои = 0, [], []
    части = list(msg.walk()) if msg.is_multipart() else [msg]
    for часть in части:
        if часть.get_content_maintype() == "multipart":
            continue
        тип = (часть.get_content_type() or "").lower()
        имя_вложения = None
        try:
            имя_вложения = часть.get_filename()
        except (TypeError, ValueError, UnicodeDecodeError):
            имя_вложения = "без имени"
        расположение = str(часть.get("Content-Disposition") or "").lower()
        if имя_вложения or расположение.startswith("attachment") \
                or тип not in ("text/plain", "text/html"):
            вложения.append("%s (%s)" % (имя_вложения or "без имени", тип or "?"))
            continue
        try:
            тело = _текст_части(часть)
        except Exception as e:      # битая кодировка вложения не роняет письмо
            сбои.append("%s: %s" % (тип, type(e).__name__))
            continue
        if not тело:
            continue
        куски.append(текст_из_html(тело) if тип == "text/html" else тело)
        текстовых += 1
    пометки = ["письмо (MIME): текстовых частей %d" % текстовых]
    if not текстовых:
        пометки.append("ни одной текстовой части не разобрано — "
                       "в разбор ушли только заголовки")
    if вложения:
        пометки.append("вложения НЕ разбираются (%d): %s"
                       % (len(вложения), ", ".join(вложения[:5])
                          + ("…" if len(вложения) > 5 else "")))
    if сбои:
        пометки.append("части не раскодированы: %s" % "; ".join(сбои[:3]))
    return "\n".join(куски), "; ".join(пометки)


def _формат_по_содержимому(имя, текст):
    расш = os.path.splitext(имя or "")[1].lower()
    голова = текст[:2048].lstrip()
    if расш in (".eml", ".mht", ".mhtml", ".msg"):
        return "письмо"
    if расш in (".json",) or голова[:1] in ("{", "["):
        return "json"
    if расш in (".html", ".htm", ".xhtml"):
        return "html"
    if re.search(r"(?i)<(!doctype html|html|table|td|tr|body|div|p)\b", голова):
        return "html"
    if расш in (".csv", ".tsv"):
        return "csv"
    return "текст"


def прочитать_документ(имя, данные):
    """Байты документа -> {формат, текст, причина}. Текст None — разбор невозможен."""
    if данные[:4] == b"%PDF":
        return {"формат": "pdf", "текст": None,
                "причина": "PDF не поддерживается (stdlib его не читает) — "
                           "передайте текст: скопируйте содержимое счёта или "
                           "сохраните как .txt"}
    if данные[:4] == b"PK\x03\x04":
        try:
            with zipfile.ZipFile(io.BytesIO(данные)) as z:
                имена = z.namelist()
        except zipfile.BadZipFile as e:
            return {"формат": "архив", "текст": None,
                    "причина": "битый ZIP (%s)" % e}
        if "word/document.xml" in имена:
            try:
                текст, прочитано, пропущено = текст_из_docx(данные)
            except (KeyError, zipfile.BadZipFile, OSError, RuntimeError) as e:
                return {"формат": "docx", "текст": None,
                        "причина": "DOCX не разобран (%s) — передайте текст" % e}
            пометки = ["прочитаны части: %s" % ", ".join(прочитано)]
            if пропущено:
                пометки.append("НЕ читались: %s" % ", ".join(пропущено[:8])
                               + ("…" if len(пропущено) > 8 else ""))
            return {"формат": "docx", "текст": текст, "причина": "; ".join(пометки)}
        return {"формат": "архив", "текст": None,
                "причина": "ZIP-архив без word/document.xml не поддерживается"}
    if _похоже_на_двоичный(данные):
        return {"формат": "двоичный", "текст": None,
                "причина": "двоичный файл, не текст — передайте текст"}
    if _похоже_на_письмо(имя, данные):
        try:
            текст, пометка = текст_из_письма(данные)
        except Exception as e:   # письмо не роняет разбор остальных документов
            return {"формат": "письмо", "текст": None,
                    "причина": "письмо не разобрано (%s: %s) — передайте текст"
                               % (type(e).__name__, e)}
        return {"формат": "письмо", "текст": текст, "причина": пометка}
    текст, кодировка = _декодировать(данные)
    формат = _формат_по_содержимому(имя, текст)
    причина = None if кодировка.startswith("utf-8") and "потер" not in кодировка \
        else "кодировка: %s" % кодировка
    if формат == "json":
        try:
            разобрано = json.loads(текст)
        except ValueError as e:
            return {"формат": "json (битый)", "текст": текст,
                    "причина": "битый JSON (%s) — разобран как текст" % e}
        return {"формат": "json", "текст": текст_из_json(разобрано),
                "причина": причина}
    if формат == "html":
        return {"формат": "html", "текст": текст_из_html(текст), "причина": причина}
    return {"формат": формат, "текст": текст, "причина": причина}


