import datetime as dt
import html
import io
import json
import os
import re
import shutil
import sys
import tempfile
import threading
import zipfile
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_tools

CACHE_DIR = os.path.expanduser(os.path.join("~", ".cache", "inn-check-ru", "erknm"))
CACHE_DIR_ВИДИМЫЙ = "~/.cache/inn-check-ru/erknm"
МАНИФЕСТ = "манифест.json.gz"
МЕСЯЦЫ_ПАПКА = "месяцы"
САЙТ = "https://proverki.gov.ru"
СТРАНИЦА = САЙТ + "/portal/public-open-data"
API = САЙТ + "/public/api/opendata"
МЕСЯЦЕВ = 12
ФОРМАТ_МЕСЯЦА = 1
ОСЕЛ_ДНЕЙ = 45              # столько после конца месяца выгрузка ещё дописывается
ПЕРЕПРОВЕРКА_ДНЕЙ = 180     # устоявшийся месяц всё равно перекачивается раз в полгода
ПУЛЬС_СЕКУНД = 300
СВЕЖЕСТЬ_ДНЕЙ = 40          # от последней выгрузки в индексе
ЛИМИТ_ZIP = 2 << 30
ЛИМИТ_XML = 16 << 30
ЛИМИТ_ПАСПОРТА = 5 << 20
ДОЛЯ_БИТЫХ = 0.01
ДОЛЯ_ИЗВЕСТНЫХ_СТАТУСОВ = 0.9
КОНТРОЛЬ_СИМВОЛОВ = 160
ЧАСТЕЙ = 256
ПОКАЗАТЬ = 20
# статусы, встреченные в выгрузке сентября 2026; незнакомый статус сохраняется
# как есть, но если таких больше 10 % — формат сменился
СТАТУСЫ = {"завершено", "предостережение объявлено", "ожидает проведения",
           "ожидает завершения", "не может быть проведено", "есть возражение",
           "отказ в проведении", "в процессе заполнения", "отменено"}
_ИМЯ_ZIP = re.compile(r"data-(\d{8})-structure-(\d{8})\.zip")


def _дата(s):
    """«2026-09-04» -> та же строка, если это настоящая дата; иначе None."""
    try:
        return dt.date.fromisoformat(s).isoformat() if s and len(s) == 10 else None
    except ValueError:
        return None


def месяцы_к_скачиванию(список, сегодня, месяцев):
    """Ответ /opendata/list -> [(год, месяц)] от свежего к старому, не позже
    текущего месяца (в списке бывают будущие месяцы — план)."""
    годы = список.get("months")
    if not isinstance(годы, dict) or not годы:
        raise ValueError("схема: в списке открытых данных нет месяцев")
    сейчас = dt.date.fromisoformat(сегодня)
    out = []
    for год, мес in годы.items():
        for м in мес:
            if not (str(год).isdigit() and isinstance(м, int) and 1 <= м <= 12):
                raise ValueError("схема: месяц %r/%r" % (год, м))
            if (int(год), м) <= (сейчас.year, сейчас.month):
                out.append((int(год), м))
    return sorted(out, reverse=True)[:месяцев]


def выгрузка_месяца(паспорт, год, месяц):
    """Паспорт месяца -> (url ZIP, дата выгрузки ISO). URL — только proverki.gov.ru."""
    url, имя = паспорт.get("dataZipUrl") or "", паспорт.get("dataZipName") or ""
    m = _ИМЯ_ZIP.fullmatch(имя)
    if not m or not url.endswith("/" + имя):
        raise ValueError("схема: паспорт %d/%d без ZIP (%r)" % (год, месяц, имя[:60]))
    if not re.match(r"https://proverki\.gov\.ru/+blob/erknm-opendata/%d/%d/" % (год, месяц), url):
        raise ValueError("схема: ZIP %d/%d не на proverki.gov.ru (%r)" % (год, месяц, url[:80]))
    д = m.group(1)
    return url, "%s-%s-%s" % (д[:4], д[4:6], д[6:])


# «>» в значении атрибута XML не экранируется: тег — это имя и пары имя="…",
# а не «всё до первого >» (ревью Codex: NAME="А > Б" обрывал SUBJECT)
_АТРИБУТЫ = r'((?:\s+[\w:.-]+\s*=\s*"[^"]*")*)\s*/?>'


def _теги(тело, элемент):
    """Все открывающие теги элемента -> строки атрибутов; тег, который не
    разобрался (одинарные кавычки и т. п.), — ValueError, а не пропуск."""
    найдено = re.findall(r"<%s\b%s" % (элемент, _АТРИБУТЫ), тело)
    if len(найдено) != len(re.findall(r"<%s\b" % элемент, тело)):
        raise ValueError("тег %s не разобран" % элемент)
    return найдено


def _атрибут(тег, имя):
    m = re.search(r'(?:^|\s)%s\s*=\s*"([^"]*)"' % имя, тег)
    return html.unescape(m.group(1)).strip() if m else ""


def _значение(тело, элемент):
    теги = _теги(тело, элемент)
    return _атрибут(теги[0], "VALUE") if теги else ""


def мероприятия_xml(куски, год, месяц):
    """Текстовые куски XML -> тела <INSPECTION …>…</INSPECTION>. Проверяет корень
    (год и месяц) и закрывающий тег — без него выгрузка оборвана."""
    хвост, корень = "", False
    for кусок in куски:
        хвост += кусок
        if not корень:
            m = re.search(r"<(?:\w+:)?INSPECTIONS\b" + _АТРИБУТЫ, хвост)
            if not m:
                if len(хвост) > 1 << 20:
                    raise ValueError("схема: нет корня INSPECTIONS")
                continue
            if (_атрибут(m.group(0), "YEAR"), _атрибут(m.group(0), "MONTH")) != (str(год), str(месяц)):
                raise ValueError("схема: в выгрузке %d/%d корень %r" % (год, месяц, m.group(0)[:120]))
            корень, хвост = True, хвост[m.end():]
        части = хвост.split("</INSPECTION>")
        хвост = части.pop()
        for ч in части:
            начало = ч.rfind("<INSPECTION ")
            if начало < 0:
                raise ValueError("схема: </INSPECTION> без <INSPECTION>")
            yield ч[начало:]
        if len(хвост) > 10 << 20:
            raise ValueError("схема: мероприятие больше 10 МБ — не тот формат")
    if not re.fullmatch(r"\s*</(?:\w+:)?INSPECTIONS>\s*", хвост):
        raise ValueError("обрыв: нет закрывающего INSPECTIONS")


def разобрать(мероприятия):
    """-> (записи, всего, битых, без_субъекта). Запись: [erpid, класс, вид, тип,
    статус, начало, окончание, орган, контроль, риск, уровень, [инн…]]."""
    записи, всего, битых, без_субъекта, известных = [], 0, 0, 0, 0
    for тело in мероприятия:
        всего += 1
        try:
            шапка = _теги(тело, "INSPECTION")[0]
            субъекты = _теги(тело, "SUBJECT")
            вид, орган = _значение(тело, "KIND_KNM"), _значение(тело, "KNO_ORGANIZATION")
            контроль, риск = _значение(тело, "KIND_CONTROL"), _значение(тело, "RISK_CATEGORY")
        except (ValueError, IndexError):
            битых += 1
            continue
        erpid, класс = _атрибут(шапка, "ERPID"), _атрибут(шапка, "CLASSIFICATION")
        статус = _атрибут(шапка, "STATUS").lower()
        if not (re.fullmatch(r"\d{10,30}", erpid) and класс in ("КНМ", "ПМ") and статус):
            битых += 1
            continue
        if статус in СТАТУСЫ:
            известных += 1
        инн = []
        for субъект in субъекты:
            и = _атрибут(субъект, "INN")
            if _атрибут(субъект, "TYPE") != "ФЛ" and re.fullmatch(r"\d{10}|\d{12}", и) and и not in инн:
                инн.append(и)
        if not инн:
            без_субъекта += 1
            continue
        контроль = " ".join(контроль.split())
        if len(контроль) > КОНТРОЛЬ_СИМВОЛОВ:
            контроль = контроль[:КОНТРОЛЬ_СИМВОЛОВ - 1] + "…"
        записи.append([erpid, класс, вид, _атрибут(шапка, "TYPE_NAME"),
                       статус, _дата(_атрибут(шапка, "START_DATE")),
                       _дата(_атрибут(шапка, "STOP_DATE")), " ".join(орган.split()), контроль,
                       риск.lower(),
                       _атрибут(шапка, "KO_LEVEL").lower(), инн])
    if not всего:
        raise ValueError("схема: в выгрузке нет мероприятий")
    if битых > всего * ДОЛЯ_БИТЫХ:
        raise ValueError("схема: %d мероприятий из %d без номера, класса или статуса"
                         % (битых, всего))
    if известных < (всего - битых) * ДОЛЯ_ИЗВЕСТНЫХ_СТАТУСОВ:
        raise ValueError("схема: известных статусов %d из %d" % (известных, всего - битых))
    return записи, всего, битых, без_субъекта


def разобрать_zip(путь, год, месяц):
    with zipfile.ZipFile(путь) as z:
        имена = [и for и in z.namelist() if и.lower().endswith(".xml")]
        if len(имена) != 1 or len(z.namelist()) != 1:
            raise ValueError("схема: в архиве %d файлов вместо одного XML" % len(z.namelist()))
        if z.getinfo(имена[0]).file_size > ЛИМИТ_XML:
            raise ValueError("схема: XML больше лимита")
        with z.open(имена[0]) as сырой:
            текст = io.TextIOWrapper(сырой, encoding="utf-8-sig")

            def куски():
                while True:
                    к = текст.read(8 << 20)
                    if not к:
                        return
                    yield к
            записи, всего, битых, без = разобрать(мероприятия_xml(куски(), год, месяц))
    return {"записи": записи, "всего": всего, "битых": битых, "без_субъекта": без}


# --- индекс -----------------------------------------------------------------

def часть(инн):
    return "%02x" % (zlib.crc32(str(инн).encode()) % ЧАСТЕЙ)


def _путь_месяца(cache_dir, год, месяц):
    return os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА, "%04d-%02d.json.gz" % (год, месяц))


def конец_месяца(год, месяц):
    return dt.date(год, месяц, calendar.monthrange(год, месяц)[1]).isoformat()


def осел(год, месяц, выгрузка, сегодня):
    """Выгрузка сделана через ОСЕЛ_ДНЕЙ после конца месяца — не перекачиваем; но
    раз в ПЕРЕПРОВЕРКА_ДНЕЙ качаем и такой месяц: портал может поправить старое."""
    return (dump_tools.старше(конец_месяца(год, месяц), выгрузка, ОСЕЛ_ДНЕЙ - 1)
            and not dump_tools.старше(выгрузка, сегодня, ПЕРЕПРОВЕРКА_ДНЕЙ))


def собрать(файлы):
    """[(год, месяц, путь к разобранному месяцу)] -> (словарь строк, {часть: {инн:
    [строки]}}, мероприятий). Месяцы читаются по одному (год выгрузок в память
    целиком не поместился бы); строка — «номер|класс|коды…|даты|уровень»,
    повторяющиеся тексты — коды в словаре. Мероприятие на стыке месяцев — из
    свежего."""
    словарь, коды, части, видели = [], {}, {}, set()

    def код(т):
        if т not in коды:
            коды[т] = len(словарь)
            словарь.append(т)
        return str(коды[т])
    for _, _, файл in sorted(файлы, reverse=True):
        for з in dump_tools.прочитать_индекс(файл)["записи"]:
            if з[0] in видели:
                continue
            видели.add(з[0])
            строка = "|".join([з[0], з[1], код(з[2]), код(з[3]), код(з[4]), з[5] or "",
                               з[6] or "", код(з[7]), код(з[8]), код(з[9]), з[10]])
            for инн in з[11]:
                части.setdefault(часть(инн), {}).setdefault(инн, []).append(строка)
    return словарь, части, len(видели)


def _записать_части(cache_dir, словарь, части, манифест):
    """Новая папка частей, потом манифест атомарно — чтение не увидит половину.
    Предыдущее поколение остаётся: читатель, успевший взять старый манифест,
    дочитает свою часть (ревью Codex); удаляются только более старые."""
    папка = tempfile.mkdtemp(dir=cache_dir, prefix="индекс-")
    try:
        for ч in ("%02x" % i for i in range(ЧАСТЕЙ)):
            dump_tools.записать_индекс(os.path.join(папка, ч + ".json.gz"), части.get(ч, {}))
        dump_tools.записать_индекс(os.path.join(папка, "словарь.json.gz"), словарь)
        манифест["папка"] = os.path.basename(папка)
        путь = os.path.join(cache_dir, МАНИФЕСТ)
        try:
            прежняя = dump_tools.прочитать_индекс(путь)["папка"]
        except Exception:
            прежняя = None
        dump_tools.записать_индекс(путь, манифест)
    except BaseException:
        shutil.rmtree(папка, ignore_errors=True)
        raise
    for имя in os.listdir(cache_dir):
        if имя.startswith("индекс-") and имя not in (манифест["папка"], прежняя):
            shutil.rmtree(os.path.join(cache_dir, имя), ignore_errors=True)


class _Пульс:
    """Пока идёт refresh, раз в ПУЛЬС_СЕКУНД трогает файл блокировки: скачивание
    месяца на медленной сети идёт дольше, чем живёт блокировка dump_tools."""

    def __init__(self, путь):
        self.путь, self.стоп = путь, threading.Event()
        self.поток = threading.Thread(target=self._бить, daemon=True)

    def _бить(self):
        while not self.стоп.wait(ПУЛЬС_СЕКУНД):
            try:
                os.utime(self.путь)
            except OSError:
                return

    def __enter__(self):
        self.поток.start()
        return self

    def __exit__(self, *exc):
        self.стоп.set()
        self.поток.join()


def refresh(cache_dir=None, get=None, сегодня=None, месяцев=МЕСЯЦЕВ):
    """Качает недостающие и неустоявшиеся месяцы, пересобирает индекс; сбой —
    старый индекс цел. get(url, referer, лимит, в_файл=None) — для тестов."""
    cache_dir = cache_dir or CACHE_DIR
    os.makedirs(os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА), exist_ok=True)
    сегодня = сегодня or dump_tools.сегодня()
    if get is None:
        try:
            op = dump_tools.opener()
        except ValueError as e:
            return {"статус": "индекс не обновлён: %s" % e}

        def get(url, referer, лимит, в_файл=None):
            return dump_tools.get(url, referer, лимит, timeout=900, в_файл=в_файл, op=op)
    try:
        блок = dump_tools.Блокировка(cache_dir).__enter__()
    except FileExistsError:
        return {"статус": "индекс не обновлён: другой refresh уже идёт"}
    try:
        with _Пульс(блок.путь):
            return _refresh(cache_dir, get, сегодня, месяцев)
    finally:
        блок.__exit__(None, None, None)


def _refresh(cache_dir, get, сегодня, месяцев):
    файлы, выгрузки, нужные, скачано = [], [], set(), 0
    try:
        список = json.loads(get(API + "/list?isFederalLaw248=true", СТРАНИЦА, ЛИМИТ_ПАСПОРТА))
        for год, мес in месяцы_к_скачиванию(список, сегодня, месяцев):
            файл = _путь_месяца(cache_dir, год, мес)
            нужные.add(os.path.basename(файл))
            м = dump_tools.прочитать_индекс(файл) if os.path.exists(файл) else None
            if м is not None and м.get("формат") != ФОРМАТ_МЕСЯЦА:
                м = None
            if м is None or not осел(год, мес, м["выгрузка"], сегодня):
                страница = "%s/check/%d/%d?isFederalLaw248=true" % (СТРАНИЦА, год, мес)
                url, выгрузка = выгрузка_месяца(json.loads(get(
                    "%s/%d/%d?isFederalLaw248=true" % (API, год, мес), страница,
                    ЛИМИТ_ПАСПОРТА)), год, мес)
                if м is None or м.get("url") != url:
                    fd, tmp = tempfile.mkstemp(dir=cache_dir, prefix=".выгрузка-", suffix=".zip")
                    os.close(fd)
                    try:
                        get(url, страница, ЛИМИТ_ZIP, в_файл=tmp)
                        м = разобрать_zip(tmp, год, мес)
                    finally:
                        os.unlink(tmp)
                    м.update(url=url, выгрузка=выгрузка, формат=ФОРМАТ_МЕСЯЦА)
                    dump_tools.записать_индекс(файл, м)
                    скачано += 1
            файлы.append((год, мес, файл))
            выгрузки.append(м["выгрузка"])
            м = None                                         # месяц в памяти не держим
    except Exception as e:
        return {"статус": "индекс не обновлён: %s: %s" % (type(e).__name__, str(e)[:200]),
                "скачано_выгрузок": скачано}
    if not файлы:
        return {"статус": "индекс не обновлён: схема: ни одного месяца"}
    словарь, части, мероприятий = собрать(файлы)
    старые = sorted(файлы)
    охват = {"с": "%04d-%02d-01" % старые[0][:2], "по": конец_месяца(*старые[-1][:2]),
             "месяцев": len(файлы),
             "пропуски": пропуски([(г, м) for г, м, _ in файлы]),
             "выгрузка": max(выгрузки)}
    _записать_части(cache_dir, словарь, части, {
        "скачан": сегодня, "охват": охват, "мероприятий": мероприятий})
    for имя in os.listdir(os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА)):
        if имя.endswith(".json.gz") and имя not in нужные:
            os.unlink(os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА, имя))
    return {"статус": "обновлено", "скачано_выгрузок": скачано, "охват": охват,
            "организаций": sum(len(ч) for ч in части.values())}


def пропуски(месяцы):
    """[(год, месяц)] -> месяцы «ГГГГ-ММ» между крайними, которых нет в списке."""
    есть = set(месяцы)
    г, м = min(есть)
    out = []
    while (г, м) < max(есть):
        if (г, м) not in есть:
            out.append("%04d-%02d" % (г, м))
        г, м = (г + 1, 1) if м == 12 else (г, м + 1)
    return out


def устарел(манифест, сегодня):
    выгрузка = манифест["охват"]["выгрузка"]
    if dump_tools.старше(выгрузка, сегодня, СВЕЖЕСТЬ_ДНЕЙ):
        return ["выгрузка ЕРКНМ в индексе от %s — старше %d дней; обновите: erknm.py "
                "--refresh (нужен РФ-IP или INN_CHECK_PROXY)" % (выгрузка, СВЕЖЕСТЬ_ДНЕЙ)]
    return []


def _строки(cache_dir, inn):
    """-> (манифест, строки ИНН, словарь). Refresh между чтением манифеста и
    части мог сменить поколение дважды — тогда читаем манифест заново."""
    for попытка in range(2):
        манифест = dump_tools.прочитать_индекс(os.path.join(cache_dir, МАНИФЕСТ))
        папка = os.path.join(cache_dir, манифест["папка"])
        try:
            строки = dump_tools.прочитать_индекс(
                os.path.join(папка, часть(inn) + ".json.gz")).get(str(inn), [])
            словарь = (dump_tools.прочитать_индекс(os.path.join(папка, "словарь.json.gz"))
                       if строки else [])
            return манифест, строки, словарь
        except FileNotFoundError:
            if попытка:
                raise
    raise AssertionError("недостижимо")


def lookup(inn, cache_dir=None, сегодня=None):
    """-> (dict|None, заметка). None — индекса нет."""
    cache_dir = cache_dir or CACHE_DIR
    if not os.path.exists(os.path.join(cache_dir, МАНИФЕСТ)):
        return None, ("индекса нет (%s) — сначала erknm.py --refresh (нужен РФ-IP или "
                      "INN_CHECK_PROXY)" % (CACHE_DIR_ВИДИМЫЙ if cache_dir == CACHE_DIR
                                            else cache_dir))
    сегодня = сегодня or dump_tools.сегодня()
    манифест, строки, словарь = _строки(cache_dir, inn)
    мер = []
    for строка in строки:
        с = строка.split("|")
        мер.append({"номер": с[0], "класс": с[1], "вид": словарь[int(с[2])],
                    "тип": словарь[int(с[3])] or None, "статус": словарь[int(с[4])],
                    "начало": с[5] or None, "окончание": с[6] or None,
                    "орган": словарь[int(с[7])], "вид_контроля": словарь[int(с[8])],
                    "риск": словарь[int(с[9])] or None, "уровень": с[10] or None})
    мер.sort(key=lambda м: (м["начало"] or "", м["номер"]), reverse=True)
    по_видам = {}
    for м in мер:
        по_видам[м["вид"]] = по_видам.get(м["вид"], 0) + 1
    предупреждения = устарел(манифест, сегодня)
    if not мер and манифест["охват"]["пропуски"]:
        # отрицательный ответ за период с дырой — не ответ (ревью Codex)
        предупреждения.append("в индексе ЕРКНМ нет месяцев %s — «мероприятий нет» за период "
                              "не доказано" % ", ".join(манифест["охват"]["пропуски"]))
    return {
        "в_реестре": bool(мер),
        "мероприятий": len(мер),
        "проверок": sum(м["класс"] == "КНМ" for м in мер),
        "внеплановых_проверок": sum("внеплан" in (м["тип"] or "").lower() for м in мер),
        "предостережений": sum(м["статус"] == "предостережение объявлено" for м in мер),
        "по_видам": по_видам,
        "показаны": мер[:ПОКАЗАТЬ],
        "охват": манифест["охват"],
        "оговорка": "мероприятия по 248-ФЗ, начатые за период выгрузок; нарушений, "
                    "предписаний и штрафов в открытых данных ЕРКНМ нет; предостережение — "
                    "сообщение о признаках возможного нарушения, а не установленное "
                    "нарушение; мероприятия, где лицо записано гражданином, не учтены",
        "скачан": манифест["скачан"],
        "предупреждения": предупреждения,
        "источник": СТРАНИЦА,
    }, "ok"


