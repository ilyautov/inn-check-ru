#!/usr/bin/env python3
"""
erknm.py — контрольные (надзорные) и профилактические мероприятия по 248-ФЗ из
ЕРКНМ (proverki.gov.ru, Генпрокуратура) по ИНН, офлайн. Только stdlib.

Открытые данные ЕРКНМ — помесячные выгрузки: страница
proverki.gov.ru/portal/public-open-data сама берёт список месяцев из
/public/api/opendata/list, а по месяцу — паспорт /public/api/opendata/<год>/<месяц>
со ссылкой на ZIP (живьём 28.09.2026: сентябрь 2026 — ZIP 246 МБ, внутри один XML
на 1,7 ГБ). Выгрузка месяца переиздаётся каждый день: результаты вносятся задним
числом. В выгрузке — мероприятия, начатые в этом месяце: проверки (КНМ) и
профилактика (ПМ), в том числе объявленные предостережения — это 70 % записей.

Чего в открытых данных нет: выявленных нарушений, предписаний и штрафов. Поэтому
индекс отвечает на вопрос «приходил ли надзор и с чем», а не «что нашли».
Предостережение — это не нарушение, а сообщение органа о признаках возможного
нарушения (ст. 49 248-ФЗ).

Месяц, выгруженный через ОСЕЛ_ДНЕЙ после своего конца, считается устоявшимся и
не перекачивается ПЕРЕПРОВЕРКА_ДНЕЙ; текущий и прошлый месяцы при каждом
refresh качаются заново. Если в списке портала нет какого-то месяца внутри
периода, отрицательный ответ — «не проверено», положительный остаётся. Сайт закрыт для не-РФ адресов: скачивание через сеть пользователя
(INN_CHECK_PROXY, в т. ч. iface://en0; см. dump_tools.py). Год выгрузок — около
3 ГБ: на медленной сети начните с --месяцев 3.

В индекс идут: учётный номер (ERPID), класс (КНМ/ПМ), вид мероприятия, тип
(плановое/внеплановое), статус, даты, контрольный орган, вид контроля,
категория риска объекта, уровень (федеральный/региональный/муниципальный). Не
идут: наименования (у ИП — ФИО), инспекторы, подписанты, адреса, тексты
предостережений. Мероприятия, где контролируемое лицо — гражданин (TYPE="ФЛ"),
в индекс не попадают.

Индекс разбит на 256 частей по ИНН: поиск читает одну часть, а не 2 млн записей.

    python3 erknm.py --refresh [--месяцев N]   # нужен РФ-IP или INN_CHECK_PROXY
    python3 erknm.py --inn 7707083893
"""

