#!/usr/bin/env python3
"""
watchlist.py — список наблюдения за контрагентами и расписание прогонов
(спек волны 2, §3.2). Только стандартная библиотека.

    python3 watchlist.py --добавить 7707083893 [--профиль отсрочка] [--комментарий "…"]
    python3 watchlist.py --убрать 7707083893
    python3 watchlist.py --список
    python3 watchlist.py --прогон [--human] [--только-изменения]
    python3 watchlist.py --установить-расписание

Файл списка: ~/.cache/inn-check-ru/watchlist.json (переопределяется переменной
окружения INN_CHECK_WATCHLIST или флагом --файл). Каталог снимков —
~/.cache/inn-check-ru/snapshots (переопределяется INN_CHECK_CACHE / --каталог).

--прогон по каждому ИНН: запуск движка (scripts/fetch_counterparty.py рядом,
переопределяется INN_CHECK_ENGINE) отдельным процессом → отпечаток
(scripts/snapshot.py) → дифф с предыдущим снимком (diff_counterparty.py) →
отчёт ТОЛЬКО по изменившимся и по тем, у кого проверка не состоялась.
Движку передаётся `--режим всё` (снимку нужны все поля, а не quick-фаза).
Молчаливого повтора без флага нет: снимок, собранный другим режимом, несравним
с полным, и «тихо собрать что попало» — как раз тот способ соврать, ради
которого этот файл существует. Не вышло с флагом — это «не проверено».

«Без изменений» печатается только тогда, когда проверка ДЕЙСТВИТЕЛЬНО
состоялась: если `_итог.проверка_состоялась` ложно или промолчал хотя бы один
deal-killer-источник (перечень — sources.deal_killer_ids()), строка получает
статус «не проверено» с перечнем источников и попадает в вывод даже в тихом
режиме. Прогон, где не проверено ничего, обязан кричать, а не молчать.
Исключение — deal-killer'ы с `требует: браузер` (ФССП, суды, ЕФРСБ): они не
собираются скриптом в принципе, стоят «не проверено» в каждом снимке и потому
не признак деградации прогона. Они не роняют статус, но печатаются в каждой
карточке отдельной строкой — спрятать их нельзя, иначе это та же ложь.
Сбой по одному ИНН не роняет список: строка «не проверено», прогон идёт дальше.

--установить-расписание НИЧЕГО НЕ УСТАНАВЛИВАЕТ: печатает готовые строки crontab
и launchd plist с реальными путями текущей установки. Правка пользовательского
crontab — за пределами того, что инструмент делает без спроса.

--только-изменения — тихий режим для крона: пустой stdout, когда ничего не
изменилось и все прогоны прошли.
"""

import importlib.util
import json
import os
import subprocess
import sys
import time

_HERE = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя):
    spec = importlib.util.spec_from_file_location(
        имя, os.path.join(_HERE, имя + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


snapshot = _модуль("snapshot")
diff_counterparty = _модуль("diff_counterparty")
sources = _модуль("sources")   # только чтение: перечень deal-killer-источников

ВЕРСИЯ_ФАЙЛА = 1
ТАЙМАУТ_ДВИЖКА = 600  # с: дедлайн сбора внутри движка — 120 с на ИНН, запас ×5
ФЛАГ_РЕЖИМА = ["--режим", "всё"]


def путь_файла(файл=None):
    """Путь списка наблюдения: --файл > INN_CHECK_WATCHLIST > кэш по умолчанию."""
    return (файл or os.environ.get("INN_CHECK_WATCHLIST")
            or os.path.join(snapshot.CACHE_DIR, "watchlist.json"))


def каталог_кэша(каталог=None):
    """База для снимков: --каталог > INN_CHECK_CACHE > ~/.cache/inn-check-ru."""
    return каталог or os.environ.get("INN_CHECK_CACHE") or snapshot.CACHE_DIR


def путь_движка():
    """Движок сбора: INN_CHECK_ENGINE > scripts/fetch_counterparty.py рядом."""
    return os.environ.get("INN_CHECK_ENGINE") or os.path.join(
        _HERE, "fetch_counterparty.py")


# --- файл списка -------------------------------------------------------------

def прочитать(файл=None):
    """Список наблюдения с диска. Нет файла или битый JSON — пустой список."""
    путь = путь_файла(файл)
    try:
        with open(путь, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {"версия": ВЕРСИЯ_ФАЙЛА, "контрагенты": []}
    if not isinstance(data, dict) or not isinstance(data.get("контрагенты"), list):
        return {"версия": ВЕРСИЯ_ФАЙЛА, "контрагенты": []}
    data.setdefault("версия", ВЕРСИЯ_ФАЙЛА)
    return data


def записать(данные, файл=None):
    путь = путь_файла(файл)
    каталог = os.path.dirname(путь)
    if каталог:
        os.makedirs(каталог, exist_ok=True)
    with open(путь, "w", encoding="utf-8") as fh:
        json.dump(данные, fh, ensure_ascii=False, indent=2)
    return путь


def _инн_годится(inn):
    inn = str(inn).strip()
    return inn.isdigit() and len(inn) in (10, 12)


def добавить(inn, профиль=None, комментарий=None, файл=None):
    """Добавляет ИНН в список (повторное добавление обновляет профиль/комментарий)."""
    inn = str(inn).strip()
    if not _инн_годится(inn):
        return {"статус": "ошибка",
                "причина": "ИНН %r: ожидается 10 или 12 цифр" % inn}
    данные = прочитать(файл)
    for запись in данные["контрагенты"]:
        if запись.get("инн") == inn:
            if профиль:
                запись["профиль"] = профиль
            if комментарий:
                запись["комментарий"] = комментарий
            путь = записать(данные, файл)
            return {"статус": "обновлено", "инн": inn, "файл": путь,
                    "запись": запись}
    запись = {"инн": inn, "профиль": профиль, "комментарий": комментарий,
              "добавлен": time.strftime("%Y-%m-%dT%H:%M:%S")}
    данные["контрагенты"].append(запись)
    путь = записать(данные, файл)
    return {"статус": "добавлено", "инн": inn, "файл": путь, "запись": запись,
            "всего": len(данные["контрагенты"])}


def убрать(inn, файл=None):
    inn = str(inn).strip()
    данные = прочитать(файл)
    было = len(данные["контрагенты"])
    данные["контрагенты"] = [з for з in данные["контрагенты"]
                             if з.get("инн") != inn]
    if len(данные["контрагенты"]) == было:
        return {"статус": "не найдено", "инн": inn,
                "причина": "ИНН %s в списке наблюдения нет" % inn,
                "файл": путь_файла(файл)}
    путь = записать(данные, файл)
    return {"статус": "убрано", "инн": inn, "файл": путь,
            "всего": len(данные["контрагенты"])}


def список(файл=None, каталог=None):
    """Список наблюдения + сколько снимков накоплено по каждому ИНН."""
    данные = прочитать(файл)
    база = каталог_кэша(каталог)
    записи = []
    for з in данные["контрагенты"]:
        снимки = snapshot.list_snapshots(з.get("инн"), база)
        запись = dict(з)
        запись["снимков"] = len(снимки)
        запись["последний_снимок"] = снимки[-1] if снимки else None
        записи.append(запись)
    return {"файл": путь_файла(файл), "всего": len(записи), "контрагенты": записи}


# --- прогон ------------------------------------------------------------------

def _запустить_движок(inn, профиль=None, движок=None):
    """(результат|None, причина). Ровно одна попытка — с `--режим всё`.

    Фолбэка «повторить без флага» здесь нет намеренно: движок флаг знает, а
    молчаливый повтор собирал бы снимок другим режимом — такие снимки несравнимы,
    и дифф показывал бы артефакт сбора вместо изменений у контрагента. Не
    отработал вызов с флагом — это ошибка прогона, то есть «не проверено».
    """
    движок = движок or путь_движка()
    cmd = [sys.executable, движок, str(inn)]
    if профиль:
        cmd += ["--профиль", профиль]
    cmd += ФЛАГ_РЕЖИМА
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=ТАЙМАУТ_ДВИЖКА, check=False)
    except (OSError, subprocess.SubprocessError) as e:
        return None, "движок не запустился: %s" % e
    try:
        данные = json.loads(proc.stdout)
    except ValueError:
        данные = None
    if proc.returncode == 0 and isinstance(данные, dict) and "ошибка" not in данные:
        return данные, None
    пояснение = (данные.get("ошибка") if isinstance(данные, dict)
                 else (proc.stderr or proc.stdout or "").strip()[:200])
    return None, ("движок с `%s` вернул код %s: %s"
                  % (" ".join(ФЛАГ_РЕЖИМА), proc.returncode, пояснение or "—"))


def _непроверенные_deal_killer(состояния, не_покрыты_снимка=None):
    """(не ответили, не покрыты скриптом) среди deal-killer-источников.

    Перечень deal-killer'ов — из реестра (sources.deal_killer_ids()), не копия.
    Разделение по `требует`: «браузер» — постоянный предел инструмента (ФССП,
    суды, ЕФРСБ собираются руками), он стоит в каждом снимке и поэтому не может
    служить признаком деградации ЭТОГО прогона; всё остальное — источник,
    который движок умеет собирать и который сегодня промолчал. Оба перечня
    попадают в отчёт, скрывать нечего; статус прогона роняет только второй.
    """
    молчат = [sid for sid in sources.deal_killer_ids()
              if состояния.get(sid) == "не проверено"]
    if не_покрыты_снимка is None:
        не_покрыты_снимка = {sid for sid in молчат
                             if sources.SOURCES.get(sid, {}).get("требует") == "браузер"}
    не_покрыты = [sid for sid in молчат if sid in не_покрыты_снимка]
    не_ответили = [sid for sid in молчат if sid not in не_покрыты]
    return не_ответили, не_покрыты


def _прогон_инн(inn, профиль=None, каталог=None, движок=None):
    """Один ИНН: движок → отпечаток → дифф с предыдущим снимком → запись.

    Статус «без изменений» ставится только когда проверка состоялась. Любая
    причина неполноты (движок не ответил, deal-killer-источник молчит, отпечаток
    не записался, прошлый снимок не читается) даёт «не проверено» с перечнем —
    и такая строка печатается даже в тихом режиме крона.
    """
    база = каталог_кэша(каталог)
    предыдущие = snapshot.list_snapshots(inn, база)
    результат, причина = _запустить_движок(inn, профиль, движок)
    if результат is None:
        return {"инн": inn, "статус": "не проверено", "причина": причина,
                "изменений": 0, "изменения": []}
    отпечаток = snapshot.fingerprint(результат)
    путь = snapshot.save(inn, отпечаток, dir=база)
    состояния = отпечаток.get("состояния") or {}
    не_ответили, не_покрыты = _непроверенные_deal_killer(
        состояния, set(отпечаток.get("не_покрыты") or ()))
    проверка_состоялась = bool(отпечаток["_итог"]["проверка_состоялась"])
    итог = {"инн": inn, "снимок": путь,
            "проверка_состоялась": проверка_состоялась,
            "состояния": состояния,
            "не_проверено_deal_killer": не_ответили + не_покрыты,
            "не_ответили_deal_killer": не_ответили,
            "не_покрыты_deal_killer": не_покрыты,
            "изменений": 0, "изменения": []}
    причины = []
    if состояния:
        # Состояния известны — можно и нужно судить о полноте проверки.
        if не_ответили:
            причины.append("deal-killer-источники не ответили: %s"
                           % ", ".join(не_ответили))
        if not проверка_состоялась:
            причины.append("движок отметил, что проверка не состоялась"
                           + (" (не проверено: %s)" % ", ".join(не_покрыты)
                              if не_покрыты and not не_ответили else ""))
    else:
        итог["состояния_известны"] = False
    if путь is None:
        причины.append("отпечаток не записан — следующий прогон сравнит "
                       "со старым снимком")
    if not предыдущие:
        итог["статус"] = "не проверено" if причины else "первый снимок"
        итог["причина"] = "; ".join(причины + [
            ("сравнивать не с чем — снимок сохранён, изменения появятся "
             "со следующего прогона")])
        return итог
    прошлый_путь = предыдущие[-1]
    прошлый = snapshot.load(прошлый_путь)
    if прошлый is None:
        итог["статус"] = "не проверено"
        итог["причина"] = "; ".join(
            причины + ["предыдущий снимок не читается: %s" % прошлый_путь])
        return итог
    дата_было = os.path.splitext(os.path.basename(прошлый_путь))[0].replace("_", " ")
    дата_стало = (os.path.splitext(os.path.basename(путь))[0].replace("_", " ")
                  if путь else "снимок не записан")
    изменения = diff_counterparty.diff(
        прошлый, отпечаток, дата_было, дата_стало,
        все_снимки=предыдущие + ([путь] if путь else []))
    итог["изменений"] = len(изменения)
    итог["изменения"] = изменения
    итог["дата_было"], итог["дата_стало"] = дата_было, дата_стало
    if причины:
        # Найденные изменения не прячем: они остаются в строке, но «спокойно»
        # такой прогон назвать нельзя — статус честный.
        итог["статус"] = "не проверено"
        итог["причина"] = "; ".join(причины)
    else:
        итог["статус"] = "изменения" if изменения else "без изменений"
    return итог


def прогон_инн(inn, профиль=None, каталог=None, движок=None):
    """Обёртка: сбой по одному ИНН не роняет прогон всего списка.

    В кроне упавший прогон выглядит как тишина, а тишина читается как «всё
    спокойно» — поэтому любое исключение превращается в строку «не проверено»,
    а остальные контрагенты списка проверяются дальше.
    """
    try:
        return _прогон_инн(inn, профиль, каталог, движок)
    except Exception as e:   # падение одного ИНН не имеет права молчать
        return {"инн": inn, "статус": "не проверено",
                "причина": "сбой прогона: %s: %s" % (type(e).__name__, e),
                "изменений": 0, "изменения": []}


def прогон(файл=None, каталог=None, движок=None):
    """Прогон всего списка.

    В «результатах» — изменившиеся И непроверенные: строку «не проверено»
    выбрасывать нельзя, иначе прогон, где не ответил ни один источник, в тихом
    режиме крона выглядит ровно как прогон, где всё спокойно.
    """
    данные = прочитать(файл)
    результаты, проверено, без_изменений = [], 0, 0
    for з in данные["контрагенты"]:
        inn = з.get("инн")
        if not inn:
            continue
        проверено += 1
        итог = прогон_инн(inn, з.get("профиль"), каталог, движок)
        итог["комментарий"] = з.get("комментарий")
        if итог["статус"] == "без изменений":
            без_изменений += 1
            continue
        результаты.append(итог)
    изменилось = sum(1 for r in результаты if r["статус"] == "изменения")
    не_проверено = sum(1 for r in результаты if r["статус"] == "не проверено")
    # Строка может быть одновременно «не проверено» и с найденными изменениями:
    # неполнота проверки не отменяет того, что уже найдено, и наоборот.
    с_изменениями = sum(1 for r in результаты if r.get("изменения"))
    return {
        "дата": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "проверено": проверено,
        "изменилось": изменилось,
        "без_изменений": без_изменений,
        "не_проверено": не_проверено,
        "с_найденными_изменениями": с_изменениями,
        "результаты": результаты,
    }


def человеческий_отчёт(отчёт):
    """Карточки изменений (diff_counterparty.human_card) + честный хвост."""
    строки = []
    for r in отчёт["результаты"]:
        карточка = r["статус"] == "изменения" or r.get("изменения")
        if карточка:
            строки.append(diff_counterparty.human_card(
                r["инн"], r.get("изменения") or [], r.get("дата_было", "?"),
                r.get("дата_стало", "?"),
                состояния=r.get("состояния"),
                итог={"проверка_состоялась": r.get("проверка_состоялась"),
                      "не_проверено_deal_killer":
                          r.get("не_проверено_deal_killer") or [],
                      "не_ответили_deal_killer":
                          r.get("не_ответили_deal_killer") or [],
                      "не_покрыты_deal_killer":
                          r.get("не_покрыты_deal_killer") or []}))
        if r["статус"] == "не проверено":
            строки.append("⚪ ИНН %s — проверка не состоялась: %s"
                          % (r["инн"], r.get("причина")))
        elif r["статус"] == "первый снимок":
            строки.append("ℹ️ ИНН %s — %s" % (r["инн"], r.get("причина")))
        строки.append("")
    хвост = ("Прогон %s: проверено %d, изменилось %d, без изменений %d, "
             "не проверено %d"
             % (отчёт["дата"], отчёт["проверено"], отчёт["изменилось"],
                отчёт["без_изменений"], отчёт["не_проверено"]))
    лишние = отчёт.get("с_найденными_изменениями", 0) - отчёт["изменилось"]
    if лишние > 0:
        хвост += (" (из них с найденными изменениями: %d — проверка по ним "
                  "неполная, но найденное в силе)" % лишние)
    строки.append(хвост)
    return "\n".join(строки).strip() + "\n"


# --- расписание --------------------------------------------------------------

МЕТКА_LAUNCHD = "tech.aifrontier.inn-check-ru.watchlist"


def расписание(файл=None, каталог=None, час=8, минута=0):
    """Готовые строки crontab и launchd plist с путями текущей установки."""
    питон = os.path.abspath(sys.executable)
    скрипт = os.path.abspath(__file__)
    лог = os.path.join(каталог_кэша(каталог), "watchlist.log")
    аргументы = [питон, скрипт, "--прогон", "--только-изменения"]
