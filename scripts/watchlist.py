# --- CLI ---------------------------------------------------------------------

USAGE = (
    "Использование:\n"
    "  python3 watchlist.py --добавить <ИНН> [--профиль <id>] [--комментарий «…»]\n"
    "  python3 watchlist.py --убрать <ИНН>\n"
    "  python3 watchlist.py --список\n"
    "  python3 watchlist.py --прогон [--human] [--только-изменения]\n"
    "  python3 watchlist.py --установить-расписание\n"
    "Общее: [--файл <watchlist.json>] [--каталог <кэш>] "
    "(или INN_CHECK_WATCHLIST / INN_CHECK_CACHE)\n")


def _опция(args, имя):
    if имя in args:
        i = args.index(имя)
        return args[i + 1] if i + 1 < len(args) else None
    for a in args:
        if a.startswith(имя + "="):
            return a.split("=", 1)[1]
    return None


def main(argv):
    args = argv[1:]
    human = "--human" in args
    тихо = "--только-изменения" in args
    файл = _опция(args, "--файл")
    каталог = _опция(args, "--каталог")

    def вывод(данные, код=0):
        sys.stdout.write(json.dumps(данные, ensure_ascii=False, indent=2) + "\n")
        return код

    if "--добавить" in args:
        inn = _опция(args, "--добавить")
        if not inn:
            sys.stderr.write(USAGE)
            return 2
        итог = добавить(inn, _опция(args, "--профиль"),
                        _опция(args, "--комментарий"), файл)
        return вывод(итог, 0 if итог["статус"] != "ошибка" else 1)
    if "--убрать" in args:
        inn = _опция(args, "--убрать")
        if not inn:
            sys.stderr.write(USAGE)
            return 2
        итог = убрать(inn, файл)
        return вывод(итог, 0 if итог["статус"] == "убрано" else 1)
    if "--список" in args:
        return вывод(список(файл, каталог))
    if "--установить-расписание" in args:
        sys.stdout.write(расписание(файл, каталог)["текст"] + "\n")
        return 0
    if "--прогон" in args:
        отчёт = прогон(файл, каталог)
        if тихо and not отчёт["результаты"]:
            return 0  # тихий режим для крона: нечего сказать — молчим
        if human:
            sys.stdout.write(человеческий_отчёт(отчёт))
            return 0
        return вывод(отчёт)
    sys.stderr.write(USAGE)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
