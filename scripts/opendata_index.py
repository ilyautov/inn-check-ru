def _путь_индекса(ид, каталог=None):
    кат = каталог or od.ДАТАСЕТЫ[ид]["каталог"]
    return os.path.join(кат, "index-%s.bin" % ид)


def _путь_меты(ид, каталог=None):
    return _путь_индекса(ид, каталог) + ".meta.json"


# ---------------------------------------------------------------- сборка

def построить(ид, путь_дампа=None, каталог=None, лимит=None, на_файл=None):
    """Собрать индекс датасета. -> (мета, причина отказа)."""
    if ид not in ИНДЕКСИРУЕМЫЕ:
        return None, "датасет %r не индексируется; есть: %s" % (
            ид, ", ".join(ИНДЕКСИРУЕМЫЕ))
    спец = ИНДЕКСИРУЕМЫЕ[ид]
    архив = путь_дампа or od.путь_дампа(ид)
    if архив is None:
        return None, ("дамп %s не скачан: opendata_refresh.py --refresh "
                      "--датасет %s" % (ид, ид))
    мета_дампа = od.читать_мету(архив) or {}
    # meta.json рядом с дампом пишет только --refresh; у дампа, положенного
    # руками, его нет. Дата обязана быть в ответе всегда, иначе сведения
    # прошлого года уедут потребителю без возраста — поэтому падаем на имя
    # файла, где дата стоит по устройству формата (data-<дата>-structure-…).
    if not мета_дампа.get("дата_выгрузки"):
        дата, структура = od.разобрать_имя(архив)
        мета_дампа = dict(мета_дампа)
        мета_дампа.setdefault("версия_структуры", структура)
        мета_дампа["дата_выгрузки"] = дата
    размер = КЛЮЧ_БАЙТ + спец["запись"]
    os.makedirs(каталог or od.ДАТАСЕТЫ[ид]["каталог"], exist_ok=True)

    def год_записи(запись):
        return спец["прочитать"](запись[КЛЮЧ_БАЙТ:]).get("год") or 0

    корзины, всего, пропущено, дубли = {}, 0, 0, 0
    врем = tempfile.mkdtemp(prefix="inn-index-%s-" % ид)
    try:
        try:
            поток = od.итерировать(ид, путь=архив, лимит=лимит, на_файл=на_файл)
            for rec in поток:
                инн = rec.get("инн")
                payload = спец["упаковать"](rec)
                if not инн or payload is None:
                    пропущено += 1
                    continue
                ключ = _ключ(инн)
                корзина = ключ[:2]
                fh = корзины.get(корзина)
                if fh is None:
                    # with-блок здесь невозможен: корзин под сотню и все они
                    # пишутся одновременно, пока идёт поток. Закрываются они
                    # все разом во внешнем finally.
                    fh = корзины[корзина] = open(  # noqa: SIM115
                        os.path.join(врем, корзина.hex() + ".bin"), "wb")
                fh.write(ключ + payload)
                всего += 1
        finally:
            for fh in корзины.values():
                fh.close()

        # Дубли схлопываются здесь, а не на входе: словарь «ИНН -> год» на 7 млн
        # ключей съел бы сотни мегабайт и обнулил смысл корзин. В корзине же
        # одинаковые ключи после сортировки стоят рядом, и выбрать САМЫЙ СВЕЖИЙ
        # год можно, глядя только на соседей. Оставить первую попавшуюся запись
        # значило бы отдавать позапрошлогоднее число как сегодняшнее.
        путь = _путь_индекса(ид, каталог)
        записей = 0
        with open(путь, "wb") as out:
            for корзина in sorted(корзины):
                with open(os.path.join(врем, корзина.hex() + ".bin"), "rb") as fh:
                    сырое = fh.read()
                строки = [сырое[i:i + размер] for i in range(0, len(сырое), размер)]
                строки.sort()
                победитель = None
                for s in строки:
                    if победитель is not None and s[:КЛЮЧ_БАЙТ] == победитель[:КЛЮЧ_БАЙТ]:
                        дубли += 1
                        if год_записи(s) > год_записи(победитель):
                            победитель = s
                        continue
                    if победитель is not None:
                        out.write(победитель)
                        записей += 1
                    победитель = s
                if победитель is not None:
                    out.write(победитель)
                    записей += 1
                del сырое, строки
    finally:
        for имя in os.listdir(врем):
            os.unlink(os.path.join(врем, имя))
        os.rmdir(врем)

    мета = {
        "версия_формата": ВЕРСИЯ_ФОРМАТА,
        "датасет": ид,
        "название": od.ДАТАСЕТЫ[ид]["название"],
        "что_даёт": спец["что_даёт"],
        "записей": записей,
        "прочитано_из_выгрузки": всего,
        "размер_записи": размер,
        "пропущено_без_значения": пропущено,
        "дублей_ИНН_в_выгрузке": дубли,
        "дата_выгрузки": мета_дампа.get("дата_выгрузки"),
        "версия_структуры": мета_дампа.get("версия_структуры"),
        "файл_дампа": os.path.basename(архив),
        "собран": time.strftime("%Y-%m-%d %H:%M:%S"),
        "неполный": bool(лимит),
    }
    with open(_путь_меты(ид, каталог), "w", encoding="utf-8") as fh:
        json.dump(мета, fh, ensure_ascii=False, indent=2)
    return мета, None


# ---------------------------------------------------------------- поиск

def _мета(ид, каталог=None):
    try:
        with open(_путь_меты(ид, каталог), encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


def найти(инн, ид, каталог=None):
    """Одна запись по ИНН. -> dict с ключом `состояние` (ок/пусто/не проверено).

    Ответ ВСЕГДА несёт дату выгрузки: сведения из дампа имеют возраст, и
    отдать их без даты значит выдать прошлое за настоящее.
    """
    if ид in od.ДАТАСЕТЫ:
        источник = ("открытые данные ФНС (file.nalog.ru/opendata/%s)"
                    % od.ДАТАСЕТЫ[ид]["датасет"])
    else:
        источник = "открытые данные ФНС"
    основа = {"датасет": ид, "инн": инн, "источник": источник}
    if ид not in ИНДЕКСИРУЕМЫЕ:
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="датасет %r не индексируется; есть: %s"
                              % (ид, ", ".join(ИНДЕКСИРУЕМЫЕ)))
        return основа
    спец = ИНДЕКСИРУЕМЫЕ[ид]
    мета = _мета(ид, каталог)
    путь = _путь_индекса(ид, каталог)
    if мета is None or not os.path.exists(путь):
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="кэш: индекс %s не построен — "
                              "opendata_index.py --построить --датасет %s"
                              % (ид, ид))
        return основа
    основа["дата_выгрузки"] = мета.get("дата_выгрузки")
    основа["индекс_собран"] = мета.get("собран")
    if мета.get("версия_формата") != ВЕРСИЯ_ФОРМАТА:
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="схема: индекс %s версии %r, ожидается %d — "
                              "пересоберите: opendata_index.py --построить "
                              "--датасет %s" % (ид, мета.get("версия_формата"),
                                                ВЕРСИЯ_ФОРМАТА, ид))
        return основа
    размер = мета.get("размер_записи") or (КЛЮЧ_БАЙТ + спец["запись"])
    if размер != КЛЮЧ_БАЙТ + спец["запись"]:
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="схема: в индексе %s запись %d байт, код ждёт %d "
                              "— пересоберите индекс"
                              % (ид, размер, КЛЮЧ_БАЙТ + спец["запись"]))
        return основа
    if мета.get("неполный"):
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="кэш: индекс %s собран с --лимит и покрывает "
                              "только часть выгрузки — «не найдено» в нём "
                              "ничего не значит. Пересоберите без лимита" % ид)
        return основа
    # ИП в этих датасетах нет вовсе: запись висит на СведНП/@ИННЮЛ (проверено
    # на живом индексе snr 22.09.2026 — ни одного 12-значного ИНН из 1,33 млн).
    # Для ИП честный ответ — «не проверено», а НЕ «пусто»: «записи нет» у
    # источника, который физически не может её содержать, читалось бы как факт
    # об ИП, а это факт об охвате датасета.
    if len((инн or "").strip()) == 12:
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="охват: датасет %s содержит только юрлица "
                              "(СведНП/@ИННЮЛ); по ИП сведений в нём нет "
                              "в принципе" % ид)
        return основа

    ключ = _ключ(инн)
    try:
        запись = _двоичный_поиск(путь, ключ, размер)
    except OSError as e:
        основа.update(состояние=НЕ_ПРОВЕРЕНО,
                      причина="кэш: индекс %s не читается: %s" % (ид, e))
        return основа
    if запись is None:
        основа.update(состояние=ПУСТО, оговорка=спец["оговорка"])
        return основа
    основа["состояние"] = ОК
    основа.update(спец["прочитать"](запись[КЛЮЧ_БАЙТ:]))
    return основа


def _двоичный_поиск(путь, ключ, размер):
    """Запись с таким ключом или None. Читаем по одной записи, файл не грузим."""
    размер_файла = os.path.getsize(путь)
    if размер_файла % размер:
        raise OSError("длина файла %d не кратна записи %d — индекс повреждён"
                      % (размер_файла, размер))
    лево, право = 0, размер_файла // размер - 1
    # Счётчик шагов — не паранойя: ошибка на единицу в сужении границ даёт не
    # неверный ответ, а вечный цикл, и в CI это читается как «задание ещё
    # идёт», то есть тот же немой отказ. Двоичный поиск по n записям обязан
    # уложиться в log2(n) + 2 шага; не уложился — поломан сам поиск.
    осталось = (размер_файла // размер).bit_length() + 2
    with open(путь, "rb") as fh:
        while лево <= право:
            осталось -= 1
            if осталось < 0:
                raise OSError("двоичный поиск не сходится на %d записях — "
                              "поломано сужение границ"
                              % (размер_файла // размер))
            середина = (лево + право) // 2
            fh.seek(середина * размер)
            запись = fh.read(размер)
            if len(запись) != размер:
                raise OSError("обрыв индекса на записи %d" % середина)
            текущий = запись[:КЛЮЧ_БАЙТ]
            if текущий == ключ:
                return запись
            if текущий < ключ:
                лево = середина + 1
            else:
                право = середина - 1
    return None


def найти_всё(инн, каталог=None):
    """{датасет: результат} по всем индексируемым датасетам."""
    return {ид: найти(инн, ид, каталог) for ид in ИНДЕКСИРУЕМЫЕ}


def статус(каталог=None):
    out = {"каталог": каталог or od.OPENDATA_DIR, "индексы": {}}
    готовых = 0
    for ид in ИНДЕКСИРУЕМЫЕ:
        мета = _мета(ид, каталог)
        путь = _путь_индекса(ид, каталог)
        есть = мета is not None and os.path.exists(путь)
        строка = {"построен": есть}
        if есть:
            строка.update(мета)
            строка["байт"] = os.path.getsize(путь)
            if not мета.get("неполный"):
                готовых += 1
        else:
            строка["причина"] = ("индекс не построен — opendata_index.py "
                                 "--построить --датасет %s" % ид)
            строка["дамп_скачан"] = od.путь_дампа(ид) is not None
        out["индексы"][ид] = строка
    out["статус"] = ("готовы все %d" % len(ИНДЕКСИРУЕМЫЕ) if готовых == len(ИНДЕКСИРУЕМЫЕ)
                     else "готовы %d из %d" % (готовых, len(ИНДЕКСИРУЕМЫЕ)))
    return out


# ---------------------------------------------------------------- CLI

USAGE = ("Использование:\n"
         "  opendata_index.py --построить [--датасет <id>] [--лимит N] [--тихо]\n"
         "  opendata_index.py --найти <ИНН> [--датасет <id>]\n"
         "  opendata_index.py --статус\n"
         "Индексируются: %s\n" % ", ".join(ИНДЕКСИРУЕМЫЕ))


def _прогресс(ид):
    def на_файл(имя, номер, всего):
        if номер % 100 == 0 or номер == всего:
            sys.stderr.write("\r%s: файл %d/%d" % (ид, номер, всего))
            sys.stderr.flush()
    return на_файл


def main(argv):
    args = argv[1:]
    if not args:
        sys.stderr.write(USAGE)
        return 2
    ид = od._арг(args, "--датасет")
    if ид is not None and ид not in ИНДЕКСИРУЕМЫЕ:
        sys.stderr.write("Индексируются только: %s\n" % ", ".join(ИНДЕКСИРУЕМЫЕ))
        return 2

    if "--статус" in args:
        res = статус()
        return od._out(res, 0 if res["статус"].startswith("готовы все") else 1)

    if "--построить" in args:
        лимит = od._арг(args, "--лимит")
        if лимит is not None:
            try:
                лимит = int(лимит)
            except ValueError:
                sys.stderr.write("--лимит должен быть числом\n")
                return 2
        цели = [ид] if ид else list(ИНДЕКСИРУЕМЫЕ)
        тихо = "--тихо" in args
        результаты, беда = {}, False
        for цель in цели:
            мета, причина = построить(цель, лимит=лимит,
                                      на_файл=None if тихо else _прогресс(цель))
            if not тихо:
                sys.stderr.write("\n")
            результаты[цель] = мета or {"статус": "не построен",
                                        "причина": причина}
            беда = беда or мета is None
        return od._out({"статус": "собрано %d/%d" % (
            sum(1 for r in результаты.values() if r.get("записей")), len(цели)),
            "индексы": результаты}, 1 if беда else 0)

    if "--найти" in args:
        инн = od._арг(args, "--найти")
        if not инн:
            sys.stderr.write("После --найти нужен ИНН\n")
            return 2
        res = найти(инн, ид) if ид else найти_всё(инн)
        состояния = [res["состояние"]] if ид else [
            v["состояние"] for v in res.values()]
        код = 0 if ОК in состояния else 1
        return od._out(res, код)

    sys.stderr.write(USAGE)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
