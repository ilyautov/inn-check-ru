# Названия налогов в дампе — ТЕКСТОМ, кодов там нет (проверено на живом paytax
# 22.09.2026). Сверяем по нормализованной подстроке: в реальных записях
# встречаются двойные пробелы («в связи с  применением»).
НАЛОГ_НДС = "налог на добавленную стоимость"
НАЛОГ_ПРИБЫЛЬ = "налог на прибыль"
НАЛОГ_УСН = "упрощенной"


def _норм(s):
    return " ".join((s or "").lower().split())


def _ключ(инн):
    """ИНН -> 12 байт ASCII, добитые нулями. Ведущий ноль сохраняется."""
    b = (инн or "").strip().encode("ascii", "ignore")[:КЛЮЧ_БАЙТ]
    return b + b"\0" * (КЛЮЧ_БАЙТ - len(b))


