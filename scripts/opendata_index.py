#!/usr/bin/env python3
"""
opendata_index.py — поиск по ИНН в дампах открытых данных ФНС. Только stdlib.

Зачем. Дампы ФНС уже лежат в кэше (`opendata_refresh.py --refresh`), и
`benchmarks.py --построить` сворачивает их в отраслевые нормы. Но сами дампы
отдают данные ПО КАЖДОМУ ИНН, а поиска по ИНН не было: численность,
спецрежим и уплаченный НДС конкретной компании движок помечал «не проверено»,
хотя ответ лежал на диске. Они сидят ещё и за детальным эндпоинтом
«Прозрачного бизнеса» (`company-proc.json`), который с не-РФ IP отвечает 500 —
дамп закрывает эту дыру офлайн.

Использование:
    python3 opendata_index.py --построить                 # все индексируемые
    python3 opendata_index.py --построить --датасет snr
    python3 opendata_index.py --найти 7707083893          # по всем датасетам
    python3 opendata_index.py --найти 7707083893 --датасет sshr2019
    python3 opendata_index.py --статус

ФОРМАТ. На датасет — файл фиксированных записей, отсортированный по ИНН, и
`.meta.json` рядом. Поиск — двоичный по файлу через seek: O(log n) обращений,
память не растёт, индекс на 7 млн ИНН занимает 126 МБ и не загружается целиком
никогда. Ключ — 12 байт ASCII, дополненных нулями справа, а НЕ число: ИНН
бывает с ведущим нулём (регион 01 — Адыгея), и uint64 его потерял бы молча.

СБОРКА без роста памяти. Записи раскладываются по корзинам первых двух цифр
ИНН (кода региона) во временные файлы, каждая корзина сортируется в памяти
(78 тыс. записей) и дописывается в итог по возрастанию ключа корзины. Первые
два байта ключа определяют корзину, поэтому склейка корзин по возрастанию даёт
глобально отсортированный файл. Внешняя сортировка целиком в stdlib.

ТРИ СОСТОЯНИЯ, как у всего остального движка:
  * `ок`          — запись найдена, значение отдано;
  * `пусто`       — индекс есть, записи по ИНН в выгрузке нет. Это факт о
                    ВЫГРУЗКЕ, а не о компании: «в sshr за 31.12.2025 сведений
                    об ИНН нет» не значит «сотрудников нет». Потребитель обязан
                    нести эту разницу дальше, поэтому она стоит в `оговорка`;
  * `не проверено`— индекса нет, он устарел или не читается; в `причина`
                    написано, чем чинить.

ДАТА ВЫГРУЗКИ — часть ответа всегда. Дамп snr на 22.09.2026 отражает состояние
на 01.08.2026, sshr — на 31.12.2025. Сведения о спецрежиме месячной давности и
о численности — годовой: отдать их без даты значит выдать прошлое за настоящее.
"""

