def _payload_sshr(rec):
    ссч = rec.get("ссч")
    if not isinstance(ссч, int):
        return None
    return struct.pack("<iH", ссч, rec.get("год") or 0)


def _чтение_sshr(payload):
    ссч, год = struct.unpack("<iH", payload)
    return {"ссч": ссч, "год": год or None}


_ФЛАГИ_СНР = ("есхн", "усн", "аусн", "срп")


def _payload_snr(rec):
    значения = маска = 0
    for сдвиг, имя in enumerate(_ФЛАГИ_СНР):
        v = rec.get(имя)
        if v is None:
            continue
        маска |= 1 << сдвиг
        if v:
            значения |= 1 << сдвиг
    if not маска:
        return None
    return struct.pack("<BBH", значения, маска, rec.get("год") or 0)


def _чтение_snr(payload):
    значения, маска, год = struct.unpack("<BBH", payload)
    out = {"год": год or None, "режимы": []}
    for сдвиг, имя in enumerate(_ФЛАГИ_СНР):
        out[имя] = bool(значения >> сдвиг & 1) if маска >> сдвиг & 1 else None
        if out[имя]:
            out["режимы"].append(имя.upper())
    return out


def _payload_paytax(rec):
    налоги = rec.get("налоги")
    if not isinstance(налоги, dict):
        return None
    ндс = прибыль = усн = 0.0
    for имя, сумма in налоги.items():
        н = _норм(имя)
        if НАЛОГ_НДС in н:
            ндс += сумма or 0.0
        elif НАЛОГ_ПРИБЫЛЬ in н:
            прибыль += сумма or 0.0
        elif НАЛОГ_УСН in н:
            усн += сумма or 0.0
    return struct.pack("<ddddH", rec.get("сумма_налогов") or 0.0, ндс,
                       прибыль, усн, rec.get("год") or 0)


def _чтение_paytax(payload):
    всего, ндс, прибыль, усн, год = struct.unpack("<ddddH", payload)
    return {"налогов_всего_руб": всего, "ндс_руб": ндс,
            "налог_на_прибыль_руб": прибыль, "усн_руб": усн,
            "год": год or None}


