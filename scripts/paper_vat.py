# --- сборка ---------------------------------------------------------------------

def analyze(fetch, canon=None, предмет=None, сумма=None):
    """Признаки «бумажного НДС» по fetch-JSON. Возвращает итоговый dict."""
    if not isinstance(fetch, dict):
        return {"статус": "не проверено",
                "причина": "на входе не JSON-объект (нужен вывод fetch_counterparty.py)",
                "дисклеймер": ДИСКЛЕЙМЕР}
    if "ошибка" in fetch and len(fetch) <= 3:
        return {"статус": "не проверено",
                "причина": "fetch_counterparty вернул ошибку: %s" % fetch.get("ошибка"),
                "дисклеймер": ДИСКЛЕЙМЕР}
    pf = _profiles()
    признаки = []
    состояние_возраста = {}
    _пр_статус(pf, fetch, признаки)
    _пр_недостоверность(pf, fetch, признаки)
    _пр_возраст(pf, fetch, canon, признаки, состояние_возраста)
    _пр_возраст_против_оборота(pf, fetch, canon, признаки, состояние_возраста)
    _пр_массовость(pf, fetch, признаки)
    _пр_штат(pf, fetch, canon, признаки)
    _пр_имущество(pf, fetch, canon, признаки)
    _пр_спецрежим(pf, fetch, canon, признаки)
    _пр_оквэд(pf, fetch, предмет, признаки)
    _пр_нагрузка(pf, fetch, признаки)
    _пр_отчётность(pf, fetch, признаки)
    _пр_вне_охвата(признаки)

    найдены = [p for p in признаки if p["статус"] == НАЙДЕН]
    нет = [p for p in признаки if p["статус"] == НЕТ]
    непров = [p for p in признаки if p["статус"] == НЕПРОВ]
    неприм = [p for p in признаки if p["статус"] == НЕПРИМ]
    вне = [p for p in признаки if p["статус"] == ВНЕ]
    знаменатель = len(найдены) + len(нет) + len(непров)
    доля = round(len(непров) / знаменатель, 3) if знаменатель else 1.0
    порог_доли, подпись_доли = _порог(canon, "бумажный_ндс_доля_не_проверено")
    если_нет_канона = порог_доли is None

    # Сбор движка — вышестоящий факт. Если deal-killer-источники молчали,
    # анализ признаков не может объявить проверку состоявшейся: собственный
    # знаменатель у него свой и может сойтись там, где сбора не было вовсе.
    итог_движка = fetch.get("_итог_проверки")
    if not isinstance(итог_движка, dict):
        сбор_состоялся, сбор_причина = False, (
            "во входных данных нет блока _итог_проверки — чем закончился сбор, "
            "неизвестно (вход собран старой версией движка или составлен вручную)")
    elif итог_движка.get("проверка_состоялась") is True:
        сбор_состоялся, сбор_причина = True, None
    else:
        сбор_состоялся = False
        сбор_причина = (итог_движка.get("вывод")
                        or "движок сообщил, что сбор не состоялся")
        # вывод движка начинается той же фразой — не удваиваем её
        for префикс in ("проверка НЕ состоялась: ", "проверка не состоялась: "):
            if сбор_причина.startswith(префикс):
                сбор_причина = сбор_причина[len(префикс):]
                break

    состоялась = (bool(знаменатель) and not если_нет_канона
                  and доля <= порог_доли and сбор_состоялся)

    if not сбор_состоялся:
        вывод = ("проверка НЕ состоялась: %s. Признаки ниже посчитаны по тому, "
                 "что источники всё-таки отдали, и отсутствие признака здесь "
                 "ничего не доказывает." % сбор_причина)
    elif если_нет_канона:
        вывод = ("проверка НЕ состоялась: %s — без порога доля «не проверено» не "
                 "оценивается" % подпись_доли)
    elif not состоялась:
        вывод = ("проверка НЕ состоялась: %d из %d признаков не проверено (%.0f%% при "
                 "пороге %.0f%%). Отсутствие признака и невозможность его проверить — "
                 "не одно и то же; перечень «не проверено» ниже."
                 % (len(непров), знаменатель, доля * 100, порог_доли * 100))
    elif найдены:
        вывод = ("проверка состоялась: посчитано %d признаков, не проверено %d. "
                 "В открытых данных видно: %s. Это факты, а не налоговый вывод."
                 % (знаменатель, len(непров),
                    "; ".join(p["факт"].replace("в открытых данных видно: ", "").rstrip(". ")
                              for p in найдены)))
    else:
        вывод = ("проверка состоялась: посчитано %d признаков, не проверено %d, "
                 "ни один признак «бумажного НДС» из посчитанных не подтвердился. "
                 "Это не означает, что вычет устоит: главное доказательство — "
                 "разрывы АСК НДС-2 — в открытых данных не видно."
                 % (знаменатель, len(непров)))

    сделка = {"предмет": предмет, "сумма_руб": сумма}
    год = _последний_год(fetch)
    выручка = _строка(год, "2110") if год else None
    if сумма and выручка:
        сделка["доля_в_выручке"] = (
            "сумма сделки — %.2f%% выручки продавца за %s г. (%s)"
            % (сумма / выручка * 100, год.get("год"), _руб(выручка)))
    elif сумма:
        сделка["доля_в_выручке"] = "выручка продавца не получена — долю не посчитать"

    return {
        "статус": "ок" if состоялась else "проверка не состоялась",
        "инн": fetch.get("инн"),
        "наименование": (_поле(fetch, "егрюл", "наименование_полное")
                         or _поле(fetch, "риски", "наименование")),
        "дата_проверки": str(_сегодня(fetch)),
        "сделка": сделка,
        "вывод": вывод,
        "счётчик": {"всего_признаков": len(признаки), "в_знаменателе": знаменатель,
                    "найдено": len(найдены), "не_выявлено": len(нет),
                    "не_проверено": len(непров), "не_применимо": len(неприм),
                    "вне_охвата": len(вне), "доля_не_проверено": доля,
                    "порог": подпись_доли},
        "что_видно": найдены,
        "что_не_выявлено": нет,
        "не_проверено": непров,
        "не_применимо": неприм,
        "вне_охвата": вне,
        "чего_не_видно_в_открытых_данных": ЧЕГО_НЕ_ВИДНО,
        "что_можно_проверить_самому": ПРОВЕРИТЬ_САМОМУ,
        "нормы": [dict(НОРМЫ[k], ключ=k) for k in НОРМЫ],
        "дисклеймер": ДИСКЛЕЙМЕР,
    }


# --- CLI --------------------------------------------------------------------------

def main(argv):
    args = argv[1:]
    предмет, сумма, канон_путь, вход = None, None, CANON_PATH, None
    i = 0
    while i < len(args):
        a = args[i]
        if a in ("-h", "--help"):
            sys.stderr.write(__doc__)
            return 2
        if a in ("--предмет", "--предмет-сделки", "--subject"):
            if i + 1 >= len(args):
                sys.stderr.write("после %s нужен текст предмета сделки\n" % a)
                return 2
            предмет, i = args[i + 1], i + 2
        elif a in ("--сумма", "--amount"):
            if i + 1 >= len(args):
                sys.stderr.write("после %s нужно число (рубли)\n" % a)
                return 2
            try:
                сумма = float(args[i + 1].replace(" ", "").replace(",", "."))
            except ValueError:
                sys.stderr.write("сумма %r не число\n" % args[i + 1])
                return 2
            i += 2
        elif a == "--канон":
            if i + 1 >= len(args):
                sys.stderr.write("после --канон нужен путь к canon_ru.json\n")
                return 2
            канон_путь, i = args[i + 1], i + 2
        elif a == "--stdin":
            вход, i = "--stdin", i + 1
        elif a.startswith("-"):
            sys.stderr.write("неизвестный аргумент %s\n" % a)
            return 2
        else:
            вход, i = a, i + 1
    if вход is None:
        sys.stderr.write(__doc__)
        return 2
    try:
        if вход == "--stdin":
            fetch = json.loads(sys.stdin.read())
        else:
            with open(вход, encoding="utf-8") as fh:
                fetch = json.load(fh)
    except (OSError, ValueError) as e:
        out = {"статус": "не проверено", "причина": "вход не читается как JSON (%s)" % e,
               "дисклеймер": ДИСКЛЕЙМЕР}
        sys.stdout.write(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
        return 1
    out = analyze(fetch, canon=load_canon(канон_путь), предмет=предмет, сумма=сумма)
    sys.stdout.write(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
    # «проверка не состоялась» — валидный результат анализа, а не сбой: код 0.
    return 1 if out.get("статус") == "не проверено" else 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv))
    except Exception as e:  # никогда не traceback'ом
        sys.stdout.write(json.dumps(
            {"статус": "не проверено",
             "причина": "внутренняя ошибка: %s: %s" % (type(e).__name__, e),
             "дисклеймер": ДИСКЛЕЙМЕР}, ensure_ascii=False, indent=2) + "\n")
        sys.exit(1)
