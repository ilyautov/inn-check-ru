_ИМЕНА_СТРОК = {"2110": ("выручка",), "1600": ("активы",), "1200": ("оборотные_активы",)}


# ГИР БО отдаёт строки отчётности в ТЫСЯЧАХ рублей, а канон и суммы сделок —
# в рублях. Та же конвенция и конвертация, что в droblenie_check.py: без неё
# компания с выручкой 20 млрд ₽ читается как 20 млн ₽ и «не превышает порог
# освобождения от НДС» — утверждение, обратное правде.
# Проверено 19.09.2026 сверкой с дампом ФНС revexp по трём ИНН: отношение
# СумДоход (руб.) к стр. 2110 — 1010, 1002 и 1025.
ТЫС_В_РУБ = 1000


def _строка(rec, code):
    """Строка отчётности В РУБЛЯХ (источник отдаёт тыс. руб.)."""
    строки = rec.get("строки")
    if isinstance(строки, dict) and isinstance(строки.get(code), (int, float)):
        return float(строки[code]) * ТЫС_В_РУБ
    for имя in _ИМЕНА_СТРОК.get(code, ()):
        if isinstance(rec.get(имя), (int, float)):
            return float(rec[имя]) * ТЫС_В_РУБ
    return None


def _последний_год(fetch):
    """Самый свежий год отчётности ГИР БО или None."""
    fin = fetch.get("финансы")
    годы = fin.get("отчётность_по_годам") if isinstance(fin, dict) else None
    годы = [g for g in (годы or []) if isinstance(g, dict)]
    if not годы:
        return None

    def ключ(g):
        try:
            return int(g.get("год"))
        except (TypeError, ValueError):
            return 0
    годы.sort(key=ключ, reverse=True)
    return годы[0]


