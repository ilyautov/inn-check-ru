def _ссч(fetch):
    """Раскрытая ССЧ (число) или None. Пустое поле — «не раскрыта», НЕ «ноль»."""
    знач = _поле(fetch, "риски", "численность_сотрудников", "среднесписочная_за_год")
    if isinstance(знач, bool) or знач is None:
        return None
    if isinstance(знач, (int, float)):
        return float(знач)
    if isinstance(знач, str):
        try:
            return float(знач.replace(" ", "").replace(",", "."))
        except ValueError:
            return None
    return None


