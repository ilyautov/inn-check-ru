def _read_canon_text(path):
    """Канон: путь репозитория -> package-data колеса. Нет нигде -> None."""
    try:
        with open(path, encoding="utf-8") as fh:
            return fh.read()
    except OSError:
        pass
    try:
        from importlib.resources import files
        return (files("inn_check_ru_data") / "canon_ru.json").read_text(encoding="utf-8")
    except Exception:
        return None


def load_canon(path=CANON_PATH):
    text = _read_canon_text(path)
    if text is None:
        return None
    try:
        пороги = json.loads(text).get("пороги")
    except (ValueError, AttributeError):
        return None
    return пороги if isinstance(пороги, dict) else None


def _порог(canon, ключ):
    """(значение, «источник (проверено дата)») или (None, причина)."""
    if not isinstance(canon, dict):
        return None, "канон data/canon_ru.json отсутствует или битый"
    rec = canon.get(ключ)
    if not isinstance(rec, dict) or rec.get("значение") is None:
        return None, "в data/canon_ru.json нет порога «%s»" % ключ
    подпись = "data/canon_ru.json:%s = %s %s%s (проверено %s)" % (
        ключ, rec["значение"], rec.get("единица") or "",
        ", эвристика, не откалибровано" if rec.get("эвристика") else "",
        rec.get("дата_проверки") or "дата неизвестна")
    return rec["значение"], подпись


def _дата(s):
    if not isinstance(s, str):
        return None
    m = _ДАТА_DMY.match(s.strip())
    if m:
        d, mo, y = m.groups()
    else:
        m = _ДАТА_ISO.match(s.strip())
        if not m:
            return None
        y, mo, d = m.groups()
    try:
        return datetime.date(int(y), int(mo), int(d))
    except ValueError:
        return None


def _сегодня(fetch):
    """Опорная дата: дата проверки из fetch-JSON, иначе сегодняшняя (UTC)."""
    for блок in (fetch.get("_доступность") or {}).values():
        if isinstance(блок, dict) and _дата(блок.get("дата")):
            return _дата(блок["дата"])
    return datetime.datetime.now(tz=datetime.timezone.utc).date()


def _месяцев(с, по):
    return (по.year - с.year) * 12 + (по.month - с.month) - (1 if по.day < с.day else 0)


def _мес_текст(мес):
    """284 -> «284 мес. (23 г. 8 мес.)»; до двух лет — просто месяцы."""
    if мес < 24:
        return "%d мес." % мес
    return "%d мес. (%d г. %d мес.)" % (мес, мес // 12, мес % 12)


def _руб(x):
    """9300000.0 -> «9,3 млн ₽»; мелкие суммы — как есть."""
    if x is None:
        return "нет данных"
    if abs(x) >= 1e9:
        return "%.2f млрд ₽" % (x / 1e9)
    if abs(x) >= 1e6:
        return "%.1f млн ₽" % (x / 1e6)
    return "%.0f ₽" % x


def _состояние(pf, fetch, блок):
    """(состояние, причина, дата). Без profiles.py — честное «не проверено»."""
    if pf is None:
        return "не проверено", "scripts/profiles.py не импортируется — состояния блоков не прочитаны", None
    try:
        return pf._состояние_блока(fetch, блок)
    except Exception as e:
        return "не проверено", "состояние блока не прочитано: %s" % type(e).__name__, None


def _поле(fetch, блок, *имена):
    """Значение первого непустого поля блока; заглядывает и в подблок «детали»."""
    b = fetch.get(блок)
    if not isinstance(b, dict):
        return None
    детали = b.get("детали") if isinstance(b.get("детали"), dict) else {}
    for имя in имена:
        for holder in (b, детали):
            if isinstance(holder, dict) and holder.get(имя) is not None:
                return holder[имя]
    return None


def _причина_деталей(fetch):
    """Почему пусты поля детального эндпоинта pb (ССЧ, спецрежим, массовость)."""
    риски = fetch.get("риски")
    детали = риски.get("детали") if isinstance(риски, dict) else None
    if isinstance(детали, dict) and детали.get("причина"):
        return "риски.детали: %s" % детали["причина"]
    return ("поле не отдано: детальный эндпоинт «Прозрачного бизнеса» "
            "(company-proc.json) данных не дал")


def _слова(текст):
    return {w[:-2] if len(w) > 5 else w for w in _СЛОВО.findall((текст or "").lower())}


