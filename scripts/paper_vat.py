def _нормы(fetch):
    """(оценка benchmarks.оценить, причина отказа). Нет таблицы -> (None, причина)."""
    bm = _benchmarks()
    if bm is None:
        return None, "scripts/benchmarks.py не импортируется — нормы не посчитать"
    try:
        инн, оквэд, регион, выручка = bm.из_fetch(fetch)
        оценка = bm.оценить(инн, оквэд, регион, выручка)
    except Exception as e:
        return None, "нормы не посчитаны: %s: %s" % (type(e).__name__, e)
    if not isinstance(оценка, dict) or оценка.get("статус") != "проверено":
        причина = (оценка or {}).get("причина") if isinstance(оценка, dict) else None
        return None, причина or _нет_бенчмарков()
    return оценка, None


def _пр_нагрузка(pf, fetch, признаки):
    """Два признака из §2 спека, которым нужны отраслевые нормы задачи 4."""
    оценка, причина_норм = _нормы(fetch)

    # Уплаченный НДС конкретной компании в открытых данных движка не виден:
    # дамп paytax агрегируется в норму отрасли, но по ИНН сюда не приходит.
    # Нормы отрасли без числа компании сравнивать не с чем — «не проверено».
    отраслевая = None
    if оценка:
        отраслевая = (оценка.get("нормы") or {}).get("ндс_к_выручке")
    признаки.append(_пр(
        "ндс_к_выручке", НЕПРОВ,
        "отношение уплаченного НДС к доходам не проверено"
        + ("" if отраслевая is None
           else " (норма отрасли — %.2f%% выручки)" % (отраслевая * 100)),
        причина="уплаченного этой компанией НДС в открытых данных нет: дамп ФНС "
                "7707329152-paytax отдаёт суммы по ИНН, но движок их не собирает; "
                "отраслевая норма без числа компании сравнивать не с чем",
        норма=_норма("ММ-3-06/333@")))

    ссч = _ссч(fetch)
    год = _последний_год(fetch)
    выручка = _строка(год, "2110") if год else None
    значение = None
    if ссч and выручка is not None and ссч > 0:
        значение = round(выручка / ссч, 2)

    if значение is None:
        признаки.append(_пр(
            "выручка_на_сотрудника", НЕПРОВ,
            "выручка на сотрудника против отраслевой медианы не проверена",
            значение=None,
            причина=("ССЧ в открытых данных не раскрыта (%s)" % _причина_деталей(fetch)
                     if ссч is None else
                     "выручки за последний год в ГИР БО нет — отношение не считается")))
        return
    if оценка is None:
        признаки.append(_пр(
            "выручка_на_сотрудника", НЕПРОВ,
            "выручка на сотрудника — %s на чел., но сравнить не с чем"
            % _руб(значение),
            значение=значение, причина=причина_норм))
        return

    медиана = (оценка.get("нормы") or {}).get("выручка_на_сотрудника")
    группа = оценка.get("группа") or {}
    хвост = "группа %s, n = %s; дампы ФНС от %s" % (
        группа.get("ключ"), группа.get("n"), _дата_дампов(оценка))

    # Нормы сами сообщают, что группа собрана по смещённой выборке (в «среднем»
    # и «крупном» есть только субъекты МСП). Поднимать из такого сравнения
    # признак нельзя: отрыв от медианы будет у любой настоящей крупной
    # компании, и это скажет про выборку, а не про контрагента.
    if оценка.get("предупреждение"):
        признаки.append(_пр(
            "выручка_на_сотрудника", НЕПРОВ,
            "выручка на сотрудника — %s на чел.; отраслевая норма для этой "
            "размерной группы непригодна" % _руб(значение),
            значение=значение,
            причина="%s (%s)" % (оценка["предупреждение"], хвост)))
        return
    if not медиана:
        признаки.append(_пр(
            "выручка_на_сотрудника", НЕПРОВ,
            "выручка на сотрудника — %s на чел.; в норме отрасли медианы нет"
            % _руб(значение),
            значение=значение,
            причина="группа найдена, но показатель «выручка на сотрудника» в ней "
                    "пуст (%s)" % хвост))
        return
    во_сколько = значение / медиана
    источник = "открытые данные ФНС, нормы benchmarks.py; %s" % хвост
    if во_сколько >= 3:
        признаки.append(_пр(
            "выручка_на_сотрудника", НАЙДЕН,
            "в открытых данных видно: выручка на сотрудника %s на чел. — в %.1f раза "
            "выше медианы отрасли (%s на чел.). Это соотношение, а не вывод о "
            "фиктивности: так же выглядят и посредник, и компания, отдавшая работы "
            "на подряд." % (_руб(значение), во_сколько, _руб(медиана)),
            источник=источник, дата=_дата_дампов(оценка), значение=значение,
            норма=_норма("ММ-3-06/333@")))
    else:
        признаки.append(_пр(
            "выручка_на_сотрудника", НЕТ,
            "выручка на сотрудника %s на чел. против медианы отрасли %s на чел. "
            "(%.1fx) — без отрыва" % (_руб(значение), _руб(медиана), во_сколько),
            источник=источник, дата=_дата_дампов(оценка), значение=значение))


