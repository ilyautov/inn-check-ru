#!/usr/bin/env python3
"""
opendata_refresh.py — слой дампов открытых данных ФНС (file.nalog.ru/opendata).
Скачивание, докачка, проверка целостности и потоковое чтение. Только stdlib.

Паттерн registries_refresh.py: дескриптор на датасет, независимая деградация,
честная причина. Дампы лежат в ~/.cache/inn-check-ru/opendata/<id>/ и НЕ едут
в репозиторий: суммарно ≈2,5 ГБ.

Использование:
    python3 opendata_refresh.py --статус
    python3 opendata_refresh.py --refresh                 # все обязательные
    python3 opendata_refresh.py --refresh --датасет rsmp  # один датасет
    python3 opendata_refresh.py --refresh --полная-проверка   # zipfile.testzip
    python3 opendata_refresh.py --показать revexp --строк 3   # разбор дампа

ССЫЛКА НЕ ЗАШИВАЕТСЯ. Имя файла дампа содержит дату выгрузки и версию
структуры (`data-<дата>-structure-<версия>.zip`), поэтому URL резолвится со
страницы датасета https://www.nalog.gov.ru/opendata/<id>/. На странице есть и
другие ссылки на file.nalog.ru (описание формата .doc/.zip, .xsd схема), и у
части датасетов выложено несколько месячных выгрузок — поэтому берётся не
«первая ссылка», а самый свежий `data-*-structure-*.zip` (проверено живьём
19.09.2026: на странице rsmp первый же href на file.nalog.ru — это
VO_RRMSPSV_2_213_04_04_06.zip, описание формата, а не данные).

ДАТА В ИМЕНИ ФАЙЛА В ДВУХ ФОРМАТАХ (снято живьём 19.09.2026):
    revexp/paytax/sshr2019/snr — YYYYMMDD (`data-20260825-...`)
    rsmp                       — DDMMYYYY (`data-10092026-...`)
Поэтому дата разбирается автоопределением: YYYYMMDD принимается, только если
год попадает в 2000..2100, иначе пробуется DDMMYYYY.

ФОРМАТ СОДЕРЖИМОГО — проверен по реальным файлам 19.09.2026, см. `структура`
в дескрипторах. Внутри ZIP — много плоских XML (у revexp 2118 файлов), в каждом
`<Файл ... ТипИнф="..."><Документ ...>` с атрибутами; текстовых узлов нет,
все значения — в атрибутах.

РАЗБОР — НЕ ElementTree. Причины две, обе практические:
  1) документы плоские и целиком атрибутивные, а объём — десятки ГБ в
     распакованном виде; split+regex по реальной структуре быстрее ET в разы;
  2) на части машин pyexpat ломается несовместимостью с системным libexpat
     (проверено здесь 19.09.2026: `import xml.etree` падает на homebrew-python),
     и тогда ET-парсер утащил бы за собой весь слой дампов.
Значения атрибутов в XML не могут содержать сырой `"` (он обязан быть
экранирован), поэтому regex `атрибут="([^"]*)"` по чанку одного `<Документ`
однозначен.
"""

