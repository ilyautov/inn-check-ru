_ДОК_RE = re.compile(r"<Документ\b")
_АТР = {}


_ПАРА = re.compile(r'([А-Яа-яA-Za-z0-9_]+)="([^"]*)"')


def _тег_rx(тег):
    rx = _АТР.get(тег)
    if rx is None:
        rx = _АТР[тег] = re.compile(r"<%s\b([^>]*)>" % re.escape(тег))
    return rx


def _пары(сырое):
    """Атрибуты элемента -> dict. Значения раскодируются: в дампе НаимОрг
    приходит как ООО &quot;ЮГ-АГРО&quot;, и без unescape кавычки утекут в
    ключи группировки и в отчёт."""
    return {k: _html.unescape(v) for k, v in _ПАРА.findall(сырое)}


def _атрибуты(чанк, тег):
    """Атрибуты первого вхождения элемента `тег` в чанке -> dict."""
    m = _тег_rx(тег).search(чанк)
    return _пары(m.group(1)) if m else {}


def _все_атрибуты(чанк, тег):
    return [_пары(m.group(1)) for m in _тег_rx(тег).finditer(чанк)]


def _число(s):
    if s in (None, ""):
        return None
    try:
        return float(s)
    except ValueError:
        return None


def _год(дата_сост):
    """'31.12.2025' -> 2025; '01.08.2026' -> 2026."""
    if not дата_сост or len(дата_сост) != 10:
        return None
    try:
        return int(дата_сост[6:])
    except ValueError:
        return None


def _общее(чанк):
    док = _атрибуты(чанк, "Документ")
    нп = _атрибуты(чанк, "СведНП")
    return {
        "инн": нп.get("ИННЮЛ"),
        "наименование": нп.get("НаимОрг"),
        "дата_сост": док.get("ДатаСост"),
        "год": _год(док.get("ДатаСост")),
    }


def _разбор_revexp(чанк):
    r = _общее(чанк)
    дх = _атрибуты(чанк, "СведДохРасх")
    r["доход"] = _число(дх.get("СумДоход"))
    r["расход"] = _число(дх.get("СумРасход"))
    return r


def _разбор_paytax(чанк):
    r = _общее(чанк)
    налоги = {}
    сумма = 0.0
    for a in _все_атрибуты(чанк, "СвУплСумНал"):
        v = _число(a.get("СумУплНал")) or 0.0
        налоги[a.get("НаимНалог") or ""] = v
        сумма += v
    r["налоги"] = налоги
    r["сумма_налогов"] = сумма
    return r


def _разбор_sshr(чанк):
    r = _общее(чанк)
    v = _атрибуты(чанк, "СведССЧР").get("КолРаб")
    try:
        r["ссч"] = int(v) if v not in (None, "") else None
    except ValueError:
        r["ссч"] = None
    return r


def _разбор_snr(чанк):
    r = _общее(чанк)
    снр = _атрибуты(чанк, "СведСНР")
    for ключ, атр in (("есхн", "ПризнЕСХН"), ("усн", "ПризнУСН"),
                      ("аусн", "ПризнАУСН"), ("срп", "ПризнСРП")):
        r[ключ] = снр.get(атр) == "1" if атр in снр else None
    return r


# КатСубМСП из реального дампа: 1 — микро, 2 — малое, 3 — среднее.
КАТЕГОРИИ_МСП = {"1": "микропредприятие", "2": "малое", "3": "среднее"}


def _разбор_rsmp(чанк):
    док = _атрибуты(чанк, "Документ")
    юл = _атрибуты(чанк, "ОргВклМСП")
    ип = _атрибуты(чанк, "ИПВклМСП")
    мн = _атрибуты(чанк, "СведМН")
    рег = _атрибуты(чанк, "Регион")
    осн = _атрибуты(чанк, "СвОКВЭДОсн")
    код = осн.get("КодОКВЭД")
    инн = юл.get("ИННЮЛ") or ип.get("ИННФЛ")
    return {
        "инн": инн,
        "наименование": юл.get("НаимЮЛПолн"),
        "тип": "юрлицо" if юл.get("ИННЮЛ") else ("ип" if ип else None),
        "дата_сост": док.get("ДатаСост"),
        "год": _год(док.get("ДатаСост")),
        "категория_мсп": КАТЕГОРИИ_МСП.get(док.get("КатСубМСП")),
        "регион": (мн.get("КодРегион") or "").zfill(2) if мн.get("КодРегион") else None,
        "регион_наименование": рег.get("Наим"),
        "регион_тип": рег.get("Тип"),
        "оквэд": код,
        "оквэд2": код.split(".")[0].zfill(2) if код else None,
        "оквэд_наименование": осн.get("НаимОКВЭД"),
    }


ПАРСЕРЫ = {
    "revexp": _разбор_revexp,
    "paytax": _разбор_paytax,
    "sshr2019": _разбор_sshr,
    "snr": _разбор_snr,
    "rsmp": _разбор_rsmp,
}


def разобрать_xml(текст, ид):
    """Один XML дампа -> генератор словарей по документам."""
    парсер = ПАРСЕРЫ[ид]
    куски = текст.split("<Документ ")
    for кусок in куски[1:]:
        конец = кусок.find("</Документ>")
        чанк = "<Документ " + (кусок if конец < 0 else кусок[:конец])
        рec = парсер(чанк)
        if рec.get("инн"):
            yield рec


def итерировать(ид, путь=None, лимит=None, на_файл=None):
    """Потоковый разбор дампа: по одному XML из ZIP за раз, ничего не копится.

    `на_файл(имя, номер, всего)` — необязательный колбэк прогресса."""
    архив = путь or путь_дампа(ид)
    if архив is None:
        raise FileNotFoundError(
            "дамп %s не найден в %s — opendata_refresh.py --refresh --датасет %s"
            % (ид, ДАТАСЕТЫ[ид]["каталог"], ид))
    выдано = 0
    with zipfile.ZipFile(архив) as z:
        имена = [n for n in z.namelist() if n.lower().endswith(".xml")]
        for номер, имя in enumerate(имена, 1):
            if на_файл:
                на_файл(имя, номер, len(имена))
            текст = z.read(имя).decode("utf-8", "replace")
            for рec in разобрать_xml(текст, ид):
                yield рec
                выдано += 1
                if лимит and выдано >= лимит:
                    return
            del текст


