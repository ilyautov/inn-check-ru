def _refresh(датасеты, полная):
    результаты = [обновить(ид, полная) for ид in датасеты]
    ок = sum(1 for r in результаты if r["статус"] in ("ок", "уже свежий"))
    return _out({"статус": "обновлено %d/%d датасетов" % (ок, len(результаты)),
                 "результаты": результаты}, 0 if ок == len(результаты) else 1)


def _показать(ид, строк):
    записи = list(итерировать(ид, лимит=строк))
    return _out({"датасет": ид, "название": ДАТАСЕТЫ[ид]["название"],
                 "структура": ДАТАСЕТЫ[ид]["структура"],
                 "период": ДАТАСЕТЫ[ид]["период"],
                 "файл": путь_дампа(ид), "записи": записи})


def _арг(args, имя):
    if имя in args:
        i = args.index(имя)
        if i + 1 < len(args):
            return args[i + 1]
    return None


def main(argv):
    args = argv[1:]
    if not args:
        sys.stderr.write(__doc__)
        return 2
    ид = _арг(args, "--датасет")
    if ид is not None and ид not in ДАТАСЕТЫ:
        sys.stderr.write("Неизвестный датасет %r; есть: %s\n"
                         % (ид, ", ".join(ДАТАСЕТЫ)))
        return 2
    if "--статус" in args:
        res = статус()
        return _out(res, 0 if res["статус"] == ПРОВЕРЕНО else 1)
    if "--refresh" in args:
        return _refresh([ид] if ид else ОБЯЗАТЕЛЬНЫЕ, "--полная-проверка" in args)
    if "--показать" in args:
        цель = _арг(args, "--показать")
        if цель not in ДАТАСЕТЫ:
            sys.stderr.write("После --показать нужен id датасета: %s\n"
                             % ", ".join(ДАТАСЕТЫ))
            return 2
        try:
            строк = int(_арг(args, "--строк") or 3)
        except ValueError:
            строк = 3
        return _показать(цель, строк)
    sys.stderr.write("Укажите --статус, --refresh или --показать <датасет>\n")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
