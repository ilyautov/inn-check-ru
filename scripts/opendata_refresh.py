# ---------------------------------------------------------------- имя и дата

_ИМЯ_RE = re.compile(r"^data-(\d{8})-structure-(\d{8})\.zip$")


def разобрать_дату(восемь):
    """'20260825' -> '2026-08-25'; '10092026' -> '2026-09-10'; иначе None.

    Оба формата реально встречаются на file.nalog.ru (см. модульный docstring),
    поэтому формат определяется по валидности, а не по дескриптору."""
    if not восемь or len(восемь) != 8 or not восемь.isdigit():
        return None
    for г, м, д in ((восемь[:4], восемь[4:6], восемь[6:]),
                    (восемь[4:], восемь[2:4], восемь[:2])):
        try:
            год, месяц, день = int(г), int(м), int(д)
        except ValueError:
            continue
        if not (2000 <= год <= 2100 and 1 <= месяц <= 12 and 1 <= день <= 31):
            continue
        try:
            time.strptime("%04d-%02d-%02d" % (год, месяц, день), "%Y-%m-%d")
        except ValueError:
            continue
        return "%04d-%02d-%02d" % (год, месяц, день)
    return None


def разобрать_имя(имя):
    """'data-20260825-structure-20180110.zip' -> (дата_выгрузки, версия_структуры)."""
    m = _ИМЯ_RE.match(os.path.basename(имя))
    if not m:
        return None, None
    return разобрать_дату(m.group(1)), разобрать_дату(m.group(2))


