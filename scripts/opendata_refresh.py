def _запрос(url, headers=None):
    h = {"User-Agent": UA}
    h.update(headers or {})
    return urllib.request.Request(url, headers=h)


def резолв(ид, ctx=None):
    """Страница датасета -> (url, имя, дата_выгрузки, версия_структуры) или
    (None, причина, None, None). Берётся самая свежая выгрузка data-*.zip."""
    d = ДАТАСЕТЫ[ид]
    try:
        with urllib.request.urlopen(_запрос(d["страница"]), timeout=TIMEOUT,
                                    context=ctx or _ssl_context()) as resp:
            html = resp.read().decode("utf-8", "replace")
    except Exception as e:
        return None, "страница датасета недоступна: %s" % type(e).__name__, None, None
    ссылки = re.findall(
        r'https://file\.nalog\.ru/opendata/%s/(data-\d{8}-structure-\d{8}\.zip)'
        % re.escape(d["датасет"]), html)
    кандидаты = []
    for имя in dict.fromkeys(ссылки):
        выгрузка, структура = разобрать_имя(имя)
        if выгрузка:
            кандидаты.append((выгрузка, структура, имя))
    if not кандидаты:
        return (None, "на странице %s нет ссылки data-*-structure-*.zip — "
                      "разметка изменилась" % d["страница"], None, None)
    кандидаты.sort(reverse=True)
    выгрузка, структура, имя = кандидаты[0]
    url = "https://file.nalog.ru/opendata/%s/%s" % (d["датасет"], имя)
    return url, имя, выгрузка, структура


def _размер_на_сервере(url, ctx):
    try:
        req = _запрос(url)
        req.get_method = lambda: "HEAD"
        with urllib.request.urlopen(req, timeout=TIMEOUT, context=ctx) as resp:
            n = resp.headers.get("Content-Length")
            return int(n) if n else None
    except Exception:
        return None


def _докачать(url, путь, ожидаемо, ctx):
    """Докачка через Range. Возвращает (скачано_байт, причина|None)."""
    есть = os.path.getsize(путь) if os.path.exists(путь) else 0
    if ожидаемо is not None and есть >= ожидаемо:
        return 0, None
    headers = {"Range": "bytes=%d-" % есть} if есть else {}
    try:
        with urllib.request.urlopen(_запрос(url, headers), timeout=TIMEOUT,
                                    context=ctx) as resp:
            # Сервер проигнорировал Range (200 вместо 206) -> пишем с нуля,
            # иначе получим склейку двух копий начала файла.
            режим = "ab" if (есть and resp.status == 206) else "wb"
            скачано = 0
            with open(путь, режим) as fh:
                while True:
                    кусок = resp.read(ЧАНК)
                    if not кусок:
                        break
                    fh.write(кусок)
                    скачано += len(кусок)
        return скачано, None
    except Exception as e:
        return 0, "%s: %s" % (type(e).__name__, e)


# ---------------------------------------------------------------- проверка

def проверить_zip(путь, полная=False):
    """(ок, режим, файлов, причина). Полная — zipfile.testzip() по спеку;
    выборочная — центральный каталог + CRC первой/средней/последней записи."""
    try:
        with zipfile.ZipFile(путь) as z:
            имена = z.namelist()
            if not имена:
                return False, "полная" if полная else "выборочная", 0, "архив пуст"
            if полная:
                битый = z.testzip()
                if битый:
                    return False, "полная", len(имена), "битая запись: %s" % битый
                return True, "полная (zipfile.testzip)", len(имена), None
            индексы = sorted({0, len(имена) // 2, len(имена) - 1})[:ВЫБОРОЧНО]
            for i in индексы:
                with z.open(имена[i]) as fh:
                    while fh.read(ЧАНК):
                        pass
            return (True, "выборочная (CRC %d из %d записей)"
                    % (len(индексы), len(имена)), len(имена), None)
    except Exception as e:
        return False, "полная" if полная else "выборочная", 0, \
            "%s: %s" % (type(e).__name__, e)


def _sha256(путь):
    h = hashlib.sha256()
    with open(путь, "rb") as fh:
        while True:
            кусок = fh.read(ЧАНК)
            if not кусок:
                break
            h.update(кусок)
    return h.hexdigest()


# ---------------------------------------------------------------- кэш

def путь_дампа(ид, каталог=None):
    """Самый свежий data-*.zip в кэше датасета или None."""
    d = каталог or ДАТАСЕТЫ[ид]["каталог"]
    try:
        файлы = [f for f in os.listdir(d) if _ИМЯ_RE.match(f)]
    except OSError:
        return None
    if not файлы:
        return None
    файлы.sort(key=lambda f: (разобрать_имя(f)[0] or "", f), reverse=True)
    return os.path.join(d, файлы[0])


def _мета_путь(путь):
    return путь + ".meta.json"


def читать_мету(путь):
    try:
        with open(_мета_путь(путь), encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError):
        return None


def обновить(ид, полная=False, ctx=None):
    """Один датасет: резолв -> докачка -> проверка ZIP -> meta.json."""
    d = ДАТАСЕТЫ[ид]
    ctx = ctx or _ssl_context()
    os.makedirs(d["каталог"], exist_ok=True)
    url, имя, выгрузка, структура = резолв(ид, ctx)
    if url is None:
        return {"датасет": ид, "название": d["название"],
                "статус": НЕ_ПРОВЕРЕНО, "причина": имя,
                "что_делать": "откройте %s и положите data-*.zip в %s"
                              % (d["страница"], d["каталог"])}
    путь = os.path.join(d["каталог"], имя)
    ожидаемо = _размер_на_сервере(url, ctx)
    было = os.path.getsize(путь) if os.path.exists(путь) else 0
    # «Файл в кэше и дамп на сервере совпали по имени» (спек §1.1): имя то же,
    # размер сошёлся, архив читается -> не перекачиваем.
    if было and (ожидаемо is None or было == ожидаемо):
        ок, режим, файлов, причина = проверить_zip(путь, полная)
        if ок:
            мета = читать_мету(путь) or {}
            if not мета.get("sha256"):
                мета = _записать_мету(путь, url, имя, выгрузка, структура,
                                      режим, файлов)
            return {"датасет": ид, "название": d["название"], "статус": "уже свежий",
                    "файл": путь, "дата_выгрузки": выгрузка,
                    "версия_структуры": структура, "байт": было,
                    "файлов_в_архиве": файлов, "проверка": режим}
    скачано, причина = _докачать(url, путь, ожидаемо, ctx)
    ок, режим, файлов, причина_zip = проверить_zip(путь, полная)
    if not ок:
        return {"датасет": ид, "название": d["название"], "статус": НЕ_ПРОВЕРЕНО,
                "файл": путь, "байт": os.path.getsize(путь) if os.path.exists(путь) else 0,
                "ожидалось_байт": ожидаемо,
                "причина": причина or причина_zip,
                "что_делать": "повторите --refresh --датасет %s: докачка идёт "
                              "через Range, скачанное не теряется" % ид}
    мета = _записать_мету(путь, url, имя, выгрузка, структура, режим, файлов)
    return {"датасет": ид, "название": d["название"], "статус": "ок",
            "файл": путь, "дата_выгрузки": выгрузка, "версия_структуры": структура,
            "байт": мета["размер"], "скачано_байт": скачано,
            "файлов_в_архиве": файлов, "проверка": режим, "sha256": мета["sha256"]}


def _записать_мету(путь, url, имя, выгрузка, структура, режим, файлов):
    мета = {
        "url": url,
        "имя": имя,
        "дата_выгрузки": выгрузка,
        "версия_структуры": структура,
        "размер": os.path.getsize(путь),
        "sha256": _sha256(путь),
        "дата_скачивания": time.strftime("%Y-%m-%d"),
        "проверка": режим,
        "файлов_в_архиве": файлов,
    }
    with open(_мета_путь(путь), "w", encoding="utf-8") as fh:
        json.dump(мета, fh, ensure_ascii=False, indent=2)
    return мета


def статус():
    """Что в кэше, насколько свежее, чего не хватает."""
    строки = {}
    нет = []
    for ид, d in ДАТАСЕТЫ.items():
        путь = путь_дампа(ид)
        if путь is None:
            строки[ид] = {"название": d["название"], "статус": "нет в кэше",
                          "обязательный": d["обязательный"],
                          "каталог": d["каталог"],
                          "что_делать": "opendata_refresh.py --refresh --датасет %s" % ид}
            if d["обязательный"]:
                нет.append(ид)
            continue
        мета = читать_мету(путь) or {}
        выгрузка = мета.get("дата_выгрузки") or разобрать_имя(путь)[0]
        возраст = None
        if выгрузка:
            try:
                возраст = round(
                    (time.time() - time.mktime(time.strptime(выгрузка, "%Y-%m-%d")))
                    / 86400.0, 1)
            except ValueError:
                возраст = None
        ок, режим, файлов, причина = проверить_zip(путь, полная=False)
        строки[ид] = {
            "название": d["название"],
            "статус": "ок" if ок else "битый",
            "обязательный": d["обязательный"],
            "файл": путь,
            "байт": os.path.getsize(путь),
            "дата_выгрузки": выгрузка,
            "версия_структуры": мета.get("версия_структуры") or разобрать_имя(путь)[1],
            "возраст_выгрузки_дней": возраст,
            "файлов_в_архиве": файлов,
            "sha256": мета.get("sha256"),
            "мета": bool(мета),
            "причина": причина,
        }
        if not ок and d["обязательный"]:
            нет.append(ид)
    предупреждения = []
    for ид, d in ДАТАСЕТЫ.items():
        if not d["обязательный"] and строки[ид]["статус"] != "ок":
            предупреждения.append(
                "%s не готов (%s) — %s; скачать: --refresh --датасет %s"
                % (ид, строки[ид]["статус"], d["название"], ид))
    if строки.get("rsmp", {}).get("статус") != "ок":
        предупреждения.append(
            "без дампа rsmp benchmarks.py --построить не соберёт отраслевой "
            "разрез: ОКВЭД по ИНН есть только там")
    return {
        "статус": ПРОВЕРЕНО if not нет else "не хватает дампов",
        "не_хватает": нет,
        "предупреждения": предупреждения,
        "каталог": OPENDATA_DIR,
        "датасеты": строки,
        "дата_проверки": time.strftime("%Y-%m-%d"),
    }


