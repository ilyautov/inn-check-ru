#!/usr/bin/env python3
"""
rar_licenses.py — лицензии на алкоголь (Государственный сводный реестр лицензий
Росалкогольтабакконтроля, РАР) по ИНН, офлайн. Только stdlib.

Набор 7710747640-reeestrlic на fsrar.gov.ru/opendata: ссылка на ZIP стоит в
паспорте набора (https://fsrar.gov.ru/opendata/7710747640-reestr). Живьём
28.09.2026: ZIP 309 МБ, внутри XML на 10,9 ГБ, выгрузка от 01.07.2026 (паспорт:
«дата актуальности 30.09.2026» — обновляется раз в квартал). Сайт закрыт для
не-РФ адресов: скачивание идёт через прокси пользователя (INN_CHECK_PROXY, в т.ч.
socks5; см. dump_tools.py).

Строка — лицензия (или её место деятельности): ИНН, вид деятельности, номер,
даты выдачи и окончания, «сведения о действии» (действующая, приостановлена,
аннулирована, прекращена, истекла, переоформлена, срок действия истек — как в
реестре), дата и основание изменения. Теги у всех строк одинаковые и называются
«…организации_сельскохозяйственного_товаропроизводителя…» даже у магазинов —
это имя поля в наборе, а не вид лицензиата.

По ИНН — лицензии с этими полями, сгруппированные по номеру (у одной лицензии
может быть много мест продажи — считается их число). В индекс не попадают
наименования (у ИП — ФИО), адреса, координаты, e-mail.

ZIP качается во временный файл кэша, XML читается потоком прямо из архива (на
диск не распаковывается), после разбора ZIP удаляется.

    python3 rar_licenses.py --refresh      # нужен РФ-IP или INN_CHECK_PROXY
    python3 rar_licenses.py --inn 7707083893
"""

import datetime as dt
import html
import io
import json
import os
import re
import sys
import tempfile
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_tools

CACHE_DIR = os.path.expanduser(os.path.join("~", ".cache", "inn-check-ru", "rar"))
CACHE_DIR_ВИДИМЫЙ = "~/.cache/inn-check-ru/rar"
ИНДЕКС = "индекс.json.gz"
ПАСПОРТ = "https://fsrar.gov.ru/opendata/7710747640-reestr"
ЛИМИТ_ZIP = 2 << 30
ЛИМИТ_XML = 60 << 30
ДОЛЯ_ПАДЕНИЯ = 0.9          # реестр копит историю: меньше 90 % прежних строк — схема/обрыв
ДОЛЯ_БЕЗ_ИНН = 0.02
СВЕЖЕСТЬ_ВЫГРУЗКИ_ДНЕЙ = 150   # квартальная выгрузка плюс месяц на публикацию
ПОКАЗАТЬ = 20
_П = "организации_сельскохозяйственного_товаропроизводителя_"
ТЕГИ = {
    "инн": "ИНН_" + _П,
    "вид": "Вид_лицензируемой_деятельности_организации",
    "номер": "Номер_лицензии__соответствующий_номеру_записи_в_реестре",
    "выдана": "Дата_выдачи_лицензии",
    "окончание": "Дата_окончания_действия_лицензии",
    "статус": "Сведения_о_действии_лицензии",
    "изменён": "Дата_изменения_сведений_о_действии_лицензии",
    "основание": "Основание_изменения_сведений_о_действии_лицензии",
}
СТАТУСЫ = {"действующая", "приостановлена", "аннулирована", "прекращена", "истекла",
           "переоформлена", "срок действия истек"}
РАЗНЫЕ = "разные сведения: "
МЕСЯЦЫ = {"янв": 1, "фев": 2, "мар": 3, "апр": 4, "май": 5, "мая": 5, "июн": 6, "июл": 7,
          "авг": 8, "сен": 9, "окт": 10, "ноя": 11, "дек": 12}


def ссылка_на_данные(html_паспорта):
    ссылки = set(re.findall(r'(https://fsrar\.gov\.ru/opendata/7710747640-reestrlic/'
                            r'data-(\d{8})t\d{4}-structure-[^"\s<]+\.zip)', html_паспорта))
    if not ссылки:
        raise ValueError("схема: в паспорте набора нет ссылки на data-*.zip")
    return max(ссылки, key=lambda с: с[1])


# --- разбор -----------------------------------------------------------------

def _дата(s):
    """«14 авг 2017», «2017-08-14» или «14.08.2017» -> ISO; пусто -> None."""
    s = " ".join((s or "").split())
    if not s:
        return None
    m = re.fullmatch(r"(\d{1,2}) ([а-я]{3})\.? (\d{4})", s.lower())
    if m and m.group(2) in МЕСЯЦЫ:
        return dt.date(int(m.group(3)), МЕСЯЦЫ[m.group(2)], int(m.group(1))).isoformat()
    m = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})", s)
    if m:
        return dt.date(*map(int, m.groups())).isoformat()
    m = re.fullmatch(r"(\d{2})\.(\d{2})\.(\d{4})", s)
    if m:
        return dt.date(int(m.group(3)), int(m.group(2)), int(m.group(1))).isoformat()
    raise ValueError("схема: дата %r" % s[:20])


_ПОЛЯ = {поле: re.compile(r"<%s>(.*?)</%s>" % (тег, тег), re.DOTALL) for поле, тег in ТЕГИ.items()}


def _значение(поле, строка):
    m = _ПОЛЯ[поле].search(строка)
    return html.unescape(m.group(1)).strip() if m else None


def строки_xml(куски):
    """Итератор текстовых кусков -> тела <row>…</row>. Без </data> в конце —
    обрыв."""
    хвост = ""
    for кусок in куски:
        хвост += кусок
        части = хвост.split("</row>")
        хвост = части.pop()
        for ч in части:
            начало = ч.rfind("<row>")
            if начало < 0:
                raise ValueError("схема: </row> без <row>")
            yield ч[начало + 5:]
        if len(хвост) > 10 << 20:
            raise ValueError("схема: строка больше 10 МБ — не тот формат")
    if not хвост.rstrip().endswith("</data>"):
        raise ValueError("обрыв: нет закрывающего </data>")


def разобрать(строки):
    """-> (по_инн {инн: {номер: [вид, статус, выдана, окончание, изменён,
    основание, мест]}}, всего, без_инн). ValueError — схема не та."""
    по_инн, всего, без_инн = {}, 0, 0
    for с in строки:
        всего += 1
        if всего == 1 and _значение("инн", с) is None:
            raise ValueError("схема: в строке нет тега %s" % ТЕГИ["инн"])
        инн = (_значение("инн", с) or "").strip()
        if not re.fullmatch(r"\d{10}|\d{12}", инн):
            без_инн += 1
            continue
        статус = (_значение("статус", с) or "").lower()
        if статус not in СТАТУСЫ:
            raise ValueError("схема: сведения о действии %r" % статус[:40])
        номер = _значение("номер", с)
        if not номер:
            raise ValueError("схема: лицензия без номера")
        лиц = по_инн.setdefault(инн, {})
        новая = [_значение("вид", с) or "", статус, _дата(_значение("выдана", с)),
                 _дата(_значение("окончание", с)), _дата(_значение("изменён", с)),
                 _значение("основание", с) or "", 1]
        старая = лиц.get(номер)
        if старая is None:
            лиц[номер] = новая
            continue
        # ещё одно место деятельности той же лицензии. Сведения расходятся (живьём
        # 115 раз: «прекращена» и «переоформлена» одной датой) — берём более позднее
        # изменение, при равной дате показываем оба, не выбираем (ревью Codex)
        новая[6] = старая[6] + 1
        if (новая[4] or "") > (старая[4] or ""):
            лиц[номер] = новая
        else:
            старая[6] = новая[6]
            было = set(старая[1].removeprefix(РАЗНЫЕ).split("; "))
            if новая[4] == старая[4] and статус not in было:
                старая[1] = РАЗНЫЕ + "; ".join(sorted(было | {статус}))
    if not всего:
        raise ValueError("схема: в выгрузке нет строк")
    if без_инн > всего * ДОЛЯ_БЕЗ_ИНН:
        raise ValueError("схема: без ИНН %d строк из %d" % (без_инн, всего))
    return по_инн, всего, без_инн


def разобрать_zip(путь):
    with zipfile.ZipFile(путь) as z:
        имена = [и for и in z.namelist() if и.lower().endswith(".xml")]
        if len(имена) != 1:
            raise ValueError("схема: в архиве %d XML вместо одного" % len(имена))
        if z.getinfo(имена[0]).file_size > ЛИМИТ_XML:
            raise ValueError("схема: XML больше лимита")
        with z.open(имена[0]) as сырой:
            текст = io.TextIOWrapper(сырой, encoding="utf-8-sig")

            def куски():
                while True:
                    к = текст.read(8 << 20)
                    if not к:
                        return
                    yield к
            return разобрать(строки_xml(куски()))


def _сжать(по_инн):
    """Повторяющиеся тексты (вид, основание) — в словари, чтобы индекс был
    десятки, а не сотни мегабайт."""
    словарь, коды = [], {}

    def код(т):
        if т not in коды:
            коды[т] = len(словарь)
            словарь.append(т)
        return коды[т]
    out = {инн: [[номер, код(л[0]), л[1], л[2], л[3], л[4], код(л[5]), л[6]]
                 for номер, л in лиц.items()] for инн, лиц in по_инн.items()}
    return out, словарь


# --- индекс -----------------------------------------------------------------

def refresh(cache_dir=None, get=None, сегодня=None):
    """Скачивает ZIP, пересобирает индекс; сбой — старый индекс цел.
    get(url, referer, лимит, в_файл=None) — для тестов."""
    cache_dir = cache_dir or CACHE_DIR
    os.makedirs(cache_dir, exist_ok=True)
    путь = os.path.join(cache_dir, ИНДЕКС)
    сегодня = сегодня or dump_tools.сегодня()
    if get is None:
        try:
            op = dump_tools.opener()
        except ValueError as e:
            return {"статус": "индекс не обновлён: %s" % e}

        def get(url, referer, лимит, в_файл=None):
            return dump_tools.get(url, referer, лимит, timeout=900, в_файл=в_файл, op=op)
    try:
        блок = dump_tools.Блокировка(cache_dir).__enter__()
    except FileExistsError:
        return {"статус": "индекс не обновлён: другой refresh уже идёт"}
    try:
        try:
            прежний = (dump_tools.прочитать_индекс(путь) if os.path.exists(путь) else {})
        except Exception:
            прежний = {}
        fd, tmp = tempfile.mkstemp(dir=cache_dir, prefix=".выгрузка-", suffix=".zip")
        os.close(fd)
        try:
            url, дата = ссылка_на_данные(get(ПАСПОРТ, "https://fsrar.gov.ru/opendata",
                                             5 << 20).decode("utf-8", "replace"))
            выгрузка = "%s-%s-%s" % (дата[:4], дата[4:6], дата[6:])
            if прежний.get("выгрузка") == выгрузка and прежний.get("url") == url:
                прежний["скачан"] = сегодня
                dump_tools.записать_индекс(путь, прежний)
                return {"статус": "обновлено: выгрузка %s уже в индексе" % выгрузка}
            get(url, ПАСПОРТ, ЛИМИТ_ZIP, в_файл=tmp)
            по_инн, всего, без_инн = разобрать_zip(tmp)
        except Exception as e:
            return {"статус": "индекс не обновлён: %s: %s" % (type(e).__name__, str(e)[:200])}
        finally:
            os.unlink(tmp)
        было = прежний.get("строк") or 0
        if всего < было * ДОЛЯ_ПАДЕНИЯ:
            return {"статус": "индекс не обновлён: схема: %d строк (было %d)" % (всего, было)}
        сжатое, словарь = _сжать(по_инн)
        dump_tools.записать_индекс(путь, {
            "url": url, "выгрузка": выгрузка, "скачан": сегодня, "строк": всего,
            "без_инн": без_инн, "словарь": словарь, "по_инн": сжатое})
        return {"статус": "обновлено", "выгрузка": выгрузка, "строк": всего,
                "организаций": len(сжатое)}
    finally:
        блок.__exit__(None, None, None)


def устарел(индекс, сегодня):
    if dump_tools.старше(индекс["выгрузка"], сегодня, СВЕЖЕСТЬ_ВЫГРУЗКИ_ДНЕЙ):
        return ["выгрузка реестра лицензий РАР от %s старше %d дней — обновите: "
                "rar_licenses.py --refresh (нужен РФ-IP или INN_CHECK_PROXY)"
                % (индекс["выгрузка"], СВЕЖЕСТЬ_ВЫГРУЗКИ_ДНЕЙ)]
    return []


def lookup(inn, cache_dir=None, сегодня=None):
    """-> (dict|None, заметка). None — индекса нет."""
    cache_dir = cache_dir or CACHE_DIR
    путь = os.path.join(cache_dir, ИНДЕКС)
    try:
        индекс = dump_tools.прочитать_индекс(путь)
    except FileNotFoundError:
        return None, ("индекса нет (%s) — сначала rar_licenses.py --refresh (нужен РФ-IP "
                      "или INN_CHECK_PROXY)"
                      % (CACHE_DIR_ВИДИМЫЙ if cache_dir == CACHE_DIR else путь))
    сегодня = сегодня or dump_tools.сегодня()
    сл = индекс["словарь"]
    лиц = [{"номер": л[0], "вид": сл[л[1]], "статус": л[2], "выдана": л[3],
            "окончание": л[4], "статус_изменён": л[5], "основание": сл[л[6]],
            "мест": л[7]} for л in индекс["по_инн"].get(str(inn), [])]
    лиц.sort(key=lambda л: л["выдана"] or "", reverse=True)
    лиц.sort(key=lambda л: л["статус"] != "действующая")
    по_статусам = {}
    for л in лиц:
        по_статусам[л["статус"]] = по_статусам.get(л["статус"], 0) + 1
    return {
        "в_реестре": bool(лиц),
        "лицензий": len(лиц),
        "по_статусам": по_статусам,
        "действующих": по_статусам.get("действующая", 0),
        "показаны": лиц[:ПОКАЗАТЬ],
        "охват": "Государственный сводный реестр лицензий РАР на алкоголь: производство, "
                 "оборот, розница и общепит — действующие и прекращённые",
        "выгрузка": индекс["выгрузка"],
        "скачан": индекс["скачан"],
        "предупреждения": устарел(индекс, сегодня),
        "источник": ПАСПОРТ,
    }, "ok"


def main(argv):
    args = argv[1:]
    if args == ["--refresh"]:
        res = refresh()
        print(json.dumps(res, ensure_ascii=False, indent=2))
        return 0 if res["статус"].startswith("обновлено") else 1
    if len(args) == 2 and args[0] == "--inn":
        res, note = lookup(args[1])
        print(json.dumps(res if res is not None else {"статус": "не проверено",
                                                      "причина": note},
                         ensure_ascii=False, indent=2))
        return 0 if res is not None else 1
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
