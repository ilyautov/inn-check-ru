#!/usr/bin/env python3
"""
fsa_registries.py — сертификаты и декларации о соответствии (Росаккредитация) по
ИНН заявителя или изготовителя, офлайн. Только stdlib.

Наборы 7736638268-rss (сертификаты) и 7736638268-rds (декларации) на
fsa.gov.ru/opendata — помесячные выгрузки в 7z (распаковывает sevenzip.py). В
выгрузке за месяц — документы, которые за этот месяц зарегистрировали или
изменили (живьём 28.09.2026 в августовской — и сертификат 2021 года, ставший
архивным). Полной базы с ИНН в открытых данных нет: в наборе 7736638268-rdsfull
ИНН заявителя вообще нет, только наименование изготовителя. Поэтому индекс — за
последние МЕСЯЦЕВ выгрузок, и это не весь реестр: документ, который за период не
менялся, сюда не попадает. Пустой ответ значит «за период изменений не было», а
не «сертификатов нет».

Один документ в нескольких месяцах — берётся самая свежая выгрузка. Период
считается по именам CSV внутри архивов (rss_20260801_20260831.csv); месяц,
который Росаккредитация не выложила (живьём — март 2026), попадает в «пропуски».

Сайт закрыт для не-РФ адресов: скачивание через прокси пользователя
(INN_CHECK_PROXY, в т.ч. socks5; см. dump_tools.py). Разобранный месяц
сохраняется в кэше — следующий refresh качает только новые выгрузки.

В индекс идут: вид, номер, статус, даты регистрации, окончания, приостановки и
прекращения, группа продукции, роль ИНН (заявитель / изготовитель). Не идут
наименования (у ИП — ФИО), адреса, контакты.

    python3 fsa_registries.py --refresh      # нужен РФ-IP или INN_CHECK_PROXY
    python3 fsa_registries.py --inn 7707083893
"""

import csv
import datetime as dt
import io
import json
import os
import re
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_tools
import sevenzip

CACHE_DIR = os.path.expanduser(os.path.join("~", ".cache", "inn-check-ru", "fsa"))
CACHE_DIR_ВИДИМЫЙ = "~/.cache/inn-check-ru/fsa"
ИНДЕКС = "индекс.json.gz"
МЕСЯЦЫ_ПАПКА = "месяцы"
ОТКРЫТЫЕ_ДАННЫЕ = "https://fsa.gov.ru/opendata/"
НАБОРЫ = {
    "сертификат": "https://fsa.gov.ru/opendata/7736638268-rss/",
    "декларация": "https://fsa.gov.ru/opendata/7736638268-rds/",
}
МЕСЯЦЕВ = 12
ФОРМАТ_МЕСЯЦА = 2           # сменился разбор — разобранные месяцы качаются заново
ЛИМИТ_7Z = 1 << 30
ЛИМИТ_CSV = 8 << 30
СВЕЖЕСТЬ_ДНЕЙ = 75          # месяц плюс публикация (живьём — 7–20 дней) плюс запас
ДОЛЯ_БИТЫХ = 0.01
ДОЛЯ_ИЗВЕСТНЫХ_СТАТУСОВ = 0.9
ПРОДУКЦИЯ_СИМВОЛОВ = 160
ПОКАЗАТЬ_ДЕЙСТВУЮЩИХ = 10
ПОКАЗАТЬ_ПРОЧИХ = 10
СТАТУСЫ = {"действует", "архивный", "приостановлен", "прекращен", "недействителен",
           "возобновлен", "частично приостановлен", "продлен"}
ДЕЙСТВУЕТ = {"действует", "возобновлен", "продлен"}
# колонки ищутся по имени без учёта регистра: у сертификатов «ИНН изготовителя»,
# у деклараций «ИНН производителя», в разных версиях структуры — разный регистр
КОЛОНКИ = {
    "id": ("id",),
    "статус": ("статус",),
    "номер": ("номер сс", "номер дс"),
    "дата": ("дата рег",),
    "срок": ("срок действия",),
    "приостановлен": ("дата приостановки",),
    "прекращен": ("дата прекращения",),
    "группа": ("группа продукции",),
    "продукция": ("полное наименование продукции", "полное наименование"),
    "инн_заявителя": ("инн заявителя",),
    "инн_изготовителя": ("инн изготовителя", "инн производителя"),
}
ОБЯЗАТЕЛЬНЫЕ = ("id", "статус", "номер", "дата", "инн_заявителя", "инн_изготовителя")


def версии(html_набора, url_набора):
    """-> [(дата данных, url 7z)] по убыванию даты; у одной даты несколько
    структур — берётся самая поздняя."""
    лучшие = {}
    for данные, структура in re.findall(r"data-(\d{8})-structure-(\d{8})\.7z", html_набора):
        if структура > лучшие.get(данные, ""):
            лучшие[данные] = структура
    if not лучшие:
        raise ValueError("схема: на странице набора нет ссылок data-*.7z")
    return [(д, "%sdata-%s-structure-%s.7z" % (url_набора, д, лучшие[д]))
            for д in sorted(лучшие, reverse=True)]


def период(имя_csv):
    """«rss_20260801_20260831.csv» или «rss_20251101-20251130.csv» -> (с, по) ISO."""
    m = re.search(r"(\d{8})[_-](\d{8})\.csv$", имя_csv or "")
    if not m:
        raise ValueError("схема: в архиве %r — не видно периода" % имя_csv)
    с, по = (dt.date(int(x[:4]), int(x[4:6]), int(x[6:])).isoformat() for x in m.groups())
    if с > по:
        raise ValueError("схема: период %s…%s" % (с, по))
    return с, по


def _дата(s):
    """«03.08.2021» -> ISO; пусто или мусор -> None (в реестре встречаются
    пустые и «00.00.0000»)."""
    m = re.fullmatch(r"(\d{2})\.(\d{2})\.(\d{4})", (s or "").strip())
    if not m:
        return None
    try:
        return dt.date(int(m.group(3)), int(m.group(2)), int(m.group(1))).isoformat()
    except ValueError:
        return None


def _инн(s):
    s = (s or "").strip()
    return s if re.fullmatch(r"\d{10}|\d{12}", s) else None


def разобрать_csv(поток):
    """Бинарный поток CSV (';', UTF-8) -> (записи, строк, битых). Запись:
    [id, номер, статус, дата, срок, приостановлен, прекращен, продукция,
    инн_заявителя, инн_изготовителя]. У строки без ИНН остаются только id и номер:
    она не попадёт в индекс, но вытеснит более старую версию документа."""
    csv.field_size_limit(1 << 30)
    r = csv.reader(io.TextIOWrapper(поток, encoding="utf-8-sig", newline=""), delimiter=";")
    try:
        шапка = [к.strip().lower() for к in next(r)]
    except StopIteration:
        raise ValueError("схема: пустой CSV") from None
    номера = {}
    for поле, варианты in КОЛОНКИ.items():
        for в in варианты:
            if в in шапка:
                номера[поле] = шапка.index(в)
                break
    нет = [п for п in ОБЯЗАТЕЛЬНЫЕ if п not in номера]
    if нет:
        raise ValueError("схема: в CSV нет колонок %s" % ", ".join(нет))

    def поле(row, имя):
        i = номера.get(имя)
        return row[i].strip() if i is not None else ""
    записи, строк, битых, известных = [], 0, 0, 0
    for row in r:
        строк += 1
        if len(row) != len(шапка):
            битых += 1
            continue
        статус = поле(row, "статус").lower().replace("ё", "е")
        if статус in СТАТУСЫ:
            известных += 1
        заявитель, изготовитель = _инн(поле(row, "инн_заявителя")), _инн(поле(row, "инн_изготовителя"))
        if not (заявитель or изготовитель):
            записи.append([поле(row, "id"), поле(row, "номер")])
            continue
        продукция = " ".join((поле(row, "группа") or поле(row, "продукция")).split())
        if len(продукция) > ПРОДУКЦИЯ_СИМВОЛОВ:
            продукция = продукция[:ПРОДУКЦИЯ_СИМВОЛОВ - 1] + "…"
        записи.append([поле(row, "id"), поле(row, "номер"), статус, _дата(поле(row, "дата")),
                       _дата(поле(row, "срок")), _дата(поле(row, "приостановлен")),
                       _дата(поле(row, "прекращен")), продукция, заявитель, изготовитель])
    if not строк:
        raise ValueError("схема: в CSV нет строк")
    if битых > строк * ДОЛЯ_БИТЫХ:
        raise ValueError("схема: %d строк из %d не по шапке" % (битых, строк))
    if известных < (строк - битых) * ДОЛЯ_ИЗВЕСТНЫХ_СТАТУСОВ:
        raise ValueError("схема: известных статусов %d из %d" % (известных, строк - битых))
    return записи, строк, битых


def разобрать_архив(путь):
    """7z с одним CSV -> {период, строк, битых, записи}."""
    имя, размер = sevenzip.оглавление(путь)
    if размер > ЛИМИТ_CSV:
        raise ValueError("схема: CSV больше лимита")
    с, по = период(имя)
    with sevenzip.открыть(путь) as поток:
        записи, строк, битых = разобрать_csv(поток)
    return {"с": с, "по": по, "файл": имя, "строк": строк, "битых": битых, "записи": записи}


# --- индекс -----------------------------------------------------------------

def _путь_месяца(cache_dir, вид, дата):
    return os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА, "%s-%s.json.gz" % (
        "rss" if вид == "сертификат" else "rds", дата))


def пропуски(периоды):
    """[(с, по)] -> дни между первым и последним, не покрытые ни одним
    периодом, отрезками [(с, по)]."""
    out, покрыто_до = [], None
    for с, по in sorted(периоды):
        if покрыто_до is not None:
            след = (dt.date.fromisoformat(покрыто_до) + dt.timedelta(days=1)).isoformat()
            if с > след:
                out.append((след, (dt.date.fromisoformat(с) - dt.timedelta(days=1)).isoformat()))
        if покрыто_до is None or по > покрыто_до:
            покрыто_до = по
    return out


def собрать(месяцы):
    """[(вид, дата, {с, по, записи})] -> индекс по ИНН. Документ из нескольких
    выгрузок берётся из самой свежей (по дате выгрузки)."""
    по_инн, видели = {}, set()
    for вид, _дата_выгрузки, м in sorted(месяцы, key=lambda x: x[1], reverse=True):
        код = "С" if вид == "сертификат" else "Д"
        for з in м["записи"]:
            ключ = (код, з[0] or з[1])
            if ключ in видели:
                continue
            видели.add(ключ)
            if len(з) == 2:                              # свежая версия без ИНН
                continue
            заявитель, изготовитель = з[8], з[9]
            for инн, роль in ((заявитель, "з"), (изготовитель, "и")):
                if not инн or (роль == "и" and инн == заявитель):
                    continue
                if роль == "з" and инн == изготовитель:
                    роль = "зи"
                по_инн.setdefault(инн, []).append([код, роль] + з[1:8])
    return по_инн


def refresh(cache_dir=None, get=None, сегодня=None, месяцев=МЕСЯЦЕВ):
    """Качает недостающие месяцы, пересобирает индекс; сбой — старый индекс цел.
    get(url, referer, лимит, в_файл=None) — для тестов."""
    cache_dir = cache_dir or CACHE_DIR
    os.makedirs(os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА), exist_ok=True)
    путь = os.path.join(cache_dir, ИНДЕКС)
    сегодня = сегодня or dump_tools.сегодня()
    if get is None:
        try:
            op = dump_tools.opener()
        except ValueError as e:
            return {"статус": "индекс не обновлён: %s" % e}

        def get(url, referer, лимит, в_файл=None):
            return dump_tools.get(url, referer, лимит, timeout=900, в_файл=в_файл, op=op)
    try:
        блок = dump_tools.Блокировка(cache_dir).__enter__()
    except FileExistsError:
        return {"статус": "индекс не обновлён: другой refresh уже идёт"}
    try:
        месяцы, нужные, скачано = [], set(), 0
        try:
            for вид, url_набора in НАБОРЫ.items():
                страница = get(url_набора, ОТКРЫТЫЕ_ДАННЫЕ, 5 << 20).decode("utf-8", "replace")
                for дата, url in версии(страница, url_набора)[:месяцев]:
                    файл = _путь_месяца(cache_dir, вид, дата)
                    нужные.add(os.path.basename(файл))
                    м = dump_tools.прочитать_индекс(файл) if os.path.exists(файл) else None
                    # та же дата с новой структурой — Росаккредитация переложила
                    # выгрузку: качаем заново
                    if м is None or м.get("url") != url or м.get("формат") != ФОРМАТ_МЕСЯЦА:
                        fd, tmp = tempfile.mkstemp(dir=cache_dir, prefix=".выгрузка-", suffix=".7z")
                        os.close(fd)
                        try:
                            get(url, url_набора, ЛИМИТ_7Z, в_файл=tmp)
                            м = разобрать_архив(tmp)
                        finally:
                            os.unlink(tmp)
                        м["url"], м["формат"] = url, ФОРМАТ_МЕСЯЦА
                        dump_tools.записать_индекс(файл, м)
                        скачано += 1
                    месяцы.append((вид, дата, м))
        except Exception as e:
            return {"статус": "индекс не обновлён: %s: %s" % (type(e).__name__, str(e)[:200])}
        по_инн = собрать(месяцы)
        периоды = {}
        for вид, _, м in месяцы:
            периоды.setdefault(вид, []).append((м["с"], м["по"]))
        охват = {вид: {"с": min(п)[0], "по": max(по for _, по in п),
                       "выгрузок": len(п),
                       "пропуски": [list(x) for x in пропуски(п)]}
                 for вид, п in периоды.items()}
        if set(охват) != set(НАБОРЫ):
            return {"статус": "индекс не обновлён: схема: нет выгрузок одного из наборов"}
        dump_tools.записать_индекс(путь, {"скачан": сегодня, "охват": охват,
                                          "документов": sum(len(з) > 2 for _, _, м in месяцы
                                                            for з in м["записи"]),
                                          "по_инн": по_инн})
        for имя in os.listdir(os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА)):
            if имя.endswith(".json.gz") and имя not in нужные:
                os.unlink(os.path.join(cache_dir, МЕСЯЦЫ_ПАПКА, имя))
        return {"статус": "обновлено", "скачано_выгрузок": скачано, "охват": охват,
                "организаций": len(по_инн)}
    finally:
        блок.__exit__(None, None, None)


def устарел(индекс, сегодня):
    out = []
    for вид, о in sorted(индекс["охват"].items()):
        if dump_tools.старше(о["по"], сегодня, СВЕЖЕСТЬ_ДНЕЙ):
            out.append("выгрузки Росаккредитации (%s) заканчиваются %s — старше %d дней; "
                       "обновите: fsa_registries.py --refresh (нужен РФ-IP или "
                       "INN_CHECK_PROXY)" % (вид, о["по"], СВЕЖЕСТЬ_ДНЕЙ))
    return out


РОЛИ = {"з": "заявитель", "и": "изготовитель", "зи": "заявитель и изготовитель"}
ВИДЫ = {"С": "сертификат", "Д": "декларация"}


def lookup(inn, cache_dir=None, сегодня=None):
    """-> (dict|None, заметка). None — индекса нет."""
    cache_dir = cache_dir or CACHE_DIR
    путь = os.path.join(cache_dir, ИНДЕКС)
    try:
        индекс = dump_tools.прочитать_индекс(путь)
    except FileNotFoundError:
        return None, ("индекса нет (%s) — сначала fsa_registries.py --refresh (нужен РФ-IP "
                      "или INN_CHECK_PROXY)"
                      % (CACHE_DIR_ВИДИМЫЙ if cache_dir == CACHE_DIR else путь))
    сегодня = сегодня or dump_tools.сегодня()
    доки = [{"вид": ВИДЫ[д[0]], "роль": РОЛИ[д[1]], "номер": д[2], "статус": д[3],
             "зарегистрирован": д[4], "действует_до": д[5], "приостановлен": д[6],
             "прекращен": д[7], "продукция": д[8]}
            for д in индекс["по_инн"].get(str(inn), [])]
    доки.sort(key=lambda д: д["зарегистрирован"] or "", reverse=True)
    сводка = {}
    for д in доки:
        по_виду = сводка.setdefault(д["вид"], {})
        по_виду[д["статус"]] = по_виду.get(д["статус"], 0) + 1
    действующие = [д for д in доки if д["статус"] in ДЕЙСТВУЕТ]
    прочие = [д for д in доки if д["статус"] not in ДЕЙСТВУЕТ]
    return {
        "в_выгрузках": bool(доки),
        "документов": len(доки),
        "по_статусам": сводка,
        "действующих": len(действующие),
        "показаны": действующие[:ПОКАЗАТЬ_ДЕЙСТВУЮЩИХ] + прочие[:ПОКАЗАТЬ_ПРОЧИХ],
        "охват": индекс["охват"],
        "оговорка": "только документы, которые Росаккредитация зарегистрировала или "
                    "изменила за период выгрузок; документ, не менявшийся за период, "
                    "сюда не попал — это не весь реестр",
        "скачан": индекс["скачан"],
        "предупреждения": устарел(индекс, сегодня),
        "источник": ОТКРЫТЫЕ_ДАННЫЕ,
    }, "ok"


def main(argv):
    args = argv[1:]
    if args == ["--refresh"]:
        res = refresh()
        print(json.dumps(res, ensure_ascii=False, indent=2))
        return 0 if res["статус"].startswith("обновлено") else 1
    if len(args) == 2 and args[0] == "--inn":
        res, note = lookup(args[1])
        print(json.dumps(res if res is not None else {"статус": "не проверено",
                                                      "причина": note},
                         ensure_ascii=False, indent=2))
        return 0 if res is not None else 1
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
