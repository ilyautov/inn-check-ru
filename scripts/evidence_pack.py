# --- RFC 3161: запрос и разбор ответа (минимальный DER, stdlib) ----------------

def _der_len(n):
    if n < 0x80:
        return bytes([n])
    b = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([0x80 | len(b)]) + b


def _der(tag, тело):
    return bytes([tag]) + _der_len(len(тело)) + тело


def _der_int(n):
    return _der(0x02, n.to_bytes(max(1, (n.bit_length() + 8) // 8), "big"))


def запрос_штампа(хеш_hex, nonce):
    """DER TimeStampReq v1: sha256-отпечаток, nonce, certReq=TRUE."""
    алгоритм = _der(0x30, _OID_SHA256 + b"\x05\x00")
    отпечаток = _der(0x30, алгоритм + _der(0x04, bytes.fromhex(хеш_hex)))
    return _der(0x30, _der_int(1) + отпечаток + _der_int(nonce) + b"\x01\x01\xff")


def _tlv(buf, i):
    """(tag, value, следующий_индекс) одного DER-элемента с позиции i."""
    if i + 2 > len(buf):
        raise ValueError("DER: обрыв на %d" % i)
    tag, длина = buf[i], buf[i + 1]
    i += 2
    if длина & 0x80:
        k = длина & 0x7F
        if k == 0 or k > 4 or i + k > len(buf):
            raise ValueError("DER: неподдерживаемая длина на %d" % i)
        длина = int.from_bytes(buf[i:i + k], "big")
        i += k
    if i + длина > len(buf):
        raise ValueError("DER: длина за пределами буфера на %d" % i)
    return tag, buf[i:i + длина], i + длина


def _дети(тело):
    out, i = [], 0
    while i < len(тело):
        tag, v, i = _tlv(тело, i)
        out.append((tag, v))
    return out


def _первый(дети, tag, что):
    for t, v in дети:
        if t == tag:
            return v
    raise ValueError("RFC 3161: нет %s" % что)


def разобрать_ответ(tsr):
    """TimeStampResp -> {статус, время_utc, хеш_hex, nonce, серийный}.

    Статус 0/1 — granted/grantedWithMods; иное — отказ TSA (время None).
    Любой битый DER — ValueError: ответ чужого сервера не должен ронять сбор.
    """
    try:
        return _разобрать_ответ(tsr)
    except ValueError:
        raise
    except Exception as e:
        raise ValueError("RFC 3161: ответ не разбирается (%s)" % type(e).__name__) from e


def _разобрать_ответ(tsr):
    tag, тело, _ = _tlv(tsr, 0)
    if tag != 0x30:
        raise ValueError("RFC 3161: ответ не SEQUENCE")
    части = _дети(тело)
    статус = int.from_bytes(_первый(_дети(части[0][1]), 0x02, "status"), "big")
    итог = {"статус": статус, "время_utc": None, "хеш_hex": None, "nonce": None,
            "серийный": None}
    if статус not in (0, 1) or len(части) < 2:
        return итог
    content_info = _дети(части[1][1])
    signed = _дети(_tlv(_первый(content_info, 0xA0, "SignedData"), 0)[1])
    encap = _дети(signed[2][1])
    if not encap or _der(0x06, encap[0][1]) != _OID_TSTINFO:
        raise ValueError("RFC 3161: в токене не TSTInfo")
    tst_der = _tlv(_первый(encap, 0xA0, "eContent"), 0)
    if tst_der[0] != 0x04:
        raise ValueError("RFC 3161: eContent не OCTET STRING")
    tst = _дети(_tlv(tst_der[1], 0)[1])
    imprint = _дети(tst[2][1])
    алгоритм = _дети(imprint[0][1])
    if _der(0x06, алгоритм[0][1]) != _OID_SHA256:
        raise ValueError("RFC 3161: отпечаток не sha256")
    итог["хеш_hex"] = imprint[1][1].hex()
    итог["серийный"] = int.from_bytes(tst[3][1], "big")
    время = tst[4][1].decode("ascii")
    m = re.match(r"(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})(?:[.,]\d+)?Z$", время)
    if not m:
        raise ValueError("RFC 3161: genTime %r" % время)
    итог["время_utc"] = "%s-%s-%sT%s:%s:%s+00:00" % m.groups()
    for t, v in tst[5:]:
        if t == 0x02:                          # первый INTEGER после genTime — nonce
            итог["nonce"] = int.from_bytes(v, "big")
            break
    return итог


def _url_без_секретов(url):
    """URL TSA для вывода и пакета: без user:password и query-строки —
    платные TSA принимают ключ в URL, а итог штампа печатается и пишется."""
    try:
        p = urllib.parse.urlsplit(url)
        хост = p.hostname or ""
        if p.port:
            хост += ":%d" % p.port
        return urllib.parse.urlunsplit((p.scheme, хост, p.path, "", ""))
    except ValueError:
        return "(URL TSA не разобран)"


def _список_tsa(штамп):
    if isinstance(штамп, (list, tuple)):
        return [u for u in штамп if u]
    if str(штамп).strip().lower() in ("1", "да", "yes", "true", "по_умолчанию"):
        return list(TSA_ПО_УМОЛЧАНИЮ)
    return [u.strip() for u in str(штамп).split(",") if u.strip()]


def _post_tsa(url, tsq):
    req = urllib.request.Request(url, data=tsq, method="POST", headers={
        "Content-Type": "application/timestamp-query",
        "Accept": "application/timestamp-reply"})
    with urllib.request.urlopen(req, timeout=TSA_TIMEOUT) as resp:
        return resp.read()


class _Замок:
    """Замок пакета (O_EXCL): одно изменение пакета за раз — добавление версии
    и штамп не должны пересечься (штамп, дописанный к версии, которую уже
    закрепила следующая, ломает цепочку)."""

    def __init__(self, корень):
        self.путь = Path(корень) / ЗАМОК

    def __enter__(self):
        try:
            fd = os.open(str(self.путь), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        except FileExistsError:
            raise ValueError("пакет уже изменяется (%s); если прошлое добавление или "
                             "штамп прерваны — удалите этот файл и файлы manual/NNN_*, "
                             "которых нет ни в одном манифесте (--проверить назовёт их "
                             "«файл не из манифеста»), и повторите" % self.путь) from None
        except OSError as e:
            raise ValueError("каталог пакета недоступен для записи: %s" % e) from None
        os.close(fd)
        return self

    def __exit__(self, *_):
        self.путь.unlink(missing_ok=True)
        return False


def поставить_штамп(каталог, штамп, post=_post_tsa, версия=None):
    """Штамп под замком пакета; см. _поставить_штамп."""
    try:
        with _Замок(каталог):
            return _поставить_штамп(каталог, штамп, post=post, версия=версия)
    except ValueError as e:
        return "не поставлен — %s" % e


def _поставить_штамп(каталог, штамп, post=_post_tsa, версия=None):
    """Штамп на манифест версии (None — последней; 1 — manifest.json): пишет
    .tsq/.tsr. Возвращает строку-итог; при отказе всех TSA — строку с причиной
    (пакет годен и без штампа). Штамп ставится только на последнюю версию и
    только если его ещё нет: прежние версии закреплены хешами следующих, и
    дописанный или переписанный задним числом штамп сломал бы цепочку."""
    корень = Path(каталог)
    последняя = (_версии(корень) or [1])[-1]
    версия = последняя if версия is None else версия
    if версия != последняя:
        return ("не поставлен — версия %d не последняя (последняя %d): прежние "
                "версии закреплены следующими" % (версия, последняя))
    манифест, _, запрос_tsa, ответ_tsa = _имена_версии(версия)
    if (корень / ответ_tsa).exists():
        return "не поставлен — у версии %d штамп уже есть, не переписываю" % версия
    хеш = _sha256((корень / манифест).read_bytes())
    nonce = secrets.randbits(63)
    tsq = запрос_штампа(хеш, nonce)
    причины = []
    for url in _список_tsa(штамп):
        имя = _url_без_секретов(url)
        try:
            tsr = post(url, tsq)
            р = разобрать_ответ(tsr)
        except (OSError, ValueError, urllib.error.URLError) as e:
            причины.append("%s: %s" % (имя, type(e).__name__ if isinstance(e, OSError)
                                       else e))
            continue
        if р["статус"] not in (0, 1):
            причины.append("%s: отказ TSA, статус %s" % (имя, р["статус"]))
            continue
        if р["хеш_hex"] != хеш or р["nonce"] != nonce:
            причины.append("%s: штамп не на наш запрос (хеш или nonce не совпал)" % имя)
            continue
        (корень / запрос_tsa).write_bytes(tsq)
        (корень / ответ_tsa).write_bytes(tsr)
        _инструкция(корень)
        return "%s, %s" % (р["время_utc"], имя)
    return "не поставлен — " + ("; ".join(причины) or "не указан ни один TSA")


# --- ручные вложения (браузерный шаг) ------------------------------------------

def добавить(каталог, файл, источник, url, дата_проверки, параметры=None,
             просмотрено=None, найдено=None, штамп=None, post=_post_tsa, now=None):
    """Ручное вложение в готовый пакет -> новая версия манифеста.

    Вложение (скриншот, сохранённая страница, выгрузка) кладётся в manual/ байт в
    байт, рядом — неизменяемая опись NNN_<ист>.опись.json: источник, URL, дата проверки
    (обязательна — день, когда смотрели, знает только пользователь),
    параметры поиска, сколько просмотрено, что найдено, sha256. Затем пишется
    manifest.N.json — опись ВСЕХ файлов и хеши всех прежних манифестов и штампов;
    прежние версии не трогаются, их штампы остаются доказательством своего
    момента. `штамп` — как у записать_пакет; None — штамп ставится, только если
    он был у предыдущей версии (INN_CHECK_TSA или TSA по умолчанию), "" — нет.
    """
    корень = Path(каталог)
    with _Замок(корень):
        return _добавить(корень, файл, источник, url, дата_проверки, параметры,
                         просмотрено, найдено, штамп, post, now)


def _добавить(корень, файл, источник, url, дата_проверки, параметры, просмотрено,
              найдено, штамп, post, now):
    итог_проверки = проверить(корень)
    if not итог_проверки["годен"]:
        raise ValueError("пакет не годен, в него не добавляю: %s"
                         % "; ".join(итог_проверки["ошибки"][:3]))
    исх = Path(файл)
    if исх.is_symlink() or not исх.is_file():
        raise ValueError("вложение не обычный файл: %s" % файл)
    данные = исх.read_bytes()
    if len(данные) > МАКС_ВЛОЖЕНИЕ:
        raise ValueError("вложение больше %d МБ" % (МАКС_ВЛОЖЕНИЕ // 1024 // 1024))
    ист = str(источник or "").strip().lower()
    if not _ИСТОЧНИК_ВЛОЖЕНИЯ.match(ист):
        raise ValueError("источник — короткий id латиницей/кириллицей: %r" % источник)
    if not re.match(r"^https?://", str(url or "")):
        raise ValueError("нужен URL страницы, где смотрели (http/https)")
    момент = now or datetime.datetime.now(datetime.timezone.utc)
    дата = str(дата_проверки or "")
    try:
        ok_дата = bool(re.match(r"^\d{4}-\d{2}-\d{2}\Z", дата)) and \
            datetime.date.fromisoformat(дата) <= (момент + datetime.timedelta(days=1)).date()
    except ValueError:
        ok_дата = False
    if not ok_дата:
        raise ValueError("дата проверки — ГГГГ-ММ-ДД, не в будущем, указывается явно "
                         "(день, когда смотрели): %r" % дата_проверки)

    версии = _версии(корень)
    n = версии[-1] + 1
    созданные = []
    try:
        return _записать_версию(корень, n, версии, исх, данные, ист, url, дата, параметры,
                                просмотрено, найдено, штамп, post, момент, созданные)
    except BaseException:
        # Сбой на полпути (диск, прерывание) не оставляет сироту, из-за которой
        # пакет стал бы негодным: созданное этим добавлением убирается.
        for путь in reversed(созданные):
            путь.unlink(missing_ok=True)
        raise


def _записать_версию(корень, n, версии, исх, данные, ист, url, дата, параметры,
                     просмотрено, найдено, штамп, post, момент, созданные):
    ручные = корень / РУЧНЫЕ
    ручные.mkdir(exist_ok=True)
    номер = 1 + max([int(м.group(1)) for м in
                     (_НОМЕР_ВЛОЖЕНИЯ.match(p.name) for p in ручные.iterdir()) if м] or [0])
    суффикс = re.sub(r"[^0-9a-z.]", "", исх.suffix.lower())[:10].rstrip(".") or ".bin"
    if not суффикс.startswith("."):
        суффикс = ".bin"
    база = "%03d_%s" % (номер, ист)
    # "xb": существующее не перезаписывается ни при каком стечении обстоятельств
    with open(ручные / (база + суффикс), "xb") as f:
        созданные.append(ручные / (база + суффикс))
        f.write(данные)
    опись = {
        "файл": "%s/%s%s" % (РУЧНЫЕ, база, суффикс),
        "источник": ист,
        "ввод": "браузер",
        "url": _url_без_секретов(url),
        "дата_проверки": дата,
        "параметры_поиска": параметры,
        "просмотрено": просмотрено,
        "найдено": найдено,
        "sha256": _sha256(данные),
        "байт": len(данные),
        "добавлено_utc": момент.isoformat(timespec="seconds"),
        "версия_манифеста": n,
        "оговорка": "вложение сделано пользователем вручную; инструмент проверяет "
                    "только его неизменность после добавления, не содержание",
    }
    with open(ручные / (база + ОПИСЬ), "xb") as f:
        созданные.append(ручные / (база + ОПИСЬ))
        f.write((json.dumps(опись, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))

    прежний = _имена_версии(версии[-1])[0]
    v1 = json.loads((корень / МАНИФЕСТ).read_text(encoding="utf-8"))
    семейство = []
    for v in версии:
        for имя in _имена_версии(v):
            p = корень / имя
            if p.is_file():
                б = p.read_bytes()
                семейство.append({"путь": имя, "sha256": _sha256(б), "байт": len(б)})
    манифест = {
        "формат": ФОРМАТ,
        "инструмент": "inn-check-ru %s" % _версия(),
        "инн": v1.get("инн"),
        "версия": n,
        "создан_utc": момент.isoformat(timespec="seconds"),
        "предыдущий": {"путь": прежний,
                       "sha256": _sha256((корень / прежний).read_bytes())},
        "добавлено": [опись["файл"], "%s/%s%s" % (РУЧНЫЕ, база, ОПИСЬ)],
        "файлы": _опись(корень),
        "прежние_версии": семейство,
        "оговорка": v1.get("оговорка"),
    }
    имя_м, имя_х, _, _ = _имена_версии(n)
    байты = (json.dumps(манифест, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    with open(корень / имя_м, "xb") as f:
        созданные.append(корень / имя_м)
        f.write(байты)
    хеш = _sha256(байты)
    with open(корень / имя_х, "xb") as f:
        созданные.append(корень / имя_х)
        f.write(("%s  %s\n" % (хеш, имя_м)).encode("utf-8"))
    созданные.clear()  # версия записана целиком: сбой штампа её уже не откатывает
    итог = {"каталог": str(корень), "версия": n, "манифест": имя_м,
            "манифест_sha256": хеш, "вложение": опись["файл"], "штамп": None}
    if штамп is None:
        был = (корень / _имена_версии(версии[-1])[3]).exists()
        штамп = (os.environ.get("INN_CHECK_TSA") or "да") if был else ""
    if штамп:
        итог["штамп"] = _поставить_штамп(корень, штамп, post=post, версия=n)
    _инструкция(корень)
    return итог


# --- проверка -----------------------------------------------------------------

def _сверить_файлы(корень, объявлено, ошибки, где=""):
    """Каждый объявленный файл на месте и с тем же хешем; пути — только внутрь."""
    for путь, ф in объявлено.items():
        p = корень / str(путь)
        # Манифест чужого пакета — недоверенный вход: путь за пределы каталога
        # или ссылка наружу сделали бы «годным» файл, которого в пакете нет.
        if (not путь or Path(str(путь)).is_absolute() or ".." in Path(str(путь)).parts
                or p.is_symlink()):
            ошибки.append("недопустимый путь в манифесте%s: %s" % (где, путь))
            continue
        if not p.is_file():
            ошибки.append("нет файла %s%s" % (путь, где))
            continue
        данные = p.read_bytes()
        if _sha256(данные) != ф.get("sha256") or len(данные) != ф.get("байт"):
            ошибки.append("изменён файл %s%s" % (путь, где))


def _сверить_штамп(корень, n, хеш, ошибки):
    """Штамп версии n: разбор, хеш манифеста, nonce. None — штампа нет."""
    _, _, запрос_tsa, ответ_tsa = _имена_версии(n)
    где = "" if n == 1 else " (версия %d)" % n
    tsr_путь = корень / ответ_tsa
    if not tsr_путь.exists():
        return None
    try:
        р = разобрать_ответ(tsr_путь.read_bytes())
    except ValueError as e:
        ошибки.append("штамп не разбирается%s: %s" % (где, e))
        return None
    if р["хеш_hex"] != хеш:
        ошибки.append("штамп поставлен на другой манифест%s" % где)
    tsq_путь = корень / запрос_tsa
    if tsq_путь.exists():
        nonce_запроса = _nonce_запроса(tsq_путь.read_bytes())
        if nonce_запроса is not None and nonce_запроса != р["nonce"]:
            ошибки.append("nonce штампа не совпадает с запросом%s" % где)
    return {"время_utc": р["время_utc"], "серийный": р["серийный"],
            "подпись": "не проверялась — openssl ts -verify, см. %s" % ИНСТРУКЦИЯ}


def _сверить_описи(корень, n, добавлено, ошибки):
    """Каждое вложение версии n — с описью, и опись говорит правду о нём."""
    описи = [п for п in добавлено if str(п).endswith(ОПИСЬ)]
    вложения = [п for п in добавлено if not str(п).endswith(ОПИСЬ)]
    if not описи or len(описи) != len(вложения):
        ошибки.append("версия %d: у вложений нет описи" % n)
    описано = []
    for путь in описи:
        try:
            оп = json.loads((корень / str(путь)).read_text(encoding="utf-8"))
        except (OSError, ValueError):
            ошибки.append("опись %s не читается" % путь)
            continue
        ф = корень / str(оп.get("файл") or "")
        if (оп.get("файл") not in вложения or оп.get("версия_манифеста") != n
                or not ф.is_file() or ф.is_symlink()
                or _sha256(ф.read_bytes()) != оп.get("sha256")
                or ф.stat().st_size != оп.get("байт")):
            ошибки.append("опись %s расходится с вложением" % путь)
        описано.append(оп.get("файл"))
    if sorted(map(str, описано)) != sorted(map(str, вложения)):
        ошибки.append("версия %d: описи не один к одному с вложениями" % n)


def проверить(каталог):
    """{годен, ошибки, файлов, штамп, версии}. Годен — только если всё сошлось.

    Версия 1 (manifest.json) — исходный сбор; версии 2.. — ручные вложения
    (--добавить). Каждая версия сверяется целиком: её файлы, её хеш и штамп, а
    у версий 2.. ещё и хеши всех прежних манифестов и штампов — подмена
    прежней версии задним числом ловится следующей.
    """
    корень = Path(каталог)
    ошибки = []
    итог = {"каталог": str(корень), "годен": False, "ошибки": ошибки,
            "файлов": 0, "штамп": None, "версии": []}
    try:
        байты = (корень / МАНИФЕСТ).read_bytes()
        манифест = json.loads(байты.decode("utf-8"))
    except (OSError, ValueError) as e:
        ошибки.append("манифест не читается: %s" % e)
        return итог
    хеш = _sha256(байты)
    try:
        записано = (корень / ХЕШ_МАНИФЕСТА).read_text(encoding="utf-8").split()[0]
    except (OSError, IndexError):
        записано = None
    if записано != хеш:
        ошибки.append("%s не совпадает с хешем манифеста" % ХЕШ_МАНИФЕСТА)
    if манифест.get("формат") != ФОРМАТ:
        ошибки.append("неизвестный формат пакета: %r" % манифест.get("формат"))

    объявлено = {ф.get("путь"): ф for ф in манифест.get("файлы") or []}
    итог["файлов"] = len(объявлено)
    _сверить_файлы(корень, объявлено, ошибки)
    все_объявленные = set(объявлено)

    # Индекс сырья ссылается на файлы с хешами — сверяем и его: подмена пары
    # «файл + строка манифеста» без правки индекса тоже должна ловиться.
    try:
        индекс = json.loads((корень / "raw" / "index.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        индекс = None
        ошибки.append("raw/index.json не читается")
    for запись in индекс or []:
        ф = объявлено.get(запись.get("файл"))
        if ф is None or ф.get("sha256") != запись.get("sha256"):
            ошибки.append("индекс сырья расходится с манифестом: %s" % запись.get("файл"))
    итог["штамп"] = _сверить_штамп(корень, 1, хеш, ошибки)

    версии = _версии(корень)
    if версии[:1] != [1] or версии != list(range(1, len(версии) + 1)):
        ошибки.append("версии манифеста идут с пропуском: %s" % версии)
    файлы_пред = объявлено
    for n in [v for v in версии if v > 1]:
        имя_м, имя_х, _, _ = _имена_версии(n)
        где = " (версия %d)" % n
        try:
            б = (корень / имя_м).read_bytes()
            мн = json.loads(б.decode("utf-8"))
        except (OSError, ValueError) as e:
            ошибки.append("%s не читается: %s" % (имя_м, e))
            continue
        хеш_n = _sha256(б)
        try:
            зап = (корень / имя_х).read_text(encoding="utf-8").split()[0]
        except (OSError, IndexError):
            зап = None
        if зап != хеш_n:
            ошибки.append("%s не совпадает с хешем манифеста" % имя_х)
        if мн.get("формат") != ФОРМАТ or мн.get("версия") != n:
            ошибки.append("%s: формат или номер версии не те" % имя_м)
        прежний = _имена_версии(n - 1)[0]
        пред = мн.get("предыдущий") or {}
        if пред.get("путь") != прежний or not (корень / прежний).is_file() or \
                _sha256((корень / прежний).read_bytes()) != пред.get("sha256"):
            ошибки.append("версия %d не ссылается на неизменённую версию %d" % (n, n - 1))
        семейство = {ф.get("путь"): ф for ф in мн.get("прежние_версии") or []}
        for путь in семейство:
            м = _СЕМЕЙСТВО.match(str(путь))
            if not м or int(м.group(1) or 1) >= n:
                ошибки.append("%s: чужой файл в прежних версиях: %s" % (имя_м, путь))
        _сверить_файлы(корень, {k: v for k, v in семейство.items() if _СЕМЕЙСТВО.match(str(k))},
                       ошибки, где)
        # Полнота: версия n закрепляет ВСЕ файлы прежних версий, что лежат в
        # каталоге, — иначе дописанный задним числом штамп прежней версии или
        # урезанная история проходили бы как годные.
        ожидаемые = {имя for v in версии if v < n for имя in _имена_версии(v)
                     if (корень / имя).is_file()}
        for имя in sorted(ожидаемые - set(семейство)):
            ошибки.append("%s не закреплён версией %d" % (имя, n))
        файлы_n = {ф.get("путь"): ф for ф in мн.get("файлы") or []}
        # Состав накопительный: всё, что было в версии n-1, есть и в n с тем же
        # хешем; новое — ровно то, что версия объявила добавленным.
        for путь, ф in файлы_пред.items():
            if путь not in файлы_n or файлы_n[путь].get("sha256") != ф.get("sha256"):
                ошибки.append("версия %d потеряла или изменила файл версии %d: %s"
                              % (n, n - 1, путь))
        добавлено = мн.get("добавлено") or []
        новые = set(файлы_n) - set(файлы_пред)
        if not добавлено or set(добавлено) != новые:
            ошибки.append("версия %d: «добавлено» %s не совпадает с новыми файлами %s"
                          % (n, sorted(добавлено), sorted(новые)))
        _сверить_файлы(корень, файлы_n, ошибки, где)
        _сверить_описи(корень, n, добавлено, ошибки)
        файлы_пред = файлы_n
        все_объявленные |= set(файлы_n)
        итог["версии"].append({"версия": n, "добавлено": мн.get("добавлено") or [],
                               "штамп": _сверить_штамп(корень, n, хеш_n, ошибки)})

    for p in корень.rglob("*"):
        if p.is_symlink():
            ошибки.append("символическая ссылка в пакете: %s"
                          % p.relative_to(корень).as_posix())
    фактически = {ф["путь"] for ф in _опись(корень)}
    for лишний in sorted(фактически - все_объявленные):
        ошибки.append("файл не из манифеста: %s" % лишний)
    известные = {имя for v in версии for имя in _имена_версии(v)}
    for p in корень.iterdir():
        if _СЕМЕЙСТВО.match(p.name) and p.name not in известные:
            ошибки.append("файл манифеста без своей версии: %s" % p.name)

    итог["годен"] = not ошибки
    # «годен» — про файлы и согласованность, не про криптографию штампа.
    есть_штампы = итог["штамп"] or any(в["штамп"] for в in итог["версии"])
    итог["что_проверено"] = (
        "хеши и состав файлов против манифеста" +
        ("; версий манифеста: %d, цепочка хешей" % len(версии) if len(версии) > 1 else "") + (
            "; штамп: статус, хеш манифеста, nonce — подпись TSA НЕ проверена "
            "(openssl ts -verify)" if есть_штампы else "; штампа нет"))
    return итог


def _nonce_запроса(tsq):
    try:
        дети = _дети(_tlv(tsq, 0)[1])
    except (ValueError, IndexError):
        return None
    целые = [v for t, v in дети if t == 0x02]
    return int.from_bytes(целые[1], "big") if len(целые) > 1 else None


