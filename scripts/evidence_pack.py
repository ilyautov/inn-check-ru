def _имена_версии(n):
    """(манифест, хеш, запрос TSA, ответ TSA) версии n; версия 1 — исторические имена."""
    if n == 1:
        return МАНИФЕСТ, ХЕШ_МАНИФЕСТА, ЗАПРОС_TSA, ОТВЕТ_TSA
    return tuple("manifest.%d.%s" % (n, ext) for ext in ("json", "sha256", "tsq", "tsr"))


def _версии(корень):
    """Номера версий манифеста, что лежат в каталоге (по возрастанию)."""
    номера = set()
    for p in корень.iterdir() if корень.is_dir() else []:
        м = _СЕМЕЙСТВО.match(p.name)
        if м and м.group(2) == "json":
            номера.add(int(м.group(1)) if м.group(1) else 1)
    return sorted(номера)

# Публичные TSA для INN_CHECK_TSA=да. Оба бесплатны; порядок — порядок попыток.
TSA_ПО_УМОЛЧАНИЮ = ("https://freetsa.org/tsr", "http://timestamp.digicert.com")
