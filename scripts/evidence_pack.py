USAGE = ("Использование: python3 evidence_pack.py --проверить <каталог>\n"
         "               python3 evidence_pack.py --штамп <каталог> [--tsa URL[,URL]]\n"
         "               python3 evidence_pack.py --добавить <каталог> <файл> --источник ID\n"
         "                   --url URL --дата ГГГГ-ММ-ДД [--параметры ТЕКСТ]\n"
         "                   [--просмотрено N] [--найдено ТЕКСТ] [--без-штампа]\n"
         "Пакет создаёт fetch_counterparty.py <ИНН> --пакет <каталог>.\n")


def main(argv):
    args = argv[1:]
    if len(args) == 2 and args[0] in ("--проверить", "--verify"):
        итог = проверить(args[1])
        sys.stdout.write(json.dumps(итог, ensure_ascii=False, indent=2) + "\n")
        return 0 if итог["годен"] else 1
    if len(args) in (2, 4) and args[0] in ("--штамп", "--timestamp"):
        tsa = os.environ.get("INN_CHECK_TSA") or "да"
        if len(args) == 4:
            if args[2] != "--tsa":
                sys.stderr.write(USAGE)
                return 2
            tsa = args[3]
        if not (Path(args[1]) / МАНИФЕСТ).exists():
            sys.stderr.write("нет %s в %s\n" % (МАНИФЕСТ, args[1]))
            return 2
        итог = поставить_штамп(args[1], tsa)
        sys.stdout.write("штамп: %s\n" % итог)
        return 1 if итог.startswith("не поставлен") else 0
    if len(args) >= 3 and args[0] in ("--добавить", "--add"):
        опции = {"--источник": None, "--url": None, "--дата": None, "--параметры": None,
                 "--просмотрено": None, "--найдено": None}
        без_штампа = False
        хвост = args[3:]
        i = 0
        while i < len(хвост):
            if хвост[i] == "--без-штампа":
                без_штампа = True
                i += 1
            elif хвост[i] in опции and i + 1 < len(хвост):
                опции[хвост[i]] = хвост[i + 1]
                i += 2
            else:
                sys.stderr.write(USAGE)
                return 2
        try:
            итог = добавить(args[1], args[2], опции["--источник"], опции["--url"],
                            дата_проверки=опции["--дата"], параметры=опции["--параметры"],
                            просмотрено=опции["--просмотрено"], найдено=опции["--найдено"],
                            штамп="" if без_штампа else None)
        except (ValueError, OSError) as e:
            sys.stderr.write("не добавлено: %s\n" % e)
            return 2
        sys.stdout.write(json.dumps(итог, ensure_ascii=False, indent=2) + "\n")
        return 1 if str(итог.get("штамп") or "").startswith("не поставлен") else 0
    sys.stderr.write(USAGE)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
