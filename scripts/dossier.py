def хеш_входа(path):
    """(sha256, размер в байтах) исходного файла — неизменность входных данных."""
    try:
        данные = Path(path).read_bytes()
    except OSError as e:
        return "не вычислен (%s)" % e, None
    return hashlib.sha256(данные).hexdigest(), len(данные)


