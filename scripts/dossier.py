#!/usr/bin/env python3
"""
dossier.py — досье должной осмотрительности: документ, фиксирующий, что было видно
в открытых источниках на дату и время проверки.

Зачем он нужен. К акту налоговой проверки прикладывают не светофор, а документ:
«вот что мы смотрели перед сделкой, вот когда, вот чего в открытых данных не было
видно». Юридическая ценность у такого документа процедурная и появляется, только
если он составлен ДО сделки — поэтому дата, время и хеш исходного JSON стоят в
шапке, а оговорка о границах документа — отдельным разделом.

Чем он НЕ является. Это не заключение (юридическое, налоговое, аудиторское) и не
справка госоргана: ни гербов, ни печатей, ни «справка выдана» тут нет и быть не
должно. Это отчёт инструмента, и подписан он так же. Ни одного утверждения о
контрагенте сверх того, что отдали источники, документ не содержит.

Использование:
    python3 dossier.py --fetch a.json                       # Markdown в stdout
    python3 dossier.py --fetch a.json --в досье.md
    python3 dossier.py --fetch a.json --docx досье.docx
    python3 dossier.py --fetch a.json --fin f.json --санкции s.json --граф g.json \\
        --профиль отсрочка --предмет "поставка ГСМ" --сумма 4200000

Вход: `--fetch <файл>` обязателен (вывод fetch_counterparty.py: блоки источников,
`_доступность` словарями, `_итог_проверки`, `_сбор`). Необязательно: `--fin`
(fin_scoring.py), `--санкции` (sanctions_check.py), `--граф` (affiliates_graph.py),
`--профиль <id>` (по умолчанию — из fetch-JSON), `--предмет`, `--сумма`.

Выход: Markdown (stdout или `--в <файл>`) и `--docx <файл>`. DOCX собирается чистым
stdlib: zipfile + минимальный WordprocessingML ([Content_Types].xml, _rels/.rels,
word/document.xml, word/_rels/document.xml.rels). Оба формата рендерятся из одного
списка блоков — расхождение форматов невозможно по построению.

Обязательные разделы (спек волны 3, §3):
    1. Кто проверен и когда — дата, время, версия инструмента, хеш входного JSON;
    2. Что проверено — таблица источников: tier, состояние, дата, первоисточник;
    3. Что НЕ проверено и почему — отдельно и заметно;
    4. Что найдено в источниках — сигналы с источником и датой, вердикт профиля;
    5. Границы этого документа — оговорка и перечень того, что закрыто законом.

Профиль с формулировкой «факты» (нейтрально, ндс_вычет) вердикт и рекомендацию не
печатает: вердикт там был бы заключением, которого инструмент не даёт.

Никогда не падает traceback'ом: нечитаемый вход превращается в раздел «не проверено»
с причиной, а не в стек.
"""

