# --- Markdown ----------------------------------------------------------------

def _md_ячейка(текст):
    return str(текст).replace("|", "\\|").replace("\n", " ").strip()


def в_markdown(блоки):
    out = []
    for b in блоки:
        т = b["тип"]
        if т == "заголовок":
            out.append("%s %s" % ("#" * int(b.get("уровень", 2)), b["текст"]))
            out.append("")
        elif т == "абзац":
            текст = b["текст"]
            if b.get("жирный"):
                текст = "**%s**" % текст
            if b.get("курсив"):
                текст = "_%s_" % текст
            out.append(текст)
            out.append("")
        elif т == "список":
            for п in b["пункты"]:
                out.append("- %s" % п)
            out.append("")
        elif т == "поля":
            for k, v in b["пары"]:
                out.append("- **%s:** %s" % (k, v))
            out.append("")
        elif т == "таблица":
            шапка = b["шапка"]
            out.append("| %s |" % " | ".join(_md_ячейка(c) for c in шапка))
            out.append("|%s|" % "|".join(["---"] * len(шапка)))
            for r in b["строки"]:
                out.append("| %s |" % " | ".join(_md_ячейка(c) for c in r))
            out.append("")
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


