def _подраздел_финансы(fetch, fin):
    фин = fetch.get("финансы") if isinstance(fetch.get("финансы"), dict) else {}
    годы = фин.get("отчётность_по_годам")
    if not isinstance(годы, list) or not годы:
        return []
    строки = []
    for g in годы:
        if not isinstance(g, dict):
            continue
        b = g.get("строки") if isinstance(g.get("строки"), dict) else {}
        строки.append([
            _текст(g.get("год")),
            _текст(_рубли(_в_рубли(g.get("выручка")))),
            _текст(_рубли(_в_рубли(g.get("прибыль_убыток")))),
            _текст(_рубли(_в_рубли(g.get("активы")))),
            _текст(_рубли(_в_рубли(b.get("1300")))),
            _текст(g.get("дата_отчётности")),
        ])
    блоки = [
        заголовок("Бухгалтерская отчётность (ГИР БО)", 3),
        таблица(["Год", "Выручка (2110)", "Прибыль/убыток (2400)",
                 "Активы (1600)", "Чистые активы (1300)", "Дата отчётности"],
                строки),
        абзац("Суммы пересчитаны в рубли: ГИР БО публикует отчётность в тысячах "
              "рублей. Показатели приведены без интерпретации — оценки "
              "«хорошо/плохо» документ не даёт, см. раздел 4."),
    ]
    if isinstance(fin, dict) and fin.get("статус") and fin["статус"] != "не проверено":
        блоки.append(поля([("Итог финансового разбора", _текст(fin.get("статус"))),
                           ("Флагов найдено", _текст(len(fin.get("флаги") or [])))]))
    return блоки


