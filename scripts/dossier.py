def _раздел_3(fetch, sources, вердикт, fin, санкции, граф, ошибки_входа,
              входы=None):
    дост = _доступность(fetch)
    порядок = _порядок_источников(fetch, sources)
    строки = []
    for sid in порядок:
        состояние, зап = _запись_источника(sid, дост)
        if состояние not in СОСТОЯНИЯ_БЕЗ_ДАННЫХ:
            continue
        оп = _описание_источника(sid, sources)
        причина = (_текст(зап.get("причина"), "причина не указана источником")
                   if состояние == "не проверено"
                   else "во входном файле нет записи об этом источнике: "
                        "обращался ли к нему инструмент — неизвестно")
        строки.append([
            оп["название"],
            _текст(оп["tier"] or зап.get("tier")),
            _dk_текст(оп),
            состояние,
            _текст(зап.get("требует") or оп["требует"]),
            причина,
        ])
    блоки = [
        заголовок(ЗАГОЛОВКИ_РАЗДЕЛОВ[2]),
        абзац("Самый важный раздел документа. «Не проверено» — это не «чисто»: "
              "источник молчал, был недоступен или не покрывается скриптом. "
              "Ни одна строка отсюда не даёт оснований считать признак "
              "отсутствующим.", жирный=True),
        заголовок("3.1. Источники, не давшие данных", 3),
    ]
    if строки:
        блоки.append(таблица(
            ["Источник", "Tier", "Deal-killer", "Состояние", "Требует",
             "Почему не проверено"], строки))
    elif порядок and дост:
        блоки.append(абзац("Все источники реестра ответили: состояние каждого "
                           "приведено в разделе 2."))
    else:
        блоки.append(абзац("Перечень источников не построен: реестр источников "
                           "недоступен, а состояний во входном файле нет. Это НЕ "
                           "значит, что источники ответили, — о них просто нет "
                           "сведений.", жирный=True))

    непроверенные_сигналы = [f for f in (вердикт.get("факты") or [])
                             if isinstance(f, dict) and f.get("статус") == "не проверен"]
    блоки.append(заголовок("3.2. Сигналы, оставшиеся непроверенными", 3))
    if непроверенные_сигналы:
        блоки.append(список(["%s" % _текст(f.get("текст"))
                             for f in непроверенные_сигналы]))
    else:
        блоки.append(абзац("Непроверенных сигналов нет."))

    # Тексты 3.2 — единственное место, где сейчас всплывают пробелы финансового
    # разбора: резолвер профиля дописывает причину fin_scoring в сигнал. Ниже
    # мы добираем пробелы, до сигнала не дошедшие, и сверяемся с этим текстом,
    # чтобы не напечатать один и тот же пробел дважды.
    тексты_32 = " ".join(_текст(f.get("текст")) for f in непроверенные_сигналы)

    прочее = []
    for подпись, флаг, узел in (("финансовый разбор", "--fin", fin),
                                ("санкционная сверка", "--санкции", санкции),
                                ("граф связей", "--граф", граф)):
        if not isinstance(узел, dict):
            if входы is None:
                continue
            if (входы or {}).get(флаг):
                прочее.append("%s (%s): вход передан, но данных из него в документ "
                              "не попало" % (подпись, флаг))
            else:
                прочее.append("%s (%s): не запускался — вход не передан. Отсутствие "
                              "этого раздела не означает, что проверять нечего"
                              % (подпись, флаг))
            continue
        if узел.get("статус") == "не проверено":
            прочее.append("%s: не проверено — %s"
                          % (подпись, _текст(узел.get("причина"),
                                             "причина не указана")))
        # fin_scoring кладёт свой список НЕ в корень, а в «финансовый_профиль»:
        # искать его только в корне значило бы иметь эту страховку и не
        # пользоваться ею. Пробел, не доехавший до сигнала профиля, иначе не
        # виден в документе вовсе.
        источники_нп = [узел.get("не_проверено")]
        профиль_узла = узел.get("финансовый_профиль")
        if isinstance(профиль_узла, dict):
            источники_нп.append(профиль_узла.get("не_проверено"))
        for нп in источники_нп:
            if not isinstance(нп, list):
                continue
            for item in нп:
                if isinstance(item, dict):
                    прочее.append("%s: %s — %s" % (
                        подпись, _текст(item.get("список") or item.get("что")),
                        _текст(item.get("причина"))))
                elif item and str(item) not in тексты_32:
                    прочее.append("%s: %s" % (подпись, _текст(item)))
    прочее += list(ошибки_входа or [])
    if sources is None:
        прочее.append("реестр источников (scripts/sources.py) не импортируется: "
                      "перечень источников построен только по входному файлу, "
                      "источник вне входа в документ не попал")
    if вердикт.get("источники_обязательные_не_проверены"):
        прочее.append("обязательные источники профиля без данных: %s"
                      % _текст(вердикт["источники_обязательные_не_проверены"]))
    номер = 3
    if прочее:
        блоки.append(заголовок("3.%d. Прочие пробелы" % номер, 3))
        блоки.append(список(прочее))
        номер += 1
    вручную = [_текст(x) for x in (вердикт.get("вручную") or []) if x]
    if вручную:
        блоки.append(заголовок("3.%d. Что инструмент не проверяет — запросить и "
                               "проверить вручную" % номер, 3))
        блоки.append(абзац("Перечень профиля «%s»: чего в открытых данных не видно "
                           "и что запрашивается у самого контрагента. Инструмент "
                           "этого не проверял." % _текст(вердикт.get("профиль"))))
        блоки.append(список(вручную))
    блоки += _критерии_осмотрительности(дост, sources, номер + (1 if вручную else 0))
    блоки.append(абзац("Закрытые законом данные (налоговая и банковская тайна и "
                       "прочее) в этот раздел не входят: они недоступны в принципе, "
                       "см. раздел 5."))
