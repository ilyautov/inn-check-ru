def _вердикт(fetch, fin, profile_id):
    """(резолв профиля, вердиктный ли профиль, ошибки). Без profiles.py — пусто."""
    profiles = _модуль("profiles")
    if profiles is None:
        return ({}, False,
                [("профили не импортируются (scripts/profiles.py) — сигналы и "
                  "вердикт в документ не попали")])
    try:
        рез = profiles.resolve(fetch, fin, profile_id)
    except Exception as e:
        return {}, False, ["профиль не разобран: %s" % e]
    формулировка = рез.get("формулировка")
    if формулировка is None:
        try:
            данные = profiles.load()
            формулировка = (данные.get("профили", {})
                            .get(рез.get("профиль") or profile_id, {})
                            .get("формулировка"))
        except Exception:
            формулировка = None
    ошибки = []
    if рез.get("статус") == "не проверено" and рез.get("причина"):
        ошибки.append("профиль не разобран: %s" % рез["причина"])
    return рез, формулировка == "вердикт", ошибки


def main(argv):
    args = argv[1:]
    if not args or "-h" in args or "--help" in args:
        sys.stderr.write(__doc__)
        return 2
    опции = {"--fetch": None, "--fin": None, "--санкции": None, "--граф": None,
             "--профиль": None, "--предмет": None, "--сумма": None,
             "--в": None, "--docx": None}
    i = 0
    while i < len(args):
        a = args[i]
        if a in опции:
            if i + 1 >= len(args):
                sys.stderr.write("нет значения для %s\n" % a)
                return 2
            опции[a] = args[i + 1]
            i += 2
            continue
        if a == "--markdown":  # формат по умолчанию, флаг принимается для явности
            i += 1
            continue
        sys.stderr.write("неизвестный аргумент: %s\n" % a)
        return 2

    if not опции["--fetch"]:
        sys.stderr.write("--fetch <файл> обязателен: досье строится по выводу "
                         "fetch_counterparty.py\n")
        return 2

    fetch, ошибка = _читать_json(опции["--fetch"], "--fetch")
    if ошибка or not isinstance(fetch, dict):
        sys.stderr.write("%s\n" % (ошибка or "--fetch: содержимое не словарь JSON"))
        return 1

    ошибки_входа = []
    fin, e = _читать_json(опции["--fin"], "--fin")
    if e:
        ошибки_входа.append(e)
    санкции, e = _читать_json(опции["--санкции"], "--санкции")
    if e:
        ошибки_входа.append(e)
    граф, e = _читать_json(опции["--граф"], "--граф")
    if e:
        ошибки_входа.append(e)

    профиль = опции["--профиль"] or fetch.get("профиль")
    вердикт, вердиктный, ошибки_профиля = _вердикт(fetch, fin, профиль)
    ошибки_входа += ошибки_профиля

    хеш, размер = хеш_входа(опции["--fetch"])
    сбор = fetch.get("_сбор") if isinstance(fetch.get("_сбор"), dict) else {}
    мета = {
        "сформирован": _штамп(_сейчас()),
        "дата_сбора": _дата_сбора(fetch),
        "версия": версия_инструмента(),
        "профиль": вердикт.get("профиль") or профиль or "не указан",
        "вопрос_профиля": вердикт.get("вопрос"),
        "режим": сбор.get("режим"),
        "файл": Path(опции["--fetch"]).name,
        "хеш": хеш,
        "размер": размер,
        "предмет": опции["--предмет"],
        "сумма": _рубли(опции["--сумма"]) if опции["--сумма"] else None,
    }

    блоки = собрать(fetch, мета, fin=fin, санкции=санкции, граф=граф,
                    вердикт=вердикт, профиль_вердиктный=вердиктный,
                    ошибки_входа=ошибки_входа, sources=_модуль("sources"))

    текст = в_markdown(блоки)
    if опции["--в"]:
        try:
            Path(опции["--в"]).write_text(текст, encoding="utf-8")
        except OSError as ex:
            sys.stderr.write("не записан Markdown %s: %s\n" % (опции["--в"], ex))
            return 1
    if опции["--docx"]:
        try:
            записать_docx(блоки, опции["--docx"])
        except OSError as ex:
            sys.stderr.write("не записан DOCX %s: %s\n" % (опции["--docx"], ex))
            return 1
    if not опции["--в"] and not опции["--docx"]:
        sys.stdout.write(текст)
    elif опции["--в"] or опции["--docx"]:
        sys.stderr.write("готово: %s\n" % ", ".join(
            p for p in (опции["--в"], опции["--docx"]) if p))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
