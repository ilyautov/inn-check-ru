def заголовок(текст, уровень=2):
    return {"тип": "заголовок", "уровень": уровень, "текст": текст}


def абзац(текст, жирный=False, курсив=False):
    return {"тип": "абзац", "текст": текст, "жирный": жирный, "курсив": курсив}


def список(пункты):
    return {"тип": "список", "пункты": [p for p in пункты if p]}


def таблица(шапка, строки):
    return {"тип": "таблица", "шапка": list(шапка),
            "строки": [list(r) for r in строки]}


def поля(пары):
    """Пары «название — значение» как список строк «**Название:** значение»."""
    return {"тип": "поля", "пары": [(k, v) for k, v in пары if v is not None]}


# --- чтение fetch-JSON -------------------------------------------------------

def _доступность(fetch):
    d = fetch.get("_доступность")
    return d if isinstance(d, dict) else {}


def _порядок_источников(fetch, sources):
    """id источников в порядке реестра, затем всё, что реестру неизвестно."""
    дост = _доступность(fetch)
    порядок = []
    if sources is not None:
        порядок = [s for s in sources.SOURCES if s in дост]
    порядок += [s for s in дост if s not in порядок]
    return порядок


def _описание_источника(sid, sources):
    """(название, tier, ссылка, deal_killer) — из реестра, с деградацией до id."""
    d = (getattr(sources, "SOURCES", {}) or {}).get(sid) if sources else None
    if not isinstance(d, dict):
        return sid, None, None, None
    return (d.get("название") or sid, d.get("tier"), d.get("документация"),
            bool(d.get("deal_killer")))


def _шапка_контрагента(fetch):
    """Идентификация контрагента из блоков ЕГРЮЛ/риски/финансы — без домысливания."""
    егрюл = fetch.get("егрюл") if isinstance(fetch.get("егрюл"), dict) else {}
    риски = fetch.get("риски") if isinstance(fetch.get("риски"), dict) else {}
    фин = fetch.get("финансы") if isinstance(fetch.get("финансы"), dict) else {}
    полное = (егрюл.get("наименование_полное") or риски.get("наименование")
              or фин.get("наименование") or егрюл.get("наименование") or None)
    краткое = егрюл.get("наименование_краткое") or фин.get("наименование") or полное
    return {
        "наименование_полное": полное,
        "наименование_краткое": краткое,
        "инн": fetch.get("инн") or егрюл.get("инн") or риски.get("inn"),
        "огрн": егрюл.get("огрн") or фин.get("огрн"),
        "кпп": егрюл.get("кпп"),
        "тип": fetch.get("тип"),
        "руководитель": егрюл.get("руководитель"),
        "дата_регистрации": (егрюл.get("дата_регистрации")
                             or риски.get("дата_регистрации")),
        "регион": егрюл.get("регион") or риски.get("регион"),
        "адрес": егрюл.get("адрес"),
        "статус": егрюл.get("статус") or риски.get("статус"),
        "оквэд": (("%s — %s" % (риски["оквэд"], риски.get("оквэд_наименование")))
                  if риски.get("оквэд") and риски.get("оквэд_наименование")
                  else риски.get("оквэд")),
    }


def _дата_сбора(fetch):
    """Дата, которой источники пометили свои ответы (не дата печати документа)."""
    даты = sorted({str(v.get("дата")) for v in _доступность(fetch).values()
                   if isinstance(v, dict) and v.get("дата")})
    return ", ".join(даты) if даты else None


