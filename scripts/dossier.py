def _итог_проверки(fetch, строк, с_состоянием):
    """Сводка `_итог_проверки`. Нет итога — «проверка состоялась: нет», не молчание.

    Молчание тут читается как «состоялась»: документ обязан сказать, что
    подтвердить полноту проверки нечем. И если шапка объявляет больше
    источников, чем состояний во входе, разницу нельзя считать проверенной.
    """
    итог = fetch.get("_итог_проверки")
    if not isinstance(итог, dict):
        return [
            поля([("Источников опрошено", "неизвестно"),
                  ("Проверка состоялась", "нет")]),
            абзац("Блока «_итог_проверки» во входном файле нет: подтвердить, что "
                  "проверка состоялась, нечем. Отсутствие итога — это «не "
                  "проверено», а не «всё в порядке».", жирный=True),
        ]
    блоки = [поля([
        ("Источников опрошено", _текст(итог.get("источников"))),
        ("Ответили", _текст(итог.get("ok"))),
        ("Ответили пустым результатом", _текст(итог.get("пусто"))),
        ("Не проверено", _текст(итог.get("не_проверено"))),
        ("Проверка состоялась", "да" if итог.get("проверка_состоялась") else "нет"),
    ])]
    объявлено = итог.get("источников")
    if (isinstance(объявлено, int) and not isinstance(объявлено, bool)
            and объявлено != с_состоянием):
        блоки.append(абзац(
            "Расхождение: в итоге проверки объявлено источников — %d, а состояний "
            "источников во входном файле — %d (строк в таблице выше — %d). Разницу "
            "нельзя считать проверенной: по этим источникам во входе нет ответа, "
            "см. раздел 3." % (объявлено, с_состоянием, строк), жирный=True))
    if итог.get("вывод"):
        блоки.append(абзац("Вывод о полноте проверки: %s" % итог["вывод"],
                           жирный=True))
    return блоки


