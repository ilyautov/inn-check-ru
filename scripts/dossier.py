def _md_текст(текст):
    """Текст для Markdown: управляющие символы вычищены, перевод строки — пробел.

    DOCX чистит ровно тот же класс символов (см. _xml), и Markdown обязан быть не
    слабее: название с переводом строки рвёт заголовок документа, а вертикальная
    табуляция и возврат каретки ломают строку таблицы у потребителя, который
    считает их переводом строки. Чистятся ВСЕ блоки, а не только ячейки таблиц.
    """
    s = _УПРАВЛЯЮЩИЕ.sub("", str(текст))
    return _ПЕРЕВОДЫ.sub(" ", s).strip()


def _md_ячейка(текст):
    return _md_текст(текст).replace("|", "\\|")


def в_markdown(блоки):
    out = []
    for b in блоки:
        т = b["тип"]
        if т == "заголовок":
            out.append("%s %s" % ("#" * int(b.get("уровень", 2)),
                                  _md_текст(b["текст"])))
            out.append("")
        elif т == "абзац":
            текст = _md_текст(b["текст"])
            if b.get("жирный"):
                текст = "**%s**" % текст
            if b.get("курсив"):
                текст = "_%s_" % текст
            out.append(текст)
            out.append("")
        elif т == "список":
            for п in b["пункты"]:
                out.append("- %s" % _md_текст(п))
            out.append("")
        elif т == "поля":
            for k, v in b["пары"]:
                out.append("- **%s:** %s" % (_md_текст(k), _md_текст(v)))
            out.append("")
        elif т == "таблица":
            шапка = b["шапка"]
            out.append("| %s |" % " | ".join(_md_ячейка(c) for c in шапка))
            out.append("|%s|" % "|".join(["---"] * len(шапка)))
            for r in b["строки"]:
                out.append("| %s |" % " | ".join(_md_ячейка(c) for c in r))
            out.append("")
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


