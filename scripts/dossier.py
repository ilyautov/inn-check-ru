def _вердикт(fetch, fin, profile_id):
    """(резолв профиля, вердиктный ли профиль, ошибки). Без profiles.py — пусто."""
    profiles = _модуль("profiles")
    if profiles is None:
        return ({}, False,
                [("профили не импортируются (scripts/profiles.py) — сигналы и "
                  "вердикт в документ не попали")])
    try:
        рез = profiles.resolve(fetch, fin, profile_id)
    except Exception as e:
        return {}, False, ["профиль не разобран: %s" % e]
    формулировка = рез.get("формулировка")
    if формулировка is None:
        try:
            данные = profiles.load()
            формулировка = (данные.get("профили", {})
                            .get(рез.get("профиль") or profile_id, {})
                            .get("формулировка"))
        except Exception:
            формулировка = None
    ошибки = []
    if рез.get("статус") == "не проверено" and рез.get("причина"):
        ошибки.append("профиль не разобран: %s" % рез["причина"])
    return рез, формулировка == "вердикт", ошибки


def _проверить_пакет(каталог, fetch_путь):
    """Итог evidence_pack.проверить + чей fetch.json лёг в основу досье."""
    ep = _модуль("evidence_pack")
    if ep is None:
        return "evidence_pack.py не импортируется"
    итог = ep.проверить(каталог)
    try:
        манифест = json.loads((Path(каталог) / ep.МАНИФЕСТ).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        манифест = {}
    итог["ответов"] = манифест.get("ответов_источников")
    итог["создан_utc"] = манифест.get("создан_utc")
    итог["манифест_sha256"] = хеш_входа(Path(каталог) / ep.МАНИФЕСТ)[0]
    в_пакете = {ф.get("путь"): ф.get("sha256") for ф in манифест.get("файлы") or []}
    if not fetch_путь:
        итог["fetch_из_пакета"] = "да — fetch.json пакета"
    elif хеш_входа(fetch_путь)[0] == в_пакете.get("fetch.json"):
        итог["fetch_из_пакета"] = "да — совпадает с fetch.json пакета"
    else:
        итог["fetch_из_пакета"] = ("НЕТ — --fetch не совпадает с fetch.json пакета: "
                                  "досье и пакет описывают разные проверки")
    return итог


