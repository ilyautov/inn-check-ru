def _штамп(dt):
    смещение = dt.strftime("%z")
    if len(смещение) == 5:
        смещение = "UTC%s:%s" % (смещение[:3], смещение[3:])
    return "%s (%s)" % (dt.strftime("%d.%m.%Y %H:%M:%S"), смещение)


def _текст(v, пусто="—"):
    if v is None or v == "" or v == []:
        return пусто
    if isinstance(v, bool):
        return "да" if v else "нет"
    if isinstance(v, (list, tuple)):
        return ", ".join(_текст(x) for x in v)
    return str(v)


# ГИР БО публикует отчётность в ТЫСЯЧАХ рублей (проверено 19.09.2026 сверкой
# с дампом ФНС revexp по трём ИНН: отношение дохода в рублях к стр. 2110 —
# 1010, 1002 и 1025). Документ прикладывают к возражениям на акт налоговой,
# и сумма, заниженная в тысячу раз, обесценивает его целиком.
ТЫС_В_РУБ = 1000


def _в_рубли(значение):
    """Строка отчётности ГИР БО -> рубли. Нечисловое возвращается как есть."""
    if isinstance(значение, bool) or not isinstance(значение, (int, float)):
        return значение
    return значение * ТЫС_В_РУБ


def _рубли(значение):
    """«4200000» -> «4 200 000 руб.»; нечисловое возвращается как есть.

    Знак стоит перед всей суммой, а не перед копейками: -1234.56 даёт
    «-1 234,56 руб.», а не «-1 235,-56 руб.». Целые суммы (ГИР БО отдаёт
    целые) считаются в целых копейках, без округления через float.
    """
    if значение is None or isinstance(значение, bool):
        return значение
    if isinstance(значение, int):
        копеек_всего = значение * 100
    else:
        try:
            число = float(str(значение).replace("\u00a0", "")
                          .replace(" ", "").replace(",", "."))
        except (TypeError, ValueError):
            return str(значение)
        копеек_всего = round(число * 100)
    знак = "-" if копеек_всего < 0 else ""
    целых, копеек = divmod(abs(копеек_всего), 100)
    разряды = f"{целых:,d}".replace(",", "\u00a0")
    if копеек:
        return "%s%s,%02d руб." % (знак, разряды, копеек)
    return "%s%s руб." % (знак, разряды)


def _читать_json(path, подпись):
    """(данные, ошибка). Ошибка — русская причина, не исключение."""
    if not path:
        return None, None
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh), None
    except OSError as e:
        return None, "%s: файл не читается (%s)" % (подпись, e)
    except ValueError as e:
        return None, "%s: файл не разбирается как JSON (%s)" % (подпись, e)


