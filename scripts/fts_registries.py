#!/usr/bin/env python3
"""
fts_registries.py — реестры ФТС по ИНН, офлайн. Только stdlib.

Открытые данные ФТС (customs.gov.ru/opendata) — CSV со страниц наборов. Сайт
закрыт для не-РФ адресов: скачивание идёт через прокси пользователя
(INN_CHECK_PROXY, в т.ч. socks5; см. dump_tools.py). Живьём 28.09.2026:

    7730176610-reesrtampredst  таможенные представители (1 074, все РФ)
    7730176610-reestrtamperev  таможенные перевозчики (4 617, из них РФ 2 726;
                               с истёкшими, аннулированными и отозванными)
    7730176610-revlsvrhr       владельцы складов временного хранения (609)
    7730176610-reestrvtamskl   владельцы таможенных складов (~390)
    7730176610-reestrmbt       владельцы магазинов беспошлинной торговли (~150)

Представители, склады и магазины в выгрузке — только действующие: «записи нет»
значит «сейчас не в реестре», истории там нет. У перевозчиков и СВХ статус — код
IDEL. Его смысл описан в структуре набора СВХ (structure-20130527T0000.csv):
1 — срок истёк, 3 — аннулирована, 4 — отозвана, 5 — отозвана по желанию
владельца, 9 — действует по дату окончания. У перевозчиков действующие идут с
кодом 0 и будущей датой окончания (1 196 из 1 201 строки с кодом 0 живьём), так
что 0 с датой окончания в будущем или без неё — действует, с прошедшей — срок
истёк. Код вне списка — «статус неизвестен (код …)», не угадываем.

В индекс не попадают адреса, телефоны, e-mail и сайты — только ИНН, номер
свидетельства, даты и статус. Иностранные перевозчики (BY, KZ, …) не берутся:
у них нет российского ИНН.

    python3 fts_registries.py --refresh      # нужен РФ-IP или INN_CHECK_PROXY
    python3 fts_registries.py --inn 7702664252
"""

import csv
import datetime as dt
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dump_tools

CACHE_DIR = os.path.expanduser(os.path.join("~", ".cache", "inn-check-ru", "fts"))
CACHE_DIR_ВИДИМЫЙ = "~/.cache/inn-check-ru/fts"
ИНДЕКС = "индекс.json.gz"
САЙТ = "https://customs.gov.ru"
РЕЕСТРЫ = {
    "таможенные_представители": {"набор": "7730176610-reesrtampredst",
                                 "название": "Реестр таможенных представителей"},
    "таможенные_перевозчики": {"набор": "7730176610-reestrtamperev",
                               "название": "Реестр таможенных перевозчиков"},
    "свх": {"набор": "7730176610-revlsvrhr",
            "название": "Реестр владельцев складов временного хранения"},
    "таможенные_склады": {"набор": "7730176610-reestrvtamskl",
                          "название": "Реестр владельцев таможенных складов"},
    "магазины_беспошлинной_торговли": {
        "набор": "7730176610-reestrmbt",
        "название": "Реестр владельцев магазинов беспошлинной торговли"},
}
IDEL = {"1": "срок истёк", "3": "аннулирована", "4": "отозвана",
        "5": "отозвана по желанию владельца"}
ЛИМИТ = 50 << 20
ДОЛЯ_ПАДЕНИЯ = 0.5
ДОЛЯ_БЕЗ_ИНН = 0.02
СВЕЖЕСТЬ_ДНЕЙ = 30


def страница(реестр):
    return "%s/opendata/%s" % (САЙТ, РЕЕСТРЫ[реестр]["набор"])


def ссылка_на_данные(html_страницы, реестр):
    """Самый свежий data-*.csv набора со страницы (ссылки стоят на ней)."""
    набор = re.escape(РЕЕСТРЫ[реестр]["набор"])
    ссылки = set(re.findall(r'href="(https://customs\.gov\.ru/storage/opendata/%s/'
                            r'data-(\d{8})T\d{4}-structure-[^"/]+\.csv)"' % набор,
                            html_страницы))
    if not ссылки:
        raise ValueError("схема: на странице набора %s нет ссылки на data-*.csv" % реестр)
    return max(ссылки, key=lambda с: с[1])


# --- разбор -----------------------------------------------------------------

def _дата(s):
    """«ГГГГ.ММ.ДД» или «ДД.ММ.ГГГГ» -> ISO; пусто -> None; иное — схема."""
    s = (s or "").strip()
    if not s:
        return None
    m = re.fullmatch(r"(\d{4})\.(\d{2})\.(\d{2})", s)
    if m:
        return dt.date(int(m.group(1)), int(m.group(2)), int(m.group(3))).isoformat()
    m = re.fullmatch(r"(\d{2})\.(\d{2})\.(\d{4})", s)
    if m:
        return dt.date(int(m.group(3)), int(m.group(2)), int(m.group(1))).isoformat()
    raise ValueError("схема: дата %r" % s[:20])


def _строки(данные):
    try:
        текст = данные.decode("utf-8-sig")
    except UnicodeDecodeError:
        текст = данные.decode("cp1251")
    if текст.lstrip()[:1] == "<":
        raise ValueError("схема: вместо CSV пришёл HTML (%r…)" % текст[:40])
    return list(csv.reader(io.StringIO(текст), delimiter=";"))


def _инн(s):
    s = (s or "").strip()
    return s if re.fullmatch(r"\d{10}|\d{12}", s) else None


def _по_кодам(строки, нужно):
    """CSV с шапкой из кодов полей (NLIC, INN, …) -> [dict]."""
    шапка = [h.strip() for h in строки[0]] if строки else []
    нет = [к for к in нужно if к not in шапка]
    if нет:
        raise ValueError("схема: в шапке нет %s" % ", ".join(нет))
    return [dict(zip(шапка, с)) for с in строки[1:] if any(x.strip() for x in с)]


def _по_тексту(строки, колонки):
    """CSV с преамбулой и текстовой шапкой -> [dict поле: значение]. Шапка —
    первая строка, где нашлись все колонки (по началу текста, без регистра);
    строки без ИНН и номера — заголовки разделов, нумерация колонок."""
    for i, с in enumerate(строки[:15]):
        норм = [" ".join(x.lower().split()) for x in с]
        кол = {}
        for поле, начало in колонки.items():
            j = next((j for j, т in enumerate(норм) if т.startswith(начало)), None)
            if j is not None:
                кол[поле] = j
        if len(кол) == len(колонки):
            return [{п: (с2[j] if j < len(с2) else "") for п, j in кол.items()}
                    for с2 in строки[i + 1:]]
    raise ValueError("схема: не найдена шапка с колонками %s" % ", ".join(колонки))


def _статус_idel(код, срок, сегодня_iso):
    if код in ("0", "9"):
        return "срок истёк" if срок and срок < сегодня_iso else "действует"
    return IDEL.get(код, "статус неизвестен (код %s)" % (код or "пусто"))


def записи_реестра(реестр, данные, сегодня_iso):
    """CSV реестра -> [(инн, запись)]. ValueError — схема не та."""
    строки = _строки(данные)
    out, без_инн, n = [], 0, 0

    def добавить(инн, з):
        nonlocal без_инн, n
        n += 1
        if not инн:
            без_инн += 1
            return
        out.append((инн, dict({"реестр": реестр}, **{к: v for к, v in з.items() if v})))

    if реестр == "таможенные_представители":
        for с in _по_кодам(строки, ("INN", "РЕГ НОМЕР", "ДАТА ВКЛЮЧЕНИЯ В РЕЕСТР")):
            добавить(_инн(с["INN"]), {"статус": "действует", "номер": с["РЕГ НОМЕР"].strip(),
                                      "включён": _дата(с["ДАТА ВКЛЮЧЕНИЯ В РЕЕСТР"])})
    elif реестр == "таможенные_перевозчики":
        for с in _по_кодам(строки, ("ST", "INN", "NLIC", "PR_PER", "DBEGIN", "DEND", "IDEL")):
            if с["ST"].strip() != "RU":
                continue
            срок = _дата(с["DEND"])
            добавить(_инн(с["INN"]), {
                "статус": _статус_idel(с["IDEL"].strip(), срок, сегодня_iso),
                "номер": (с["NLIC"] + с["PR_PER"]).strip(), "выдано": _дата(с["DBEGIN"]),
                "срок": срок})
    elif реестр == "свх":
        for с in _по_кодам(строки, ("ST", "INN", "NLIC", "DBEGIN", "DEND", "IDEL", "D_ISL")):
            if с["ST"].strip() != "RU":
                continue
            срок = _дата(с["DEND"])
            добавить(_инн(с["INN"]), {
                "статус": _статус_idel(с["IDEL"].strip(), срок, сегодня_iso),
                "номер": с["NLIC"].strip(), "выдано": _дата(с["DBEGIN"]), "срок": срок,
                "статус_изменён": _дата(с["D_ISL"])})
    else:
        колонки = ({"номер": "реквизиты документа", "включён": "дата включения",
                    "инн": "инн"} if реестр == "таможенные_склады" else
                   {"номер": "номер свидетельства", "включён": "дата включения",
                    "инн": "идентификационный номер налогоплательщика"})
        for с in _по_тексту(строки, колонки):
            номер = с["номер"].strip()
            if not _инн(с["инн"]) and not re.search(r"\d{5}/", номер):
                continue          # раздел управления, нумерация колонок; строка с ИНН
                #                   не пропускается никогда
            добавить(_инн(с["инн"]), {"статус": "действует", "номер": номер,
                                      "включён": _дата(с["включён"])})
    if n == 0:
        raise ValueError("схема: в реестре %s нет строк" % реестр)
    if без_инн > n * ДОЛЯ_БЕЗ_ИНН:
        raise ValueError("схема: в реестре %s без ИНН %d строк из %d" % (реестр, без_инн, n))
    return out


# --- индекс -----------------------------------------------------------------

def построить_индекс(файлы, путь, прежние=None, сегодня=None):
    """файлы: {реестр: (bytes, url)} -> индекс на диск. Всё или ничего."""
    сегодня = сегодня or dump_tools.сегодня()
    по_инн, реестры = {}, {}
    for реестр, (данные, url) in файлы.items():
        зап = записи_реестра(реестр, данные, сегодня)
        было = ((прежние or {}).get(реестр) or {}).get("записей") or 0
        if not зап or len(зап) < было * ДОЛЯ_ПАДЕНИЯ:
            raise ValueError("схема: в реестре %s %d записей (было %d)" % (реестр, len(зап), было))
        for инн, з in зап:
            по_инн.setdefault(инн, []).append(з)
        m = re.search(r"data-(\d{4})(\d{2})(\d{2})", url)
        реестры[реестр] = {"название": РЕЕСТРЫ[реестр]["название"], "url": url,
                           "записей": len(зап), "скачан": сегодня,
                           "выгрузка": "%s-%s-%s" % m.groups() if m else None}
    dump_tools.записать_индекс(путь, {"построен": сегодня, "реестры": реестры,
                                      "по_инн": по_инн})
    return реестры


def _получить_набор(реестр, get):
    стр = страница(реестр)
    html = get(стр, САЙТ + "/opendata", ЛИМИТ).decode("utf-8", "replace")
    url, _ = ссылка_на_данные(html, реестр)
    return get(url, стр, ЛИМИТ), url


def refresh(cache_dir=None, get=None, сегодня=None):
    """Скачивает все пять реестров и пересобирает индекс; сбой любого — старый
    индекс цел."""
    cache_dir = cache_dir or CACHE_DIR
    os.makedirs(cache_dir, exist_ok=True)
    путь = os.path.join(cache_dir, ИНДЕКС)
    if get is None:
        try:
            op = dump_tools.opener()
        except ValueError as e:
            return {"статус": "индекс не обновлён: %s" % e}

        def get(url, referer, лимит):
            return dump_tools.get(url, referer, лимит, op=op)
    try:
        блок = dump_tools.Блокировка(cache_dir).__enter__()
    except FileExistsError:
        return {"статус": "индекс не обновлён: другой refresh уже идёт"}
    try:
        файлы, итог = {}, {}
        for реестр in РЕЕСТРЫ:
            try:
                файлы[реестр] = _получить_набор(реестр, get)
                итог[реестр] = "скачан"
            except Exception as e:
                итог[реестр] = "не скачан: %s: %s" % (type(e).__name__, str(e)[:160])
        if len(файлы) != len(РЕЕСТРЫ):
            return {"статус": "индекс не обновлён: скачаны не все реестры", "реестры": итог}
        try:
            прежние = (dump_tools.прочитать_индекс(путь).get("реестры")
                       if os.path.exists(путь) else None)
        except Exception:
            прежние = None
        try:
            реестры = построить_индекс(файлы, путь, прежние, сегодня)
        except Exception as e:
            return {"статус": "индекс не обновлён: %s" % str(e)[:200], "реестры": итог}
        return {"статус": "обновлено", "реестры": реестры}
    finally:
        блок.__exit__(None, None, None)


def устарел(индекс, сегодня):
    скачан = min((р.get("скачан") or "1970-01-01") for р in индекс["реестры"].values())
    if dump_tools.старше(скачан, сегодня, СВЕЖЕСТЬ_ДНЕЙ):
        return ["реестры ФТС скачаны %s, старше %d дней — обновите: fts_registries.py "
                "--refresh (нужен РФ-IP или INN_CHECK_PROXY)" % (скачан, СВЕЖЕСТЬ_ДНЕЙ)]
    return []


def lookup(inn, cache_dir=None, сегодня=None):
    """-> (dict|None, заметка). None — индекса нет."""
    cache_dir = cache_dir or CACHE_DIR
    путь = os.path.join(cache_dir, ИНДЕКС)
    try:
        индекс = dump_tools.прочитать_индекс(путь)
    except FileNotFoundError:
        return None, ("индекса нет (%s) — сначала fts_registries.py --refresh (нужен РФ-IP "
                      "или INN_CHECK_PROXY)"
                      % (CACHE_DIR_ВИДИМЫЙ if cache_dir == CACHE_DIR else путь))
    сегодня = сегодня or dump_tools.сегодня()
    # срок мог истечь после сборки индекса: «действует» пересчитывается на сегодня
    # (ревью Codex)
    записи = [dict(з, статус="срок истёк") if з["статус"] == "действует" and з.get("срок")
              and з["срок"] < сегодня else з for з in индекс["по_инн"].get(str(inn), [])]
    return {
        "в_реестрах": bool(записи),
        "действует_в": sorted({з["реестр"] for з in записи if з["статус"] == "действует"}),
        "записи": записи,
        "охват": "реестры ФТС: таможенные представители, владельцы СВХ, таможенных "
                 "складов и магазинов беспошлинной торговли — только действующие; "
                 "таможенные перевозчики — с истёкшими, аннулированными и отозванными",
        "скачан": {k: р.get("скачан") for k, р in индекс["реестры"].items()},
        "выгрузка": {k: р.get("выгрузка") for k, р in индекс["реестры"].items()},
        "предупреждения": устарел(индекс, сегодня),
        "источник": САЙТ + "/opendata",
    }, "ok"


def main(argv):
    args = argv[1:]
    if args == ["--refresh"]:
        res = refresh()
        print(json.dumps(res, ensure_ascii=False, indent=2))
        return 0 if res["статус"] == "обновлено" else 1
    if len(args) == 2 and args[0] == "--inn":
        res, note = lookup(args[1])
        print(json.dumps(res if res is not None else {"статус": "не проверено",
                                                      "причина": note},
                         ensure_ascii=False, indent=2))
        return 0 if res is not None else 1
    sys.stderr.write(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
