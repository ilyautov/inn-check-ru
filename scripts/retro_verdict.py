#!/usr/bin/env python3
"""
retro_verdict.py — вердикт на дату в прошлом по снимку, сохранённому ТОГДА
(спек v2, задача 6). Офлайн, только стандартная библиотека.

Зачем. Должная осмотрительность доказывается тем, что было видно ДО сделки, а
не сегодняшней карточкой контрагента. «Мы проверяли в марте» стоит ровно
столько, сколько стоит запись, сделанная в марте. Скрипт берёт последний
снимок с датой НЕ ПОЗЖЕ запрошенной и считает по нему светофор профиля.

Чего скрипт не делает НИКОГДА:
  * не берёт снимок новее запрошенной даты — это данные из будущего, и вердикт
    «надо было увидеть» на них был бы подлогом;
  * не добирает недостающее из сети — ретроспектива собирается из прошлого,
    а не досочиняется настоящим;
  * не превращает «источник не сохранён в отпечатке» в «признака не было»:
    такие сигналы остаются «не проверен», и 🟢 на них не выдаётся.

Отпечаток (snapshot.py) хранит не весь слепок: формат 2 добавил блок
«вердикт» — агрегаты deal-killer-источников, без которых светофор не считается.
По отпечаткам формата 1 ретроспектива честно отвечает, каких источников нет.

Использование:
    python3 retro_verdict.py <ИНН> --дата 2026-03-01 [--профиль отсрочка]
    python3 retro_verdict.py <ИНН> --список          # какие снимки есть
    python3 retro_verdict.py --снимок файл.json --дата 2026-03-01
"""

import datetime
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def _модуль(имя):
    spec = importlib.util.spec_from_file_location(имя, os.path.join(HERE, имя + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


snapshot = _модуль("snapshot")
profiles = _модуль("profiles")

# Из чего восстанавливается блок fetch-JSON: {блок: {ключ_fetch: ключ_в_полях}}.
# «поля» отпечатка — плоские, блоки fetch_counterparty.py — вложенные.
ИЗ_ПОЛЕЙ = {
    "егрюл": {"статус": "статус", "руководитель": "руководитель",
              "адрес": "адрес", "дата_прекращения": "дата_прекращения"},
    "риски": {"недостоверность_сведений": "недостоверность_сведений",
              "налоговая_задолженность": "налоговая_задолженность"},
    "мсп": {"статус_мсп": "мсп_статус", "категория": "мсп_категория"},
}

ОГОВОРКА = ("ретроспектива показывает то, что было видно НА ДАТУ СНИМКА из "
            "открытых источников, а не всё, что существовало на эту дату: "
            "источник, молчавший тогда, остаётся «не проверено» навсегда — "
            "задним числом он не переспрашивается")


def _дата(s):
    """«YYYY-MM-DD» (или ISO с временем) -> date; иначе None."""
    if not isinstance(s, str):
        return None
    try:
        return datetime.date.fromisoformat(s.strip()[:10])
    except ValueError:
        return None


def дата_снимка(snap, путь=None):
    """Дата снимка: поле «дата» отпечатка, иначе из имени файла."""
    d = _дата((snap or {}).get("дата")) if isinstance(snap, dict) else None
    if d:
        return d
    if путь:
        return _дата(os.path.basename(путь)[:10])
    return None


def выбрать(снимки, на_дату):
    """(путь, снимок, отвергнутые_из_будущего) — последний снимок НЕ ПОЗЖЕ даты."""
    годные, из_будущего = [], []
    for путь in снимки:
        snap = snapshot.load(путь)
        if not isinstance(snap, dict):
            continue
        d = дата_снимка(snap, путь)
        if d is None:
            continue
        (годные if d <= на_дату else из_будущего).append((d, путь, snap))
    годные.sort(key=lambda x: x[0])
    if not годные:
        return None, None, [(d, p) for d, p, _ in sorted(из_будущего)]
    d, путь, snap = годные[-1]
    return путь, snap, [(x, p) for x, p, _ in sorted(из_будущего)]


def восстановить(snap):
    """Отпечаток -> (fetch-подобный JSON, отчёт о восстановлении).

    Состояние блока ставится «не проверено» не только там, где источник молчал
    в тот день, но и там, где отпечаток не сохранил его значений: иначе блок
    без значений с состоянием «ok» читается как «признаков не найдено».
    """
    поля = snap.get("поля") if isinstance(snap.get("поля"), dict) else {}
    вердикт = snap.get("вердикт") if isinstance(snap.get("вердикт"), dict) else {}
    состояния = snap.get("состояния") if isinstance(snap.get("состояния"), dict) else {}
    версия = snap.get("версия_формата")
    дата = (snap.get("дата") or "")[:10]

    fetch = {"инн": snap.get("инн"), "тип": "ип" if len(str(snap.get("инн") or "")) == 12
             else "юрлицо"}
    for блок, карта in ИЗ_ПОЛЕЙ.items():
        значения = {ключ: поля.get(источник) for ключ, источник in карта.items()
                    if поля.get(источник) is not None}
        if значения:
            fetch[блок] = значения
    for блок, значения in вердикт.items():
        if isinstance(значения, dict) and значения:
            fetch.setdefault(блок, {}).update(значения)

    годы = поля.get("финансы_годы")
    if isinstance(годы, list) and годы:
        fetch["финансы"] = {"отчётность_по_годам": годы}

    без_значений, молчали = [], []
    доступность = {}
    for блок, состояние in состояния.items():
        есть_значения = bool(fetch.get(блок))
        if состояние == "не проверено":
            молчали.append(блок)
            доступность[блок] = {
                "состояние": "не проверено", "дата": дата,
                "причина": "снимок: источник не ответил в день проверки"}
        elif состояние == "пусто" and not есть_значения:
            # «пусто» в день сбора — подтверждённое отсутствие (в ЕФРСБ нет дела),
            # значений у него нет по природе; «не проверено» здесь было бы потерей.
            доступность[блок] = {"состояние": "пусто", "дата": дата, "причина": None}
        elif not есть_значения:
            без_значений.append(блок)
            доступность[блок] = {
                "состояние": "не проверено", "дата": дата,
                "причина": "отпечаток: значения источника не сохранены "
                           "(формат %s) — сегодня их уже не восстановить"
                           % (версия if версия is not None else "?")}
        else:
            доступность[блок] = {"состояние": состояние, "дата": дата,
                                 "причина": None}
    fetch["_доступность"] = доступность
    # `_итог_проверки` из снимка НЕ переносится: он считался по тому, что
    # собралось тогда, а восстановить удалось меньше. Пусть резолвер считает
    # итог по восстановленным состояниям — иначе «проверка состоялась» будет
    # про день сбора, а светофор — про урезанные данные.
    отчёт = {
        "из": "отпечаток" if версия is not None else "полный снимок",
        "версия_формата": версия,
        "источники_без_значений": sorted(без_значений),
        "источники_молчали_тогда": sorted(молчали),
    }
    return fetch, отчёт


def retro(inn, на_дату, профиль=None, каталог=None, снимок_путь=None):
    """Вердикт на дату. Никогда не падает traceback'ом: отказ — это JSON."""
    д = _дата(на_дату)
    if д is None:
        return {"статус": "не проверено", "инн": inn,
                "причина": "дата не разобрана: ожидается ГГГГ-ММ-ДД, получено %r"
                           % на_дату}
    if снимок_путь:
        снимки = [снимок_путь]
    else:
        снимки = snapshot.list_snapshots(inn, каталог)
    if not снимки:
        return {"статус": "не проверено", "инн": inn, "на_дату": str(д),
                "причина": "снимков по этому ИНН нет: ретроспектива собирается "
                           "из сохранённых проверок, а не из сегодняшних данных. "
                           "Снимки пишут watchlist.py --прогон и batch_check.py "
                           "--снимки",
                "оговорка": ОГОВОРКА}
    путь, snap, из_будущего = выбрать(снимки, д)
    if snap is None:
        ближайший = str(из_будущего[0][0]) if из_будущего else None
        return {
            "статус": "не проверено", "инн": inn, "на_дату": str(д),
            "причина": "на %s снимков нет: самый ранний — %s. Снимок новее "
                       "запрошенной даты не берётся: это данные из будущего, и "
                       "вердикт «надо было увидеть» на них был бы подлогом"
                       % (д, ближайший or "нет"),
            "снимков_новее": len(из_будущего),
            "оговорка": ОГОВОРКА}

    д_снимка = дата_снимка(snap, путь)
    полный = not snapshot._diff.это_отпечаток(snap)
    if полный:
        fetch, отчёт = snap, {"из": "полный снимок", "версия_формата": None,
                              "источники_без_значений": [],
                              "источники_молчали_тогда": []}
    else:
        fetch, отчёт = восстановить(snap)

    профиль = профиль or ((snap.get("сбор") or {}).get("профиль")
                          if isinstance(snap.get("сбор"), dict) else None)
    вердикт = profiles.resolve(fetch, None, профиль)

    сбор = snap.get("сбор") if isinstance(snap.get("сбор"), dict) else {}
    предупреждения = []
    отставание = (д - д_снимка).days if д_снимка else None
    if отставание:
        предупреждения.append(
            "снимок старше запрошенной даты на %d дн.: показано состояние на %s, "
            "а не на %s — что изменилось между этими датами, снимок не знает"
            % (отставание, д_снимка, д))
    if сбор.get("режим") == "quick" or сбор.get("неполный"):
        предупреждения.append(
            "снимок собран режимом «%s» (неполный): часть источников тогда не "
            "запрашивалась вовсе" % (сбор.get("режим") or "quick"))
    if сбор.get("профиль") and профиль and сбор["профиль"] != профиль:
        предупреждения.append(
            "снимок собран под профиль «%s», а вердикт считается под «%s»: "
            "источники, ненужные тому профилю, тогда не собирались"
            % (сбор["профиль"], профиль))
    if вердикт.get("светофор") is None and вердикт.get("формулировка") != "факты":
        предупреждения.append(
            "светофор на эту дату не выдаётся: часть deal-killer-источников не "
            "восстановлена. «Добрать по каскаду» здесь невозможно — прошлое не "
            "переспрашивается; чтобы ретроспектива считалась, снимки должны "
            "собираться полным режимом заранее")
    if отчёт["источники_без_значений"]:
        предупреждения.append(
            "отпечаток не сохранил значений источников: %s — их сигналы "
            "остались «не проверен», 🟢 по ним не выдаётся"
            % ", ".join(отчёт["источники_без_значений"]))

    return {
        "статус": "ок",
        "инн": inn,
        "на_дату": str(д),
        "снимок": {"дата": str(д_снимка) if д_снимка else None,
                   "путь": путь,
                   "вид": "полный слепок" if полный else "отпечаток формата %s"
                          % отчёт["версия_формата"],
                   "отставание_дней": отставание,
                   "сбор": сбор or None},
        "профиль": профиль,
        "вердикт": вердикт,
        "восстановление": отчёт,
        "предупреждения": предупреждения,
        "оговорка": ОГОВОРКА,
    }


def список(inn, каталог=None):
    out = []
    for путь in snapshot.list_snapshots(inn, каталог):
        snap = snapshot.load(путь)
        if not isinstance(snap, dict):
            out.append({"путь": путь, "вид": "не читается"})
            continue
        отпечаток = snapshot._diff.это_отпечаток(snap)
        d = дата_снимка(snap, путь)
        out.append({"дата": str(d) if d else None, "путь": путь,
                    "вид": ("отпечаток формата %s" % snap.get("версия_формата"))
                           if отпечаток else "полный слепок",
                    "вердикт_восстановим": bool(snap.get("вердикт")) or not отпечаток,
                    "сбор": snap.get("сбор")})
    return {"статус": "ок", "инн": inn, "снимков": len(out), "снимки": out}


USAGE = ("Использование: python3 retro_verdict.py <ИНН> --дата ГГГГ-ММ-ДД "
         "[--профиль <id>] [--каталог <dir>]\n"
         "               python3 retro_verdict.py <ИНН> --список [--каталог <dir>]\n"
         "               python3 retro_verdict.py --снимок <файл.json> "
         "--дата ГГГГ-ММ-ДД [--профиль <id>]\n")


def main(argv):
    args = argv[1:]

    def опция(имя):
        if имя in args:
            i = args.index(имя)
            return args[i + 1] if i + 1 < len(args) else None
        return None

    дата = опция("--дата")
    профиль = опция("--профиль")
    каталог = опция("--каталог")
    снимок_путь = опция("--снимок")
    позиционные = []
    пропустить = False
    for a in args:
        if пропустить:
            пропустить = False
            continue
        if a in ("--дата", "--профиль", "--каталог", "--снимок"):
            пропустить = True
            continue
        if a == "--список":
            continue
        позиционные.append(a)

    inn = позиционные[0] if позиционные else None
    if "--список" in args:
        if not inn:
            sys.stderr.write(USAGE)
            return 2
        sys.stdout.write(json.dumps(список(inn, каталог), ensure_ascii=False,
                                    indent=2) + "\n")
        return 0
    if not дата or (not inn and not снимок_путь):
        sys.stderr.write(USAGE)
        return 2
    if снимок_путь and not inn:
        snap = snapshot.load(снимок_путь)
        inn = (snap or {}).get("инн")
    out = retro(inn, дата, профиль=профиль, каталог=каталог,
                снимок_путь=снимок_путь)
    sys.stdout.write(json.dumps(out, ensure_ascii=False, indent=2) + "\n")
    # «не проверено» — это ответ, а не сбой: exit 0, как и у остальных
    # скриптов движка, иначе оркестратор примет честный отказ за поломку.
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
