def poles_eq(a, b, eps=1e-6):
    return a is not None and abs(a - b) < eps


def case_показатели_и_их_n(bm):
    """Главное против тихой деградации: у каждого показателя своё число
    наблюдений, и ниже порога вместо медианы стоит None, а не «похожее число».

    Закрывает мутации: медиана ССЧ по одному элементу; медиана нагрузки по
    одному элементу; пустая куча даёт 0.0 вместо None (нагрузка и НДС);
    ССЧ = 0 и деление через `or 1`."""
    errors = []
    # 20 компаний с доходом; налоги, ССЧ и НДС известны ровно у ОДНОЙ.
    записи = []
    for i in range(20):
        зап = {"оквэд2": "47", "регион": "50", "доход": (i + 1) * 1_000_000.0}
        if i == 0:
            зап.update({"налоги": 500_000.0, "ндс": 200_000.0,
                        "ндс_обязан": True, "ссч": 1, "усн": True})
        записи.append(зап)
    группы, _, _ = bm.агрегировать(записи, ПОРОГИ, порог_n=20, порог_показателя=20)
    поля = dict(zip(bm.ПОЛЯ, группы["47|50|микро"]))
    check(errors, поля["n"] == 20, "n по доходу = %s" % поля["n"])
    for показатель, счётчик in bm.ПОКАЗАТЕЛИ:
        check(errors, поля[показатель] is None,
              "%s посчитан по ОДНОМУ наблюдению и опубликован как норма: %s"
              % (показатель, поля[показатель]))
        check(errors, поля[счётчик] == 1,
              "%s = %s, ждём 1: счётчик наблюдений обязан говорить правду"
              % (счётчик, поля[счётчик]))
    # Пустая куча: ни одного наблюдения -> None и 0, а НЕ 0.0
    пусто = [{"оквэд2": "62", "регион": "77", "доход": (i + 1) * 1_000_000.0}
             for i in range(20)]
    группы2, _, _ = bm.агрегировать(пусто, ПОРОГИ, порог_n=20, порог_показателя=20)
    поля2 = dict(zip(bm.ПОЛЯ, группы2["62|77|микро"]))
    for показатель, счётчик in bm.ПОКАЗАТЕЛИ:
        check(errors, поля2[показатель] is None,
              "%s без единого наблюдения = %r; 0.0 — это утверждение «норма "
              "равна нулю», которого в данных не было"
              % (показатель, поля2[показатель]))
        check(errors, поля2[счётчик] == 0,
              "%s без наблюдений = %s, ждём 0" % (счётчик, поля2[счётчик]))
    # ССЧ = 0: в медиану ССЧ входит, в «доход на сотрудника» — нет (делить на
    # ноль нечего, и подменять ноль единицей нельзя).
    нулевые = [{"оквэд2": "10", "регион": "77", "доход": 5_000_000.0, "ссч": 0}
               for _ in range(20)]
    группы3, _, _ = bm.агрегировать(нулевые, ПОРОГИ, порог_n=20, порог_показателя=20)
    поля3 = dict(zip(bm.ПОЛЯ, группы3["10|77|микро"]))
    check(errors, поля3["ссч"] == 0, "медиана ССЧ при нулевом штате: %s" % поля3["ссч"])
    check(errors, поля3["n_ссч"] == 20, "n_ссч = %s" % поля3["n_ссч"])
    check(errors, поля3["n_выручка_на_сотрудника"] == 0
          and поля3["выручка_на_сотрудника"] is None,
          "ССЧ = 0 просочилась в «доход на сотрудника» (деление через `or 1`): "
          "%s по %s наблюдениям"
          % (поля3["выручка_на_сотрудника"], поля3["n_выручка_на_сотрудника"]))
    # Ровно на пороге показатель публикуется, на единицу ниже — нет
    for сколько, ждём_none in ((20, False), (19, True)):
        ряд = []
        for i in range(20):
            зап = {"оквэд2": "01", "регион": "50", "доход": 1_000_000.0}
            if i < сколько:
                зап["ссч"] = 7
            ряд.append(зап)
        гр, _, _ = bm.агрегировать(ряд, ПОРОГИ, порог_n=20, порог_показателя=20)
        п = dict(zip(bm.ПОЛЯ, гр["01|50|микро"]))
        check(errors, (п["ссч"] is None) == ждём_none,
              "при %d наблюдениях ССЧ = %r (порог показателя 20)"
              % (сколько, п["ссч"]))
    return errors


def case_доля_усн_знаменатель(bm):
    """Отсутствие ИНН в дампе snr — это «спецрежима нет», а не «неизвестно».

    Самый дорогой дефект ревью: в группе 46|23|среднее при n = 244 запись в snr
    была одна, и публиковалась доля_усн = 1.0 вместо честных 0,004."""
    errors = []
    # 244 компании, спецрежим известен у одной (она на УСН)
    записи = []
    for i in range(244):
        записи.append({"оквэд2": "46", "регион": "23", "доход": 1_000_000.0,
                       "усн": i == 0})
    группы, _, _ = bm.агрегировать(записи, ПОРОГИ, порог_n=20, порог_показателя=20)
    поля = dict(zip(bm.ПОЛЯ, группы["46|23|микро"]))
    check(errors, поля["n_доля_усн"] == 244,
          "в знаменатель доли вошло %s из 244 компаний: подтверждённое «режима "
          "нет» выпало из знаменателя" % поля["n_доля_усн"])
    check(errors, poles_eq(поля["доля_усн"], 1 / 244, 1e-4),
          "доля_усн = %s, честное значение 0,004" % поля["доля_усн"])
    # None остаётся «неизвестно» и из знаменателя выпадает — иначе дамп snr,
    # который не сджойнился вовсе, превратился бы в «все на ОСНО».
    неизвестно = [{"оквэд2": "46", "регион": "23", "доход": 1_000_000.0,
                   "усн": None} for _ in range(244)]
    группы2, _, _ = bm.агрегировать(неизвестно, ПОРОГИ, порог_n=20,
                                    порог_показателя=20)
    поля2 = dict(zip(bm.ПОЛЯ, группы2["46|23|микро"]))
    check(errors, поля2["n_доля_усн"] == 0 and поля2["доля_усн"] is None,
          "«спецрежим неизвестен» обязан давать None, а не 0.0: %s по %s"
          % (поля2["доля_усн"], поля2["n_доля_усн"]))

    # То же самое, но сквозь реальный джойн: у части компаний записи в snr нет
    пути = _все_дампы()
    if any(v is None for v in пути.values()):
        return errors + ["нет фикстур дампов в %s" % FIXTURES]
    with tempfile.TemporaryDirectory() as tmp:
        урезанный = _обрезать_snr(пути["snr"], os.path.join(tmp, "snr.zip"), 5)
        поток, _, покрытие, _ = bm.собрать_записи(dict(пути, snr=урезанный),
                                                  тихо=True)
        записи = list(поток)
        известно = [з for з in записи if з["усн"] is not None]
        check(errors, len(известно) == len(записи) and записи,
              "после джойна у %d из %d компаний спецрежим «неизвестен», хотя "
              "дамп snr прочитан: отсутствие в нём — это ОСНО"
              % (len(записи) - len(известно), len(записи)))
        на_усн = sum(1 for з in записи if з["усн"])
        check(errors, 0 < на_усн < len(записи),
              "при 5 записях в snr на УСН оказалось %d из %d — знаменатель "
              "опять собран не по всей группе" % (на_усн, len(записи)))
        check(errors, покрытие["из_них_без_записи_в_snr_считаются_осно"] > 0
              and покрытие["спецрежим_определён"] is True,
              "покрытие не сообщает, сколько компаний отнесено к ОСНО: %s"
              % покрытие)
    # Дамп snr не сджойнился вовсе -> «неизвестно» у всех, а не «все на ОСНО»
    with tempfile.TemporaryDirectory() as tmp:
        пустой = os.path.join(tmp, "snr.zip")
        _обрезать_snr(пути["snr"], пустой, 0)
        поток, _, покрытие, _ = bm.собрать_записи(dict(пути, snr=пустой), тихо=True)
        записи = list(поток)
        check(errors, записи and all(з["усн"] is None for з in записи),
              "пустой дамп snr превратился в «все на ОСНО» — это выдуманная "
              "норма вместо отсутствия данных")
        check(errors, покрытие["спецрежим_определён"] is False,
              "покрытие не признаёт, что спецрежим не определён: %s" % покрытие)
    return errors


def case_ндс_только_плательщики(bm):
    """Норма НДС считается по тем, кто НДС должен, а не по всем подряд.

    3012 групп из 5244 публиковали `ндс_к_выручке = 0.0`, потому что в кучу
    попадали спецрежимники, у которых НДС ноль по закону."""
    errors = []
    записи = []
    # 30 спецрежимников с нулевым НДС (обязанности нет) и 20 плательщиков с 3%
    for i in range(30):
        записи.append({"оквэд2": "47", "регион": "50", "доход": 10_000_000.0,
                       "налоги": 600_000.0, "ндс": 0.0, "ндс_обязан": False,
                       "усн": True})
    for i in range(20):
        записи.append({"оквэд2": "47", "регион": "50", "доход": 10_000_000.0,
                       "налоги": 900_000.0, "ндс": 300_000.0, "ндс_обязан": True,
                       "усн": False})
    группы, _, _ = bm.агрегировать(записи, ПОРОГИ, порог_n=20, порог_показателя=20)
    поля = dict(zip(bm.ПОЛЯ, группы["47|50|микро"]))
    check(errors, поля["n_ндс_к_выручке"] == 20,
          "в норму НДС попало %s компаний из 20 плательщиков: отсутствие "
          "обязанности засчитано за наблюдение «заплатил ноль»"
          % поля["n_ндс_к_выручке"])
    check(errors, poles_eq(поля["ндс_к_выручке"], 0.03),
          "ндс_к_выручке = %s, ждём 0.03 по плательщикам (по всем вышло бы 0.0)"
          % поля["ндс_к_выручке"])
    check(errors, поля["n_нагрузка"] == 50,
          "нагрузка считается по всем, у кого есть paytax: %s" % поля["n_нагрузка"])
    # Население не объявлено -> нормы НДС нет вовсе, а не «по всем подряд»
    без_населения = [{"оквэд2": "62", "регион": "77", "доход": 10_000_000.0,
                      "ндс": 0.0} for _ in range(30)]
    группы2, _, _ = bm.агрегировать(без_населения, ПОРОГИ, порог_n=20,
                                    порог_показателя=20)
    поля2 = dict(zip(bm.ПОЛЯ, группы2["62|77|микро"]))
    check(errors, поля2["ндс_к_выручке"] is None and поля2["n_ндс_к_выручке"] == 0,
          "без явного «ндс_обязан» норма НДС обязана отсутствовать, а не "
          "равняться %s" % поля2["ндс_к_выручке"])
    # И то же сквозь реальный джойн фикстур: там 40 компаний, все на
    # спецрежиме, НДС фактически заплатили девять — норма строится по ним.
    пути = _все_дампы()
    if not any(v is None for v in пути.values()):
        поток, _, _, _ = bm.собрать_записи(пути, тихо=True)
        записи = list(поток)
        обязаны = [з for з in записи if з["ндс_обязан"]]
        нулевые_обязаны = [з for з in обязаны if (з["ндс"] or 0) == 0]
        check(errors, обязаны and len(обязаны) < len(записи),
              "в фикстурах все 40 компаний на спецрежиме; плательщиками НДС "
              "признаны %d из %d" % (len(обязаны), len(записи)))
        check(errors, not нулевые_обязаны,
              "спецрежимник с нулевым НДС признан обязанным: %d штук"
              % len(нулевые_обязаны))
    return errors


def case_порог(bm):
    """n < 20 — группа не публикуется и схлопывается на (ОКВЭД2, размер)."""
    errors = []
    записи = []
    # два региона по 12 компаний: порознь ниже порога, вместе — 24
    for регион in ("50", "77"):
        for i in range(12):
            записи.append({"оквэд2": "62", "регион": регион,
                           "доход": (i + 1) * 1_000_000.0})
    группы, без_региона, стат = bm.агрегировать(записи, ПОРОГИ, порог_n=20)
    check(errors, группы == {}, "группа с n = 12 попала в таблицу: %s" % list(группы))
    check(errors, "62|микро" in без_региона,
          "схлопнутая группа не построена: %s" % list(без_региона))
    check(errors, dict(zip(bm.ПОЛЯ, без_региона["62|микро"]))["n"] == 24,
          "в схлопнутой группе не все компании")
    check(errors, стат["групп_отсеяно_порогом"] == 2,
          "отсеяно порогом: %s" % стат["групп_отсеяно_порогом"])
    # и региона, и отрасли мало -> нет группы совсем
    мало = [{"оквэд2": "01", "регион": "50", "доход": 1_000_000.0}
            for _ in range(5)]
    группы2, без_региона2, _ = bm.агрегировать(мало, ПОРОГИ, порог_n=20)
    check(errors, группы2 == {} and без_региона2 == {},
          "группа с n = 5 не должна публиковаться ни на одном уровне")
    return errors


