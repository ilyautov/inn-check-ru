def case_резолв_ссылки(od):
    """Резолв идёт по РАЗМЕТКЕ страницы, а не по зашитому URL: берётся самая
    свежая выгрузка, описание формата за данные не принимается, а изменившаяся
    разметка даёт честный отказ."""
    errors = []
    html = (FIXTURES / "страница_rsmp.html").read_text(encoding="utf-8")
    url, имя, выгрузка, структура = od.выбрать_ссылку(html, "rsmp")
    check(errors, имя == "data-10092026-structure-12052026.zip",
          "взята не самая свежая выгрузка: %s" % имя)
    check(errors, выгрузка == "2026-09-10" and структура == "2026-05-12",
          "дата/версия из имени: %s / %s" % (выгрузка, структура))
    check(errors, url == ("https://file.nalog.ru/opendata/7707329152-rsmp/"
                          "data-10092026-structure-12052026.zip"),
          "url собран неверно: %s" % url)
    check(errors, "VO_RRMSPSV" not in (url or ""),
          "описание формата принято за данные: %s" % url)
    # МУТАЦИЯ «зашитый URL»: другой датасет обязан дать ДРУГОЙ адрес
    html2 = (FIXTURES / "страница_revexp.html").read_text(encoding="utf-8")
    url2, имя2, _, _ = od.выбрать_ссылку(html2, "revexp")
    check(errors, url2 and "7707329152-revexp" in url2 and url2 != url,
          "резолв revexp дал %r — адрес не зависит от датасета" % url2)
    check(errors, имя2 == "data-20260825-structure-20180110.zip",
          "имя дампа revexp: %s" % имя2)
    # ссылка на чужой датасет на странице rsmp не должна утаскиваться
    check(errors, "7707329152-revexp" not in (url or ""),
          "с страницы rsmp взята ссылка соседнего датасета: %s" % url)
    # разметка изменилась -> отказ с причиной, а не первая попавшаяся ссылка
    html3 = (FIXTURES / "страница_без_данных.html").read_text(encoding="utf-8")
    url3, причина, в3, с3 = od.выбрать_ссылку(html3, "rsmp")
    check(errors, url3 is None and "разметка изменилась" in (причина or "")
          and в3 is None and с3 is None,
          "страница без дампов должна давать отказ: %s / %s" % (url3, причина))
    return errors


def case_целостность_архива(od):
    """`проверить_zip` обязана ловить пустой, обрезанный и битый архив —
    иначе «ок» в статусе ничего не значит."""
    errors = []
    исходный = _дамп("revexp")
    if исходный is None:
        return ["нет фикстуры revexp"]
    ок, режим, файлов, причина = od.проверить_zip(исходный)
    check(errors, ок and файлов >= 1 and причина is None,
          "целая фикстура не прошла проверку: %s / %s" % (режим, причина))
    check(errors, "из %d" % файлов in режим or "testzip" in режим,
          "режим проверки не говорит, сколько записей прочитано: %r" % режим)
    ок_п, режим_п, файлов_п, _ = od.проверить_zip(исходный, полная=True)
    check(errors, ок_п and "testzip" in режим_п,
          "полная проверка целой фикстуры: %s / %s" % (ок_п, режим_п))
    with tempfile.TemporaryDirectory() as tmp:
        # обрезанный файл
        обрезанный = os.path.join(tmp, "обрезанный.zip")
        сырое = Path(исходный).read_bytes()
        Path(обрезанный).write_bytes(сырое[:len(сырое) // 2])
        ок2, _, _, причина2 = od.проверить_zip(обрезанный)
        check(errors, not ок2 and причина2,
              "обрезанный архив прошёл проверку как «ок»")
        # битая запись: портим сжатые данные, не трогая размер
        битый = os.path.join(tmp, "битый.zip")
        порченое = bytearray(сырое)
        порченое[200:2200] = b"\x00" * 2000
        Path(битый).write_bytes(bytes(порченое))
        ок3, _, _, причина3 = od.проверить_zip(битый, полная=True)
        check(errors, not ок3 and причина3,
              "полная проверка не заметила порчу содержимого")
        # пустой архив
        пустой = os.path.join(tmp, "пустой.zip")
        with zipfile.ZipFile(пустой, "w"):
            pass
        ок4, _, _, причина4 = od.проверить_zip(пустой)
        check(errors, not ок4 and "пуст" in (причина4 or ""),
              "пустой архив: %s / %s" % (ок4, причина4))
        # не архив вовсе
        не_zip = os.path.join(tmp, "не-архив.zip")
        Path(не_zip).write_bytes("это не zip".encode())
        ок5, _, _, причина5 = od.проверить_zip(не_zip)
        check(errors, not ок5 and причина5, "мусор принят за архив")
    return errors


def case_мета_и_sha256(od):
    """meta.json пишется и — главное — РЕАЛЬНО СВЕРЯЕТСЯ.

    Ревью подтвердило: 4 КБ нулей в середине копии дампа без изменения размера
    проходили как «ок», потому что хеш никто не читал. Закрывает заодно
    мутацию «_sha256 — константа»."""
    errors = []
    исходный = _дамп("revexp")
    if исходный is None:
        return ["нет фикстуры revexp"]
    with tempfile.TemporaryDirectory() as tmp:
        путь = os.path.join(tmp, "data-20260825-structure-20180110.zip")
        shutil.copyfile(исходный, путь)
        # _sha256 не константа: разные файлы — разные хеши, и совпадает с hashlib
        другой = os.path.join(tmp, "другой.bin")
        Path(другой).write_bytes("другое содержимое".encode())
        import hashlib
        check(errors, od._sha256(другой)
              == hashlib.sha256("другое содержимое".encode()).hexdigest(),
              "_sha256 не считает sha256")
        check(errors, od._sha256(путь) != od._sha256(другой),
              "_sha256 возвращает одно и то же на разных файлах — это константа")
        # мета пишется и читается
        ок_zip, режим, файлов, _ = od.проверить_zip(путь)
        мета = od._записать_мету(путь, "https://file.nalog.ru/x/y.zip",
                                 os.path.basename(путь), "2026-08-25",
                                 "2018-01-10", режим, файлов)
        назад = od.читать_мету(путь)
        check(errors, назад == мета, "meta.json не читается назад: %s" % назад)
        for ключ in ("url", "имя", "дата_выгрузки", "версия_структуры", "размер",
                     "sha256", "проверка", "файлов_в_архиве"):
            check(errors, назад.get(ключ), "в meta.json нет ключа %r" % ключ)
        ок, причина = od.проверить_хеш(путь)
        check(errors, ок is True and причина is None,
              "целый файл не сошёлся со своей же метой: %s" % причина)
        # ПОРЧА СЕРЕДИНЫ БЕЗ ИЗМЕНЕНИЯ РАЗМЕРА — ровно тот случай, который
        # выборочная проверка ZIP пропускает, а хеш обязан поймать
        сырое = bytearray(Path(путь).read_bytes())
        середина = len(сырое) // 2
        сырое[середина:середина + 64] = b"\x00" * 64
        Path(путь).write_bytes(bytes(сырое))
        ок2, причина2 = od.проверить_хеш(путь)
        check(errors, ок2 is False and "sha256" in (причина2 or ""),
              "порча середины при том же размере прошла сверку хеша: %s / %s"
              % (ок2, причина2))
        check(errors, os.path.getsize(путь) == мета["размер"],
              "тест сам изменил размер — проверялся бы не хеш, а длина")
        # размер изменился -> тоже отказ, и причина про размер
        Path(путь).write_bytes(bytes(сырое) + b"tail-bytes")
        ок3, причина3 = od.проверить_хеш(путь)
        check(errors, ок3 is False and "размер" in (причина3 or ""),
              "изменение размера не поймано: %s / %s" % (ок3, причина3))
        # меты нет -> честное «сверять не с чем», а не True
        os.remove(od._мета_путь(путь))
        ок4, причина4 = od.проверить_хеш(путь)
        check(errors, ок4 is None and причина4,
              "без меты проверка хеша обязана дать None: %s / %s" % (ок4, причина4))
    return errors


def _прогнать(имя, функция, модуль):
    """Исключение внутри кейса — это FAIL этого кейса, а не падение прогона.

    Иначе мутация, которая роняет код (например, форматирование фразы при
    отсутствующем перцентиле), обрывает eval до первой строки PASS/FAIL — и со
    стороны выглядит так, будто ни один кейс не сработал."""
    try:
        return функция(модуль)
    except Exception as e:
        import traceback
        return ["кейс упал исключением %s: %s\n%s"
                % (type(e).__name__, e, traceback.format_exc(limit=4))]


