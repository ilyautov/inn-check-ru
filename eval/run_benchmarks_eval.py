def _обрезать_snr(исходный, куда, оставить):
    """Копия дампа snr, где записи есть только у первых `оставить` компаний.

    Нужна, чтобы проверить главное: ИНН, которого в snr НЕТ, — это
    подтверждённое «спецрежима нет», и он обязан стоять в знаменателе доли."""
    with zipfile.ZipFile(исходный) as z:
        имя = z.namelist()[0]
        текст = z.read(имя).decode("utf-8")
    куски = текст.split("<Документ ")
    новый = куски[0] + "".join("<Документ " + к for к in куски[1:оставить + 1])
    if not новый.rstrip().endswith("</Файл>"):
        новый = новый.split("</Документ>")
        новый = "</Документ>".join(новый[:-1]) + "</Документ></Файл>"
    with zipfile.ZipFile(куда, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(имя, новый)
    return куда


