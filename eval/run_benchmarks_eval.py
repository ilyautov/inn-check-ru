def case_сборка_из_фикстур(bm):
    """Сквозная сборка по вырезкам реальных дампов: джойн пяти источников,
    дата дампов и версия структуры попали в таблицу."""
    errors = []
    пути = {ид: _дамп(ид) for ид in ("revexp", "paytax", "sshr2019", "snr", "rsmp")}
    if any(v is None for v in пути.values()):
        return ["нет фикстур дампов в %s" % FIXTURES]
    таблица, причина = bm.построить(пути, порог_n=2, тихо=True)
    if таблица is None:
        return ["сборка не состоялась: %s" % причина]
    check(errors, таблица["порог_n"] == 2, "порог_n не записан")
    check(errors, таблица["дата_дампов"].get("revexp") == "2026-08-25",
          "дата дампов: %s" % таблица["дата_дампов"])
    check(errors, таблица["версия_структуры"].get("revexp") == "2018-01-10",
          "версия структуры: %s" % таблица["версия_структуры"])
    check(errors, таблица["групп"] == len(таблица["группы"])
          + len(таблица["группы_без_региона"]),
          "счётчик групп не сходится")
    check(errors, таблица["покрытие"]["юрлиц_в_реестре_мсп"] > 0,
          "карта ОКВЭД пуста")
    check(errors, таблица["покрытие"]["из_них_с_доходом_revexp"] > 0,
          "джойн revexp не сработал: %s" % таблица["покрытие"])
    check(errors, таблица["покрытие"]["из_них_с_налогами_paytax"] > 0,
          "джойн paytax не сработал")
    check(errors, таблица["покрытие"]["из_них_со_спецрежимом_snr"] > 0,
          "джойн snr не сработал")
    check(errors, таблица["размерные_группы"]["границы_дохода_руб"]["микро"]
          == 120000000, "границы размерных групп не из канона")
    check(errors, таблица["размерные_группы"]["источник"]["микро"]["источник_url"],
          "у границ размерных групп нет источника")
    check(errors, любая_группа_валидна(таблица, bm),
          "в собранной таблице нет ни одной валидной группы")
    return errors


def любая_группа_валидна(таблица, bm):
    поля = таблица.get("поля") or bm.ПОЛЯ
    for значения in list(таблица["группы_без_региона"].values()):
        зап = dict(zip(поля, значения))
        if зап["n"] >= 2 and зап["p50"] and зап["p25"] <= зап["p50"] <= зап["p75"]:
            return True
    return False


