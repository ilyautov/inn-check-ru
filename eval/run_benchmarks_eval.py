#!/usr/bin/env python3
"""
run_benchmarks_eval.py — офлайн-eval потока «отраслевые нормы» (волна 3, §1):
разбор реальных вырезок дампов ФНС (пять форматов), сборка таблицы норм из
фикстур, агрегация на синтетике с заранее известным ответом, порог публикации
n < 20 со схлопыванием региона, lookup по существующей и отсутствующей группе
и честное «не проверено», когда нормы не построены.

Сети нет: фикстуры eval/fixtures/opendata/ — маленькие вырезки реальных дампов
(открытые данные, обезличивать нечего). PASS/FAIL, чистый stdlib, гоняется в CI.
"""

import importlib.util
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "eval" / "fixtures" / "opendata"


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


# ---------------------------------------------------------------- фикстуры

def _дамп(ид):
    каталог = FIXTURES / ид
    файлы = sorted(каталог.glob("data-*-structure-*.zip"))
    return str(файлы[0]) if файлы else None


ПОРОГИ = {"микро": 120000000.0, "малое": 800000000.0, "среднее": 2000000000.0}


# ---------------------------------------------------------------- кейсы

def case_имена_дампов(od):
    """Дата выгрузки в имени файла живёт в двух форматах — оба обязаны читаться."""
    errors = []
    check(errors, od.разобрать_дату("20260825") == "2026-08-25",
          "YYYYMMDD не разобран: %s" % od.разобрать_дату("20260825"))
    check(errors, od.разобрать_дату("10092026") == "2026-09-10",
          "DDMMYYYY не разобран: %s" % od.разобрать_дату("10092026"))
    check(errors, od.разобрать_дату("99999999") is None,
          "мусор принят за дату")
    выгрузка, структура = od.разобрать_имя("data-20260825-structure-20180110.zip")
    check(errors, (выгрузка, структура) == ("2026-08-25", "2018-01-10"),
          "имя дампа разобрано неверно: %s / %s" % (выгрузка, структура))
    check(errors, od.разобрать_имя("structure-20180110.xsd") == (None, None),
          "описание структуры принято за дамп")
    return errors


def case_разбор_форматов(od):
    """Пять реальных форматов: ОТКРДАННЫЕ1/3/4/5 и РЕЕСТРМСП."""
    errors = []
    for ид in ("revexp", "paytax", "sshr2019", "snr", "rsmp"):
        путь = _дамп(ид)
        if путь is None:
            errors.append("нет фикстуры дампа %s в %s" % (ид, FIXTURES / ид))
            continue
        записи = list(od.итерировать(ид, путь))
        check(errors, len(записи) >= 5,
              "%s: разобрано записей %d" % (ид, len(записи)))
        if not записи:
            continue
        for зап in записи:
            check(errors, (зап.get("инн") or "").isdigit(),
                  "%s: ИНН не цифры: %r" % (ид, зап.get("инн")))
        зап = записи[0]
        if ид == "revexp":
            check(errors, isinstance(зап.get("доход"), float),
                  "revexp: доход не число: %r" % зап.get("доход"))
            check(errors, isinstance(зап.get("расход"), float),
                  "revexp: расход не число: %r" % зап.get("расход"))
            check(errors, зап.get("год") == 2025,
                  "revexp: год %r (ждём 2025 из ДатаСост)" % зап.get("год"))
            check(errors, "&quot;" not in (зап.get("наименование") or ""),
                  "revexp: XML-сущности не раскодированы: %r" % зап.get("наименование"))
        elif ид == "paytax":
            check(errors, isinstance(зап.get("налоги"), dict) and зап["налоги"],
                  "paytax: пустой список налогов")
            check(errors, any("Налог" in k or "взнос" in k for k in зап["налоги"]),
                  "paytax: наименования налогов не похожи на реальные: %s"
                  % list(зап["налоги"])[:2])
            check(errors, abs(зап["сумма_налогов"] - sum(зап["налоги"].values())) < 1e-6,
                  "paytax: сумма налогов не сходится")
        elif ид == "sshr2019":
            check(errors, all(з.get("ссч") is None or isinstance(з["ссч"], int)
                              for з in записи), "sshr2019: ССЧ не целое")
        elif ид == "snr":
            check(errors, all(isinstance(з.get("усн"), bool) for з in записи),
                  "snr: признак УСН не bool")
            check(errors, set(зап) >= {"есхн", "усн", "аусн", "срп"},
                  "snr: не все признаки спецрежимов разобраны: %s" % sorted(зап))
        elif ид == "rsmp":
            check(errors, зап.get("тип") == "юрлицо",
                  "rsmp: тип субъекта %r" % зап.get("тип"))
            check(errors, (зап.get("оквэд") or "").replace(".", "").isdigit(),
                  "rsmp: ОКВЭД не разобран: %r" % зап.get("оквэд"))
            check(errors, зап.get("оквэд2") == (зап.get("оквэд") or "").split(".")[0],
                  "rsmp: ОКВЭД2 не первые два знака: %r из %r"
                  % (зап.get("оквэд2"), зап.get("оквэд")))
            check(errors, len(зап.get("регион") or "") == 2,
                  "rsmp: код региона %r" % зап.get("регион"))
            check(errors, зап.get("регион_наименование"),
                  "rsmp: наименование региона пустое")
    return errors


def case_перцентили(bm):
    """Перцентили на синтетике с ответом, посчитанным вручную."""
    errors = []
    # 1..11: p50 = 6, p10 = 2, p90 = 10 (линейная интерполяция по n-1 = 10)
    ряд = list(range(1, 12))
    for q, ждём in ((0, 1), (10, 2), (25, 3.5), (50, 6), (75, 8.5), (90, 10), (100, 11)):
        есть = bm.перцентиль(ряд, q)
        check(errors, abs(есть - ждём) < 1e-9,
              "перцентиль %d: %s, ждём %s" % (q, есть, ждём))
    check(errors, bm.перцентиль([], 50) is None, "пустой ряд должен дать None")
    check(errors, bm.перцентиль([7], 90) == 7.0, "ряд из одного элемента")
    check(errors, bm.медиана([3, 1, 2]) == 2, "медиана не сортирует вход")
    # обратная задача: 6 в ряду p10=2,p25=3.5,p50=6,p75=8.5,p90=10 -> ровно 50
    точки = [(10, 2), (25, 3.5), (50, 6), (75, 8.5), (90, 10)]
    место, оговорка = bm.позиция_перцентиля(6, точки)
    check(errors, место == 50 and оговорка is None,
          "позиция медианы: %s (%s)" % (место, оговорка))
    место, _ = bm.позиция_перцентиля(7.25, точки)
    check(errors, место == 62, "позиция 7,25 между p50 и p75: %s" % место)
    место, оговорка = bm.позиция_перцентиля(0.5, точки)
    check(errors, место == 10 and оговорка and "не выше" in оговорка,
          "значение ниже p10 должно давать граничную оценку: %s / %s"
          % (место, оговорка))
    место, оговорка = bm.позиция_перцентиля(1e9, точки)
    check(errors, место == 90 and оговорка and "не ниже" in оговорка,
          "значение выше p90 должно давать граничную оценку: %s / %s"
          % (место, оговорка))
    return errors


def case_агрегация(bm):
    """Агрегация на синтетике: перцентили, нагрузка, ССЧ, доля УСН — все
    значения известны заранее."""
    errors = []
    # 21 компания в (47, 50, микро): доход 1..21 млн, налоги 5%, ССЧ 10,
    # УСН у первых 14 из 21.
    записи = []
    for i in range(21):
        доход = (i + 1) * 1_000_000.0
        записи.append({"оквэд2": "47", "регион": "50", "доход": доход,
                       "налоги": доход * 0.05, "ндс": доход * 0.02,
                       "ссч": 10, "усн": i < 14})
    группы, без_региона, стат = bm.агрегировать(записи, ПОРОГИ, порог_n=20)
    check(errors, list(группы) == ["47|50|микро"],
          "ключи групп: %s" % list(группы))
    поля = dict(zip(bm.ПОЛЯ, группы["47|50|микро"]))
    check(errors, поля["n"] == 21, "n = %s" % поля["n"])
    check(errors, поля["p50"] == 11_000_000, "p50 = %s" % поля["p50"])
    check(errors, поля["p10"] == 3_000_000, "p10 = %s" % поля["p10"])
    check(errors, поля["p90"] == 19_000_000, "p90 = %s" % поля["p90"])
    check(errors, poles_eq(поля["нагрузка"], 0.05), "нагрузка = %s" % поля["нагрузка"])
    check(errors, poles_eq(поля["ндс_к_выручке"], 0.02),
          "ндс_к_выручке = %s" % поля["ндс_к_выручке"])
    check(errors, поля["ссч"] == 10, "медиана ССЧ = %s" % поля["ссч"])
    check(errors, поля["выручка_на_сотрудника"] == 1_100_000,
          "выручка на сотрудника = %s" % поля["выручка_на_сотрудника"])
    check(errors, poles_eq(поля["доля_усн"], 14 / 21, 1e-3),
          "доля УСН = %s" % поля["доля_усн"])
    check(errors, "47|микро" in без_региона,
          "схлопнутый уровень не построен: %s" % list(без_региона))
    check(errors, стат["компаний_в_агрегации"] == 21,
          "компаний в агрегации: %s" % стат["компаний_в_агрегации"])
    # размерные группы: доход у границ канона
    записи2 = [{"оквэд2": "10", "регион": "77", "доход": d} for d in
               (119_999_999.0, 120_000_000.0, 799_999_999.0, 800_000_000.0,
                1_999_999_999.0, 2_000_000_000.0)]
    имена = [bm.размерная_группа(з["доход"], ПОРОГИ) for з in записи2]
    check(errors, имена == ["микро", "малое", "малое", "среднее", "среднее",
                            "крупное"],
          "границы размерных групп: %s" % имена)
    return errors


def poles_eq(a, b, eps=1e-6):
    return a is not None and abs(a - b) < eps


def case_порог(bm):
    """n < 20 — группа не публикуется и схлопывается на (ОКВЭД2, размер)."""
    errors = []
    записи = []
    # два региона по 12 компаний: порознь ниже порога, вместе — 24
    for регион in ("50", "77"):
        for i in range(12):
            записи.append({"оквэд2": "62", "регион": регион,
                           "доход": (i + 1) * 1_000_000.0})
    группы, без_региона, стат = bm.агрегировать(записи, ПОРОГИ, порог_n=20)
    check(errors, группы == {}, "группа с n = 12 попала в таблицу: %s" % list(группы))
    check(errors, "62|микро" in без_региона,
          "схлопнутая группа не построена: %s" % list(без_региона))
    check(errors, dict(zip(bm.ПОЛЯ, без_региона["62|микро"]))["n"] == 24,
          "в схлопнутой группе не все компании")
    check(errors, стат["групп_отсеяно_порогом"] == 2,
          "отсеяно порогом: %s" % стат["групп_отсеяно_порогом"])
    # и региона, и отрасли мало -> нет группы совсем
    мало = [{"оквэд2": "01", "регион": "50", "доход": 1_000_000.0}
            for _ in range(5)]
    группы2, без_региона2, _ = bm.агрегировать(мало, ПОРОГИ, порог_n=20)
    check(errors, группы2 == {} and без_региона2 == {},
          "группа с n = 5 не должна публиковаться ни на одном уровне")
    return errors


def _таблица(группы, без_региона, поля=None):
    return {
        "версия_таблицы": 1, "порог_n": 20, "поля": поля,
        "дата_дампов": {"revexp": "2026-08-25"},
        "размерные_группы": {"границы_дохода_руб": ПОРОГИ},
        "регионы": {"52": "Нижегородская обл."},
        "группы": группы, "группы_без_региона": без_региона,
    }


def case_lookup(bm):
    """Есть группа -> перцентиль и фраза; нет группы -> «не проверено»."""
    errors = []
    группа = [412, 2_000_000, 4_000_000, 8_000_000, 14_000_000, 25_000_000,
              0.031, 4, 1_800_000, 0.78, 0.012]
    таблица = _таблица({"86|52|микро": группа}, {"86|микро": группа}, bm.ПОЛЯ)
    res = bm.оценить("5261000000", "86.23", "52", 9_300_000, таблица=таблица)
    check(errors, res["статус"] == "проверено", "статус: %s" % res)
    check(errors, res["размерная_группа"] == "микро",
          "размерная группа: %s" % res["размерная_группа"])
    check(errors, res["группа"]["n"] == 412, "n: %s" % res["группа"]["n"])
    check(errors, 50 <= res["перцентиль_выручки"] <= 75,
          "перцентиль 9,3 млн между p50 и p75: %s" % res["перцентиль_выручки"])
    фраза = res["фраза"]
    for кусок in ("перцентиль", "ОКВЭД 86.23", "Нижегородская", "микро", "n = 412"):
        check(errors, кусок in фраза, "во фразе нет %r: %s" % (кусок, фраза))
    check(errors, res["нормы"]["p50"] == 8_000_000,
          "нормы группы не отдаются: %s" % res["нормы"])
    # региона в таблице нет -> схлопнутый уровень; регион при этом ИЗВЕСТЕН
    # по справочнику, и во фразе его называть всё равно нельзя
    res2 = bm.оценить("5261000000", "86.23", "52", 9_300_000,
                      таблица=_таблица({}, {"86|микро": группа}, bm.ПОЛЯ))
    check(errors, res2["статус"] == "проверено"
          and res2["группа"]["ключ"] == "86|микро",
          "не сработало схлопывание региона: %s" % res2.get("группа"))
    check(errors, "в регионе" not in res2["фраза"],
          "на схлопнутом уровне регион называть нельзя: %s" % res2["фраза"])
    # регион можно передать названием, а не кодом
    res_имя = bm.оценить("5261000000", "86.23", "Нижегородская обл.", 9_300_000,
                         таблица=таблица)
    check(errors, res_имя.get("код_региона") == "52"
          and res_имя["группа"]["ключ"] == "86|52|микро",
          "регион названием не сопоставлен: %s" % res_имя.get("код_региона"))
    check(errors, bm.код_региона("НИЖЕГОРОДСКАЯ ОБЛАСТЬ", таблица) == "52",
          "регистр и тип субъекта должны отбрасываться")
    check(errors, bm.код_региона("Тмутараканская обл.", таблица) is None,
          "несуществующий регион не должен сопоставляться")
    # «среднее»/«крупное» обязаны нести оговорку о смещённой выборке
    крупная = [61, 2_226_239_000, 3_320_268_000, 9_252_364_000,
               19_614_397_000, 63_220_602_000, 0.0, 2, 3_320_268_000, 0.94, 0.0]
    res_кр = bm.оценить("5036045205", "47.11", "50", 396_350_822_000,
                        таблица=_таблица({}, {"47|крупное": крупная}, bm.ПОЛЯ))
    check(errors, res_кр["статус"] == "проверено"
          and res_кр.get("предупреждение")
          and "МСП" in res_кр["предупреждение"],
          "у группы «крупное» нет оговорки о смещённой выборке: %s"
          % res_кр.get("предупреждение"))
    # группы нет совсем
    res3 = bm.оценить("5261000000", "01.11", "52", 9_300_000, таблица=таблица)
    check(errors, res3["статус"] == "не проверено", "статус: %s" % res3["статус"])
    check(errors, "не построены" in res3.get("причина", ""),
          "причина отсутствия группы: %s" % res3.get("причина"))
    check(errors, "перцентиль_выручки" not in res3,
          "без группы перцентиль выдавать нельзя")
    # крупная компания, для которой группы нет: честное «не проверено»,
    # а не медиана наугад
    res4 = bm.оценить("2309085638", "47.11", "23", 59_206_475_000, таблица=таблица)
    check(errors, res4["статус"] == "не проверено"
          and res4.get("размерная_группа") == "крупное",
          "крупная компания вне таблицы: %s" % res4)
    return errors


def case_нормы_не_построены(bm):
    """Нет data/benchmarks_ru.json -> «не проверено» с причиной, а не p50."""
    errors = []
    with tempfile.TemporaryDirectory() as tmp:
        нет = os.path.join(tmp, "benchmarks_ru.json")
        таблица, причина = bm.загрузить(нет)
        check(errors, таблица is None and "не построены" in (причина or ""),
              "загрузка отсутствующей таблицы: %s / %s" % (таблица, причина))
        res = bm.оценить("7707083893", "47.11", "77", 9_300_000, путь=нет)
        check(errors, res["статус"] == "не проверено", "статус: %s" % res["статус"])
        check(errors, "не построены" in res.get("причина", ""),
              "причина: %s" % res.get("причина"))
        check(errors, "перцентиль_выручки" not in res and "нормы" not in res,
              "без таблицы нельзя отдавать ни перцентиль, ни нормы: %s" % res)
        битый = os.path.join(tmp, "битый.json")
        Path(битый).write_text("{не json", encoding="utf-8")
        таблица2, причина2 = bm.загрузить(битый)
        check(errors, таблица2 is None and "битая" in (причина2 or ""),
              "битая таблица: %s / %s" % (таблица2, причина2))
    # нет ОКВЭД — отрасль неизвестна
    таблица = _таблица({}, {}, bm.ПОЛЯ)
    res = bm.оценить("7707083893", None, "77", 1000.0, таблица=таблица)
    check(errors, res["статус"] == "не проверено" and "ОКВЭД" in res["причина"],
          "без ОКВЭД: %s" % res)
    res = bm.оценить("7707083893", "47.11", "77", None, таблица=таблица)
    check(errors, res["статус"] == "не проверено" and "выручка" in res["причина"],
          "без выручки: %s" % res)
    return errors


