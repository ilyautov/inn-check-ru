def case_таблица_репозитория(bm):
    """Если data/benchmarks_ru.json собран — он обязан быть валидным и
    укладываться в целевые 3 МБ (спек §1.2)."""
    errors = []
    путь = ROOT / "data" / "benchmarks_ru.json"
    if not путь.exists():
        return errors  # таблица собирается локально, её отсутствие — не провал
    размер = путь.stat().st_size
    check(errors, размер <= bm.ЦЕЛЕВОЙ_РАЗМЕР,
          "таблица %d байт, целевой предел %d" % (размер, bm.ЦЕЛЕВОЙ_РАЗМЕР))
    таблица, причина = bm.загрузить(str(путь))
    check(errors, таблица is not None, "таблица не читается: %s" % причина)
    if not таблица:
        return errors
    for ключ in ("дата_дампов", "версия_структуры", "групп", "порог_n", "поля"):
        check(errors, таблица.get(ключ) is not None,
              "в таблице нет обязательного ключа %r" % ключ)
    check(errors, таблица["порог_n"] >= 20,
          "порог публикации опущен ниже 20: %s" % таблица["порог_n"])
    поля = таблица["поля"]
    плохие = [k for k, v in list(таблица["группы"].items())[:5000]
              if len(v) != len(поля) or v[0] < таблица["порог_n"]]
    check(errors, not плохие,
          "группы с неверной длиной или n ниже порога: %s" % плохие[:3])
    return errors


