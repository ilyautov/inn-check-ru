#!/usr/bin/env python3
"""
run_opendata_index_eval.py — офлайн-eval поиска по ИНН в дампах ФНС.

Сеть не трогается: индексы строятся из маленьких фикстур
`eval/fixtures/opendata/<ид>/data-*.zip` во временный каталог.

Что здесь проверяется по существу — не «работает ли поиск», а то, чем этот
слой опасен:
  * ИНН с ведущим нулём не теряется (ключ — байты, а не число);
  * «записи нет» отдаётся как `пусто` с оговоркой, а не как «ноль сотрудников»;
  * отсутствие индекса, неполный индекс и чужая версия формата дают
    «не проверено» с причиной, а не тихое «пусто»;
  * ИП, которых в этих датасетах нет в принципе, получают «не проверено»
    с причиной `охват:`, а не «пусто»;
  * дата выгрузки есть в КАЖДОМ ответе: сведения из дампа имеют возраст;
  * двоичный поиск совпадает с полным перебором на всех ключах индекса.
"""

import json
import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
FIXTURES = ROOT / "eval" / "fixtures" / "opendata"
sys.path.insert(0, str(SCRIPTS))

import opendata_index as oi


def дамп(ид):
    файлы = sorted((FIXTURES / ид).glob("data-*.zip"))
    return файлы[0] if файлы else None


def check(errors, условие, текст):
    if not условие:
        errors.append(текст)


def собрать(tmpdir, ид, **kw):
    return oi.построить(ид, путь_дампа=str(дамп(ид)), каталог=tmpdir, **kw)


def ключи_индекса(tmpdir, ид):
    """Все ключи индекса подряд — эталон для сверки двоичного поиска."""
    путь = oi._путь_индекса(ид, tmpdir)
    размер = oi.КЛЮЧ_БАЙТ + oi.ИНДЕКСИРУЕМЫЕ[ид]["запись"]
    сырое = Path(путь).read_bytes()
    return [сырое[i:i + oi.КЛЮЧ_БАЙТ] for i in range(0, len(сырое), размер)]


# --- кейсы -------------------------------------------------------------------

def case_сборка(tmpdir):
    """Индекс собирается по всем трём датасетам и отражает содержимое дампа."""
    errors = []
    for ид in oi.ИНДЕКСИРУЕМЫЕ:
        мета, причина = собрать(tmpdir, ид)
        check(errors, мета is not None, "%s не собрался: %s" % (ид, причина))
        if not мета:
            continue
        check(errors, мета["записей"] > 0, "%s: индекс пуст" % ид)
        check(errors, мета.get("дата_выгрузки"),
              "%s: в мете нет даты выгрузки — сведения уедут без возраста" % ид)
        check(errors, мета.get("версия_формата") == oi.ВЕРСИЯ_ФОРМАТА,
              "%s: версия формата %r" % (ид, мета.get("версия_формата")))
    return errors


def case_ведущий_ноль(tmpdir):
    """ИНН 0912003672 (Карачаево-Черкесия) не теряет ведущий ноль.

    Ключ — 12 байт ASCII, а не uint64: числовой ключ склеил бы 0912003672 и
    912003672 в один и отдал бы чужую запись, не сказав ни слова. В живом
    индексе snr таких ИНН 64 872 из 1,33 млн (проверено 22.09.2026).
    """
    errors = []
    собрать(tmpdir, "sshr2019")
    с_нулём = oi.найти("0912003672", "sshr2019", tmpdir)
    check(errors, с_нулём["состояние"] == oi.ОК,
          "ИНН с ведущим нулём не найден: %r" % с_нулём.get("состояние"))
    check(errors, с_нулём.get("ссч") == 5,
          "ССЧ по 0912003672: %r, ждали 5" % с_нулём.get("ссч"))
    без_нуля = oi.найти("912003672", "sshr2019", tmpdir)
    check(errors, без_нуля["состояние"] == oi.ПУСТО,
          "ИНН без ведущего нуля нашёл чужую запись: %r" % без_нуля)
    return errors


def case_пусто_не_ноль(tmpdir):
    """«Записи нет» — это `пусто` с оговоркой, а не «сотрудников нет».

    Разница между «ССЧ = 0» и «записи в выгрузке нет» — та самая, ради которой
    у движка три состояния. Первое — факт о компании, второе — факт о выгрузке.
    """
    errors = []
    собрать(tmpdir, "sshr2019")
    нет = oi.найти("7707083893", "sshr2019", tmpdir)   # Сбербанка в дампе нет
    check(errors, нет["состояние"] == oi.ПУСТО,
          "отсутствующий ИНН дал %r" % нет["состояние"])
    check(errors, "ссч" not in нет,
          "у состояния «пусто» проставлено значение ССЧ: %r" % нет.get("ссч"))
    оговорка = нет.get("оговорка") or ""
    check(errors, "не равно" in оговорка and "сотрудник" in оговорка,
          "оговорка не разводит «нет записи» и «нет сотрудников»: %r"
          % оговорка[:120])
    check(errors, нет.get("дата_выгрузки"),
          "в ответе «пусто» нет даты выгрузки")
    return errors


def case_нет_индекса(tmpdir):
    """Индекс не построен -> «не проверено» с командой починки, а не «пусто»."""
    errors = []
    пусто_кат = os.path.join(tmpdir, "без-индекса")
    os.makedirs(пусто_кат, exist_ok=True)
    r = oi.найти("0912003672", "snr", пусто_кат)
    check(errors, r["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "без индекса состояние %r — молчание выдано за ответ" % r["состояние"])
    причина = r.get("причина") or ""
    check(errors, причина.startswith("кэш:"),
          "причина без машинного префикса «кэш:»: %r" % причина[:80])
    check(errors, "--построить" in причина,
          "причина не называет команду сборки: %r" % причина[:120])
    return errors


def case_неполный_индекс(tmpdir):
    """Индекс, собранный с --лимит, не имеет права отвечать «пусто».

    Он покрывает кусок выгрузки, и «не найдено» в нём не значит ничего.
    """
    errors = []
    кат = os.path.join(tmpdir, "неполный")
    os.makedirs(кат, exist_ok=True)
    мета, причина = oi.построить("sshr2019", путь_дампа=str(дамп("sshr2019")),
                                 каталог=кат, лимит=3)
    check(errors, мета is not None, "неполный индекс не собрался: %s" % причина)
    check(errors, мета and мета.get("неполный") is True,
          "индекс с лимитом не помечен неполным")
    r = oi.найти("7707083893", "sshr2019", кат)
    check(errors, r["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "неполный индекс ответил %r вместо «не проверено»" % r["состояние"])
    check(errors, "лимит" in (r.get("причина") or ""),
          "причина не называет лимит: %r" % (r.get("причина") or "")[:120])
    # а вот запись, которая в него попала, отдаётся как есть
    первый = ключи_индекса(кат, "sshr2019")[0].rstrip(b"\0").decode()
    check(errors, oi.найти(первый, "sshr2019", кат)["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "неполный индекс отдал значение, не пометив неполноту")
    return errors


def case_чужая_версия(tmpdir):
    """Индекс другой версии формата -> «не проверено» с префиксом «схема:»."""
    errors = []
    кат = os.path.join(tmpdir, "версия")
    os.makedirs(кат, exist_ok=True)
    собрать(кат, "snr")
    путь_меты = oi._путь_меты("snr", кат)
    мета = json.loads(Path(путь_меты).read_text(encoding="utf-8"))
    мета["версия_формата"] = oi.ВЕРСИЯ_ФОРМАТА + 1
    Path(путь_меты).write_text(json.dumps(мета, ensure_ascii=False),
                               encoding="utf-8")
    r = oi.найти("0912003672", "snr", кат)
    check(errors, r["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "чужая версия формата дала %r" % r["состояние"])
    check(errors, (r.get("причина") or "").startswith("схема:"),
          "причина без префикса «схема:»: %r" % (r.get("причина") or "")[:80])

    # запись стала шире, а мета осталась прежней — поиск обязан отказаться,
    # а не читать соседние байты как своё поле
    мета["версия_формата"] = oi.ВЕРСИЯ_ФОРМАТА
    мета["размер_записи"] = мета["размер_записи"] + 4
    Path(путь_меты).write_text(json.dumps(мета, ensure_ascii=False),
                               encoding="utf-8")
    r2 = oi.найти("0912003672", "snr", кат)
    check(errors, r2["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "несовпадение размера записи дало %r" % r2["состояние"])
    return errors


def case_битый_индекс(tmpdir):
    """Обрезанный файл индекса -> «не проверено», а не traceback."""
    errors = []
    кат = os.path.join(tmpdir, "битый")
    os.makedirs(кат, exist_ok=True)
    собрать(кат, "snr")
    путь = oi._путь_индекса("snr", кат)
    сырое = Path(путь).read_bytes()
    Path(путь).write_bytes(сырое[:-3])          # длина не кратна записи
    try:
        r = oi.найти("0912003672", "snr", кат)
    except Exception as e:
        return ["битый индекс уронил поиск: %s: %s" % (type(e).__name__, e)]
    check(errors, r["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "битый индекс дал %r" % r["состояние"])
    check(errors, "не читается" in (r.get("причина") or "")
          or "повреждён" in (r.get("причина") or ""),
          "причина не говорит о поломке индекса: %r"
          % (r.get("причина") or "")[:120])
    return errors


def case_ип_вне_охвата(tmpdir):
    """12-значный ИНН -> «не проверено» с причиной `охват:`, а не «пусто».

    ИП в этих датасетах нет по устройству: запись висит на СведНП/@ИННЮЛ.
    «Записи нет» у источника, который физически не может её содержать, — это
    факт об охвате датасета, а не об ИП.
    """
    errors = []
    собрать(tmpdir, "snr")
    r = oi.найти("500100732259", "snr", tmpdir)
    check(errors, r["состояние"] == oi.НЕ_ПРОВЕРЕНО,
          "ИП получил %r вместо «не проверено»" % r["состояние"])
    check(errors, (r.get("причина") or "").startswith("охват:"),
          "причина без префикса «охват:»: %r" % (r.get("причина") or "")[:80])
