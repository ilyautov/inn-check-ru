def case_дата_в_каждом_ответе(tmpdir):
    """Дата выгрузки стоит в ответе при любом состоянии, кроме «индекса нет».

    Сведения из дампа имеют возраст: snr на 22.09.2026 отражает 01.08.2026,
    sshr — 31.12.2025. Отдать их без даты значит выдать прошлое за настоящее.
    """
    errors = []
    for ид in oi.ИНДЕКСИРУЕМЫЕ:
        собрать(tmpdir, ид)
