def case_статус(tmpdir):
    """--статус отличает построенный индекс от отсутствующего."""
    errors = []
    кат = os.path.join(tmpdir, "статус")
    os.makedirs(кат, exist_ok=True)
    пусто = oi.статус(кат)
    check(errors, not пусто["статус"].startswith("готовы все"),
          "пустой каталог объявлен готовым: %r" % пусто["статус"])
    check(errors, all(not v["построен"] for v in пусто["индексы"].values()),
          "индекс объявлен построенным на пустом каталоге")
    for ид in oi.ИНДЕКСИРУЕМЫЕ:
        собрать(кат, ид)
    полный = oi.статус(кат)
    check(errors, полный["статус"].startswith("готовы все"),
          "собранные индексы не признаны готовыми: %r" % полный["статус"])
    return errors


def case_cli(tmpdir):
    """CLI: найденный ИНН -> 0, ненайденный -> 1, мусор -> 2 и не traceback."""
    errors = []
    скрипт = str(SCRIPTS / "opendata_index.py")

    p = subprocess.run([sys.executable, скрипт], capture_output=True, text=True,
                       check=False)
    check(errors, p.returncode == 2, "без аргументов код %d" % p.returncode)
    check(errors, "Traceback" not in p.stderr, "без аргументов traceback")

    p = subprocess.run([sys.executable, скрипт, "--найти"], capture_output=True,
                       text=True, check=False)
    check(errors, p.returncode == 2, "--найти без ИНН код %d" % p.returncode)

    p = subprocess.run([sys.executable, скрипт, "--построить", "--датасет", "revexp"],
                       capture_output=True, text=True, check=False)
    check(errors, p.returncode == 2,
          "неиндексируемый датасет принят: код %d" % p.returncode)
    check(errors, "Traceback" not in p.stderr, "неизвестный датасет — traceback")
    return errors


def case_размер_записи(tmpdir):
    """Размер записи в коде и в файле сходится, ключ — ровно 12 байт."""
    errors = []
    for ид, спец in oi.ИНДЕКСИРУЕМЫЕ.items():
        мета, _ = собрать(tmpdir, ид)
        ожидаемый = oi.КЛЮЧ_БАЙТ + спец["запись"]
        check(errors, мета and мета["размер_записи"] == ожидаемый,
              "%s: в мете %r, в коде %d"
              % (ид, (мета or {}).get("размер_записи"), ожидаемый))
        факт = os.path.getsize(oi._путь_индекса(ид, tmpdir))
        check(errors, факт % ожидаемый == 0,
              "%s: длина файла %d не кратна записи %d" % (ид, факт, ожидаемый))
        check(errors, факт // ожидаемый == мета["записей"],
              "%s: в файле %d записей, в мете %d"
              % (ид, факт // ожидаемый, мета["записей"]))
    check(errors, oi.КЛЮЧ_БАЙТ == 12, "ключ перестал быть 12-байтным")
    check(errors, len(oi._ключ("0912003672")) == oi.КЛЮЧ_БАЙТ,
          "ключ из 10-значного ИНН не добит до 12 байт")
    check(errors, struct.calcsize("<iH") == 6, "разъехалась упаковка sshr")
    return errors


