def main():
    отсутствуют = [ид for ид in oi.ИНДЕКСИРУЕМЫЕ if дамп(ид) is None]
    if отсутствуют:
        print("FAIL: нет фикстур дампов: %s" % ", ".join(отсутствуют))
        return 1
    всего = failed = 0
    for имя, кейс in КЕЙСЫ:
        всего += 1
        with tempfile.TemporaryDirectory() as tmpdir:
            try:
                ошибки = кейс(tmpdir)
            except Exception as e:      # кейс не имеет права падать traceback'ом
                ошибки = ["исключение в кейсе: %s: %s" % (type(e).__name__, e)]
        if ошибки:
            failed += 1
            print("FAIL %s" % имя)
            for e in ошибки:
                print("  - %s" % e)
        else:
            print("PASS %s" % имя)
    if failed:
        print("FAIL: %d/%d кейсов упало" % (failed, всего))
        return 1
    print("PASS: все %d кейсов зелёные" % всего)
    return 0


