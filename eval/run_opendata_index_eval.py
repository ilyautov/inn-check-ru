def case_поиск_равен_перебору(tmpdir):
    """Двоичный поиск совпадает с полным перебором на ВСЕХ ключах индекса.

    Границы (первая и последняя запись) — любимое место ошибки на единицу,
    поэтому проверяются не выборочно, а целиком: фикстуры маленькие.
    """
    errors = []
    for ид in oi.ИНДЕКСИРУЕМЫЕ:
        собрать(tmpdir, ид)
        ключи = ключи_индекса(tmpdir, ид)
        check(errors, ключи == sorted(ключи), "%s: индекс не отсортирован" % ид)
        check(errors, len(set(ключи)) == len(ключи),
              "%s: в индексе дубли ключей" % ид)
        потеряны = [k for k in ключи
                    if oi.найти(k.rstrip(b"\0").decode(), ид, tmpdir)["состояние"]
                    != oi.ОК]
        check(errors, not потеряны,
              "%s: двоичный поиск не нашёл %d из %d существующих записей (%s)"
              % (ид, len(потеряны), len(ключи),
                 ", ".join(k.rstrip(b"\0").decode() for k in потеряны[:3])))
    return errors


def case_дубли_свежий_год(tmpdir):
    """Один ИНН в выгрузке дважды -> в индекс идёт запись за свежий год.

    Оставить первую попавшуюся значило бы отдавать позапрошлогоднюю
    численность как сегодняшнюю, ничем это не пометив.
    """
    import zipfile
    errors = []
    кат = os.path.join(tmpdir, "дубли")
    os.makedirs(кат, exist_ok=True)
    зип = os.path.join(кат, "data-20260825-structure-20200408.zip")
    док = ('<Документ ИдДок="%s" ДатаДок="25.08.2026" ДатаСост="31.12.%d">'
           '<СведНП НаимОрг="ООО ДУБЛЬ" ИННЮЛ="0912003672"/>'
           '<СведССЧР КолРаб="%d"/></Документ>')
    xml = ('<?xml version="1.0" encoding="UTF-8"?>'
           '<Файл ВерсФорм="4.01" ТипИнф="ОТКРДАННЫЕ3" КолДок="2">'
           + док % ("a", 2023, 7) + док % ("b", 2025, 42) + "</Файл>")
    with zipfile.ZipFile(зип, "w") as z:
        z.writestr("VO_OTKRDAN_3_dubli.xml", xml)
    мета, причина = oi.построить("sshr2019", путь_дампа=зип, каталог=кат)
    check(errors, мета is not None, "не собрался: %s" % причина)
    if not мета:
        return errors
    check(errors, мета["записей"] == 1,
          "дубль ИНН не схлопнут: записей %d" % мета["записей"])
    check(errors, мета["дублей_ИНН_в_выгрузке"] == 1,
          "дубль не посчитан: %r" % мета.get("дублей_ИНН_в_выгрузке"))
    r = oi.найти("0912003672", "sshr2019", кат)
    check(errors, r.get("ссч") == 42 and r.get("год") == 2025,
          "из дубля взята несвежая запись: ссч=%r год=%r"
          % (r.get("ссч"), r.get("год")))
    return errors


def case_значения(tmpdir):
    """Значения читаются из дампа без искажения: режимы, ССЧ, НДС."""
    errors = []
    for ид in oi.ИНДЕКСИРУЕМЫЕ:
        собрать(tmpdir, ид)

    снр = oi.найти("0912003672", "snr", tmpdir)
    check(errors, снр["состояние"] == oi.ОК, "snr: %r" % снр.get("состояние"))
    check(errors, снр.get("усн") is True and снр.get("есхн") is False,
          "признаки спецрежима прочитаны неверно: %r"
          % {k: снр.get(k) for k in ("есхн", "усн", "аусн", "срп")})
    check(errors, снр.get("режимы") == ["УСН"],
          "список режимов: %r" % снр.get("режимы"))

    # Отсутствующий в XML признак обязан стать None, а не False: «не заявлен»
    # и «сведений нет» — разные вещи, и маска известности хранится отдельно.
    import zipfile
    кат = os.path.join(tmpdir, "частичный-снр")
    os.makedirs(кат, exist_ok=True)
    зип = os.path.join(кат, "data-20260825-structure-20230425.zip")
    xml = ('<?xml version="1.0" encoding="UTF-8"?>'
           '<Файл ВерсФорм="4.02" ТипИнф="ОТКРДАННЫЕ1" КолДок="1">'
           '<Документ ИдДок="c" ДатаДок="25.08.2026" ДатаСост="01.08.2026">'
           '<СведНП НаимОрг="ООО ЧАСТЬ" ИННЮЛ="0912003672"/>'
           '<СведСНР ПризнУСН="1"/></Документ></Файл>')
    with zipfile.ZipFile(зип, "w") as z:
        z.writestr("VO_OTKRDAN_1_part.xml", xml)
    oi.построить("snr", путь_дампа=зип, каталог=кат)
    част = oi.найти("0912003672", "snr", кат)
    check(errors, част.get("усн") is True, "усн: %r" % част.get("усн"))
    check(errors, част.get("есхн") is None,
          "отсутствующий в XML признак стал %r вместо None — «сведений нет» "
          "выдано за «не применяет»" % част.get("есхн"))

    ссч = oi.найти("0912003721", "sshr2019", tmpdir)
    check(errors, ссч.get("ссч") == 10, "ССЧ: %r" % ссч.get("ссч"))

    нал = oi.найти("0912003672", "paytax", tmpdir)
    check(errors, нал["состояние"] == oi.ОК, "paytax: %r" % нал.get("состояние"))
    check(errors, нал.get("усн_руб") == 306082.0,
          "УСН из дампа: %r, ждали 306082.0 (имя налога с двойным пробелом — "
          "«в связи с  применением», нормализация обязана его пережить)"
          % нал.get("усн_руб"))
    check(errors, (нал.get("налогов_всего_руб") or 0) >= нал.get("усн_руб", 0),
          "сумма всех налогов меньше одного из них")
    return errors


