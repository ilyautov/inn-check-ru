def case_env_переопределение(mod, tmp):
    """INN_CHECK_CACHE / INN_CHECK_WATCHLIST — те же переменные, что у watchlist.py."""
    errors = []
    каталог, наблюдение = _подставной_кэш(tmp)
    было = (os.environ.get("INN_CHECK_CACHE"), os.environ.get("INN_CHECK_WATCHLIST"))
    os.environ["INN_CHECK_CACHE"] = каталог
    os.environ["INN_CHECK_WATCHLIST"] = наблюдение
    try:
        res = разобрать(mod, "ИНН %s и ИНН %s" % (СБЕР, ИП1), "счёт.txt")
        по_инн = {z["инн"]: z["статус"] for z in res["найдено"]}
        check(errors, по_инн.get(СБЕР) == "уже проверялся",
              "INN_CHECK_CACHE не учтён: %r" % по_инн.get(СБЕР))
        check(errors, по_инн.get(ИП1) == "новый",
              "новый ИНН из env-кэша: %r" % по_инн.get(ИП1))
    finally:
        for имя, значение in zip(("INN_CHECK_CACHE", "INN_CHECK_WATCHLIST"), было):
            if значение is None:
                os.environ.pop(имя, None)
            else:
                os.environ[имя] = значение
    return errors


