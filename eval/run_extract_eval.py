def _подставной_кэш(tmp):
    """Каталог снимков с одним проверенным ИНН + список наблюдения с другим."""
    каталог = os.path.join(tmp, "кэш")
    снимки = os.path.join(каталог, "snapshots", СБЕР)
    os.makedirs(снимки, exist_ok=True)
    with open(os.path.join(снимки, "2026-09-18_10-00-00.json"), "w",
              encoding="utf-8") as fh:
        json.dump({"инн": СБЕР}, fh, ensure_ascii=False)
    наблюдение = os.path.join(каталог, "watchlist.json")
    with open(наблюдение, "w", encoding="utf-8") as fh:
        json.dump({"версия": 1, "контрагенты": [
            {"инн": ЮЛ2, "профиль": "отсрочка", "добавлен": "2026-09-18T10:00:00"}]},
            fh, ensure_ascii=False)
    return каталог, наблюдение


