def загрузить(имя, путь):
    spec = importlib.util.spec_from_file_location(имя, str(путь))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def инны(результат):
    return sorted(z["инн"] for z in результат["найдено"])


def разобрать(mod, текст, имя="документ.txt", **kw):
    """Текст -> результат собрать() (кэш и список наблюдения — из kw)."""
    return mod.собрать([(имя, текст.encode("utf-8"))], **kw)


def пустой_кэш(tmp):
    """Каталог снимков и список наблюдения, в которых заведомо никого нет."""
    каталог = os.path.join(tmp, "кэш-пустой")
    os.makedirs(os.path.join(каталог, "snapshots"), exist_ok=True)
    return {"каталог": каталог,
            "файл_наблюдения": os.path.join(каталог, "watchlist.json")}


