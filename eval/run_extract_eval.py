def _запуск(аргументы, env=None, вход=None):
    окружение = dict(os.environ)
    окружение.update(env or {})
    return subprocess.run([sys.executable, str(СКРИПТ)] + аргументы,
                          capture_output=True, text=True, timeout=120,
                          env=окружение, input=вход, check=False)


def case_cli(mod, tmp):
    errors = []
    каталог, наблюдение = _подставной_кэш(tmp)
    файл = os.path.join(tmp, "счёт_cli.txt")
    with open(файл, "w", encoding="utf-8") as fh:
        fh.write(СЧЁТ)
    общие = ["--каталог", каталог, "--список-наблюдения", наблюдение]

    p = _запуск([файл, "--json"] + общие)
    check(errors, p.returncode == 0, "--json: код %d, stderr %s"
          % (p.returncode, p.stderr[-300:]))
    try:
        данные = json.loads(p.stdout)
    except ValueError as e:
        данные = None
        errors.append("--json: не JSON (%s): %s" % (e, p.stdout[:200]))
    if данные:
        check(errors, sorted(z["инн"] for z in данные["найдено"])
              == sorted([ЮЛ2, СБЕР, ИП1]),
              "--json: найдено %s" % [z["инн"] for z in данные["найдено"]])
        check(errors, данные["итого"]["новых"] == 1,
              "--json: новых %r, ждали 1" % данные["итого"]["новых"])
        check(errors, "отбракованные" not in данные,
              "--json без --отбракованные не должен печатать отбракованные")

    p = _запуск([файл, "--json", "--только-новые", "--отбракованные"] + общие)
    данные = json.loads(p.stdout)
    check(errors, [z["инн"] for z in данные["найдено"]] == [ИП1],
          "--только-новые: %s" % [z["инн"] for z in данные["найдено"]])
    check(errors, данные.get("отбракованные"),
          "--отбракованные: список пуст")

    p = _запуск(["--stdin"] + общие, вход=СЧЁТ)
    check(errors, p.returncode == 0 and ИП1 in p.stdout,
          "--stdin: код %d, вывод %r" % (p.returncode, p.stdout[:200]))
    check(errors, "Найдено ИНН: 3" in p.stdout,
          "--stdin: сводка не та: %r" % p.stdout[:200])

    p = _запуск([os.path.join(tmp, "нет-такого.txt")] + общие)
    check(errors, p.returncode == 0 and "не прочитан" in (p.stdout + p.stderr),
          "отсутствующий файл: код %d, %r" % (p.returncode, p.stdout[:200]))
    check(errors, "Traceback" not in p.stderr, "traceback в stderr: %s" % p.stderr[-300:])

    p = _запуск([])
    check(errors, p.returncode == 2 and "Использование" in p.stderr,
          "без аргументов: код %d, stderr %r" % (p.returncode, p.stderr[:200]))
    return errors


def case_проверить(mod, tmp):
    """--проверить отдаёт в батч ТОЛЬКО новые ИНН и ТОЛЬКО с --режим quick."""
    errors = []
    каталог, наблюдение = _подставной_кэш(tmp)
    протокол = os.path.join(tmp, "батч-аргументы.json")
    заглушка = os.path.join(tmp, "батч_заглушка.py")
    with open(заглушка, "w", encoding="utf-8") as fh:
        fh.write("import json, sys\n"
                 "json.dump(sys.argv[1:], open(%r, 'w'), ensure_ascii=False)\n"
                 "print('| инн | светофор |')\n" % протокол)
    файл = os.path.join(tmp, "счёт_проверка.txt")
    with open(файл, "w", encoding="utf-8") as fh:
        fh.write(СЧЁТ)
    общие = ["--каталог", каталог, "--список-наблюдения", наблюдение]
    env = {"INN_CHECK_EXTRACT_BATCH": заглушка}

    p = _запуск([файл, "--проверить", "--профиль", "отсрочка"] + общие, env=env)
    check(errors, p.returncode == 0, "--проверить: код %d, %s" % (p.returncode, p.stderr[-300:]))
    try:
        with open(протокол, encoding="utf-8") as fh:
            аргументы = json.load(fh)
    except (OSError, ValueError) as e:
        аргументы = []
        errors.append("батч не запущен (%s)" % e)
    check(errors, [a for a in аргументы if a.isdigit()] == [ИП1],
          "в батч ушли ИНН %s, ждали только новый %s"
          % ([a for a in аргументы if a.isdigit()], ИП1))
    check(errors, "--режим" in аргументы
          and аргументы[аргументы.index("--режим") + 1] == "quick",
          "батч запущен без --режим quick: %s" % аргументы)
    check(errors, "--профиль" in аргументы, "профиль не передан: %s" % аргументы)
    check(errors, "| инн | светофор |" in p.stdout,
          "вывод батча не попал в отчёт: %r" % p.stdout[-200:])

    # нечего проверять — батч не запускается вовсе
    os.remove(протокол)
    только_известные = "ИНН %s и ИНН %s" % (СБЕР, ЮЛ2)
    p = _запуск(["--stdin", "--проверить"] + общие, env=env, вход=только_известные)
    check(errors, not os.path.exists(протокол),
          "батч запущен, хотя новых ИНН нет")
    check(errors, "новых ИНН нет" in p.stdout,
          "не сказано, почему батч не запускался: %r" % p.stdout[-200:])

    # батч сломан — extract_inn не падает и говорит об этом
    p = _запуск([файл, "--проверить"] + общие,
                env={"INN_CHECK_EXTRACT_BATCH": os.path.join(tmp, "нет-батча.py")})
    check(errors, p.returncode == 0, "сломанный батч уронил extract_inn: %d" % p.returncode)
    check(errors, "Traceback" not in p.stderr, "traceback: %s" % p.stderr[-300:])
    return errors


def main():
    mod = загрузить("extract_inn", СКРИПТ)
    tmp = tempfile.mkdtemp(prefix="extract-eval-")
    try:
        cases = {
            "текст-счёта": case_текст(mod, tmp),
            "мусор-не-проходит": case_мусор(mod, tmp),
            "форматы-файлов": case_форматы(mod, tmp),
            "форматы-записи-инн": case_форматы_записи(mod, tmp),
            "дедуп": case_дедуп(mod, tmp),
            "новый-vs-уже-проверялся": case_уже_проверялся(mod, tmp),
            "переопределение-кэша-env": case_env_переопределение(mod, tmp),
            "устойчивость-входа": case_устойчивость(mod, tmp),
            "cli": case_cli(mod, tmp),
            "проверить-в-батч": case_проверить(mod, tmp),
        }
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    failed = 0
    for name, errors in cases.items():
        if errors:
            failed += 1
            print("FAIL %s" % name)
            for e in errors:
                print("  - %s" % e)
        else:
            print("PASS %s" % name)
    if failed:
        print("FAIL: %d/%d кейсов упало" % (failed, len(cases)))
        return 1
    print("PASS: все %d кейсов зелёные" % len(cases))
    return 0


if __name__ == "__main__":
    sys.exit(main())
