def _запуск(аргументы, env=None, вход=None):
    окружение = dict(os.environ)
    окружение.update(env or {})
    return subprocess.run([sys.executable, str(СКРИПТ)] + аргументы,
                          capture_output=True, text=True, timeout=120,
                          env=окружение, input=вход, check=False)


