    with zipfile.ZipFile(не_docx, "w") as z:
        z.writestr("readme.txt", "ИНН %s" % СБЕР)
    res = mod.собрать([(не_docx, Path(не_docx).read_bytes())], **пусто)
    check(errors, res["файлы"][0]["статус"] == "не поддерживается",
          "ZIP без word/document.xml: %r" % res["файлы"][0])
    res = mod.собрать([("битый.docx", b"PK\x03\x04\x00\x01\x02\x03broken")], **пусто)
    check(errors, res["файлы"][0]["статус"] == "не поддерживается",
          "битый ZIP: %r" % res["файлы"][0])
    return errors


