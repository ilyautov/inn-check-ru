def дата(дней_назад=0):
    """Дата снимка относительно СЕГОДНЯ: фикстура с вшитым «2026-09-18»
    протухла бы сама и однажды покрасила бы eval без единого изменения кода."""
    return time.strftime("%Y-%m-%d", time.localtime(time.time() - дней_назад * 86400))


def время(дней_назад=0):
    return time.strftime("%Y-%m-%dT%H:%M:%S",
                         time.localtime(time.time() - дней_назад * 86400))


def положить_снимок(каталог, инн, дней_назад=0, содержимое=..., имя=None):
    """Снимок в подставном кэше. `содержимое=None` — пустой файл."""
    папка = os.path.join(каталог, "snapshots", str(инн))
    os.makedirs(папка, exist_ok=True)
    путь = os.path.join(папка, имя or ("%s_10-00-00.json" % дата(дней_назад)))
    if содержимое is ...:
        содержимое = {"версия_формата": 1, "инн": инн, "дата": время(дней_назад),
                      "поля": {}, "состояния": {}, "сбор": {"режим": "всё"},
                      "хеш_остального": "sha256:0", "_итог": {}}
    with open(путь, "w", encoding="utf-8") as fh:
        if содержимое is None:
            fh.write("")
        elif isinstance(содержимое, str):
            fh.write(содержимое)
        else:
            json.dump(содержимое, fh, ensure_ascii=False)
    return путь


def загрузить(имя, путь):
    spec = importlib.util.spec_from_file_location(имя, str(путь))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def инны(результат):
    return sorted(z["инн"] for z in результат["найдено"])


def разобрать(mod, текст, имя="документ.txt", **kw):
    """Текст -> результат собрать() (кэш и список наблюдения — из kw)."""
    return mod.собрать([(имя, текст.encode("utf-8"))], **kw)


def пустой_кэш(tmp):
    """Каталог снимков и список наблюдения, в которых заведомо никого нет."""
    каталог = os.path.join(tmp, "кэш-пустой")
    os.makedirs(os.path.join(каталог, "snapshots"), exist_ok=True)
    return {"каталог": каталог,
            "файл_наблюдения": os.path.join(каталог, "watchlist.json")}


