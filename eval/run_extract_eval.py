def case_текст(mod, tmp):
    errors = []
    пусто = пустой_кэш(tmp)
    res = разобрать(mod, СЧЁТ, "счёт.txt", **пусто)
    check(errors, инны(res) == sorted([ЮЛ2, СБЕР, ИП1]),
          "из счёта извлечено %s, ждали %s" % (инны(res), sorted([ЮЛ2, СБЕР, ИП1])))
    по_инн = {z["инн"]: z for z in res["найдено"]}
    check(errors, по_инн[ИП1]["тип"] == "ип", "12 цифр — не ИП: %r" % по_инн[ИП1]["тип"])
    check(errors, по_инн[СБЕР]["тип"] == "юрлицо",
          "10 цифр — не юрлицо: %r" % по_инн[СБЕР]["тип"])
    check(errors, "Кузнецов" in по_инн[ИП1]["контекст"],
          "контекст ИП не содержит соседнего текста: %r" % по_инн[ИП1]["контекст"])
    check(errors, len(по_инн[ИП1]["контекст"]) <= 2 * 80 + 12 + 4,
          "контекст длиннее ±80 символов: %d" % len(по_инн[ИП1]["контекст"]))
    check(errors, по_инн[СБЕР]["строка"] == 8,
          "строка ИНН покупателя %r, ждали 8" % по_инн[СБЕР]["строка"])
    причины = {z["как_записано"]: z["причина"] for z in res["отбракованные"]}
    for мусор, кусок in (("40702810400000012345", "не 10 и не 12"),
                         ("89161234567", "не 10 и не 12"),
                         ("773601001", "не 10 и не 12"),
                         ("1027700132195", "не 10 и не 12"),
                         ("7736010017707083893", "не 10 и не 12"),
                         ("1234567890", "контрольное число"),
                         ("0000000000", "региона"),
                         ("9999999999", "контрольное число")):
        check(errors, кусок in (причины.get(мусор) or ""),
              "%s: причина отбраковки %r, ждали «%s»"
              % (мусор, причины.get(мусор), кусок))
    check(errors, (причины.get(СБЕР) or "").startswith("число слито"),
          "артикул «%sAB» не отбракован: %r" % (СБЕР, причины.get(СБЕР)))
    return errors


