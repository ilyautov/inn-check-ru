def case_негодный_снимок(mod, tmp):
    """Дефект: «уже проверялся» ставилось по факту существования файла.

    Пустой файл после обрыва, битый JSON после полного диска, снимок с ЧУЖИМ
    ИНН внутри и снимок 2019 года — каждый из них молча исключал контрагента
    из проверки перед оплатой.
    """
    errors = []
    случаи = {
        "пустой файл": (None, None),
        "битый JSON": ("{это не json", None),
        "чужой ИНН внутри": ({"версия_формата": 1, "инн": ЮЛ3, "дата": время(1)},
                             None),
        "снимок без поля инн": ({"версия_формата": 1, "дата": время(1)}, None),
    }
    for что, (содержимое, _) in случаи.items():
        каталог = os.path.join(tmp, "негодный-%d" % abs(hash(что)))
        положить_снимок(каталог, СБЕР, дней_назад=1, содержимое=содержимое)
        наблюдение = os.path.join(каталог, "watchlist.json")
        with open(наблюдение, "w", encoding="utf-8") as fh:
            json.dump({"версия": 1, "контрагенты": []}, fh)
        res = разобрать(mod, "ИНН %s" % СБЕР, "счёт.txt", каталог=каталог,
                        файл_наблюдения=наблюдение)
        статус = res["найдено"][0]["статус"]
        check(errors, статус == "новый",
              "%s: снимок засчитан за проверку (статус %r)" % (что, статус))
        check(errors, any(СБЕР in п for п in res["предупреждения"]),
              "%s: негодный снимок молчит, предупреждения %r"
              % (что, res["предупреждения"]))

    # несвежий снимок: не «новый», но и не исключение из проверки
    каталог = os.path.join(tmp, "несвежий")
    положить_снимок(каталог, СБЕР, дней_назад=400)
    наблюдение = os.path.join(каталог, "watchlist.json")
    with open(наблюдение, "w", encoding="utf-8") as fh:
        json.dump({"версия": 1, "контрагенты": []}, fh)
    res = разобрать(mod, "ИНН %s и ИНН %s" % (СБЕР, ИП1), "счёт.txt",
                    каталог=каталог, файл_наблюдения=наблюдение)
    по_инн = {z["инн"]: z for z in res["найдено"]}
    check(errors, по_инн[СБЕР]["статус"] == "снимок устарел",
          "снимок 400-дневной давности: статус %r" % по_инн[СБЕР]["статус"])
    check(errors, "дней назад" in (по_инн[СБЕР]["почему"] or ""),
          "не сказано, насколько стар снимок: %r" % по_инн[СБЕР]["почему"])
    check(errors, sorted(mod.к_проверке(res)) == sorted([СБЕР, ИП1]),
          "устаревший снимок исключил ИНН из проверки: %r" % mod.к_проверке(res))
    check(errors, res["итого"]["устарели"] == 1 and res["итого"]["новых"] == 1,
          "сводка по устаревшим: %r" % res["итого"])

    # снимок быстрого прогона помечается неполным
    каталог = os.path.join(tmp, "неполный")
    положить_снимок(каталог, СБЕР, дней_назад=1, содержимое={
        "версия_формата": 1, "инн": СБЕР, "дата": время(1), "поля": {},
        "состояния": {}, "сбор": {"режим": "quick", "неполный": True},
        "хеш_остального": "sha256:0", "_итог": {}})
    res = разобрать(mod, "ИНН %s" % СБЕР, "счёт.txt", каталог=каталог,
                    файл_наблюдения=os.path.join(каталог, "нет.json"))
    почему = res["найдено"][0]["почему"] or ""
    check(errors, res["найдено"][0]["статус"] == "уже проверялся",
          "снимок quick-прогона: статус %r" % res["найдено"][0]["статус"])
    check(errors, "неполный" in почему and "quick" in почему,
          "снимок quick выдан за полный: %r" % почему)
    return errors


def case_кэш_недоступен(mod, tmp):
    """Дефект: несуществующий каталог, каталог без прав и битый список
    наблюдения давали «новых 2, предупреждений 0» — опечатка в `--каталог`
    выглядела ровно как пустой кэш."""
    errors = []
    текст = "ИНН %s и ИНН %s" % (СБЕР, ЮЛ2)

    нет_каталога = os.path.join(tmp, "нет-такого-кэша")
    res = разобрать(mod, текст, "счёт.txt", каталог=нет_каталога,
                    файл_наблюдения=os.path.join(нет_каталога, "watchlist.json"))
    check(errors, any("каталог" in п for п in res["предупреждения"]),
          "несуществующий каталог снимков молчит: %r" % res["предупреждения"])
    check(errors, all(z["статус"] == "новый" for z in res["найдено"]),
          "на недоступном кэше все ИНН должны быть «новыми»")

    # каталог снимков без прав на чтение
    закрытый = os.path.join(tmp, "закрытый")
    положить_снимок(закрытый, СБЕР, дней_назад=1)
    корень = os.path.join(закрытый, "snapshots")
    os.chmod(корень, 0o000)
    try:
        res = разобрать(mod, текст, "счёт.txt", каталог=закрытый,
                        файл_наблюдения=os.path.join(закрытый, "watchlist.json"))
        доступен = os.access(корень, os.R_OK | os.X_OK)
        if not доступен:        # под root права ничего не значат — кейс пропускаем
            check(errors, any("прав" in п for п in res["предупреждения"]),
                  "каталог без прав чтения молчит: %r" % res["предупреждения"])
    finally:
        os.chmod(корень, 0o755)

    # битый список наблюдения: разбор не падает, но и не молчит
    каталог, _ = _подставной_кэш(tmp, имя="кэш-для-битого")
    битый = os.path.join(tmp, "битый_watchlist.json")
    with open(битый, "w", encoding="utf-8") as fh:
        fh.write("{это не json")
    res2 = разобрать(mod, "Счёт: ИНН %s, ИНН %s, ИНН %s" % (СБЕР, ЮЛ2, ИП1),
                     "счёт.txt", каталог=каталог, файл_наблюдения=битый)
    check(errors, len(res2["найдено"]) == 3,
          "битый список наблюдения сломал разбор: %s" % инны(res2))
    check(errors, any("список наблюдения" in п for п in res2["предупреждения"]),
          "битый список наблюдения молчит: %r" % res2["предупреждения"])
    по_инн = {z["инн"]: z["статус"] for z in res2["найдено"]}
    check(errors, по_инн[ЮЛ2] == "новый",
          "ИНН из НЕпрочитанного списка наблюдения показан как проверенный: %r"
          % по_инн[ЮЛ2])

    # список наблюдения без прав чтения
    закрытый_список = os.path.join(tmp, "закрытый_watchlist.json")
    with open(закрытый_список, "w", encoding="utf-8") as fh:
        json.dump({"версия": 1, "контрагенты": []}, fh)
    os.chmod(закрытый_список, 0o000)
    try:
        res3 = разобрать(mod, текст, "счёт.txt", каталог=каталог,
                         файл_наблюдения=закрытый_список)
        if not os.access(закрытый_список, os.R_OK):
            check(errors, any("список наблюдения" in п
                              for п in res3["предупреждения"]),
                  "список без прав молчит: %r" % res3["предупреждения"])
    finally:
        os.chmod(закрытый_список, 0o644)
    return errors


def case_env_переопределение(mod, tmp):
    """INN_CHECK_CACHE / INN_CHECK_WATCHLIST — те же переменные, что у watchlist.py."""
    errors = []
    каталог, наблюдение = _подставной_кэш(tmp)
    было = (os.environ.get("INN_CHECK_CACHE"), os.environ.get("INN_CHECK_WATCHLIST"))
    os.environ["INN_CHECK_CACHE"] = каталог
    os.environ["INN_CHECK_WATCHLIST"] = наблюдение
    try:
        res = разобрать(mod, "ИНН %s и ИНН %s" % (СБЕР, ИП1), "счёт.txt")
        по_инн = {z["инн"]: z["статус"] for z in res["найдено"]}
        check(errors, по_инн.get(СБЕР) == "уже проверялся",
              "INN_CHECK_CACHE не учтён: %r" % по_инн.get(СБЕР))
        check(errors, по_инн.get(ИП1) == "новый",
              "новый ИНН из env-кэша: %r" % по_инн.get(ИП1))
    finally:
        for имя, значение in zip(("INN_CHECK_CACHE", "INN_CHECK_WATCHLIST"), было):
            if значение is None:
                os.environ.pop(имя, None)
            else:
                os.environ[имя] = значение
    return errors


