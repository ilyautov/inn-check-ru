def case_линейность(mod, tmp):
    """Дефект: `_границы_ок` копировал весь префикс документа на КАЖДОГО
    кандидата — 17 МБ CSV разбирались 141 секунду и съедали 2,5 ГБ."""
    errors = []

    def строки(n):
        return "".join("%d;ООО «Ромашка-%d»;%s;773601001\n" % (i, i, СБЕР)
                       for i in range(n))

    замеры = {}
    for n in (10000, 40000):
        текст = строки(n)
        начало = time.monotonic()
        найденные, _отбр, _прич = mod.разобрать_текст(текст, "выгрузка.csv")
        замеры[n] = time.monotonic() - начало
        check(errors, len(найденные) == n,
              "на %d строках найдено %d вхождений" % (n, len(найденные)))
    # вчетверо больше строк — примерно вчетверо больше времени. Квадратичный
    # разбор дал бы шестнадцатикратный рост; порог с запасом, чтобы не мигать.
    предел = 8 * замеры[10000] + 0.2
    check(errors, замеры[40000] <= предел,
          "разбор нелинеен: 10k — %.2f с, 40k — %.2f с (предел %.2f с)"
          % (замеры[10000], замеры[40000], предел))
    return errors


