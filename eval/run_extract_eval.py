def case_docx_колонтитул(mod, tmp):
    """Дефект: читался только word/document.xml — реквизиты поставщика из
    колонтитула терялись без единого слова, хотя имена файлов архива уже
    прочитаны."""
    errors = []
    пусто = пустой_кэш(tmp)

    def часть(текст):
        return ('<?xml version="1.0" encoding="UTF-8"?>'
                '<w:document xmlns:w="x"><w:body><w:p><w:r><w:t>%s</w:t>'
                '</w:r></w:p></w:body></w:document>' % текст)

    путь = os.path.join(tmp, "счёт_колонтитул.docx")
    with zipfile.ZipFile(путь, "w") as z:
        z.writestr("[Content_Types].xml", "<Types/>")
        z.writestr("word/document.xml", часть("Договор поставки № 44"))
        z.writestr("word/footer1.xml", часть("Поставщик ООО «А», ИНН %s" % ЮЛ2))
        z.writestr("word/header1.xml", часть("ИП Б, ИНН %s" % ИП1))
        z.writestr("word/styles.xml", "<styles/>")
        z.writestr("word/чертёж.xml", "<drawing/>")
    res = mod.собрать([(путь, Path(путь).read_bytes())], **пусто)
    check(errors, инны(res) == sorted([ЮЛ2, ИП1]),
          "ИНН из колонтитула потерян: %s" % инны(res))
    причина = res["файлы"][0].get("причина") or ""
    check(errors, "footer1.xml" in причина and "header1.xml" in причина,
          "не сказано, какие части прочитаны: %r" % причина)
    check(errors, "чертёж.xml" in причина and "НЕ читались" in причина,
          "непрочитанная часть архива замолчана: %r" % причина)
    check(errors, "styles.xml" not in причина,
          "служебная разметка попала в пометку: %r" % причина)
    return errors


