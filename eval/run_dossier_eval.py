def case_управляющие_символы(tmpdir):
    """Управляющие символы во входе: Markdown не рвётся, XML остаётся валидным.

    Вертикальная табуляция в названии делает word/document.xml not well-formed
    (Word файл не откроет), а в Markdown она и возврат каретки ломают строку
    у потребителя, который считает их переводом строки. Оба пути вывода
    обязаны чистить одно и то же.
    """
    вход = FIXTURES / "fetch_кавычки.json"
    сырой = вход.read_text(encoding="utf-8")
    ошибки = []
    for знак in (r"\u000b", r"\r", r"\n"):
        if знак not in сырой:
            ошибки.append("фикстура бесполезна: в JSON-тексте нет «%s»" % знак)
    if ошибки:
        return ошибки
    md, docx = Path(tmpdir) / "упр.md", Path(tmpdir) / "упр.docx"
    out, err, код = прогон(["--fetch", вход, "--в", md, "--docx", docx])
    if код != 0:
        return ["dossier.py вернул %d: %s" % (код, err.strip())]
    текст = md.read_text(encoding="utf-8")
    грязь = sorted({ord(c) for c in текст if ord(c) < 32 and c != "\n"}
                   | {ord(c) for c in текст if ord(c) == 127})
    if грязь:
        ошибки.append("в Markdown остались управляющие символы %s — строка "
                      "рвётся у потребителя" % грязь)
    первая = текст.splitlines()[0]
    if not первая.startswith("# Досье должной осмотрительности") \
            or "(ИНН " not in первая:
        ошибки.append("перевод строки в названии разорвал заголовок документа: %r"
                      % первая[:90])
    хвосты = [l for l in текст.splitlines() if "канал связи оборвался" in l]
    if not хвосты:
        ошибки.append("хвост причины после управляющих символов потерян")
    for l in хвосты:
        if not (l.startswith("|") and l.rstrip().endswith("|")):
            ошибки.append("управляющий символ разорвал строку таблицы: %r" % l[:90])
    try:
        сырьё = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
    except (OSError, KeyError, zipfile.BadZipFile) as e:
        return ошибки + ["word/document.xml не прочитан: %s" % e]
    запрещённые = sorted({ord(c) for c in сырьё
                          if ord(c) < 32 and c not in "\t\n\r"})
    if запрещённые:
        ошибки.append("word/document.xml содержит запрещённые XML 1.0 символы %s — "
                      "файл not well-formed, Word его не откроет" % запрещённые)
    ошибки += _проверить_docx(docx, обязательный_текст=["Ромашка & Ко"])
    return ошибки


def case_формат_сумм():
    """_рубли(): знак перед суммой, а не перед копейками."""
    досье = _модуль("dossier")
    if досье is None:
        return ["scripts/dossier.py не импортируется как модуль"]
    ожидания = [(-1234.56, "-1 234,56 руб."), (1234.56, "1 234,56 руб."),
                (-1234, "-1 234 руб."), (4200000, "4 200 000 руб."),
                ("4200000", "4 200 000 руб."), (0, "0 руб."),
                (396350822000, "396 350 822 000 руб.")]
    ошибки = []
    for значение, ждём in ожидания:
        факт = досье._рубли(значение)
        if isinstance(факт, str):
            факт = факт.replace("\u00a0", " ")
        if факт != ждём:
            ошибки.append("_рубли(%r) = %r, ожидалось %r" % (значение, факт, ждём))
    return ошибки


