#!/usr/bin/env python3
"""
run_dossier_eval.py — офлайн-прогон scripts/dossier.py по фикстурам
eval/fixtures/dossier/. Сети не требует, чистый stdlib, гоняется в CI.

Что проверяется (спек волны 3, §3):
  * Markdown содержит все пять обязательных разделов;
  * источник со состоянием «не проверено» попадает в раздел «НЕ проверено»
    и не теряется по дороге (проверяется поимённо для каждого такого источника,
    вместе с причиной из `_доступность`);
  * источники «не проверено» из вспомогательных входов (--санкции, --граф)
    тоже не теряются;
  * хеш входного JSON стоит в шапке и меняется при любой правке входа;
  * DOCX — валидный ZIP из четырёх частей WordprocessingML, XML разбирается,
    текст всех пяти разделов в документе присутствует;
  * профиль «нейтрально» (формулировка «факты») не печатает ни вердикт,
    ни рекомендацию — вердикт там был бы заключением;
  * экранирование: компания «Ромашка & Ко» с кавычками, амперсандом и угловыми
    скобками не ломает ни Markdown-таблицу, ни XML документа.

Разбор XML требует рабочего pyexpat. Если интерпретатор собран без него
(встречается на macOS с поломанным homebrew-питоном), XML-кейсы честно
помечаются ПРОПУЩЕН, а не выдаются за пройденные.
"""

import hashlib
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOSSIER = ROOT / "scripts" / "dossier.py"
FIXTURES = ROOT / "eval" / "fixtures" / "dossier"

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"

РАЗДЕЛЫ = (
    "1. Кто проверен и когда",
    "2. Что проверено",
    "3. Что НЕ проверено и почему",
    "4. Что найдено в источниках",
    "5. Границы этого документа",
)

ЧАСТИ_DOCX = ("[Content_Types].xml", "_rels/.rels",
              "word/_rels/document.xml.rels", "word/document.xml")

try:
    import xml.etree.ElementTree as ET
    ET.fromstring("<a/>")
    XML_ДОСТУПЕН, XML_ПРИЧИНА = True, None
except Exception as e:
    ET, XML_ДОСТУПЕН, XML_ПРИЧИНА = None, False, str(e)


def прогон(аргументы):
    """(stdout, stderr, код) запуска dossier.py тем же интерпретатором."""
    p = subprocess.run([sys.executable, str(DOSSIER)] + [str(a) for a in аргументы],
                       capture_output=True, text=True, check=False)
    return p.stdout, p.stderr, p.returncode


def markdown(фикстура, *хвост):
    out, err, код = прогон(["--fetch", FIXTURES / фикстура] + list(хвост))
    if код != 0:
        return None, ["dossier.py вернул %d: %s" % (код, err.strip())]
    return out, []


def не_проверенные_источники(фикстура):
    """{id: причина} источников со состоянием «не проверено» во входном JSON."""
    данные = json.loads((FIXTURES / фикстура).read_text(encoding="utf-8"))
    дост = данные.get("_доступность") or {}
    return {sid: (v or {}).get("причина")
            for sid, v in дост.items()
            if isinstance(v, dict) and v.get("состояние") == "не проверено"}


def _раздел_текста(текст, номер):
    """Кусок Markdown от заголовка раздела `номер` до следующего «## »."""
    начало = текст.find("## " + РАЗДЕЛЫ[номер - 1])
    if начало < 0:
        return ""
    конец = текст.find("\n## ", начало + 1)
    return текст[начало:конец if конец > 0 else len(текст)]


# --- кейсы -------------------------------------------------------------------

def case_разделы(фикстура):
    текст, ошибки = markdown(фикстура)
    if ошибки:
        return ошибки
    for заголовок in РАЗДЕЛЫ:
        if ("## " + заголовок) not in текст:
            ошибки.append("нет раздела «%s»" % заголовок)
    if not текст.startswith("# Досье должной осмотрительности"):
        ошибки.append("документ не начинается с заголовка досье")
    for запрещено in ("справка выдана", "гербов", "Печать:", "М.П."):
        if запрещено.lower() in текст.lower() and запрещено != "гербов":
            ошибки.append("документ мимикрирует под справку госоргана: «%s»" % запрещено)
    for обязательно in ("не является заключением", "ДО сделки",
                        "не заменяет проверку по закрытым данным"):
        if обязательно not in текст:
            ошибки.append("в документе нет юридической рамки: «%s»" % обязательно)
    return ошибки


def case_не_проверено_не_теряется(фикстура):
    текст, ошибки = markdown(фикстура)
    if ошибки:
        return ошибки
    раздел3 = _раздел_текста(текст, 3)
    if not раздел3:
        return ["раздел 3 не найден"]
    непроверенные = не_проверенные_источники(фикстура)
    if not непроверенные:
        return ["фикстура бесполезна: в ней нет источников «не проверено»"]
    sources = _реестр()
    for sid, причина in непроверенные.items():
        имя = ((sources or {}).get(sid) or {}).get("название") or sid
        if имя not in раздел3:
            ошибки.append("источник «%s» со состоянием «не проверено» потерян: "
                          "его нет в разделе 3" % имя)
        if причина and причина[:40] not in раздел3:
            ошибки.append("причина источника «%s» не доехала до раздела 3" % имя)
    return ошибки


def _реестр():
    try:
        sys.path.insert(0, str(ROOT / "scripts"))
        import sources
        return sources.SOURCES
    except Exception:
        return {}


def case_вспомогательные_пробелы():
    """«не проверено» из --санкции и --граф тоже попадает в раздел 3."""
    текст, ошибки = markdown("fetch_отсрочка.json",
                             "--fin", FIXTURES / "fin_отсрочка.json",
                             "--санкции", FIXTURES / "sanctions_частично.json",
                             "--граф", FIXTURES / "graph_ok.json")
    if ошибки:
        return ошибки
    раздел3 = _раздел_текста(текст, 3)
    for кусок in ("перечень не скачан: TLS-ошибка",
                  "соседи по адресу за глубиной 2 не обходились"):
        if кусок not in раздел3:
            ошибки.append("пробел вспомогательного входа потерян: «%s»" % кусок)
    раздел2 = _раздел_текста(текст, 2)
    for кусок in ("Сверка с санкционными перечнями", "Граф связей"):
        if кусок not in раздел2:
            ошибки.append("подраздел «%s» не попал в раздел 2" % кусок)
    return ошибки


def case_единицы_гирбо():
    """ГИР БО публикует тысячи рублей — в досье суммы обязаны быть рублями.

    Документ прикладывают к возражениям на акт налоговой: сумма, заниженная
    в тысячу раз, обесценивает его целиком. Сверено с дампом ФНС revexp
    19.09.2026 — отношение дохода в рублях к стр. 2110 у трёх ИНН 1010,
    1002 и 1025. В фикстуре выручка 2025 г. = 396 350 822 тыс. руб.
    """
    текст, ошибки = markdown("fetch_отсрочка.json")
    if ошибки:
        return ошибки
    # разряды разделены неразрывным пробелом — сравниваем по обычному
    раздел2 = _раздел_текста(текст, 2).replace("\u00a0", " ")
    if "396 350 822 000 руб." not in раздел2:
        ошибки.append("выручка не пересчитана в рубли: в таблице ГИР БО нет "
                      "«396 350 822 000 руб.»")
    if "396 350 822 руб." in раздел2:
        ошибки.append("выручка напечатана в тысячах рублей как рубли — "
                      "занижение в 1000 раз")
    if "тысячах рублей" not in раздел2:
        ошибки.append("таблица ГИР БО не оговаривает единицы источника")
    return ошибки


def case_хеш(tmpdir):
    """Хеш входа стоит в шапке и меняется при правке входа."""
    исходный = FIXTURES / "fetch_отсрочка.json"
    текст, ошибки = markdown("fetch_отсрочка.json")
    if ошибки:
        return ошибки
    ожидаемый = hashlib.sha256(исходный.read_bytes()).hexdigest()
    m = re.search(r"sha256 исходного файла:\*\* ([0-9a-f]{64})", текст)
    if not m:
        return ["в шапке нет строки «sha256 исходного файла» с хешем"]
    if m.group(1) != ожидаемый:
        ошибки.append("хеш в документе %s != sha256 файла %s"
                      % (m.group(1), ожидаемый))
    # Правим вход — хеш обязан измениться.
    правленый = Path(tmpdir) / "fetch_правленый.json"
    данные = json.loads(исходный.read_text(encoding="utf-8"))
    данные["егрюл"]["наименование_краткое"] = "АО \"ДИКСИ ЮГ\" (правка)"
    правленый.write_text(json.dumps(данные, ensure_ascii=False, indent=1) + "\n",
                         encoding="utf-8")
    out, err, код = прогон(["--fetch", правленый])
    if код != 0:
        return ошибки + ["прогон по правленому входу упал: %s" % err.strip()]
    m2 = re.search(r"sha256 исходного файла:\*\* ([0-9a-f]{64})", out)
    if not m2:
        ошибки.append("в документе по правленому входу нет хеша")
    elif m2.group(1) == m.group(1):
        ошибки.append("хеш не изменился при изменении входа — неизменность "
                      "входных данных не фиксируется")
    return ошибки


def case_нейтрально_без_вердикта():
    текст, ошибки = markdown("fetch_нейтрально.json")
    if ошибки:
        return ошибки
    for запрещено in ("**Вердикт:**", "**Рекомендация:**"):
        if запрещено in текст:
            ошибки.append("профиль «нейтрально» печатает «%s» — это было бы "
                          "заключением" % запрещено.strip("*:"))
    if "фактический" not in текст:
        ошибки.append("в разделе 4 нет пояснения, почему вердикта нет")
    # Вердиктный профиль, наоборот, обязан их печатать.
    текст2, ошибки2 = markdown("fetch_отсрочка.json")
    if ошибки2:
        return ошибки + ошибки2
    for обязательно in ("**Вердикт:**", "**Рекомендация:**"):
        if обязательно not in текст2:
            ошибки.append("вердиктный профиль «отсрочка» не печатает «%s»"
                          % обязательно)
    return ошибки


def case_экранирование(tmpdir):
    """Кавычки, амперсанд и угловые скобки в названии не ломают ни MD, ни XML."""
    docx = Path(tmpdir) / "кавычки.docx"
    md = Path(tmpdir) / "кавычки.md"
    out, err, код = прогон(["--fetch", FIXTURES / "fetch_кавычки.json",
                            "--в", md, "--docx", docx])
    if код != 0:
        return ["dossier.py вернул %d: %s" % (код, err.strip())]
    текст = md.read_text(encoding="utf-8")
    ошибки = []
    if "Ромашка & Ко" not in текст:
        ошибки.append("название с амперсандом не доехало до Markdown")
    if "&amp;" in текст:
        ошибки.append("в Markdown просочилось XML-экранирование (&amp;)")
    # Строки таблиц не должны разваливаться лишними разделителями колонок.
    for строка in текст.splitlines():
        if строка.startswith("|") and not строка.startswith("|---"):
            колонок = len(re.findall(r"(?<!\\)\|", строка)) - 1
            if колонок not in (2, 5, 6):
                ошибки.append("строка таблицы с %d колонками: %s"
                              % (колонок, строка[:80]))
    ошибки += _проверить_docx(docx, обязательный_текст=["Ромашка & Ко"])
    if XML_ДОСТУПЕН:
        документ = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
        if "&amp;" not in документ:
            ошибки.append("амперсанд в word/document.xml не экранирован")
        if "<Юг>" in документ:
            ошибки.append("угловые скобки из данных попали в XML сырыми")
    return ошибки


def _проверить_docx(путь, обязательный_текст=()):
    ошибки = []
    if not Path(путь).exists():
        return ["DOCX не создан: %s" % путь]
    try:
        z = zipfile.ZipFile(путь)
    except zipfile.BadZipFile as e:
        return ["DOCX не открывается как ZIP: %s" % e]
    битый = z.testzip()
    if битый:
        ошибки.append("битая запись в ZIP: %s" % битый)
    имена = z.namelist()
    for часть in ЧАСТИ_DOCX:
        if часть not in имена:
            ошибки.append("в DOCX нет обязательной части %s" % часть)
    if not XML_ДОСТУПЕН:
        return ошибки
    тексты = []
    for имя in имена:
        try:
            корень = ET.fromstring(z.read(имя))
        except ET.ParseError as e:
            ошибки.append("%s не разбирается как XML: %s" % (имя, e))
            continue
        if имя == "word/document.xml":
            if not корень.tag.endswith("}document"):
                ошибки.append("корень document.xml — %s, а не w:document" % корень.tag)
            тексты = [(t.text or "") for t in корень.iter(W + "t")]
    весь = "".join(тексты)
    for заголовок in РАЗДЕЛЫ:
        if заголовок not in весь:
            ошибки.append("в тексте DOCX нет раздела «%s»" % заголовок)
    for кусок in обязательный_текст:
        if кусок not in весь:
            ошибки.append("в тексте DOCX нет «%s»" % кусок)
    if not [t for t in тексты if t.strip()]:
        ошибки.append("в DOCX нет ни одного непустого текстового прогона")
    return ошибки


def case_docx(tmpdir):
    docx = Path(tmpdir) / "досье.docx"
    out, err, код = прогон(["--fetch", FIXTURES / "fetch_отсрочка.json",
                            "--fin", FIXTURES / "fin_отсрочка.json",
                            "--docx", docx, "--предмет", "поставка ГСМ",
                            "--сумма", "4200000"])
    if код != 0:
        return ["dossier.py вернул %d: %s" % (код, err.strip())]
    ошибки = _проверить_docx(docx, обязательный_текст=[
        "поставка ГСМ", "4 200 000 руб.", "5036045205"])
    if out.strip():
        ошибки.append("при --docx документ не должен дублироваться в stdout")
    return ошибки


def case_без_fetch():
    out, err, код = прогон([])
    ошибки = []
    if код == 0:
        ошибки.append("запуск без аргументов обязан быть ошибкой")
    out, err, код = прогон(["--профиль", "отсрочка"])
    if код == 0 or "--fetch" not in err:
        ошибки.append("без --fetch должна быть внятная ошибка про --fetch")
    return ошибки


def case_мусорный_вход(tmpdir):
    """Битый вход — русская причина на stderr, а не traceback."""
    мусор = Path(tmpdir) / "мусор.json"
    мусор.write_text("{это не json", encoding="utf-8")
    out, err, код = прогон(["--fetch", мусор])
    ошибки = []
    if "Traceback" in err:
        ошибки.append("битый вход уронил скрипт traceback'ом")
    if код == 0:
        ошибки.append("битый вход обязан давать ненулевой код возврата")
    if "не разбирается как JSON" not in err:
        ошибки.append("нет внятной русской причины: %s" % err.strip()[:120])
    return ошибки


КЕЙСЫ_БЕЗ_TMP = [
    ("все пять разделов (отсрочка)", lambda: case_разделы("fetch_отсрочка.json")),
    ("все пять разделов (кавычки)", lambda: case_разделы("fetch_кавычки.json")),
    ("единицы ГИР БО: тысячи рублей", case_единицы_гирбо),
    ("«не проверено» не теряется (отсрочка)",
     lambda: case_не_проверено_не_теряется("fetch_отсрочка.json")),
    ("«не проверено» не теряется (кавычки)",
     lambda: case_не_проверено_не_теряется("fetch_кавычки.json")),
    ("пробелы --санкции/--граф не теряются", case_вспомогательные_пробелы),
    ("профиль «нейтрально» без вердикта и рекомендации",
     case_нейтрально_без_вердикта),
    ("--fetch обязателен", case_без_fetch),
]

КЕЙСЫ_С_TMP = [
    ("хеш входа в шапке и меняется при правке входа", case_хеш),
    ("DOCX: валидный ZIP, разбираемый XML, текст разделов", case_docx),
    ("экранирование: ООО «Ромашка & Ко»", case_экранирование),
    ("битый вход — причина, а не traceback", case_мусорный_вход),
]


def main():
    if not DOSSIER.exists():
        print("FAIL: нет scripts/dossier.py")
        return 1
    if not XML_ДОСТУПЕН:
        print("ВНИМАНИЕ: xml.etree недоступен в этом интерпретаторе (%s)."
              % XML_ПРИЧИНА)
        print("          Разбор word/document.xml ПРОПУЩЕН — запустите eval "
              "питоном с рабочим pyexpat.")
        print()
    всего = failed = 0
    with tempfile.TemporaryDirectory() as tmpdir:
        кейсы = [(имя, fn) for имя, fn in КЕЙСЫ_БЕЗ_TMP]
        кейсы += [(имя, (lambda f=fn: f(tmpdir))) for имя, fn in КЕЙСЫ_С_TMP]
        for имя, fn in кейсы:
            всего += 1
            ошибки = fn()
            if ошибки:
                failed += 1
                print("FAIL %s" % имя)
                for e in ошибки:
                    print("  - %s" % e)
            else:
                print("PASS %s" % имя)
    if failed:
        print("FAIL: %d/%d кейсов упало" % (failed, всего))
        return 1
    print("PASS: все %d кейсов зелёные%s"
          % (всего, "" if XML_ДОСТУПЕН else " (XML-разбор пропущен, см. выше)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
