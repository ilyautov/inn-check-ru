def case_разделы(фикстура):
    текст, ошибки = markdown(фикстура)
    if ошибки:
        return ошибки
    for заголовок in РАЗДЕЛЫ:
        if ("## " + заголовок) not in текст:
            ошибки.append("нет раздела «%s»" % заголовок)
    if not текст.startswith("# Досье должной осмотрительности"):
        ошибки.append("документ не начинается с заголовка досье")
    for запрещено in ("справка выдана", "гербов", "Печать:", "М.П."):
        if запрещено.lower() in текст.lower() and запрещено != "гербов":
            ошибки.append("документ мимикрирует под справку госоргана: «%s»" % запрещено)
    for обязательно in ("не является заключением", "ДО сделки",
                        "не заменяет проверку по закрытым данным"):
        if обязательно not in текст:
            ошибки.append("в документе нет юридической рамки: «%s»" % обязательно)
    return ошибки


def case_не_проверено_не_теряется(фикстура):
    текст, ошибки = markdown(фикстура)
    if ошибки:
        return ошибки
    раздел3 = _раздел_текста(текст, 3)
    if not раздел3:
        return ["раздел 3 не найден"]
    непроверенные = не_проверенные_источники(фикстура)
    if not непроверенные:
        return ["фикстура бесполезна: в ней нет источников «не проверено»"]
    sources = _реестр()
    for sid, причина in непроверенные.items():
        имя = ((sources or {}).get(sid) or {}).get("название") or sid
        if имя not in раздел3:
            ошибки.append("источник «%s» со состоянием «не проверено» потерян: "
                          "его нет в разделе 3" % имя)
        if причина and причина[:40] not in раздел3:
            ошибки.append("причина источника «%s» не доехала до раздела 3" % имя)
    return ошибки


def _реестр():
    try:
        sys.path.insert(0, str(ROOT / "scripts"))
        import sources
        return sources.SOURCES
    except Exception:
        return {}


def _модуль(имя):
    """scripts/<имя> как модуль; None — если не импортируется."""
    try:
        sys.path.insert(0, str(ROOT / "scripts"))
        return __import__(имя)
    except Exception:
        return None


def _вердикт(фикстура, профиль=None):
    """profiles.resolve() по фикстуре — эталон того, что обязано быть в документе."""
    profiles = _модуль("profiles")
    if profiles is None:
        return None
    данные = json.loads((FIXTURES / фикстура).read_text(encoding="utf-8"))
    return profiles.resolve(данные, None, профиль or данные.get("профиль"))


def _строки_таблиц(кусок):
    """Строки Markdown-таблиц внутри куска документа (без разделителей)."""
    return [l for l in кусок.splitlines()
            if l.startswith("|") and not l.startswith("|---")]


def case_вспомогательные_пробелы():
    """«не проверено» из --санкции и --граф тоже попадает в раздел 3."""
    текст, ошибки = markdown("fetch_отсрочка.json",
                             "--fin", FIXTURES / "fin_отсрочка.json",
                             "--санкции", FIXTURES / "sanctions_частично.json",
                             "--граф", FIXTURES / "graph_ok.json")
    if ошибки:
        return ошибки
    раздел3 = _раздел_текста(текст, 3)
    for кусок in ("перечень не скачан: TLS-ошибка",
                  "соседи по адресу за глубиной 2 не обходились"):
        if кусок not in раздел3:
            ошибки.append("пробел вспомогательного входа потерян: «%s»" % кусок)
    раздел2 = _раздел_текста(текст, 2)
    for кусок in ("Сверка с санкционными перечнями", "Граф связей"):
        if кусок not in раздел2:
            ошибки.append("подраздел «%s» не попал в раздел 2" % кусок)
    return ошибки


def case_пробел_fin_вне_сигналов(tmpdir):
    """Пробел финансового разбора, не доехавший до сигнала профиля, виден.

    fin_scoring кладёт список «не_проверено» не в корень ответа, а в
    «финансовый_профиль». Досье искало его только в корне: страховка
    существовала и никогда не срабатывала. Сегодня все пять пробелов
    fin_scoring всплывают другим путём — резолвер профиля дописывает
    причину в текст сигнала, — и дефект не виден. Но показатель, у
    которого сигнала в профиле нет, исчезал бы из документа молча.

    Кейс берёт ровно такой пробел (формулировка, которой нет ни в одном
    сигнале) и требует его в разделе 3. Второй проверкой — что пробел,
    уже названный в 3.2, не печатается дважды: раздел «что не проверено»
    читают целиком, и дубль в нём стоит дорого.
    """
    fin = json.loads((FIXTURES / "fin_отсрочка.json").read_text(encoding="utf-8"))
    профиль = fin.setdefault("финансовый_профиль", {})
    профиль["не_проверено"] = [
        "рентабельность продаж — нет строки 2200 за последний год",
        "текущая ликвидность — нет строк 1200/1500",
    ]
    путь = Path(tmpdir) / "fin_с_пробелом.json"
    путь.write_text(json.dumps(fin, ensure_ascii=False), encoding="utf-8")

    текст, ошибки = markdown("fetch_отсрочка.json", "--fin", путь)
    if ошибки:
        return ошибки
    раздел3 = _раздел_текста(текст, 3)
    сирота = "рентабельность продаж — нет строки 2200"
    if сирота not in раздел3:
        ошибки.append("пробел финансового разбора вне сигналов профиля потерян: "
                      "«%s» нет в разделе 3" % сирота)
    if раздел3.count("текущая ликвидность — нет строк 1200/1500") > 1:
        ошибки.append("пробел, уже названный в 3.2, напечатан в разделе 3 дважды")
    return ошибки


def case_единицы_гирбо():
    """ГИР БО публикует тысячи рублей — в досье суммы обязаны быть рублями.

    Документ прикладывают к возражениям на акт налоговой: сумма, заниженная
    в тысячу раз, обесценивает его целиком. Сверено с дампом ФНС revexp
    19.09.2026 — отношение дохода в рублях к стр. 2110 у трёх ИНН 1010,
    1002 и 1025. В фикстуре выручка 2025 г. = 396 350 822 тыс. руб.
    """
    текст, ошибки = markdown("fetch_отсрочка.json")
    if ошибки:
        return ошибки
    # разряды разделены неразрывным пробелом — сравниваем по обычному
    раздел2 = _раздел_текста(текст, 2).replace("\u00a0", " ")
    if "396 350 822 000 руб." not in раздел2:
        ошибки.append("выручка не пересчитана в рубли: в таблице ГИР БО нет "
                      "«396 350 822 000 руб.»")
    if "396 350 822 руб." in раздел2:
        ошибки.append("выручка напечатана в тысячах рублей как рубли — "
                      "занижение в 1000 раз")
    if "тысячах рублей" not in раздел2:
        ошибки.append("таблица ГИР БО не оговаривает единицы источника")
    return ошибки


def case_хеш(tmpdir):
    """Хеш входа стоит в шапке и меняется при правке входа."""
    исходный = FIXTURES / "fetch_отсрочка.json"
    текст, ошибки = markdown("fetch_отсрочка.json")
    if ошибки:
        return ошибки
    ожидаемый = hashlib.sha256(исходный.read_bytes()).hexdigest()
    m = re.search(r"sha256 исходного файла:\*\* ([0-9a-f]{64})", текст)
    if not m:
        return ["в шапке нет строки «sha256 исходного файла» с хешем"]
    if m.group(1) != ожидаемый:
        ошибки.append("хеш в документе %s != sha256 файла %s"
                      % (m.group(1), ожидаемый))
    # Правим вход — хеш обязан измениться.
    правленый = Path(tmpdir) / "fetch_правленый.json"
    данные = json.loads(исходный.read_text(encoding="utf-8"))
    данные["егрюл"]["наименование_краткое"] = "АО \"ДИКСИ ЮГ\" (правка)"
    правленый.write_text(json.dumps(данные, ensure_ascii=False, indent=1) + "\n",
                         encoding="utf-8")
    out, err, код = прогон(["--fetch", правленый])
    if код != 0:
        return ошибки + ["прогон по правленому входу упал: %s" % err.strip()]
    m2 = re.search(r"sha256 исходного файла:\*\* ([0-9a-f]{64})", out)
    if not m2:
        ошибки.append("в документе по правленому входу нет хеша")
    elif m2.group(1) == m.group(1):
        ошибки.append("хеш не изменился при изменении входа — неизменность "
                      "входных данных не фиксируется")
    return ошибки


def case_нейтрально_без_вердикта():
    текст, ошибки = markdown("fetch_нейтрально.json")
    if ошибки:
        return ошибки
    for запрещено in ("**Вердикт:**", "**Рекомендация:**"):
        if запрещено in текст:
            ошибки.append("профиль «нейтрально» печатает «%s» — это было бы "
                          "заключением" % запрещено.strip("*:"))
    if "фактический" not in текст:
        ошибки.append("в разделе 4 нет пояснения, почему вердикта нет")
    # Вердиктный профиль, наоборот, обязан их печатать.
    текст2, ошибки2 = markdown("fetch_отсрочка.json")
    if ошибки2:
        return ошибки + ошибки2
    for обязательно in ("**Вердикт:**", "**Рекомендация:**"):
        if обязательно not in текст2:
            ошибки.append("вердиктный профиль «отсрочка» не печатает «%s»"
                          % обязательно)
    return ошибки


def case_экранирование(tmpdir):
    """Кавычки, амперсанд и угловые скобки в названии не ломают ни MD, ни XML."""
    docx = Path(tmpdir) / "кавычки.docx"
    md = Path(tmpdir) / "кавычки.md"
    out, err, код = прогон(["--fetch", FIXTURES / "fetch_кавычки.json",
                            "--в", md, "--docx", docx])
    if код != 0:
        return ["dossier.py вернул %d: %s" % (код, err.strip())]
    текст = md.read_text(encoding="utf-8")
    ошибки = []
    if "Ромашка & Ко" not in текст:
        ошибки.append("название с амперсандом не доехало до Markdown")
    if "&amp;" in текст:
        ошибки.append("в Markdown просочилось XML-экранирование (&amp;)")
    # Строки таблиц не должны разваливаться лишними разделителями колонок.
    for строка in текст.splitlines():
        if строка.startswith("|") and not строка.startswith("|---"):
            колонок = len(re.findall(r"(?<!\\)\|", строка)) - 1
            if колонок not in (2, 5, 6):
                ошибки.append("строка таблицы с %d колонками: %s"
                              % (колонок, строка[:80]))
    ошибки += _проверить_docx(docx, обязательный_текст=["Ромашка & Ко"])
    if XML_ДОСТУПЕН:
        документ = zipfile.ZipFile(docx).read("word/document.xml").decode("utf-8")
        if "&amp;" not in документ:
            ошибки.append("амперсанд в word/document.xml не экранирован")
        if "<Юг>" in документ:
            ошибки.append("угловые скобки из данных попали в XML сырыми")
    return ошибки


def _проверить_docx(путь, обязательный_текст=()):
    ошибки = []
    if not Path(путь).exists():
        return ["DOCX не создан: %s" % путь]
    try:
        z = zipfile.ZipFile(путь)
    except zipfile.BadZipFile as e:
        return ["DOCX не открывается как ZIP: %s" % e]
    битый = z.testzip()
    if битый:
        ошибки.append("битая запись в ZIP: %s" % битый)
    имена = z.namelist()
    for часть in ЧАСТИ_DOCX:
        if часть not in имена:
            ошибки.append("в DOCX нет обязательной части %s" % часть)
    if not XML_ДОСТУПЕН:
        return ошибки
    тексты = []
    for имя in имена:
        try:
            корень = ET.fromstring(z.read(имя))
        except ET.ParseError as e:
            ошибки.append("%s не разбирается как XML: %s" % (имя, e))
            continue
        if имя == "word/document.xml":
            if not корень.tag.endswith("}document"):
                ошибки.append("корень document.xml — %s, а не w:document" % корень.tag)
            тексты = [(t.text or "") for t in корень.iter(W + "t")]
    весь = "".join(тексты)
    for заголовок in РАЗДЕЛЫ:
        if заголовок not in весь:
            ошибки.append("в тексте DOCX нет раздела «%s»" % заголовок)
    for кусок in обязательный_текст:
        if кусок not in весь:
            ошибки.append("в тексте DOCX нет «%s»" % кусок)
    if not [t for t in тексты if t.strip()]:
        ошибки.append("в DOCX нет ни одного непустого текстового прогона")
    return ошибки


def case_docx(tmpdir):
    docx = Path(tmpdir) / "досье.docx"
    out, err, код = прогон(["--fetch", FIXTURES / "fetch_отсрочка.json",
                            "--fin", FIXTURES / "fin_отсрочка.json",
                            "--docx", docx, "--предмет", "поставка ГСМ",
                            "--сумма", "4200000"])
    if код != 0:
        return ["dossier.py вернул %d: %s" % (код, err.strip())]
    ошибки = _проверить_docx(docx, обязательный_текст=[
        "поставка ГСМ", "4 200 000 руб.", "5036045205"])
    if out.strip():
        ошибки.append("при --docx документ не должен дублироваться в stdout")
    return ошибки


def case_без_fetch():
    out, err, код = прогон([])
    ошибки = []
    if код == 0:
        ошибки.append("запуск без аргументов обязан быть ошибкой")
    out, err, код = прогон(["--профиль", "отсрочка"])
    if код == 0 or "--fetch" not in err:
        ошибки.append("без --fetch должна быть внятная ошибка про --fetch")
    return ошибки


def case_мусорный_вход(tmpdir):
    """Битый вход — русская причина на stderr, а не traceback."""
    мусор = Path(tmpdir) / "мусор.json"
    мусор.write_text("{это не json", encoding="utf-8")
    out, err, код = прогон(["--fetch", мусор])
    ошибки = []
    if "Traceback" in err:
        ошибки.append("битый вход уронил скрипт traceback'ом")
    if код == 0:
        ошибки.append("битый вход обязан давать ненулевой код возврата")
    if "не разбирается как JSON" not in err:
        ошибки.append("нет внятной русской причины: %s" % err.strip()[:120])
    return ошибки


def case_нет_доступности():
    """Вход без `_доступность` и `_итог_проверки` — самое опасное место документа.

    «Не проверено» не имеет права стать «все источники ответили», а строка
    «Проверка состоялась: нет» не имеет права пропасть вместе с блоком итога.
    """
    данные = json.loads((FIXTURES / "fetch_ручной.json").read_text(encoding="utf-8"))
    ошибки = []
    if данные.get("_доступность") or данные.get("_итог_проверки"):
        return ["фикстура бесполезна: в ней есть «_доступность»/«_итог_проверки»"]
    текст, ош = markdown("fetch_ручной.json")
    if ош:
        return ош
    раздел2, раздел3 = _раздел_текста(текст, 2), _раздел_текста(текст, 3)
    for ложь in ("Все источники, к которым обращался инструмент, ответили",
                 "Все источники реестра ответили"):
        if ложь in текст:
            ошибки.append("о источниках нет никаких сведений, а документ пишет "
                          "«%s»" % ложь)
    if "**Проверка состоялась:** нет" not in раздел2:
        ошибки.append("без «_итог_проверки» пропала строка «Проверка состоялась: "
                      "нет» — молчание читается как «состоялась»")
    for sid, d in (_реестр() or {}).items():
        имя = d.get("название") or sid
        if имя not in раздел3:
            ошибки.append("источник «%s» без сведений во входе не попал в раздел 3"
                          % имя)
    if "сведений во входе нет" not in раздел3:
        ошибки.append("в разделе 3 нет состояния «сведений во входе нет»")
    return ошибки


def case_без_реестра():
    """Реестр источников не импортировался — перечень строить не из чего.

    Единственный путь, на котором таблица источников пуста. Пустая таблица не
    даёт права написать «все источники ответили»: о них просто ничего не
    известно, и сам факт деградации обязан быть в документе.
    """
    досье = _модуль("dossier")
    if досье is None:
        return ["scripts/dossier.py не импортируется как модуль"]
    мета = {"сформирован": "01.01.2026 00:00:00 (UTC+03:00)", "версия": "тест",
            "хеш": "0" * 64, "размер": 0, "файл": "нет.json"}
    блоки = досье.собрать({"инн": "7707083893"}, мета, sources=None,
                          входы={"--fin": None, "--санкции": None, "--граф": None})
    текст = досье.в_markdown(блоки)
    ошибки = []
    for ложь in ("Все источники, к которым обращался инструмент, ответили",
                 "Все источники реестра ответили"):
        if ложь in текст:
            ошибки.append("реестра нет и состояний нет, а документ пишет «%s»"
                          % ложь)
    if "Перечень источников не построен" not in _раздел_текста(текст, 2):
        ошибки.append("раздел 2 не говорит, что перечень источников не построен")
    if "Перечень источников не построен" not in _раздел_текста(текст, 3):
        ошибки.append("раздел 3 не говорит, что перечень источников не построен")
    if "не импортируется" not in _раздел_текста(текст, 3):
        ошибки.append("деградация «реестр источников недоступен» не названа "
                      "в разделе 3")
    if "**Проверка состоялась:** нет" not in _раздел_текста(текст, 2):
        ошибки.append("без итога проверки пропала строка «Проверка состоялась: нет»")
    return ошибки


def case_источник_вне_входа():
    """Источник, которого нет в `_доступность`, обязан быть в разделах 2 и 3.

    Квик-режим и ручной JSON выглядят именно так. Выпавший deal-killer читается
    как проверенный, а шапка при этом продолжает объявлять 12 источников.
    """
    данные = json.loads((FIXTURES / "fetch_квик.json").read_text(encoding="utf-8"))
    дост = данные.get("_доступность") or {}
    итог = данные.get("_итог_проверки") or {}
    реестр = _реестр() or {}
    пропавшие = [sid for sid in реестр if sid not in дост]
    if not пропавшие:
        return ["фикстура бесполезна: во входе есть все источники реестра"]
    if not [sid for sid in пропавшие if (реестр[sid] or {}).get("deal_killer")]:
        return ["фикстура бесполезна: среди пропавших нет deal-killer-источника"]
    текст, ошибки = markdown("fetch_квик.json")
    if ошибки:
        return ошибки
    раздел2, раздел3 = _раздел_текста(текст, 2), _раздел_текста(текст, 3)
    for sid in пропавшие:
        имя = (реестр[sid] or {}).get("название") or sid
        строки2 = [l for l in _строки_таблиц(раздел2) if имя in l]
        if not строки2:
            ошибки.append("источник «%s» отсутствует во входе и выпал из таблицы "
                          "раздела 2" % имя)
        elif "сведений во входе нет" not in строки2[0]:
            ошибки.append("источник «%s» без записи во входе показан как "
                          "проверенный: %s" % (имя, строки2[0][:120]))
        if имя not in раздел3:
            ошибки.append("источник «%s» отсутствует во входе и выпал из раздела 3 "
                          "— «что НЕ проверено» его не перечисляет" % имя)
    if "Расхождение" not in раздел2:
        ошибки.append("в шапке объявлено источников %s, состояний во входе %d — "
                      "документ молчит о расхождении"
                      % (итог.get("источников"), len(дост)))
    return ошибки


def case_пояснение_состояний():
    """Таблица раздела 2 не имеет права объяснить «не проверено» как ответ."""
    текст, ошибки = markdown("fetch_отсрочка.json")
    if ошибки:
        return ошибки
    раздел2 = _раздел_текста(текст, 2)
    без_данных = [l for l in _строки_таблиц(раздел2)
                  if "| не проверено (" in l or "| сведений во входе нет (" in l]
    if not без_данных:
        return ["фикстура бесполезна: в таблице раздела 2 нет непроверенных источников"]
    for l in без_данных:
        if "источник ответил" in l:
            ошибки.append("непроверенный источник описан как ответивший — читатель "
                          "получает «всё в порядке» там, где данных нет: %s"
                          % l[:140])
        if "см. раздел 3" not in l:
            ошибки.append("строка без данных не отсылает к разделу 3: %s" % l[:140])
    пусто = [l for l in _строки_таблиц(раздел2) if "| пусто (" in l]
    for l in пусто:
        if "источник ответил, записей по контрагенту нет" not in l:
            ошибки.append("состояние «пусто» перестало означать ответ источника: %s"
                          % l[:140])
    return ошибки


def case_непроверенные_сигналы():
    """Подраздел 3.2 обязан перечислить непроверенные сигналы поимённо."""
    текст, ошибки = markdown("fetch_отсрочка.json")
    if ошибки:
        return ошибки
    раздел3 = _раздел_текста(текст, 3)
    if "3.2. Сигналы, оставшиеся непроверенными" not in раздел3:
        ошибки.append("в разделе 3 нет подраздела «Сигналы, оставшиеся "
                      "непроверенными»")
    рез = _вердикт("fetch_отсрочка.json")
    if not isinstance(рез, dict):
        return ошибки + ["profiles.resolve() не отдал вердикт — эталон не построен"]
    непроверенные = [f.get("текст") for f in (рез.get("факты") or [])
                     if isinstance(f, dict) and f.get("статус") == "не проверен"]
    if len(непроверенные) < 3:
        return ошибки + ["фикстура бесполезна: непроверенных сигналов %d"
                         % len(непроверенные)]
    if "Непроверенных сигналов нет." in раздел3:
        ошибки.append("непроверенных сигналов %d, а документ пишет «Непроверенных "
                      "сигналов нет.»" % len(непроверенные))
    for т in непроверенные:
        ключ = (т or "")[:60]
        if ключ and ключ not in раздел3:
            ошибки.append("непроверенный сигнал потерян: «%s…»" % ключ[:50])
    return ошибки


