#!/usr/bin/env python3
"""
run_dossier_eval.py — офлайн-прогон scripts/dossier.py по фикстурам
eval/fixtures/dossier/. Сети не требует, чистый stdlib, гоняется в CI.

Что проверяется (спек волны 3, §3):
  * Markdown содержит все пять обязательных разделов;
  * источник со состоянием «не проверено» попадает в раздел «НЕ проверено»
    и не теряется по дороге (проверяется поимённо для каждого такого источника,
    вместе с причиной из `_доступность`);
  * источники «не проверено» из вспомогательных входов (--санкции, --граф)
    тоже не теряются;
  * хеш входного JSON стоит в шапке и меняется при любой правке входа;
  * DOCX — валидный ZIP из четырёх частей WordprocessingML, XML разбирается,
    текст всех пяти разделов в документе присутствует;
  * профиль «нейтрально» (формулировка «факты») не печатает ни вердикт,
    ни рекомендацию — вердикт там был бы заключением;
  * экранирование: компания «Ромашка & Ко» с кавычками, амперсандом и угловыми
    скобками не ломает ни Markdown-таблицу, ни XML документа;
  * молчание не превращается в «всё в порядке»: вход без `_доступность` и без
    `_итог_проверки` не даёт ни «все источники ответили», ни пропажи строки
    «Проверка состоялась: нет»;
  * источник, записи о котором во входе нет вообще (квик-режим, ручной JSON),
    стоит и в разделе 2, и в разделе 3 отдельным состоянием, а расхождение
    между шапкой и таблицей названо вслух;
  * пояснения состояний в таблице раздела 2 не выдают «не проверено» за ответ
    источника, а подраздел 3.2 не рапортует «непроверенных сигналов нет» при
    непроверенных сигналах;
  * `--fin` со статусом «не проверено» без причины не исчезает, а непереданные
    `--fin` / `--санкции` / `--граф` названы явно;
  * перечень «вручную» из профиля доезжает до раздела 3;
  * управляющие символы во входе: Markdown не рвётся, word/document.xml
    остаётся валидным XML;
  * `_рубли()` ставит знак перед суммой, а не перед копейками.

Разбор XML требует рабочего pyexpat. Если интерпретатор собран без него
(встречается на macOS с поломанным homebrew-питоном), XML-кейсы честно
помечаются ПРОПУЩЕН, а не выдаются за пройденные.
"""

import hashlib
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOSSIER = ROOT / "scripts" / "dossier.py"
FIXTURES = ROOT / "eval" / "fixtures" / "dossier"

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"

РАЗДЕЛЫ = (
    "1. Кто проверен и когда",
    "2. Что проверено",
    "3. Что НЕ проверено и почему",
    "4. Что найдено в источниках",
    "5. Границы этого документа",
)

ЧАСТИ_DOCX = ("[Content_Types].xml", "_rels/.rels",
              "word/_rels/document.xml.rels", "word/document.xml")

try:
    import xml.etree.ElementTree as ET
    ET.fromstring("<a/>")
    XML_ДОСТУПЕН, XML_ПРИЧИНА = True, None
except Exception as e:
    ET, XML_ДОСТУПЕН, XML_ПРИЧИНА = None, False, str(e)


def прогон(аргументы):
    """(stdout, stderr, код) запуска dossier.py тем же интерпретатором."""
    p = subprocess.run([sys.executable, str(DOSSIER)] + [str(a) for a in аргументы],
                       capture_output=True, text=True, check=False)
    return p.stdout, p.stderr, p.returncode


def markdown(фикстура, *хвост):
    out, err, код = прогон(["--fetch", FIXTURES / фикстура] + list(хвост))
    if код != 0:
        return None, ["dossier.py вернул %d: %s" % (код, err.strip())]
    return out, []


def не_проверенные_источники(фикстура):
    """{id: причина} источников со состоянием «не проверено» во входном JSON."""
    данные = json.loads((FIXTURES / фикстура).read_text(encoding="utf-8"))
    дост = данные.get("_доступность") or {}
    return {sid: (v or {}).get("причина")
            for sid, v in дост.items()
            if isinstance(v, dict) and v.get("состояние") == "не проверено"}


def _раздел_текста(текст, номер):
    """Кусок Markdown от заголовка раздела `номер` до следующего «## »."""
    начало = текст.find("## " + РАЗДЕЛЫ[номер - 1])
    if начало < 0:
        return ""
    конец = текст.find("\n## ", начало + 1)
    return текст[начало:конец if конец > 0 else len(текст)]


