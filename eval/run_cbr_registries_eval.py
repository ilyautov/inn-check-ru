def xlsx(листы, inline=False):
    """{имя: [[значения строки]]} -> bytes XLSX. Строки — общие строки (или
    inlineStr), числа (int) — числовые ячейки."""
    общие, индекс = [], {}
    z = io.BytesIO()
    with zipfile.ZipFile(z, "w") as zf:
        wb, rels = [], []
        for n, (имя, строки) in enumerate(листы.items(), 1):
            wb.append('<sheet name="%s" sheetId="%d" r:id="rId%d"/>' % (html.escape(имя), n, n))
            rels.append('<Relationship Id="rId%d" Type="x" Target="worksheets/sheet%d.xml"/>'
                        % (n, n))
            xml = []
            for r, строка in enumerate(строки, 1):
                ячейки = []
                for c, v in enumerate(строка):
                    ref = "%s%d" % ("ABCDEFGHIJKLMNOPQRS"[c], r)
                    if isinstance(v, int):
                        ячейки.append('<c r="%s"><v>%d</v></c>' % (ref, v))
                    elif inline:
                        ячейки.append('<c r="%s" t="inlineStr"><is><t>%s</t></is></c>'
                                      % (ref, html.escape(v)))
                    else:
                        if v not in индекс:
                            индекс[v] = len(общие)
                            общие.append(v)
                        ячейки.append('<c r="%s" t="s"><v>%d</v></c>' % (ref, индекс[v]))
                xml.append('<row r="%d">%s</row>' % (r, "".join(ячейки)))
            zf.writestr("xl/worksheets/sheet%d.xml" % n,
                        "<worksheet><sheetData>%s</sheetData></worksheet>" % "".join(xml))
        zf.writestr("xl/workbook.xml", '<workbook><sheets>%s</sheets></workbook>' % "".join(wb))
        zf.writestr("xl/_rels/workbook.xml.rels",
                    "<Relationships>%s</Relationships>" % "".join(rels))
        zf.writestr("xl/sharedStrings.xml", "<sst>%s</sst>" % "".join(
            "<si><t>%s</t></si>" % html.escape(s) for s in общие))
    return z.getvalue()


