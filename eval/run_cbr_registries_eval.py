def получатель(подмена=None, сломать=None):
    файлы = {"list_MFO.xlsx": мфо(), "list_KPK_gov.xlsx": кпк(), "list_skpk.xlsx": скпк(),
             "list_PS.xlsx": ломбарды()}
    файлы.update(подмена or {})

    def получить(url, лимит):
        имя = url.rsplit("/", 1)[1]
        if имя == сломать:
            raise OSError("сеть")
        return файлы[имя]
    return получить


