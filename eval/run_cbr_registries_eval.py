def case_движок():
    errors = []
    дом = os.environ.get("HOME")
    with tempfile.TemporaryDirectory() as td:
        os.environ["HOME"] = td
        try:
            fc = load("fetch_counterparty")
            данные, av = fc.fetch_cbr_registries(None, "7325081622")
            check(errors, данные is None and av["причина"].startswith("кэш:"), "нет индекса")
            cbr = load("cbr_registries")
            cbr.refresh(cache_dir=cbr.CACHE_DIR, получить=получатель())
            данные, av = fc.fetch_cbr_registries(None, "7325081622")
            check(errors, av["состояние"] == "ok" and данные["действует_в"] == ["мфо"],
                  "ok: %r" % av)
            пусто, av2 = fc.fetch_cbr_registries(None, "7700000000")
            check(errors, пусто is None and av2["состояние"] == "пусто"
                  and "включая исключённые" in av2["причина"], "пусто: %r" % av2)
            snap = load("snapshot")
            а = {"инн": "7325081622", "реестры_цб": данные, "_доступность": {"реестры_цб": av}}
            б = json.loads(json.dumps(а, ensure_ascii=False))
            б["реестры_цб"]["скачан"] = {k: "2026-10-05" for k in б["реестры_цб"]["скачан"]}
            б["реестры_цб"]["предупреждения"] = ["x"]
            check(errors, snap.хеш_остального(а) == snap.хеш_остального(б),
                  "дата скачивания в хеше снимка")
            б["реестры_цб"]["записи"][0]["статус"] = "исключена"
            check(errors, snap.хеш_остального(а) != snap.хеш_остального(б),
                  "исключение из реестра не видно в снимке")
            # устаревший индекс: «нет» — не проверено
            путь = os.path.join(cbr.CACHE_DIR, cbr.ИНДЕКС)
            и = cbr._прочитать(путь)
            for р in и["реестры"].values():
                р["скачан"] = "2026-01-01"
            with gzip.open(путь, "wt", encoding="utf-8") as fh:
                json.dump(и, fh, ensure_ascii=False)
            _, av = fc.fetch_cbr_registries(None, "7700000000")
            check(errors, av["состояние"] == "не проверено" and "старше" in av["причина"],
                  "устаревший: %r" % av)
            check(errors, "реестры_цб" in fc.FETCHERS
                  and fc.SOURCES["реестры_цб"]["deal_killer"] is False, "регистрация")
        finally:
            if дом is None:
                os.environ.pop("HOME", None)
            else:
                os.environ["HOME"] = дом
    return "блок-движка", errors


def main():
    cbr = load("cbr_registries")
    failed = 0
    for имя, errors in (case_индекс(cbr), case_схема(cbr), case_движок()):
        if errors:
            failed += 1
            print("FAIL %s" % имя)
            for e in errors:
                print("  -", e)
        else:
            print("PASS %s" % имя)
    if failed:
        print("FAIL: %d/3 кейсов упало" % failed)
        return 1
    print("PASS: все 3 кейсов зелёные")
    return 0


