def case_устаревший_кэш(sc, tmp):
    """Дефект №2: кэш годичной давности раньше отдавался как «проверено»
    с припиской «перечень устарел». Спек волны 1 §10 требует обратного:
    свежий кэш -> ok, иначе «не проверено» — по протухшему перечню
    «совпадений 0» не значит «чисто»."""
    errors = []
    копия = tmp / "terrorists-list.html"
    shutil.copy(str(РФМ), str(копия))
    старое = time.time() - 365 * 86400
    os.utime(str(копия), (старое, старое))
    restore = подменить_кэш(sc, рфм=копия, ofac=tmp / "нет.csv", eu=tmp / "нет.xml",
                            освежить=False)
    try:
        res, ok = sc.сверить(inn="1653019714")
        блок = res["по_спискам"]["рфм"]
        check(errors, блок["статус"] == sc.НЕ_ПРОВЕРЕНО,
              "устаревший кэш выдан как проверенный: статус %r" % блок["статус"])
        check(errors, "устарел" in (блок.get("причина") or ""),
              "в причине нет слова про устаревание: %r" % блок.get("причина"))
        check(errors, блок["возраст_кэша_дней"] and блок["возраст_кэша_дней"] > sc.CACHE_TTL_DAYS,
              "возраст кэша %r" % блок["возраст_кэша_дней"])
        check(errors, not ok, "exit-код говорит «проверено» по годичному кэшу")
        check(errors, res["статус"] == sc.НЕ_ПРОВЕРЕНО,
              "верхний статус по годичному кэшу %r" % res["статус"])
        check(errors, [x["список"] for x in res["не_проверено"]] == ["рфм"],
              "устаревший список не вынесен в верхний блок: %r" % res["не_проверено"])
        check(errors, res["совпадений"] == 0,
              "по устаревшему кэшу выдано совпадение как проверенное: %r" % res["совпадения"])
        check(errors, "оговорка" in res, "нет оговорки в верхнем блоке")
        # граница: кэш в пределах TTL сверяется как обычно
        свежее = time.time() - (sc.CACHE_TTL_DAYS - 1) * 86400
        os.utime(str(копия), (свежее, свежее))
        res2, ok2 = sc.сверить(inn="1653019714")
        check(errors, ok2 and res2["совпадений"] == 1,
              "кэш в пределах TTL не сверяется: статус %r, совпадений %d"
              % (res2["статус"], res2["совпадений"]))
    finally:
        restore()
    return errors


