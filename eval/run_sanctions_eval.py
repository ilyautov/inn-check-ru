"""
run_sanctions_eval.py — офлайн-eval санкционного контура sanctions_check.py.

Покрывает то, чего не было покрыто вообще: разбор HTML перечня Росфинмониторинга
(четыре раздела, организации с ИНН/ОГРН/датой, алиасы, физлица с ФИО и датой
рождения, «ОБЪЕДИНЕНИЕ, ВКЛЮЧАЮЩЕЕ: …» с несколькими людьми в одной записи),
правила сверки (ИНН — точно; имя — только точное совпадение с обязательной
пометкой про дату рождения; однофамилец и частичное имя НЕ находятся) и то, что
ветки OFAC и EU не сломаны.

Отдельный упор — на «тихую деградацию», когда отсутствие или порча данных
выглядят как «проверено, совпадений 0» (санкционное совпадение — deal-killer,
ложное «чисто» здесь дороже всего):

  частичный кэш  нет перечня РФМ, есть OFAC/EU -> сверка по ИНН «не проверено»
                 (российских ИНН в данных OFAC/EU нет вообще);
  устаревший кэш возраст > CACHE_TTL_DAYS -> «не проверено», а не приписка;
  пропавший раздел -> «проверено частично» + вынос в ВЕРХНИЙ блок, при этом
                 пустой раздел с пометкой источника — факт, а не дефект;
  кодировка      кэш не в UTF-8 -> «не проверено», а не 0 совпадений по ФИО.

Фикстуры: eval/fixtures/sanctions/ (вырезки из живых файлов 19.09.2026).
Сети не требует, PASS/FAIL, чистый stdlib — гоняется в CI.
"""

