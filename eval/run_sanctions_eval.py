def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def есть_expat():
    """Разбор XML (ветка EU) требует pyexpat. На некоторых сборках Python он
    не грузится — это дефект интерпретатора, а не парсера, поэтому кейс
    пропускается с явным объяснением, а не падает."""
    try:
        import pyexpat  # noqa: F401
        return True
    except Exception:
        return False


def подменить_кэш(sc, рфм=None, ofac=None, eu=None, освежить=True):
    """Ставит фикстуры вместо путей кэша и возвращает функцию восстановления.

    По умолчанию подставленным файлам проставляется текущее время: свежесть
    кэша — гейт сверки, а возраст файла в репозитории к предмету кейса не
    относится (иначе eval краснел бы через неделю после checkout'а). Свежесть
    проверяется отдельно и явно — case_устаревший_кэш (освежить=False)."""
    старые = {k: sc.SOURCES[k]["file"] for k in sc.SOURCES}
    for ключ, путь in (("рфм", рфм), ("ofac", ofac), ("eu", eu)):
        if путь is not None:
            sc.SOURCES[ключ]["file"] = str(путь)
            if освежить and os.path.exists(str(путь)):
                os.utime(str(путь), None)

    def restore():
        for k, v in старые.items():
            sc.SOURCES[k]["file"] = v
    return restore


def записи_рфм(sc):
    """-> (записи, статус, причина): контракт парсера — три состояния."""
    return sc._entries_rfm(str(РФМ))


def найти(entries, номер, раздел):
    for e in entries:
        if e["номер"] == номер and e["раздел"] == раздел:
            return e
    return None


def case_разделы(sc):
    """Все четыре раздела разбираются, шапка сайта и хлебные крошки — нет."""
    errors = []
    entries, статус, причина = записи_рфм(sc)
    check(errors, entries is not None, "фикстура РФМ не разобралась вовсе")
    if entries is None:
        return errors
    check(errors, статус == sc.ПРОВЕРЕНО, "статус разбора целой фикстуры %r" % статус)
    check(errors, причина is None, "неожиданная оговорка: %r" % причина)
    счёт = {}
    for e in entries:
        счёт[e["раздел"]] = счёт.get(e["раздел"], 0) + 1
    ожидание = {
        "национальная часть / организации": 9,
        "национальная часть / физические лица": 7,
        "международная часть / организации": 2,
        "международная часть / физические лица": 2,
    }
    check(errors, счёт == ожидание, "разбивка по разделам %r != %r" % (счёт, ожидание))
    check(errors, all(e["имя"] for e in entries),
          "есть записи без имени: %r" % [e for e in entries if not e["имя"]][:2])
    мусор = [e["имя"] for e in entries
             if "Главная" in e["имя"] or "Росфинмониторинге" in e["имя"]]
    check(errors, not мусор, "в записи попали пункты меню сайта: %r" % мусор)
    for e in entries:
        check(errors, e["часть"] in ("национальная часть", "международная часть"),
              "часть %r" % e["часть"])
        check(errors, e["тип_записи"] in ("организация", "физлицо"),
              "тип записи %r" % e["тип_записи"])
    return errors


