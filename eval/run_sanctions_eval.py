def case_кодировка(sc, tmp):
    """Дефект №4: кэш в cp1251 — латиница цела, кириллица мусор, «записей
    разобрано: 20, предупреждений нет», а сверка по ФИО молча даёт 0 совпадений.
    Канарейка по ИНН дефект не ловит: цифры кодировку переживают."""
    errors = []
    битая = tmp / "cp1251.html"
    битая.write_bytes(РФМ.read_text(encoding="utf-8").encode("cp1251", errors="replace"))
    entries, статус, причина = sc._entries_rfm(str(битая))
    check(errors, entries is None,
          "cp1251-страница разобрана как годная: %r записей"
          % (len(entries) if entries else None))
    check(errors, статус == sc.НЕ_ПРОВЕРЕНО, "статус %r" % статус)
    check(errors, причина and "кодировка" in причина, "причина %r" % причина)
    restore = подменить_кэш(sc, рфм=битая, ofac=tmp / "нет.csv", eu=tmp / "нет.xml")
    try:
        res, ok = sc.сверить(name="БАСАЕВ ШИРВАНИ САЛМАНОВИЧ")
        check(errors, not ok and res["статус"] == sc.НЕ_ПРОВЕРЕНО,
              "битая кодировка выдана как проверенная сверка: %r" % res["статус"])
        check(errors, res["совпадений"] == 0, "совпадения по мусорным именам")
        res2, ok2 = sc.сверить(inn="7901006096")
        check(errors, not ok2,
              "канарейка по ИНН не краснеет на смене кодировки: %r" % res2["статус"])
    finally:
        restore()
    # целый UTF-8 порога не задевает
    текст, доля, проблема = sc._прочитать_текст(str(РФМ))
    check(errors, проблема is None and текст and доля == 0,
          "целая UTF-8-фикстура объявлена битой: %r (замен %r)" % (проблема, доля))
    # скачивание: объявленная кодировка приводится к UTF-8, ложная — отвергается
    данные, кодировка, _пред, проблема2 = sc._в_utf8("ПРОВЕРКА".encode("cp1251"),
                                                     "windows-1251")
    check(errors, проблема2 is None and данные and данные.decode("utf-8") == "ПРОВЕРКА",
          "перекодировка cp1251 -> UTF-8 при скачивании сломана: %r" % проблема2)
    check(errors, кодировка == "windows-1251", "кодировка в мете %r" % кодировка)
    данные3, _к, _п, проблема3 = sc._в_utf8("ПРОВЕРКА".encode("cp1251"), "utf-8")
    check(errors, данные3 is None and проблема3,
          "байты cp1251 при объявленной UTF-8 сохранены как годные")
    имя1, откуда1 = sc._объявленная_кодировка(
        {"Content-Type": "text/html; charset=windows-1251"}, b"")
    check(errors, (имя1 or "").lower() == "windows-1251" and откуда1 == "Content-Type",
          "кодировка из Content-Type: %r/%r" % (имя1, откуда1))
    имя2, _откуда2 = sc._объявленная_кодировка(
        {}, b'<html><head><meta charset="cp1251">')
    check(errors, (имя2 or "").lower() == "cp1251", "кодировка из <meta>: %r" % имя2)
    return errors


