def _цепочка_pdf(b):
    """PDF -> руководитель эталона на подставном pypdf (eval — stdlib, без pypdf)."""
    import types
    errors = []

    def pypdf_из(страницы=None, ошибка=None):
        мод = types.ModuleType("pypdf")

        class Страница:
            def __init__(self, т):
                self.т = т

            def extract_text(self):
                return self.т

        class PdfReader:
            def __init__(self, путь):
                if ошибка:
                    raise ошибка
                self.pages = [Страница(т) for т in страницы]
        мод.PdfReader = PdfReader
        return мод

    class PdfStreamError(Exception):   # как в pypdf: не наследует ValueError
        pass
    строка = {"t": "tok", "i": "1"}
    был = sys.modules.get("pypdf")
    выписка = b._выписка
    b._выписка = lambda inn, t: (Path("фиктивный.pdf"), None)
    try:
        for имя, мод, ждём in (
                ("две страницы", pypdf_из(ВЫПИСКА.replace("\n20 ИНН", "\x00" "20 ИНН").split("\x00")),
                 # страница рвёт раздел о лице между ФИО и ИНН
                 {"руководитель": b.хеш_фио("КОНКУРСНЫЙ УПРАВЛЯЮЩИЙ: Иванов Иван Иванович"),
                  "должности": ["КОНКУРСНЫЙ УПРАВЛЯЮЩИЙ"]}),
                ("страница без текста", pypdf_из([ВЫПИСКА, "  "]),
                 "не_собрано"),
                ("битый PDF", pypdf_из(ошибка=PdfStreamError("truncated")), "не_собрано")):
            sys.modules["pypdf"] = мод
            try:
                р = b._руководитель_эталона("1", {"rows": [строка]})
            except Exception as e:
                errors.append("%s: исключение %r" % (имя, e))
                continue
            if ждём == "не_собрано":
                check(errors, set(р) == {"не_собрано"}, "%s: %r" % (имя, р))
            else:
                check(errors, р == ждём, "%s: %r" % (имя, р))
        b._выписка = lambda inn, t: (None, "выписка: нужна капча")
        check(errors, b._руководитель_эталона("1", {"rows": [строка]})
              == {"не_собрано": "выписка: нужна капча"}, "отказ выписки не «не собрано»")
    finally:
        b._выписка = выписка
        if был is None:
            sys.modules.pop("pypdf", None)
        else:
            sys.modules["pypdf"] = был
    return errors


