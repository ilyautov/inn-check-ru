def case_a_разбор(bc):
    errors = []
    ожидание = [ИНН_КРАСНЫЙ, ИНН_ЧИСТЫЙ]
    входы = {
        "запятая+ИНН": "Название,ИНН,Сумма\nАльфа,%s,100\nБета,%s,200\n" % tuple(ожидание),
        "точка с запятой+inn": "name;inn;sum\nA;%s;1\nB;%s;2\n" % tuple(ожидание),
        "таб+ИНН контрагента": "Контрагент\tИНН контрагента\tДолг\nA\t%s\t1\nB\t%s\t2\n"
                               % tuple(ожидание),
        "без заголовка": "%s\n%s\n" % tuple(ожидание),
        "без заголовка, две колонки": "Альфа,%s\nБета,%s\n" % tuple(ожидание),
    }
    for имя, текст in входы.items():
        значения, как = bc.разобрать_таблицу(текст)
        check(errors, значения == ожидание,
              "%s: получено %r (%s)" % (имя, значения, как))
    # --колонка N перебивает автоопределение (колонка 1 — мусор, 2 — ИНН)
    текст = "ИНН старый,ИНН новый\n0000000000,%s\n1111111111,%s\n" % tuple(ожидание)
    значения, как = bc.разобрать_таблицу(текст, колонка=2)
    check(errors, значения == ожидание, "--колонка 2: %r (%s)" % (значения, как))
    # пустой файл не бросает
    check(errors, bc.разобрать_таблицу("")[0] == [], "пустой файл должен дать []")
    check(errors, bc.разобрать_таблицу("\n \n")[0] == [], "файл из пробелов должен дать []")
    return errors


