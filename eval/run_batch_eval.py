def _инн10(основа):
    """9 цифр + контрольное число: валидные ИНН там, где важно только их
    количество (тест обрыва)."""
    веса = (2, 4, 10, 3, 5, 9, 4, 6, 8)
    return основа + str(sum(int(d) * w for d, w in zip(основа, веса)) % 11 % 10)


