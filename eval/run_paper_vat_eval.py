def case_i_collection_gate(pv, canon):
    """Сбор движка не состоялся — анализ признаков не вправе сказать «ок».

    Своя доля «не проверено» у paper_vat может сойтись и тогда, когда
    deal-killer-источники молчали: у него свой знаменатель. Тогда чистый
    вывод «признаков не подтвердилось» читается как «контрагент чист», хотя
    проверки не было. Гейт обязан смотреть на _итог_проверки движка.
    """
    errors = []
    база = читать("чистая.json")
    # контроль: на неизменённой фикстуре статус «ок» — иначе кейс ничего не ловит
    check(errors, pv.analyze(dict(база), canon=canon).get("статус") == "ок",
          "контроль: чистая фикстура должна давать «ок»")

    молчали = dict(база)
    молчали["_итог_проверки"] = dict(база.get("_итог_проверки") or {})
    молчали["_итог_проверки"]["проверка_состоялась"] = False
    молчали["_итог_проверки"]["вывод"] = (
        "проверка НЕ состоялась: 5 из 7 deal-killer-источников не проверено "
        "— светофор 🟢 недопустим")
    out = pv.analyze(молчали, canon=canon)
    check(errors, out.get("статус") == "проверка не состоялась",
          "сбор не состоялся, а статус %r" % out.get("статус"))
    вывод = out.get("вывод") or ""
    check(errors, "deal-killer" in вывод,
          "вывод не называет причину от движка: %r" % вывод[:160])
    check(errors, not вывод.startswith("проверка НЕ состоялась: проверка"),
          "фраза «проверка НЕ состоялась» удвоена: %r" % вывод[:80])

    # блока нет вовсе (старый снимок, ручной вход) — тоже не «ок»
    без_итога = {k: v for k, v in база.items() if k != "_итог_проверки"}
    out2 = pv.analyze(без_итога, canon=canon)
    check(errors, out2.get("статус") == "проверка не состоялась",
          "вход без _итог_проверки: статус %r" % out2.get("статус"))
    check(errors, "_итог_проверки" in (out2.get("вывод") or ""),
          "вход без _итог_проверки: причина не названа")
    return errors


