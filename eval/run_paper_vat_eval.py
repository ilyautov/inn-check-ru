#!/usr/bin/env python3
"""
run_paper_vat_eval.py — офлайн-eval scripts/paper_vat.py (волна 3, поток K).

Фикстуры: eval/fixtures/paper_vat/*.json — синтетический вывод
fetch_counterparty.py (блоки источников + словари `_доступность` + `_итог_проверки`).

Кейсы:
  (а) чистая компания — ни одного признака «бумажного НДС»;
  (б) однодневка — поднимается ожидаемый набор признаков;
  (в) «не проверено» НЕ превращается в «признак отсутствует» — плюс МУТАЦИОННАЯ
      проверка кусачести: если подсунуть скрипту багованный `_ссч`, который
      читает пустое поле как ноль, кейс обязан упасть. Тест, который не падает
      на внесённом дефекте, ничего не проверяет;
  (г) порог «проверка не состоялась» по доле признаков «не проверено»;
  (д) УСН — отдельная честная формулировка про освобождение от НДС, без вывода
      «вычета быть не может»;
  (е) профиль `ндс_вычет` резолвится через profiles.resolve(), светофора не даёт,
      и все сигналы, на которые он ссылается, есть в каталоге;
  (ж) формулировочная дисциплина: ни в одном выводе нет налоговых заключений;
  (з) CLI: битый вход и --предмет/--сумма не падают traceback'ом.

PASS/FAIL, чистый stdlib, сети не требует — гоняется в CI.
"""

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
FIXTURES = ROOT / "eval" / "fixtures" / "paper_vat"
PAPER_VAT = SCRIPTS / "paper_vat.py"

# Признаки, которые обязана поднять компания-однодневка (все поля pb ОТДАНЫ).
ОЖИДАЕМЫЕ_ОДНОДНЕВКА = {
    "недостоверность_сведений", "возраст_компании", "возраст_против_оборота",
    "массовый_адрес", "массовый_руководитель", "ресурсы_штат", "ресурсы_имущество",
}

# Признаки, поля которых живут за детальным эндпоинтом pb: при «не проверено»
# источника они обязаны быть «не проверено», а не «не выявлено».
ЗА_ДЕТАЛЯМИ_PB = {"массовый_адрес", "массовый_руководитель", "ресурсы_штат",
                  "спецрежим_против_ндс", "недостоверность_сведений"}

# Формулировки, которых в выводе быть не должно: это налоговые заключения.
ЗАПРЕЩЁННЫЕ_ФОРМУЛИРОВКИ = (
    "вычет не устоит", "вычета быть не может", "вычет неправомер",
    "снимут вычет", "доначисл", "фирма-однодневка", "является технической компанией",
    "уклонение от уплаты", "рекомендуем отказать", "сделка притворн",
)

# Обороты, в которых «вычет устоит» стоит под отрицанием — их снимаем перед
# поиском запрещённых формулировок, иначе честная оговорка читалась бы как вердикт.
ОГОВОРКИ = ("не означает, что вычет устоит", "«вычет устоит / не устоит»")


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def читать(имя):
    with open(FIXTURES / имя, encoding="utf-8") as fh:
        return json.load(fh)


def по_статусам(out):
    """{id признака: статус} по всем спискам вывода."""
    d = {}
    for ключ in ("что_видно", "что_не_выявлено", "не_проверено", "не_применимо",
                 "вне_охвата"):
        for p in out.get(ключ) or []:
            d[p["id"]] = p["статус"]
    return d


