def case_a_clean(pv, canon):
    errors = []
    out = pv.analyze(читать("чистая.json"), canon=canon)
    check(errors, out.get("статус") == "ок",
          "чистая: статус %r, ожидался «ок»" % out.get("статус"))
    check(errors, out.get("что_видно") == [],
          "чистая: подняты признаки %s" % [p["id"] for p in out.get("что_видно") or []])
    статусы = по_статусам(out)
    for pid in ("возраст_компании", "ресурсы_штат", "ресурсы_имущество",
                "массовый_адрес", "массовый_руководитель", "недостоверность_сведений"):
        check(errors, статусы.get(pid) == "не выявлено",
              "чистая: признак %s = %r, ожидалось «не выявлено» (источник ответил)"
              % (pid, статусы.get(pid)))
    # вывод должен прямо сказать, что «чисто» != «вычет устоит»
    check(errors, "АСК НДС-2" in (out.get("вывод") or ""),
          "чистая: вывод не оговаривает, что разрывов АСК НДС-2 в открытых данных не видно")
    return errors


def case_b_shell(pv, canon):
    errors = []
    out = pv.analyze(читать("однодневка.json"), canon=canon)
    check(errors, out.get("статус") == "ок",
          "однодневка: статус %r, ожидался «ок» (все источники ответили)" % out.get("статус"))
    найдены = {p["id"] for p in out.get("что_видно") or []}
    пропущены = ОЖИДАЕМЫЕ_ОДНОДНЕВКА - найдены
    check(errors, not пропущены, "однодневка: не подняты признаки %s" % sorted(пропущены))
    # у каждого найденного признака обязаны быть источник и дата
    for p in out.get("что_видно") or []:
        check(errors, p.get("источник") and p.get("дата"),
              "однодневка: признак %s без источника/даты: %r" % (p["id"], p))
    # порог должен быть процитирован с пометкой «эвристика»
    возраст = [p for p in out["что_видно"] if p["id"] == "возраст_компании"]
    check(errors, возраст and "эвристика" in (возраст[0].get("порог") or ""),
          "однодневка: порог возраста без пометки «эвристика»: %r"
          % (возраст[0].get("порог") if возраст else None))
    return errors


def _проверить_не_проверено(pv, canon):
    """Тело кейса (в): вынесено, чтобы мутационный прогон гонял ровно его."""
    errors = []
    out = pv.analyze(читать("не_проверено.json"), canon=canon)
    статусы = по_статусам(out)
    найдены = {p["id"] for p in out.get("что_видно") or []}
    for pid in ЗА_ДЕТАЛЯМИ_PB:
        check(errors, статусы.get(pid) == "не проверено",
              "не_проверено: признак %s = %r, ожидалось «не проверено» "
              "(источник не ответил — это НЕ «признака нет»)" % (pid, статусы.get(pid)))
        check(errors, pid not in найдены,
              "не_проверено: признак %s поднят из недоступного источника" % pid)
    # причина «не проверено» обязана называть источник, а не быть отпиской
    ссч = [p for p in out["не_проверено"] if p["id"] == "ресурсы_штат"]
    check(errors, ссч and "company-proc.json" in (ссч[0].get("причина") or ""),
          "не_проверено: у признака ресурсы_штат причина не называет источник: %r"
          % (ссч[0].get("причина") if ссч else None))
    check(errors, ссч and "НЕ означает" in (ссч[0].get("причина") or ""),
          "не_проверено: причина по ССЧ не проговаривает, что пустое поле ≠ «сотрудников нет»")
    return errors


def case_c_not_checked_vs_absent(pv, canon):
    errors = _проверить_не_проверено(pv, canon)
    # --- мутация: пустое поле ССЧ читается как ноль. Кейс обязан УПАСТЬ. ---
    подлинный = pv._ссч

    def багованный_ссч(fetch):
        знач = подлинный(fetch)
        return 0.0 if знач is None else знач

    pv._ссч = багованный_ссч
    try:
        после_мутации = _проверить_не_проверено(pv, canon)
    finally:
        pv._ссч = подлинный
    check(errors, после_мутации,
          "МУТАЦИЯ НЕ УКУСИЛА: с багованным `_ссч` (пустое поле = ноль) кейс всё равно "
          "зелёный — значит, он ничего не проверяет")
    # и контрольный прогон после восстановления
    check(errors, _проверить_не_проверено(pv, canon) == [],
          "после отката мутации кейс не восстановился")
    return errors


def case_d_threshold(pv, canon):
    errors = []
    out = pv.analyze(читать("не_проверено.json"), canon=canon)
    check(errors, out.get("статус") == "проверка не состоялась",
          "порог: статус %r, ожидалось «проверка не состоялась»" % out.get("статус"))
    check(errors, "проверка НЕ состоялась" in (out.get("вывод") or ""),
          "порог: вывод не говорит «проверка НЕ состоялась»: %r" % out.get("вывод"))
    сч = out.get("счётчик") or {}
    check(errors, сч.get("доля_не_проверено", 0) > 0.5,
          "порог: доля «не проверено» %r должна быть больше 0.5" % сч.get("доля_не_проверено"))
    # «вне охвата» не должно раздувать знаменатель
    check(errors, сч.get("в_знаменателе") == сч.get("найдено", 0) + сч.get("не_выявлено", 0)
          + сч.get("не_проверено", 0),
          "порог: знаменатель %r не равен найдено+не_выявлено+не_проверено" % сч.get("в_знаменателе"))
    check(errors, сч.get("вне_охвата", 0) > 0,
          "порог: признаки «вне охвата» должны быть в выводе отдельным списком")
    # обратная сторона: на полном наборе данных проверка состоялась
    полный = pv.analyze(читать("однодневка.json"), canon=canon)
    check(errors, полный.get("статус") == "ок",
          "порог кусается не туда: на полных данных статус %r" % полный.get("статус"))
    # без канона порогов сравнивать не с чем -> проверка не состоялась
    без_канона = pv.analyze(читать("однодневка.json"), canon=None)
    check(errors, без_канона.get("статус") == "проверка не состоялась",
          "без канона порогов статус %r, ожидалось «проверка не состоялась»"
          % без_канона.get("статус"))
    return errors


def case_e_usn(pv, canon):
    errors = []
    out = pv.analyze(читать("усн.json"), canon=canon)
    найдены = {p["id"]: p for p in out.get("что_видно") or []}
    p = найдены.get("спецрежим_против_ндс")
    check(errors, p is not None,
          "УСН: признак спецрежим_против_ндс не поднят (найдено: %s)" % sorted(найдены))
    if p is None:
        return errors
    текст = p["факт"]
    check(errors, "УСН" in текст, "УСН: в факте не назван режим: %r" % текст)
    check(errors, "освобожд" in текст.lower(),
          "УСН: факт не объясняет освобождение от НДС: %r" % текст)
    check(errors, "порог" in текст.lower(),
          "УСН: факт не упоминает порог освобождения: %r" % текст)
    нормы = {n["ссылка"] for n in p.get("норма") or []}
    check(errors, any("145" in n for n in нормы), "УСН: нет ссылки на ст. 145 НК РФ: %s" % нормы)
    check(errors, any("173" in n for n in нормы), "УСН: нет ссылки на п. 5 ст. 173 НК РФ: %s" % нормы)
    # компания на УСН НЕ должна получать вывод «вычета быть не может»
    низ = (out.get("вывод") or "").lower() + текст.lower()
    for фраза in ("вычета быть не может", "вычет не устоит"):
        check(errors, фраза not in низ, "УСН: в выводе налоговое заключение «%s»" % фраза)
    return errors


def case_f_profile(pf, profiles):
    errors = []
    prof = (profiles.get("профили") or {}).get("ндс_вычет")
    check(errors, isinstance(prof, dict), "профиля ндс_вычет нет в data/profiles_ru.json")
    if not isinstance(prof, dict):
        return errors
    check(errors, prof.get("формулировка") == "факты",
          "ндс_вычет: формулировка %r, ожидалось «факты»" % prof.get("формулировка"))
    check(errors, prof.get("рекомендации") is None,
          "ндс_вычет: рекомендации должны быть null — иначе это налоговое заключение")
    каталог = profiles.get("сигналы") or {}
    for sid in list(prof.get("deal_killers") or []) + list(prof.get("severity_override") or {}):
        check(errors, sid in каталог, "ндс_вычет: сигнал %s не из каталога" % sid)
    for sid in ("штат_не_нулевой", "спецрежим_раскрыт"):
        check(errors, sid in каталог, "новый сигнал %s не попал в каталог сигналов" % sid)
    # резолвится существующим резолвером, без правки его логики
    fetch = читать("однодневка.json")
    res = pf.resolve(fetch, None, "ндс_вычет", profiles)
    check(errors, res.get("профиль") == "ндс_вычет",
          "resolve() не вернул профиль ндс_вычет: %r" % res.get("профиль"))
    check(errors, res.get("светофор") is None,
          "ндс_вычет: светофор %r, а его быть не должно" % res.get("светофор"))
    check(errors, res.get("рекомендация") is None,
          "ндс_вычет: рекомендация %r, а её быть не должно" % res.get("рекомендация"))
    check(errors, res.get("факты"), "ндс_вычет: список фактов пуст")
    # новые сигналы обязаны различать «раскрыто» и «не раскрыто»
    сигналы = {s["сигнал"]: s for s in res.get("факты") or []}
    check(errors, сигналы.get("штат_не_нулевой", {}).get("статус") == "не выявлено"
          or сигналы.get("штат_не_нулевой", {}).get("статус") == "отсутствует",
          "однодневка (ССЧ=0, поле отдано): штат_не_нулевой = %r, ожидалось «отсутствует»"
          % сигналы.get("штат_не_нулевой", {}).get("статус"))
    res_нп = pf.resolve(читать("не_проверено.json"), None, "ндс_вычет", profiles)
    сигналы_нп = {s["сигнал"]: s for s in res_нп.get("факты") or []}
    for sid in ("штат_не_нулевой", "спецрежим_раскрыт"):
        check(errors, сигналы_нп.get(sid, {}).get("статус") == "не проверен",
              "не_проверено: сигнал %s = %r, ожидалось «не проверен»"
              % (sid, сигналы_нп.get(sid, {}).get("статус")))
    return errors


def case_g_wording(pv, canon):
    errors = []
    for имя in ("чистая.json", "однодневка.json", "не_проверено.json", "усн.json"):
        out = pv.analyze(читать(имя), canon=canon,
                         предмет="монтаж систем вентиляции", сумма=2400000)
        текст = json.dumps(out, ensure_ascii=False).lower()
        for оговорка in ОГОВОРКИ:
            текст = текст.replace(оговорка.lower(), "")
        check(errors, "вычет устоит" not in текст,
              "%s: утверждение «вычет устоит» вне честной оговорки" % имя)
        for фраза in ЗАПРЕЩЁННЫЕ_ФОРМУЛИРОВКИ:
            check(errors, фраза not in текст,
                  "%s: в выводе налоговое заключение «%s»" % (имя, фраза))
        check(errors, "не является" not in (out.get("дисклеймер") or "").lower()
              or "заключение" in (out.get("дисклеймер") or "").lower(),
              "%s: дисклеймер не говорит, что это не заключение" % имя)
        check(errors, out.get("чего_не_видно_в_открытых_данных"),
              "%s: нет списка «чего не видно»" % имя)
        check(errors, out.get("что_можно_проверить_самому"),
              "%s: нет списка «что проверить самому»" % имя)
        # --предмет включает сравнение с ОКВЭД
        статусы = по_статусам(out)
        check(errors, статусы.get("оквэд_против_предмета") in ("найден", "не выявлено",
                                                               "не проверено"),
              "%s: с --предмет признак оквэд_против_предмета = %r"
              % (имя, статусы.get("оквэд_против_предмета")))
        check(errors, (out.get("сделка") or {}).get("доля_в_выручке") is not None
              or имя == "не_проверено.json",
              "%s: --сумма передана, а доли в выручке в выводе нет" % имя)
    # розничный ОКВЭД против монтажа — слова не пересекаются
    out = pv.analyze(читать("однодневка.json"), canon=canon,
                     предмет="монтаж систем вентиляции")
    оквэд = [p for p in out["что_видно"] if p["id"] == "оквэд_против_предмета"]
    check(errors, оквэд, "ОКВЭД «розничная торговля» против «монтаж вентиляции» не поднят")
    if оквэд:
        check(errors, "грубое сравнение" in оквэд[0]["факт"],
              "признак ОКВЭД не оговаривает грубость сравнения: %r" % оквэд[0]["факт"])
    return errors


def case_h_cli():
    errors = []
    # битый вход — JSON с причиной, не traceback
    proc = subprocess.run([sys.executable, str(PAPER_VAT), "--stdin"],
                          input="не json", capture_output=True, text=True, check=False)
    check(errors, "Traceback" not in proc.stderr,
          "CLI на битом входе упал traceback'ом: %s" % proc.stderr[-300:])
    try:
        out = json.loads(proc.stdout)
        check(errors, out.get("статус") == "не проверено" and out.get("причина"),
              "CLI на битом входе: %r" % out)
    except ValueError:
        errors.append("CLI на битом входе вернул не JSON: %.200s" % proc.stdout)
    # нормальный прогон файла с параметрами сделки
    proc = subprocess.run([sys.executable, str(PAPER_VAT),
                           str(FIXTURES / "однодневка.json"),
                           "--предмет", "монтаж систем вентиляции",
                           "--сумма", "2 400 000"],
                          capture_output=True, text=True, check=False)
    check(errors, proc.returncode == 0, "CLI: код возврата %s, stderr: %s"
          % (proc.returncode, proc.stderr[-300:]))
    try:
        out = json.loads(proc.stdout)
        check(errors, (out.get("сделка") or {}).get("сумма_руб") == 2400000.0,
              "CLI: --сумма разобрана как %r" % (out.get("сделка") or {}).get("сумма_руб"))
    except ValueError:
        errors.append("CLI: вывод не JSON")
    # «проверка не состоялась» — валидный результат, код 0
    proc = subprocess.run([sys.executable, str(PAPER_VAT), str(FIXTURES / "не_проверено.json")],
                          capture_output=True, text=True, check=False)
    check(errors, proc.returncode == 0,
          "CLI: «проверка не состоялась» должна давать код 0, получено %s" % proc.returncode)
    # без аргументов — usage, код 2
    proc = subprocess.run([sys.executable, str(PAPER_VAT)],
                          capture_output=True, text=True, check=False)
    check(errors, proc.returncode == 2, "CLI без аргументов: код %s, ожидался 2" % proc.returncode)
    return errors


def case_i_collection_gate(pv, canon):
    """Сбор движка не состоялся — анализ признаков не вправе сказать «ок».

    Своя доля «не проверено» у paper_vat может сойтись и тогда, когда
    deal-killer-источники молчали: у него свой знаменатель. Тогда чистый
    вывод «признаков не подтвердилось» читается как «контрагент чист», хотя
    проверки не было. Гейт обязан смотреть на _итог_проверки движка.
    """
    errors = []
    база = читать("чистая.json")
    # контроль: на неизменённой фикстуре статус «ок» — иначе кейс ничего не ловит
    check(errors, pv.analyze(dict(база), canon=canon).get("статус") == "ок",
          "контроль: чистая фикстура должна давать «ок»")

    молчали = dict(база)
    молчали["_итог_проверки"] = dict(база.get("_итог_проверки") or {})
    молчали["_итог_проверки"]["проверка_состоялась"] = False
    молчали["_итог_проверки"]["вывод"] = (
        "проверка НЕ состоялась: 5 из 7 deal-killer-источников не проверено "
        "— светофор 🟢 недопустим")
    out = pv.analyze(молчали, canon=canon)
    check(errors, out.get("статус") == "проверка не состоялась",
          "сбор не состоялся, а статус %r" % out.get("статус"))
    вывод = out.get("вывод") or ""
    check(errors, "deal-killer" in вывод,
          "вывод не называет причину от движка: %r" % вывод[:160])
    check(errors, not вывод.startswith("проверка НЕ состоялась: проверка"),
          "фраза «проверка НЕ состоялась» удвоена: %r" % вывод[:80])

    # блока нет вовсе (старый снимок, ручной вход) — тоже не «ок»
    без_итога = {k: v for k, v in база.items() if k != "_итог_проверки"}
    out2 = pv.analyze(без_итога, canon=canon)
    check(errors, out2.get("статус") == "проверка не состоялась",
          "вход без _итог_проверки: статус %r" % out2.get("статус"))
    check(errors, "_итог_проверки" in (out2.get("вывод") or ""),
          "вход без _итог_проверки: причина не названа")
    return errors


def case_j_units(pv, canon):
    """ГИР БО отдаёт тысячи рублей — пороги и текст обязаны быть в рублях.

    Без пересчёта компания с выручкой 20 млрд ₽ читается как 20 млн ₽ и
    «не превышает порог освобождения от НДС» — утверждение, обратное правде.
    Сверено с дампом ФНС revexp 19.09.2026: отношение дохода в рублях к
    стр. 2110 у трёх ИНН — 1010, 1002 и 1025.
    """
    errors = []
    база = читать("чистая.json")
    год = (база.get("финансы") or {}).get("отчётность_по_годам")[0]
    # 1 000 тыс. руб. = 1 млн ₽; если пересчёта нет, в тексте будет «1000 ₽»
    год["строки"]["2110"] = 1000.0
    год["выручка"] = 1000.0
    out = pv.analyze(база, canon=canon, сумма=500000)
    доля = (out.get("сделка") or {}).get("доля_в_выручке") or ""
    check(errors, "1.0 млн ₽" in доля,
          "выручка 1000 тыс. руб. напечатана не как 1.0 млн ₽: %r" % доля)
    check(errors, "50.00%" in доля,
          "сделка 500 тыс. ₽ при выручке 1 млн ₽ — не 50%%: %r" % доля)
    return errors


def case_l_benchmarks(pv, canon):
    """Сопряжение с отраслевыми нормами (задача 4) и отказ от смещённой группы.

    Нормы сами помечают «среднее» и «крупное» предупреждением: ОКВЭД в
    открытых данных ФНС есть только в реестре МСП, поэтому настоящего
    крупного бизнеса в этих группах нет. Отрыв от такой медианы скажет про
    выборку, а не про контрагента — признак из него подниматься не должен.
    """
    errors = []
    бенч = ROOT / "data" / "benchmarks_ru.json"
    if not бенч.exists():
        return ["SKIP: data/benchmarks_ru.json не построен"]

    def прогон(выручка_тыс, ссч, оквэд, регион):
        d = читать("чистая.json")
        год = (d.get("финансы") or {}).get("отчётность_по_годам")[0]
        год["строки"]["2110"] = float(выручка_тыс)
        год["выручка"] = float(выручка_тыс)
        d.setdefault("риски", {})["оквэд"] = оквэд
        d["риски"]["численность_сотрудников"] = ссч
        d["риски"].setdefault("детали", {})["численность_сотрудников"] = ссч
        d.setdefault("егрюл", {})["регион"] = регион
        out = pv.analyze(d, canon=canon)
        для = {}
        for ключ in ("что_видно", "что_не_выявлено", "не_проверено",
                     "не_применимо", "вне_охвата"):
            for пр in out.get(ключ) or []:
                для[пр["id"]] = пр
        return для.get("выручка_на_сотрудника") or {}

    # группа 56|01|микро (ОКВЭД2 56 «общепит», Адыгея, микро): медиана
    # выручки на сотрудника ≈ 2,6 млн ₽. 40 млн ₽ на одного — отрыв больше
    # трёх раз, признак обязан подняться.
    отрыв = прогон(40000, 1, "56.10", "Республика Адыгея")
    check(errors, отрыв.get("статус") == "найден",
          "отрыв от медианы не поднял признак: %r / %s"
          % (отрыв.get("статус"), (отрыв.get("причина") or отрыв.get("факт"))))
    check(errors, "медианы отрасли" in (отрыв.get("факт") or ""),
          "факт не называет медиану отрасли: %r" % (отрыв.get("факт") or "")[:120])

    # выручка выводит компанию в «крупное», где группа существует (47|крупное),
    # но собрана по смещённой выборке: сравнение обязано стать «не проверено»,
    # а не признаком
    смещённая = прогон(50_000_000, 1, "47.11", "Московская область")
    check(errors, смещённая.get("статус") == "не проверено",
          "сравнение со смещённой группой дало %r вместо «не проверено»"
          % смещённая.get("статус"))
    check(errors, "только по субъектам МСП" in (смещённая.get("причина") or ""),
          "причина не называет смещение выборки: %r"
          % (смещённая.get("причина") or "")[:160])
    return errors


