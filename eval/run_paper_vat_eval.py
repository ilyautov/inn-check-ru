def case_l_benchmarks(pv, canon):
    """Сопряжение с отраслевыми нормами (задача 4) и отказ от смещённой группы.

    Нормы сами помечают «среднее» и «крупное» предупреждением: ОКВЭД в
    открытых данных ФНС есть только в реестре МСП, поэтому настоящего
    крупного бизнеса в этих группах нет. Отрыв от такой медианы скажет про
    выборку, а не про контрагента — признак из него подниматься не должен.
    """
    errors = []
    бенч = ROOT / "data" / "benchmarks_ru.json"
    if not бенч.exists():
        # Пропуск — не провал: таблица норм строится отдельным прогоном по
        # дампам ФНС и в репозиторий может не входить. Вызывающий код считает
        # непустой список ошибками, поэтому пропуск возвращается маркером.
        return [SKIP, "data/benchmarks_ru.json не построен (scripts/benchmarks.py --построить)"]

    def прогон(выручка_тыс, ссч, оквэд, регион, канон=...):
        канон = canon if канон is ... else канон
        d = читать("чистая.json")
        год = (d.get("финансы") or {}).get("отчётность_по_годам")[0]
        год["строки"]["2110"] = float(выручка_тыс)
        год["выручка"] = float(выручка_тыс)
        d.setdefault("риски", {})["оквэд"] = оквэд
        d["риски"]["численность_сотрудников"] = ссч
        d["риски"].setdefault("детали", {})["численность_сотрудников"] = ссч
        d.setdefault("егрюл", {})["регион"] = регион
        out = pv.analyze(d, canon=канон)
        для = {}
        for ключ in ("что_видно", "что_не_выявлено", "не_проверено",
                     "не_применимо", "вне_охвата"):
            for пр in out.get(ключ) or []:
                для[пр["id"]] = пр
        return для.get("выручка_на_сотрудника") or {}

    # группа 56|01|микро (ОКВЭД2 56 «общепит», Адыгея, микро): медиана
    # выручки на сотрудника ≈ 2,6 млн ₽. 40 млн ₽ на одного — отрыв больше
    # трёх раз, признак обязан подняться.
    отрыв = прогон(40000, 1, "56.10", "Республика Адыгея")
    check(errors, отрыв.get("статус") == "найден",
          "отрыв от медианы не поднял признак: %r / %s"
          % (отрыв.get("статус"), (отрыв.get("причина") or отрыв.get("факт"))))
    check(errors, "медианы отрасли" in (отрыв.get("факт") or ""),
          "факт не называет медиану отрасли: %r" % (отрыв.get("факт") or "")[:120])

    # выручка выводит компанию в «крупное», где группа существует (47|крупное),
    # но собрана по смещённой выборке: сравнение обязано стать «не проверено»,
    # а не признаком
    смещённая = прогон(50_000_000, 1, "47.11", "Московская область")
    check(errors, смещённая.get("статус") == "не проверено",
          "сравнение со смещённой группой дало %r вместо «не проверено»"
          % смещённая.get("статус"))
    check(errors, "только по субъектам МСП" in (смещённая.get("причина") or ""),
          "причина не называет смещение выборки: %r"
          % (смещённая.get("причина") or "")[:160])

    check(errors, "бумажный_ндс_кратность_медианы" in (отрыв.get("порог") or ""),
          "признак не цитирует порог кратности из канона: %r" % отрыв.get("порог"))
    return errors


def case_s_период_норм(pv, canon):
    """Отчётность старше норм не превращается в бодрый перцентиль.

    benchmarks.оценить() отказывается сравнивать отчётность 2019 года с
    нормами 2025-го — но только если ей передали год. Год едет атрибутом
    `Выборка.год`, а не пятым элементом кортежа, поэтому распаковка
    `инн, оквэд, регион, выручка = из_fetch(...)` теряет его, ничего не
    ломая на вид: статус остаётся «проверено», перцентиль выдаётся, а
    оговорка про период уезжает в поле, которого в paper_vat никто не
    читает. Кейс краснеет, если год перестанут доносить.
    """
    errors = []
    бенч = ROOT / "data" / "benchmarks_ru.json"
    if not бенч.exists():
        return [SKIP, "data/benchmarks_ru.json не построен"]

    def прогон(сдвиг_лет):
        """Сдвигает ВСЕ годы отчётности: свежий год ищется сортировкой, и
        состарить только первую запись значило бы не состарить ничего."""
        d = читать("чистая.json")
        записи = (d.get("финансы") or {}).get("отчётность_по_годам") or []
        for запись in записи:
            запись["год"] = str(int(запись["год"]) - сдвиг_лет)
        записи[0]["строки"]["2110"] = 40000.0
        записи[0]["выручка"] = 40000.0
        for запись in записи[1:]:
            запись["строки"]["2110"] = 40000.0
            запись["выручка"] = 40000.0
        d.setdefault("риски", {})["оквэд"] = "56.10"
        d["риски"]["численность_сотрудников"] = 1
        d["риски"].setdefault("детали", {})["численность_сотрудников"] = 1
        d.setdefault("егрюл", {})["регион"] = "Республика Адыгея"
        out = pv.analyze(d, canon=canon)
        для = {}
        for ключ in ("что_видно", "что_не_выявлено", "не_проверено",
                     "не_применимо", "вне_охвата"):
            for пр in out.get(ключ) or []:
                для[пр["id"]] = пр
        return для.get("выручка_на_сотрудника") or {}

    свежая = прогон(0)
    check(errors, свежая.get("статус") == "найден",
          "на свежей отчётности признак не поднялся (кейс потерял смысл): %r / %s"
          % (свежая.get("статус"), (свежая.get("причина") or свежая.get("факт"))))

    старая = прогон(6)   # самый свежий год отчётности уезжает на 6 лет назад
    check(errors, старая.get("статус") == "не проверено",
          "отчётность 2019 г. сравнена с нормами 2025 г.: статус %r вместо "
          "«не проверено» — год не дошёл до benchmarks.оценить()"
          % старая.get("статус"))
    check(errors, "нормами" in (старая.get("причина") or "")
          and "2019" in (старая.get("причина") or ""),
          "причина не называет разрыв периодов: %r"
          % (старая.get("причина") or "")[:200])
    return errors


