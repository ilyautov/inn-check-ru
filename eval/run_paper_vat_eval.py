def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def читать(имя):
    with open(FIXTURES / имя, encoding="utf-8") as fh:
        return json.load(fh)


def по_статусам(out):
    """{id признака: статус} по всем спискам вывода."""
    d = {}
    for ключ in ("что_видно", "что_не_выявлено", "не_проверено", "не_применимо",
                 "вне_охвата"):
        for p in out.get(ключ) or []:
            d[p["id"]] = p["статус"]
    return d


