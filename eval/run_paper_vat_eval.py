#!/usr/bin/env python3
"""
run_paper_vat_eval.py — офлайн-eval scripts/paper_vat.py (волна 3, поток K).

Фикстуры: eval/fixtures/paper_vat/*.json — синтетический вывод
fetch_counterparty.py (блоки источников + словари `_доступность` + `_итог_проверки`).
Числа в блоке «финансы» — ТЫСЯЧИ рублей: ровно то, что публикует ГИР БО и что
`paper_vat._строка()` умножает на 1000. Фикстура, написанная в рублях, тихо
превращает 12,4 млн ₽ в 12,4 млрд ₽ и делает мёртвой целую ветку вывода.

Кейсы:
  (а) чистая компания — ни одного признака «бумажного НДС»;
  (б) однодневка — поднимается ожидаемый набор признаков;
  (в) «не проверено» НЕ превращается в «признак отсутствует» — и когда пуст
      детальный эндпоинт pb внутри ok-блока, и когда не проверен БЛОК «риски»
      целиком. Плюс МУТАЦИОННАЯ проверка кусачести: если подсунуть скрипту
      багованный `_ссч`, который читает пустое поле как ноль, кейс обязан
      упасть. Тест, который не падает на внесённом дефекте, ничего не проверяет;
  (г) порог «проверка не состоялась» по доле признаков «не проверено» и
      граница: в РЕАЛЬНОЙ конфигурации движка (детальных флагов pb нет) доля
      садится ровно на порог 0.5, и вывод обязан сказать про это вслух;
  (д) УСН — ОБЕ ветки порога освобождения по отдельности, по статусу признака и
      по напечатанным числам, а не по наличию слов «УСН» и «освобожд» в тексте;
  (е) профиль `ндс_вычет` резолвится через profiles.resolve(), светофора не даёт,
      и все сигналы, на которые он ссылается, есть в каталоге;
  (ж) формулировочная дисциплина по ВСЕМ веткам вывода. Сканировать рендер
      фикстур мало: ревьюер вписал налоговое заключение в ветку «УСН ниже
      порога» и в ветку ликвидации — из фикстур того набора они были
      недостижимы, и eval остался зелёным. Поэтому текст берётся ДВАЖДЫ: из
      рендера всех фикстур И напрямую из исходника — все строковые литералы
      scripts/paper_vat.py через ast. Второй источник покрывает ветку
      независимо от того, дотягивается ли до неё хоть одна фикстура;
  (з) CLI: битый вход и --предмет/--сумма не падают traceback'ом;
  (и) сбор движка не состоялся — анализ не вправе сказать «ок»;
  (к) единицы ГИР БО (тысячи рублей);
  (л) сопряжение с отраслевыми нормами (пропускается, если таблицы нет);
  (м) «пусто» ГИР БО не превращается в признак у тех, кто отчётность публиковать
      не обязан: ИП, банк/страховщик/КГН/спецрежим;
  (н) флаги pb трёхзначны: пустая строка и «н/д» — «не проверено», а не
      «признака нет» и не «признак найден»;
  (о) ССЧ = 0 при непустой выручке — честная причина отказа, а не «выручки нет»;
  (п) ликвидированная компания: инструмент не приписывает реестру слово,
      которого реестр не давал;
  (р) кратность к отраслевой медиане берётся из канона, а не зашита в код
      (без зависимости от data/benchmarks_ru.json — оценка подменяется заглушкой).

PASS/FAIL, чистый stdlib, сети не требует — гоняется в CI.
"""

