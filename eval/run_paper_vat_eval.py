def main():
    pv = load_module("paper_vat", PAPER_VAT)
    pf = load_module("profiles", SCRIPTS / "profiles.py")
    canon = pv.load_canon()
    if canon is None:
        print("FAIL: data/canon_ru.json не читается — пороги бумажного НДС не проверить")
        return 1
    for ключ in ("бумажный_ндс_возраст_месяцев", "бумажный_ндс_существенная_выручка",
                 "бумажный_ндс_ссч_минимум", "бумажный_ндс_внеоборотные_минимум",
                 "бумажный_ндс_доля_не_проверено", "бумажный_ндс_выручка_на_сотрудника",
                 "бумажный_ндс_доля_ндс_к_выручке"):
        rec = canon.get(ключ)
        if not isinstance(rec, dict) or rec.get("значение") is None:
            print("FAIL: в data/canon_ru.json нет порога %s" % ключ)
            return 1
        if not rec.get("эвристика") or not rec.get("калибровка"):
            print("FAIL: порог %s не помечен как эвристический/неоткалиброванный" % ключ)
            return 1
    try:
        profiles = pf.load()
    except Exception as e:
        print("FAIL: data/profiles_ru.json не читается: %s" % e)
        return 1

    кейсы = [
        ("а-чистая-без-признаков", lambda: case_a_clean(pv, canon)),
        ("б-однодневка-ожидаемый-набор", lambda: case_b_shell(pv, canon)),
        ("в-не-проверено-vs-отсутствует(+мутация)", lambda: case_c_not_checked_vs_absent(pv, canon)),
        ("г-порог-проверка-не-состоялась", lambda: case_d_threshold(pv, canon)),
        ("д-усн-честная-формулировка", lambda: case_e_usn(pv, canon)),
        ("е-профиль-ндс_вычет", lambda: case_f_profile(pf, profiles)),
        ("ж-язык-фактов-без-заключений", lambda: case_g_wording(pv, canon)),
        ("з-cli", case_h_cli),
        ("и-сбор-не-состоялся-гейт", lambda: case_i_collection_gate(pv, canon)),
        ("к-единицы-гирбо-тысячи-рублей", lambda: case_j_units(pv, canon)),
        ("л-сопряжение-с-нормами", lambda: case_l_benchmarks(pv, canon)),
    ]
    failed = 0
    for имя, кейс in кейсы:
        try:
            errors = кейс()
        except Exception as e:  # кейс не имеет права падать traceback'ом
            errors = ["исключение в кейсе: %s: %s" % (type(e).__name__, e)]
        if errors:
            failed += 1
            print("FAIL %s" % имя)
            for e in errors:
                print("  - %s" % e)
        else:
            print("PASS %s" % имя)
    if failed:
        print("FAIL: %d/%d кейсов упало" % (failed, len(кейсы)))
        return 1
    print("PASS: все %d кейсов зелёные" % len(кейсы))
    return 0


if __name__ == "__main__":
    sys.exit(main())
