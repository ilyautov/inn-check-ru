#!/usr/bin/env python3
"""
run_pledge_text_eval.py — разбор текста страницы reestr-zalogov.ru (pledge_text.py)
и ручной блок «залоги» из текста: живая страница по ИНН 1650032058 (ПАО «КАМАЗ»,
28.09.2026, залогодержатели — банки и скрытые) и её правки — чужой ИНН,
залогодержатель-физлицо и ИП, несколько страниц, пропущенная строка, нет строк,
нет пагинации, созалогодатель. Хост расширения принимает текст только с сайта
реестра. PASS/FAIL, stdlib, CI.
"""

import datetime
import importlib.util
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ТЕКСТ = (ROOT / "eval" / "fixtures" / "pledge" / "kamaz_1650032058.txt").read_text(
    encoding="utf-8")
ИНН = "1650032058"
URL = "https://www.reestr-zalogov.ru/search"
СЕГОДНЯ = datetime.date(2026, 9, 28)
ФИО = "ФИО УБРАНО ИЗ ФИКСТУРЫ"


def load(имя):
    sys.path.insert(0, str(ROOT / "scripts"))
    spec = importlib.util.spec_from_file_location(имя, ROOT / "scripts" / ("%s.py" % имя))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def отказ(f, *a, **kw):
    try:
        f(*a, **kw)
    except ValueError as e:
        return str(e)
    return None


def case_живая_страница(pt):
    errors = []
    r = pt.разобрать(ТЕКСТ, ИНН)
    check(errors, r["уведомлений"] == 9, "уведомлений %r" % r["уведомлений"])
    check(errors, r["последнее"] == "2025-09-25", "последнее %r" % r["последнее"])
    check(errors, r["полно"] is True, "полно %r" % r["полно"])
    д = r["залогодержатели"]
    check(errors, д.get(pt.СКРЫТ) == 3, "скрытых %r" % д.get(pt.СКРЫТ))
    check(errors, д.get('ПАО "АК БАРС" БАНК') == 1, "АК БАРС: %r" % д)
    check(errors, sum(1 for k in д if "Внешэкономбанк" in k) == 1
          and д[next(k for k in д if "Внешэкономбанк" in k)] == 2, "ВЭБ: %r" % д)
    check(errors, sum(д.values()) == 9 and "стороны не разобраны" not in д,
          "стороны: %r" % д)
    # номера и даты — как на странице, по порядку
    check(errors, r["уведомления"][3] == {"дата": "2020-02-26", "номер": "2020-004-511617-392",
                                          "залогодержатель": 'ПАО "АК БАРС" БАНК'},
          "4-е уведомление: %r" % r["уведомления"][3])
    # залогодатель (сама компания) не записывается
    check(errors, "КАМАЗ" not in json.dumps(r, ensure_ascii=False), "имя залогодателя в выводе")
    # CRLF и NBSP (копирование в Windows) — тот же результат
    check(errors, pt.разобрать(ТЕКСТ.replace("\n", "\r\n").replace(" ", "\xa0"), ИНН) == r,
          "CRLF/NBSP меняют разбор")
    return "живая-страница", errors


def case_правки(pt):
    errors = []
    # чужой ИНН в параметрах поиска
    check(errors, "не по ИНН" in (отказ(pt.разобрать, ТЕКСТ, "7707083893") or ""), "чужой ИНН")
    # поиск по наименованию (ИНН в параметрах пуст)
    по_имени = ТЕКСТ.replace("ИНН: 1650032058", "ИНН: ")
    check(errors, "не по ИНН" in (отказ(pt.разобрать, по_имени, ИНН) or ""), "поиск по имени")
    for сузили in ("Наименование: КАМАЗ, ОГРН: , ИНН", "Наименование: , ОГРН: 1021602013971, ИНН"):
        т = ТЕКСТ.replace("Наименование: , ОГРН: , ИНН", сузили)
        check(errors, "не по ИНН" in (отказ(pt.разобрать, т, ИНН) or ""), "сужен: %s" % сузили)
    check(errors, "Параметры поиска" in (отказ(pt.разобрать, "просто текст", ИНН) or ""),
          "не страница реестра")
    check(errors, отказ(pt.разобрать, "", ИНН), "пустой текст")
    check(errors, "длиннее" in (отказ(pt.разобрать, "x" * (pt.МАКС_ТЕКСТ + 1), ИНН) or ""),
          "лимит размера")
    # залогодержатель — физлицо и ИП: имя не записывается
    # «лизинг» в имени ИП не делает его организацией
    for держатель in (ФИО, "ИП " + ФИО, "Индивидуальный предприниматель " + ФИО,
                      "ИП %s (лизинг техники)" % ФИО, "Банков Фондов Обществов"):
        т = ТЕКСТ.replace('ПАО "АК БАРС" БАНК', держатель)
        r = pt.разобрать(т, ИНН)
        check(errors, r["уведомления"][3]["залогодержатель"] == pt.НЕ_ОРГАНИЗАЦИЯ
              and ФИО not in json.dumps(r, ensure_ascii=False),
              "физлицо %r записано: %r" % (держатель, r["уведомления"][3]))
    # несколько страниц — неполно
    r = pt.разобрать(ТЕКСТ.replace("\n  1  \n", "\n  1  2  3  \n"), ИНН)
    check(errors, r["полно"] is False and "страниц результатов 3" in r["примечание"],
          "несколько страниц: %r" % ((r["полно"], r["примечание"]),))
    # пропущенная строка уведомления
    т = ТЕКСТ.replace("3    10.03.2020    2020-004-549044-985", "")
    check(errors, "не по порядку" in (отказ(pt.разобрать, т, ИНН) or ""), "пропуск строки")
    # нет строк уведомлений: «ничего не найдено» живьём не видели — не угадываем
    голова = ТЕКСТ[:ТЕКСТ.index("1    25.09.2025")]
    check(errors, "строк уведомлений не найдено" in (отказ(pt.разобрать, голова, ИНН) or ""),
          "нет строк")
    # текст оборван до пагинации
    т = ТЕКСТ[:ТЕКСТ.index("\n  1  \n")]
    check(errors, "не целиком" in (отказ(pt.разобрать, т, ИНН) or ""), "нет пагинации")
    # пагинация вырезана, хвост страницы остался: строки годов (1979, 1980…) из
    # выпадающего списка — не номера страниц
    т = ТЕКСТ.replace("\n  1  \n", "\n")
    check(errors, "не целиком" in (отказ(pt.разобрать, т, ИНН) or ""), "годы как страницы")
    # скопировано до пагинации, без «Внимание!» — не целиком
    т = ТЕКСТ[:ТЕКСТ.index("Внимание!")]
    check(errors, "не целиком" in (отказ(pt.разобрать, т, ИНН) or ""), "без «Внимание!»")
    # созалогодатель (три строки сторон) — стороны не угадываются
    т = ТЕКСТ.replace('ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО "КАМАЗ"\nПАО "АК БАРС" БАНК',
                      'ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО "КАМАЗ"\n%s\nПАО "АК БАРС" БАНК' % ФИО)
    r = pt.разобрать(т, ИНН)
    check(errors, r["уведомления"][3]["залогодержатель"] == "стороны не разобраны"
          and ФИО not in json.dumps(r, ensure_ascii=False),
          "созалогодатель: %r" % r["уведомления"][3])
    return "правки-страницы", errors


def case_ручной_блок(mb, profiles):
    errors = []
    арг = {"блок": "залоги", "инн": ИНН, "url": URL, "дата": "2026-09-28",
           "итог": "проверено", "сегодня": СЕГОДНЯ}
    б = mb.собрать(текст=ТЕКСТ, **арг)
    check(errors, б["статус"] == "проверено" and б["уведомлений"] == 9
          and б["последнее"] == "2025-09-25" and "уведомлений 9" in б["найдено"],
          "блок: %r" % {k: б.get(k) for k in ("статус", "уведомлений", "найдено")})
    fetch = {"инн": ИНН, "залоги": б, "_доступность": {"залоги": {
        "состояние": "не проверено", "причина": "не покрыто: браузерный источник"}}}
    сост = profiles._состояние_блока(fetch, "залоги")[0]
    check(errors, сост == "ok", "резолвер: %r" % сост)
    # несколько страниц -> «не проверено», разобранное сохраняется
    б = mb.собрать(текст=ТЕКСТ.replace("\n  1  \n", "\n  1  2  \n"), **арг)
    check(errors, б["статус"].startswith("не проверено: страниц результатов 2")
          and б["уведомлений"] == 9, "неполный: %r" % б["статус"])
    check(errors, profiles._состояние_блока(dict(fetch, залоги=б), "залоги")[0]
          == "не проверено", "неполный блок засчитан")
    # текст и поля вместе, текст у блока без разбора, чужой ИНН
    check(errors, "поля не вводятся" in (отказ(mb.собрать, текст=ТЕКСТ,
                                               **dict(арг, поля={"уведомлений": "1"})) or ""),
          "текст с полями")
    check(errors, "только у блоков" in (отказ(mb.собрать, текст=ТЕКСТ, **dict(
        арг, блок="суды", url="https://kad.arbitr.ru/", поля=None)) or ""), "текст у судов")
    check(errors, "не по ИНН" in (отказ(mb.собрать, текст=ТЕКСТ,
                                        **dict(арг, инн="7707083893")) or ""), "чужой ИНН")
    # текст — только со страницы реестра залогов
    for url in ("https://example.org/", "https://reestr-zalogov.ru.evil.ru/",
                "https://u@www.reestr-zalogov.ru/", "http://www.reestr-zalogov.ru/"):
        check(errors, "только со страницы" in (отказ(mb.собрать, текст=ТЕКСТ,
                                                       **dict(арг, url=url)) or ""),
              "текст с %s принят" % url)
    # «ничего не найдено» — вручную, полем
    б = mb.собрать(поля={"уведомлений": "0"}, **арг)
    check(errors, б["уведомлений"] == 0 and б["статус"] == "проверено", "ноль вручную: %r" % б)
    return "ручной-блок", errors


def case_хост(host):
    errors = []
    with tempfile.TemporaryDirectory() as td:
        база = {"команда": "ручной_блок", "инн": ИНН, "блок": "залоги", "url": URL,
                "дата": "2026-09-28", "итог": "проверено", "текст": ТЕКСТ}
        о = host.обработать(dict(база, операция="op-zalog-0001"), корень=Path(td).resolve())
        check(errors, о.get("ok") and о.get("состояние") == "ok"
              and "уведомлений 9" in (о.get("найдено") or ""), "хост: %r" % о)
        файл = Path(о.get("записано") or td)
        check(errors, файл.is_file() and json.loads(файл.read_text(encoding="utf-8"))
              .get("уведомлений") == 9, "файл блока: %r" % файл)
        о = host.обработать(dict(база, операция="op-zalog-0002",
                                 url="https://kad.arbitr.ru/"), корень=Path(td).resolve())
        check(errors, not о.get("ok") and "url не с сайта" in о.get("ошибка", ""),
              "чужой сайт: %r" % о)
        о = host.обработать(dict(база, операция="op-zalog-0003", текст=["x"]),
                            корень=Path(td).resolve())
        check(errors, not о.get("ok"), "текст не строкой: %r" % о)
    return "хост", errors


def main():
    pt = load("pledge_text")
    mb = load("manual_block")
    profiles = load("profiles")
    host = load("native_host")
    failed = 0
    for имя, errors in (case_живая_страница(pt), case_правки(pt),
                        case_ручной_блок(mb, profiles), case_хост(host)):
        if errors:
            failed += 1
            print("FAIL %s" % имя)
            for e in errors:
                print("  -", e)
        else:
            print("PASS %s" % имя)
    if failed:
        print("FAIL: %d/4 кейсов упало" % failed)
        return 1
    print("PASS: все 4 кейсов зелёные")
    return 0


if __name__ == "__main__":
    sys.exit(main())
