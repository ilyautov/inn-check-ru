def case_f_itog_not_leaking(rv, snapshot, td):
    """«Проверка состоялась» в снимке — про день сбора, а не про восстановленное."""
    errors = []
    кэш = Path(td) / "f"
    путь = положить(snapshot, кэш, "2026-03-01", формат=1)
    снимок = json.loads(путь.read_text(encoding="utf-8"))
    check(errors, снимок.get("_итог", {}).get("проверка_состоялась") is True,
          "фикстура негодна: в снимке нет «проверка состоялась»")
