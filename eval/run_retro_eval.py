def положить(snapshot, каталог, дата, слепок=None, формат=None):
    """Кладёт отпечаток (или полный слепок) в кэш снимков с заданной датой."""
    каталог_инн = Path(snapshot.snapshots_dir(ИНН, str(каталог)))
    каталог_инн.mkdir(parents=True, exist_ok=True)
    данные = полный_снимок() if слепок is None else слепок
    if формат == "полный":
        содержимое = dict(данные)
        содержимое["дата"] = дата + "T10:00:00"
    else:
        содержимое = snapshot.fingerprint(данные, дата=дата + "T10:00:00")
        if формат == 1:                      # отпечаток старого формата
            содержимое.pop("вердикт", None)
            содержимое["версия_формата"] = 1
    путь = каталог_инн / (дата + "_10-00-00.json")
    путь.write_text(json.dumps(содержимое, ensure_ascii=False), encoding="utf-8")
    return путь


