#!/usr/bin/env python3
"""
run_retro_eval.py — офлайн-eval ретроспективного вердикта (задача 6).

Ретроспектива нужна ровно для одного: показать, что было видно ДО сделки.
Поэтому проверяются не столько «считается ли светофор», сколько границы, за
которыми ретроспектива превращается в подлог:

  (а) вердикт считается по снимку на дату, и дата снимка видна в выводе;
  (б) снимок НОВЕЕ запрошенной даты не берётся — это данные из будущего;
  (в) снимков нет — отказ, а не сегодняшние данные задним числом;
  (г) отпечаток формата 1 (без блока «вердикт») — источники без значений
      названы поимённо, их сигналы «не проверен», 🟢 не выдаётся;
  (д) формат 2 восстанавливает 🔴 (санкции, банкротство);
  (е) «проверка состоялась» из снимка не протекает в вердикт по урезанным данным;
  (ж) отставание снимка от даты и разнородный профиль сбора — в предупреждениях;
  (з) CLI: --список, кривая дата, чужой ИНН — без traceback.

PASS/FAIL, чистый stdlib, сети не требует.
"""

import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"
ИНН = "7707083893"


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check(errors, cond, msg):
    if not cond:
        errors.append(msg)


def _av(state, причина=None):
    return {"состояние": state, "причина": причина, "tier": "🟢",
            "требует": "сеть", "дата": "2026-03-01"}


