def case_f_itog_not_leaking(rv, snapshot, td):
    """«Проверка состоялась» в снимке — про день сбора, а не про восстановленное."""
    errors = []
    кэш = Path(td) / "f"
    путь = положить(snapshot, кэш, "2026-03-01", формат=1)
    снимок = json.loads(путь.read_text(encoding="utf-8"))
    check(errors, снимок.get("_итог", {}).get("проверка_состоялась") is True,
          "фикстура негодна: в снимке нет «проверка состоялась»")
    out = rv.retro(ИНН, "2026-03-02", профиль="отсрочка", каталог=str(кэш))
    check(errors, out.get("вердикт", {}).get("проверка_состоялась") is False,
          "итог из снимка протёк в вердикт по урезанным данным: %r"
          % out.get("вердикт", {}).get("проверка_состоялась"))
    # Перечень непроверенного должен быть про ВОССТАНОВЛЕННОЕ сегодня, а не
    # про то, что собралось в тот день: в снимке-то собралось всё.
    нп = set(out.get("вердикт", {}).get("источники_обязательные_не_проверены") or [])
    check(errors, {"санкции", "фссп"} <= нп,
          "непроверенными названы не те источники: %r" % sorted(нп))
    return errors


def case_g_collect_mismatch(rv, snapshot, td):
    errors = []
    кэш = Path(td) / "g"
    # Как это лежит в полном слепке движка: режим — в «_сбор», профиль —
    # отдельным полем верхнего уровня (см. diff_counterparty.условия_сбора).
    слепок = полный_снимок()
    слепок["_сбор"] = {"режим": "quick"}
    слепок["профиль"] = "предоплата"
    положить(snapshot, кэш, "2026-03-01", слепок=слепок)
    out = rv.retro(ИНН, "2026-03-02", профиль="отсрочка", каталог=str(кэш))
    тексты = " ".join(out.get("предупреждения") or [])
    check(errors, "quick" in тексты or "неполный" in тексты,
          "не предупреждает о неполном режиме сбора: %r" % тексты)
    check(errors, "предоплата" in тексты,
          "не предупреждает о чужом профиле сбора: %r" % тексты)
    # без --профиль берётся профиль, которым собирали
    out2 = rv.retro(ИНН, "2026-03-02", каталог=str(кэш))
    check(errors, out2.get("профиль") == "предоплата",
          "профиль по умолчанию должен браться из снимка: %r" % out2.get("профиль"))
    return errors


def case_h_cli(snapshot, td):
    errors = []
    кэш = Path(td) / "h"
    положить(snapshot, кэш, "2026-03-01")

    def запуск(args):
        return subprocess.run(
            [sys.executable, str(SCRIPTS / "retro_verdict.py")] + args,
            capture_output=True, text=True, timeout=60, check=False)

    p = запуск([ИНН, "--список", "--каталог", str(кэш)])
    check(errors, "Traceback" not in p.stderr, "traceback на --список: %s" % p.stderr[-200:])
    out = json.loads(p.stdout or "{}")
    check(errors, out.get("снимков") == 1 and out["снимки"][0].get("вердикт_восстановим") is True,
          "--список: %r" % out)

    p2 = запуск([ИНН, "--дата", "вчера", "--каталог", str(кэш)])
    check(errors, "Traceback" not in p2.stderr, "traceback на кривой дате")
    out2 = json.loads(p2.stdout or "{}")
    check(errors, out2.get("статус") == "не проверено"
          and "ГГГГ-ММ-ДД" in (out2.get("причина") or ""),
          "кривая дата: %r" % out2)

    p3 = запуск(["7700000000", "--дата", "2026-03-01", "--каталог", str(кэш)])
    check(errors, p3.returncode == 0 and "Traceback" not in p3.stderr,
          "чужой ИНН уронил скрипт: %s" % p3.stderr[-200:])
    return errors



def case_i_silent_source(rv, snapshot, td):
    """Блок с данными при состоянии «не проверено» — ловушка: данные стухшие.

    Движок оставляет блок в слепке и тогда, когда источник не ответил (там
    лежит прошлая или пустая заготовка). Класть такое в отпечаток нельзя:
    ретроспектива прочитает «производств 0» как факт, которого в тот день
    никто не видел.
    """
    errors = []
    кэш = Path(td) / "i"
    слепок = полный_снимок()
    слепок["_доступность"]["фссп"] = _av("не проверено", "гео: fssp.gov.ru")
    положить(snapshot, кэш, "2026-03-01", слепок=слепок)

    отпечаток = json.loads(
        (Path(snapshot.snapshots_dir(ИНН, str(кэш))) /
         "2026-03-01_10-00-00.json").read_text(encoding="utf-8"))
    check(errors, "фссп" not in (отпечаток.get("вердикт") or {}),
          "агрегаты молчавшего источника попали в отпечаток: %r"
          % (отпечаток.get("вердикт") or {}).get("фссп"))

    out = rv.retro(ИНН, "2026-03-02", профиль="отсрочка", каталог=str(кэш))
    восст = out.get("восстановление") or {}
    check(errors, "фссп" in (восст.get("источники_молчали_тогда") or []),
          "молчавший тогда источник не назван: %r" % восст)
    факты = {f.get("сигнал"): f.get("статус") for f in
             out.get("вердикт", {}).get("факты", [])}
    check(errors, факты.get("фссп_крупные") == "не проверен",
          "сигнал молчавшего источника: %r" % факты.get("фссп_крупные"))
    check(errors, out.get("вердикт", {}).get("светофор") is None,
          "🟢 выдан при непроверенном deal-killer-источнике: %r"
          % out.get("вердикт", {}).get("светофор"))
    return errors


def main():
    rv = load_module("retro_verdict", SCRIPTS / "retro_verdict.py")
    snapshot = load_module("snapshot", SCRIPTS / "snapshot.py")
    with tempfile.TemporaryDirectory() as td:
        cases = {
            "а-вердикт-на-дату": case_a_verdict_on_date(rv, snapshot, td),
            "б-снимок-из-будущего-не-берётся": case_b_no_future(rv, snapshot, td),
            "в-снимков-нет": case_c_no_snapshots(rv, td),
            "г-отпечаток-формата-1": case_d_format1(rv, snapshot, td),
            "д-формат-2-восстанавливает-🔴": case_e_format2_red(rv, snapshot, td),
            "е-итог-снимка-не-протекает": case_f_itog_not_leaking(rv, snapshot, td),
            "ж-режим-и-профиль-сбора": case_g_collect_mismatch(rv, snapshot, td),
            "з-cli": case_h_cli(snapshot, td),
            "и-молчавший-источник-с-данными": case_i_silent_source(rv, snapshot, td),
        }
    failed = 0
    for name, errors in cases.items():
        if errors:
            failed += 1
            print("FAIL %s" % name)
            for e in errors:
                print("  - %s" % e)
        else:
            print("PASS %s" % name)
    if failed:
        print("FAIL: %d/%d кейсов упало" % (failed, len(cases)))
        return 1
    print("PASS: все %d кейсов зелёные" % len(cases))
    return 0


if __name__ == "__main__":
    sys.exit(main())
