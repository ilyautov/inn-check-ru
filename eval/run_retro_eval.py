def case_i_silent_source(rv, snapshot, td):
    """Блок с данными при состоянии «не проверено» — ловушка: данные стухшие.

    Движок оставляет блок в слепке и тогда, когда источник не ответил (там
    лежит прошлая или пустая заготовка). Класть такое в отпечаток нельзя:
    ретроспектива прочитает «производств 0» как факт, которого в тот день
    никто не видел.
    """
    errors = []
    кэш = Path(td) / "i"
    слепок = полный_снимок()
    слепок["_доступность"]["фссп"] = _av("не проверено", "гео: fssp.gov.ru")
    # заготовка движка: следов ручной проверки (дата, URL) нет
    for k in ("ввод", "дата_проверки", "url"):
        слепок["фссп"].pop(k, None)
    положить(snapshot, кэш, "2026-03-01", слепок=слепок)

    отпечаток = json.loads(
        (Path(snapshot.snapshots_dir(ИНН, str(кэш))) /
         "2026-03-01_10-00-00.json").read_text(encoding="utf-8"))
    check(errors, "фссп" not in (отпечаток.get("вердикт") or {}),
          "агрегаты молчавшего источника попали в отпечаток: %r"
          % (отпечаток.get("вердикт") or {}).get("фссп"))

    out = rv.retro(ИНН, "2026-03-02", профиль="отсрочка", каталог=str(кэш))
    восст = out.get("восстановление") or {}
    check(errors, "фссп" in (восст.get("источники_молчали_тогда") or []),
          "молчавший тогда источник не назван: %r" % восст)
    факты = {f.get("сигнал"): f.get("статус") for f in
             out.get("вердикт", {}).get("факты", [])}
    check(errors, факты.get("фссп_крупные") == "не проверен",
          "сигнал молчавшего источника: %r" % факты.get("фссп_крупные"))
    check(errors, out.get("вердикт", {}).get("светофор") is None,
          "🟢 выдан при непроверенном deal-killer-источнике: %r"
          % out.get("вердикт", {}).get("светофор"))
    return errors


