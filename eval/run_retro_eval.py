def case_d_format1(rv, snapshot, td):
    """Формат 1 не хранил агрегатов deal-killer'ов — и молчать об этом нельзя."""
    errors = []
    кэш = Path(td) / "d"
    положить(snapshot, кэш, "2026-03-01", формат=1)
    out = rv.retro(ИНН, "2026-03-02", профиль="отсрочка", каталог=str(кэш))
    без = (out.get("восстановление") or {}).get("источники_без_значений") or []
    for блок in ("санкции", "фссп", "банкротство"):
        check(errors, блок in без,
              "%s не назван среди источников без значений: %r" % (блок, без))
    check(errors, out.get("вердикт", {}).get("светофор") is None,
          "по формату 1 выдан светофор %r — 🟢 на невосстановимых источниках "
          "недопустим" % out.get("вердикт", {}).get("светофор"))
    факты = {f.get("сигнал"): f.get("статус") for f in
             out.get("вердикт", {}).get("факты", [])}
    check(errors, факты.get("рфм_совпадение") == "не проверен",
          "санкционный сигнал по формату 1: %r" % факты.get("рфм_совпадение"))
    check(errors, any("не переспрашивается" in p or "прошлое" in p
                      for p in out.get("предупреждения") or []),
          "нет предупреждения, что добрать задним числом нельзя: %r"
          % out.get("предупреждения"))
    return errors


